function search = buildAzElVisibilityRoutes( ...
        obstacleField, initialState, goalState, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   search = buildAzElVisibilityRoutes( ...
%       obstacleField, initialState, goalState)
%   search = buildAzElVisibilityRoutes( ...
%       obstacleField, initialState, goalState, optionOverrides)
%**************************************************************************
% PURPOSE
%   - Build collision-checked visibility routes from a bounded candidate
%     set while retaining full protected polygons for collision validation.
%**************************************************************************
% INPUTS
%   - obstacleField (scalar packed obstacle field)
%       Output from buildAzElTimeObstacleField.
%   - initialState, goalState (scalar structs)
%       time_s and position_deg fields.
%   - optionOverrides (scalar struct, optional; default struct())
%       Internal search and reduction controls. UseParallel accepts
%       "auto", "on", "off", or a logical scalar and falls back to serial
%       execution when Parallel Computing Toolbox is unavailable.
%       RequiredSnapshotTimes_s adds only the source samples nearest the
%       requested adaptive-refinement times.
%       DetectSnapshotEvents promotes source slices for single-obstacle
%       changes and adds times around pairwise protected-bounds overlap.
%       BuildFullVisibilityGraphs and BuildMergedVisibilityGraph are
%       internal stage controls used by the public planner's adaptive
%       dense-scene search. BuildAlternativeTopologyRoute permits one
%       bounded distinct route for a time-invariant planner field.
%       BuildSpaceTimeVisibilityGraph connects spatial candidates across
%       directed time layers. MaximumVelocity_deg_s limits its edges.
%**************************************************************************
% OUTPUTS
%   - search (scalar struct)
%       VisibilityGraphs and CandidateReductionDiagnostics.
%**************************************************************************
% UNITS
%   - Position is degrees and time is seconds.
%**************************************************************************

%% Section 1: Resolve Options & Validate Inputs

if nargin < 4 || isempty(optionOverrides)
    optionOverrides = struct();
end
defaults = struct( ...
    "MaximumSnapshotsPerObstacle", Inf, ...
    "RequiredSnapshotTimes_s", zeros(0, 1), ...
    "DetectSnapshotEvents", true, ...
    "SnapshotProbeEdgeCount", 4, ...
    "SnapshotCountChangeThreshold", 0.10, ...
    "SnapshotEdgeRotationThreshold_deg", 5, ...
    "SnapshotBoundaryMotionThreshold_deg", 1, ...
    "CandidateClearance_deg", 0, ...
    "CornerAngleThreshold_deg", 15, ...
    "PolygonCandidateMode", "adaptive", ...
    "ExtremeDirectionCount", 16, ...
    "MaximumTangenciesPerReference", 2, ...
    "VisibilitySampleStep_deg", 0.10, ...
    "ConnectivityPathCostChangeThreshold", 0.05, ...
    "BuildFullVisibilityGraphs", true, ...
    "BuildMergedVisibilityGraph", true, ...
    "BuildAlternativeTopologyRoute", false, ...
    "BuildSpaceTimeVisibilityGraph", false, ...
    "GoalTimeMode", "earliestArrival", ...
    "MaximumVelocity_deg_s", [Inf Inf], ...
    "SpaceTimeLayerCount", 17, ...
    "MaximumSpaceTimeCandidateCount", 32, ...
    "MaximumSpaceTimeDiagnosticEdgeCount", 5000, ...
    "CollisionTimePaddingSamples", 0, ...
    "UseParallel", false, ...
    "Verbose", false);
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("buildAzElVisibilityRoutes:InvalidOptions", ...
        "optionOverrides must be a scalar struct.");
end
[options, unknownFields] = azElInternal.resolveOptions( ...
    defaults, optionOverrides);
if ~isempty(unknownFields)
    warning("buildAzElVisibilityRoutes:UnknownOptions", ...
        "Ignoring unknown option fields: %s. No behavior changed.", ...
        strjoin(unknownFields, ", "));
end
validateattributes(options.MaximumSnapshotsPerObstacle, {'numeric'}, ...
    {'real','scalar','positive'});
if isfinite(options.MaximumSnapshotsPerObstacle) && ...
        fix(options.MaximumSnapshotsPerObstacle) ~= ...
        options.MaximumSnapshotsPerObstacle
    error("buildAzElVisibilityRoutes:InvalidSnapshotLimit", ...
        "MaximumSnapshotsPerObstacle must be a positive integer or Inf.");
end
validateattributes(options.RequiredSnapshotTimes_s, {'numeric'}, ...
    {'real', 'finite', 'vector'});
options.RequiredSnapshotTimes_s = ...
    unique(double(options.RequiredSnapshotTimes_s(:)));
logicalOptionNames = ["DetectSnapshotEvents" ...
    "BuildFullVisibilityGraphs" "BuildMergedVisibilityGraph" ...
    "BuildAlternativeTopologyRoute" ...
    "BuildSpaceTimeVisibilityGraph" "Verbose"];
for logicalOptionIndex = 1:numel(logicalOptionNames)
    optionName = logicalOptionNames(logicalOptionIndex);
    options.(optionName) = azElInternal.normalizeLogicalScalar( ...
        options.(optionName), optionName, ...
        "buildAzElVisibilityRoutes:InvalidLogicalOption");
end
validateattributes(options.SnapshotProbeEdgeCount, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', 'positive'});
validateattributes(options.SnapshotCountChangeThreshold, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'nonnegative'});
validateattributes(options.SnapshotEdgeRotationThreshold_deg, ...
    {'numeric'}, {'real', 'scalar', 'nonnegative'});
validateattributes(options.SnapshotBoundaryMotionThreshold_deg, ...
    {'numeric'}, {'real', 'scalar', 'nonnegative'});
validateattributes(options.CandidateClearance_deg, {'numeric'}, ...
    {'scalar','real','finite','nonnegative'});
polygonCandidateMode = lower(string(options.PolygonCandidateMode));
if ~isscalar(polygonCandidateMode) || ~any( ...
        polygonCandidateMode == ["adaptive" "allcorners" "extreme"])
    error("buildAzElVisibilityRoutes:InvalidPolygonCandidateMode", ...
        "PolygonCandidateMode must be adaptive, allCorners, or extreme.");
end
if polygonCandidateMode == "allcorners"
    options.PolygonCandidateMode = "allCorners";
else
    options.PolygonCandidateMode = polygonCandidateMode;
end
validateattributes(options.ExtremeDirectionCount, {'numeric'}, ...
    {'scalar','integer','>=',4});
validateattributes(options.MaximumTangenciesPerReference, {'numeric'}, ...
    {'scalar','integer','nonnegative'});
validateattributes(options.VisibilitySampleStep_deg, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(options.ConnectivityPathCostChangeThreshold, ...
    {'numeric'}, {'scalar', 'real', 'finite', '>=', 0, '<=', 1});
options.GoalTimeMode = lower(string(options.GoalTimeMode));
if ~isscalar(options.GoalTimeMode) || ~any( ...
        options.GoalTimeMode == ["earliestarrival" "fixedarrival"])
    error("buildAzElVisibilityRoutes:InvalidGoalTimeMode", ...
        "GoalTimeMode must be earliestArrival or fixedArrival.");
end
validateattributes(options.MaximumVelocity_deg_s, {'numeric'}, ...
    {'real', 'positive', 'vector', 'numel', 2});
options.MaximumVelocity_deg_s = ...
    reshape(double(options.MaximumVelocity_deg_s), 1, 2);
validateattributes(options.SpaceTimeLayerCount, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', '>=', 3});
validateattributes(options.MaximumSpaceTimeCandidateCount, {'numeric'}, ...
    {'real', 'scalar', 'positive'});
if isfinite(options.MaximumSpaceTimeCandidateCount) && ...
        fix(options.MaximumSpaceTimeCandidateCount) ~= ...
        options.MaximumSpaceTimeCandidateCount
    error("buildAzElVisibilityRoutes:InvalidSpaceTimeCandidateLimit", ...
        "MaximumSpaceTimeCandidateCount must be an integer or Inf.");
end
validateattributes(options.MaximumSpaceTimeDiagnosticEdgeCount, ...
    {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', 'nonnegative'});
validateattributes(options.CollisionTimePaddingSamples, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', 'nonnegative'});
options.UseParallel = azElInternal.normalizeParallelMode( ...
    options.UseParallel, ...
    "buildAzElVisibilityRoutes:InvalidUseParallel");
fieldIsPacked = isstruct(obstacleField) && isscalar(obstacleField) && ...
    isfield(obstacleField, "Format") && ...
    string(obstacleField.Format) == "AzElTimeObstacleField";
if ~fieldIsPacked
    error("buildAzElVisibilityRoutes:InvalidObstacleField", ...
        "obstacleField must come from buildAzElTimeObstacleField.");
end

%% Section 2: Select Snapshots & Boundary Candidates

snapshotSelection = azElInternal.selectAzElVisibilitySnapshots( ...
    obstacleField, initialState, goalState, options);
candidatePoints = snapshotSelection.CandidatePointsAzElTime;
candidateObstacleIndex = snapshotSelection.CandidateObstacleIndex;
candidateSampleIndex = snapshotSelection.CandidateSampleIndex;
candidateRegionIndex = snapshotSelection.CandidateRegionIndex;
snapshotDiagnostics = snapshotSelection.SnapshotDiagnostics;
candidateReductionDiagnostics = ...
    snapshotSelection.CandidateReductionDiagnostics;

%% Section 3: Build Snapshot Visibility Graphs

[visibilityGraphs, mergedGraphCandidates, parallelExecution] = ...
    azElInternal.buildAzElSnapshotVisibilityGraphs( ...
    obstacleField, snapshotSelection, options);
[mergedVisibilityGraphs, obstacleMergeDiagnostics] = ...
    selectMergedObstacleGraph(mergedGraphCandidates);
spaceTimeVisibilityGraph = ...
    azElInternal.buildAzElSpaceTimeVisibilityGraph();
if options.BuildSpaceTimeVisibilityGraph
    snapshotGraphs = [visibilityGraphs(:); mergedVisibilityGraphs(:)];
    spaceTimeVisibilityGraph = ...
        azElInternal.buildAzElSpaceTimeVisibilityGraph( ...
        obstacleField, snapshotGraphs, initialState, goalState, options);
end
[connectivityDiagnostics, connectivityChangeIntervals] = ...
    visibilityConnectivityDiagnostics(visibilityGraphs, ...
    options.ConnectivityPathCostChangeThreshold);
for graphIndex = 1:numel(visibilityGraphs)
    activeCandidate = visibilityGraphs(graphIndex).NodeCandidateIndex(3:end);
    activeCandidate = activeCandidate( ...
        visibilityGraphs(graphIndex).CandidateActiveMask);
    for diagnosticIndex = 1:numel(candidateReductionDiagnostics)
        diagnostic = candidateReductionDiagnostics(diagnosticIndex);
        belongs = candidateObstacleIndex == diagnostic.ObstacleIndex & ...
            candidateSampleIndex == diagnostic.SampleIndex & ...
            candidateRegionIndex == diagnostic.RegionIndex;
        activeCount = nnz(ismember(find(belongs), activeCandidate));
        candidateReductionDiagnostics(diagnosticIndex). ...
            GraphActiveCandidateCount = activeCount;
        if diagnostic.SelectedCandidateCount > 0
            candidateReductionDiagnostics(diagnosticIndex). ...
                RelevanceReductionPercent = 100 * ...
                (1 - activeCount / diagnostic.SelectedCandidateCount);
        end
    end
end

%% Section 4: Assemble Search Diagnostics

search = struct( ...
    "VisibilityGraphs", visibilityGraphs, ...
    "MergedVisibilityGraphs", mergedVisibilityGraphs, ...
    "SpaceTimeVisibilityGraph", spaceTimeVisibilityGraph, ...
    "ObstacleMergeDiagnostics", obstacleMergeDiagnostics, ...
    "ConnectivityDiagnostics", connectivityDiagnostics, ...
    "ConnectivityChangeIntervals", connectivityChangeIntervals, ...
    "PairwiseEventTimes_s", snapshotSelection.PairwiseEventTimes_s, ...
    "PairwiseEventDiagnostics", ...
    snapshotSelection.PairwiseEventDiagnostics, ...
    "SnapshotDiagnostics", snapshotDiagnostics, ...
    "CandidateReductionDiagnostics", candidateReductionDiagnostics, ...
    "CandidatePointsAzElTime", candidatePoints, ...
    "ParallelExecution", parallelExecution, ...
    "Options", options);
end

%% Section 5: Local Functions

function [selectedGraph, diagnostics] = ...
        selectMergedObstacleGraph(graphCandidates)
% PURPOSE
%   - Retain the shortest successful sparse merged graph so a dense
%     obstacle history adds one bounded planner contender.
selectedGraph = graphCandidates([]);
successfulIndex = find([graphCandidates.Success] & ...
    [graphCandidates.ObstacleMergeComplete]);
selectedCandidateIndex = 0;
if ~isempty(successfulIndex)
    pathCost_deg = [graphCandidates(successfulIndex).PathCost_deg];
    [~, localIndex] = min(pathCost_deg);
    selectedCandidateIndex = successfulIndex(localIndex);
    selectedGraph = graphCandidates(selectedCandidateIndex);
end

selectedTime_s = NaN;
selectedSourceObstacleCount = 0;
selectedMaximumGraphObstacleCount = 0;
selectedMergedGroupCount = 0;
selectedGraphObstacleCount = 0;
if ~isempty(selectedGraph)
    selectedTime_s = selectedGraph.Time_s;
    selectedSourceObstacleCount = selectedGraph.SourceObstacleCount;
    selectedMaximumGraphObstacleCount = ...
        selectedGraph.MaximumGraphObstacleCount;
    selectedMergedGroupCount = selectedGraph.MergedGroupCount;
    selectedGraphObstacleCount = selectedGraph.GraphObstacleCount;
end
diagnostics = struct( ...
    "ThresholdObstacleCount", 4, ...
    "AttemptedGraphCount", numel(graphCandidates), ...
    "SuccessfulGraphCount", numel(successfulIndex), ...
    "SelectedCandidateIndex", selectedCandidateIndex, ...
    "SelectedTime_s", selectedTime_s, ...
    "SelectedSourceObstacleCount", selectedSourceObstacleCount, ...
    "SelectedMaximumGraphObstacleCount", ...
    selectedMaximumGraphObstacleCount, ...
    "SelectedMergedGroupCount", selectedMergedGroupCount, ...
    "SelectedGraphObstacleCount", selectedGraphObstacleCount, ...
    "Selected", ~isempty(selectedGraph));
end

function [diagnostics, changeIntervals] = ...
        visibilityConnectivityDiagnostics(visibilityGraphs, ...
        pathCostChangeThreshold)
% PURPOSE
%   - Detect graph splits, merges, and start-to-goal connectivity changes
%     that make an adjacent time interval valuable for refinement.
diagnosticTemplate = struct( ...
    "Time_s", NaN, ...
    "ConsideredNodeCount", 0, ...
    "ConnectedComponentCount", 0, ...
    "StartComponentSize", 0, ...
    "GoalComponentSize", 0, ...
    "StartGoalConnected", false, ...
    "DirectEdgeAvailable", false, ...
    "ShortestPathCost_deg", Inf);
diagnostics = repmat(diagnosticTemplate, numel(visibilityGraphs), 1);

for snapshotIndex = 1:numel(visibilityGraphs)
    visibilityGraph = visibilityGraphs(snapshotIndex);
    consideredNode = [true; true; ...
        visibilityGraph.CandidateActiveMask(:)];
    edgeAvailable = isfinite(visibilityGraph.EdgeCost_deg);
    edgeAvailable = edgeAvailable(consideredNode, consideredNode);
    edgeAvailable(1:size(edgeAvailable, 1) + 1:end) = false;
    componentGraph = graph(edgeAvailable, 'upper');
    componentIndex = conncomp(componentGraph).';
    componentCount = max(componentIndex);
    if isempty(componentCount)
        componentCount = 0;
    end

    diagnostic = diagnosticTemplate;
    diagnostic.Time_s = visibilityGraph.Time_s;
    diagnostic.ConsideredNodeCount = nnz(consideredNode);
    diagnostic.ConnectedComponentCount = componentCount;
    diagnostic.DirectEdgeAvailable = ...
        size(visibilityGraph.EdgeCost_deg, 1) >= 2 && ...
        isfinite(visibilityGraph.EdgeCost_deg(1, 2));
    diagnostic.ShortestPathCost_deg = visibilityGraph.PathCost_deg;
    if numel(componentIndex) >= 2
        startComponent = componentIndex(1);
        goalComponent = componentIndex(2);
        diagnostic.StartComponentSize = nnz( ...
            componentIndex == startComponent);
        diagnostic.GoalComponentSize = nnz( ...
            componentIndex == goalComponent);
        diagnostic.StartGoalConnected = ...
            startComponent == goalComponent;
    end
    diagnostics(snapshotIndex) = diagnostic;
end

intervalTemplate = struct( ...
    "EarlierTime_s", NaN, ...
    "LaterTime_s", NaN, ...
    "ComponentCountChanged", false, ...
    "StartGoalConnectivityChanged", false, ...
    "DirectEdgeAvailabilityChanged", false, ...
    "ShortestPathCostChangedSignificantly", false, ...
    "Significant", false);
changeIntervals = repmat(intervalTemplate, 0, 1);

for intervalIndex = 1:max(0, numel(diagnostics) - 1)
    earlier = diagnostics(intervalIndex);
    later = diagnostics(intervalIndex + 1);
    componentCountChanged = earlier.ConnectedComponentCount ~= ...
        later.ConnectedComponentCount;
    endpointConnectivityChanged = earlier.StartGoalConnected ~= ...
        later.StartGoalConnected;
    directEdgeChanged = earlier.DirectEdgeAvailable ~= ...
        later.DirectEdgeAvailable;
    finitePathPair = isfinite(earlier.ShortestPathCost_deg) && ...
        isfinite(later.ShortestPathCost_deg);
    pathCostChanged = finitePathPair && abs( ...
        later.ShortestPathCost_deg - earlier.ShortestPathCost_deg) > ...
        pathCostChangeThreshold * max( ...
        1, min(earlier.ShortestPathCost_deg, ...
        later.ShortestPathCost_deg));
    if ~(componentCountChanged || endpointConnectivityChanged || ...
            directEdgeChanged || pathCostChanged)
        continue;
    end
    interval = intervalTemplate;
    interval.EarlierTime_s = earlier.Time_s;
    interval.LaterTime_s = later.Time_s;
    interval.ComponentCountChanged = componentCountChanged;
    interval.StartGoalConnectivityChanged = ...
        endpointConnectivityChanged;
    interval.DirectEdgeAvailabilityChanged = directEdgeChanged;
    interval.ShortestPathCostChangedSignificantly = pathCostChanged;
    interval.Significant = true;
    changeIntervals(end + 1, 1) = interval; %#ok<AGROW>
end
end
