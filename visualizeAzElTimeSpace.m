function spaceView = visualizeAzElTimeSpace( ...
        obstacleField, startState, goalState, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = visualizeAzElTimeSpace()
%   spaceView = visualizeAzElTimeSpace( ...
%       obstacleField, startState, goalState)
%   spaceView = visualizeAzElTimeSpace( ...
%       obstacleField, startState, goalState, options)
%**************************************************************************
% PURPOSE
%   - Draw packed azimuth/elevation obstacles in az/el/time space.
%   - Connect compatible polygon samples into translucent swept surfaces.
%   - Draw the direct three-dimensional vector from start to goal.
%   - Draw a vertical time line through the goal azimuth/elevation.
%   - Mark circle tangencies and significant polygon corners as graph nodes.
%   - Select the fewest-edge boundary chain between a start-visible node
%     and a node that can connect directly to the goal on each slice.
%   - Build one global visibility graph so a route may transfer between
%     candidates on several obstacles before it reaches the goal.
%**************************************************************************
% INPUTS
%   - obstacleField (scalar struct)
%       Output from buildAzElTimeObstacleField(azElData).
%   - startState, goalState (scalar structs)
%       time_s and position_deg fields. Other state fields are ignored.
%   - optionOverrides (scalar struct, optional)
%       Display controls returned by the zero-input defaults call.
%       Stored azElData metadata automatically supplies the original
%       polygon and applied margin. Explicit legacy overrides remain valid.
%**************************************************************************
% OUTPUTS
%   - spaceView (scalar struct)
%       Obstacle field, graphics handles, direct vector, visibility masks,
%       selected boundary chains, and diagnostics.
%**************************************************************************
% UNITS
%   - Azimuth/elevation are degrees and time is seconds.

%% Section 1: Validate Inputs & Resolve Display Options
defaultOptions = struct( ...
    "MaximumDisplayedSlicesPerObstacle", 60, ...
    "SliceFaceAlpha", 0.12, ...
    "SweptSurfaceAlpha", 0.10, ...
    "ShowSweptSurfaces", true, ...
    "ShowBoundaryCandidates", true, ...
    "ShowBoundaryConnections", true, ...
    "ShowVisibilityGraph", true, ...
    "SafetyMarginDeg", 0, ...
    "OriginalObstacleField", struct(), ...
    "CandidateClearance_deg", 0, ...
    "CornerAngleThreshold_deg", 15, ...
    "VisibilitySampleStep_deg", 0.10, ...
    "FigureVisible", string(get(groot, "DefaultFigureVisible")), ...
    "Title", "Azimuth/elevation/time obstacle space");
if nargin == 0
    spaceView = defaultOptions;
    return;
end
if nargin < 4 || isempty(optionOverrides)
    optionOverrides = struct();
end
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("visualizeAzElTimeSpace:InvalidOptions", ...
        "options must be a scalar struct.");
end
unknownFields = setdiff( ...
    fieldnames(optionOverrides), fieldnames(defaultOptions), "stable");
if ~isempty(unknownFields)
    warning("visualizeAzElTimeSpace:UnknownOptions", ...
        "Ignoring unknown option fields: %s.", ...
        strjoin(string(unknownFields), ", "));
    optionOverrides = rmfield(optionOverrides, unknownFields);
end
options = defaultOptions;
overrideFields = fieldnames(optionOverrides);
for fieldIndex = 1:numel(overrideFields)
    fieldName = overrideFields{fieldIndex};
    if ~isempty(optionOverrides.(fieldName))
        options.(fieldName) = optionOverrides.(fieldName);
    end
end
validateattributes(options.MaximumDisplayedSlicesPerObstacle, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(options.SliceFaceAlpha, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<=', 1});
validateattributes(options.SweptSurfaceAlpha, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0, '<=', 1});
validateattributes(options.ShowSweptSurfaces, ...
    {'logical', 'numeric'}, {'scalar'});
options.ShowSweptSurfaces = logical(options.ShowSweptSurfaces);
validateattributes(options.ShowBoundaryCandidates, ...
    {'logical', 'numeric'}, {'scalar'});
options.ShowBoundaryCandidates = logical(options.ShowBoundaryCandidates);
validateattributes(options.ShowBoundaryConnections, ...
    {'logical', 'numeric'}, {'scalar'});
options.ShowBoundaryConnections = logical(options.ShowBoundaryConnections);
validateattributes(options.ShowVisibilityGraph, ...
    {'logical', 'numeric'}, {'scalar'});
options.ShowVisibilityGraph = logical(options.ShowVisibilityGraph);
validateattributes(options.SafetyMarginDeg, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'nonnegative'});
validateattributes(options.CandidateClearance_deg, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'nonnegative'});
validateattributes(options.CornerAngleThreshold_deg, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive', '<=', 180});
validateattributes(options.VisibilitySampleStep_deg, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
options.FigureVisible = lower(string(options.FigureVisible));
if ~isscalar(options.FigureVisible) || ...
        ~any(options.FigureVisible == ["on" "off"])
    error("visualizeAzElTimeSpace:InvalidFigureVisible", ...
        "FigureVisible must be on or off.");
end
options.Title = string(options.Title);
if ~isscalar(options.Title)
    error("visualizeAzElTimeSpace:InvalidTitle", ...
        "Title must be scalar text.");
end

fieldIsPacked = isstruct(obstacleField) && isscalar(obstacleField) && ...
    isfield(obstacleField, "Format") && ...
    string(obstacleField.Format) == "AzElTimeObstacleField" && ...
    isfield(obstacleField, "Obstacles");
if ~fieldIsPacked
    error("visualizeAzElTimeSpace:InvalidObstacleField", ...
        "obstacleField must come from buildAzElTimeObstacleField.");
end
originalObstacleField = options.OriginalObstacleField;
hasOriginalObstacleField = isstruct(originalObstacleField) && ...
    isscalar(originalObstacleField) && ...
    isfield(originalObstacleField, "Format") && ...
    string(originalObstacleField.Format) == "AzElTimeObstacleField" && ...
    isfield(originalObstacleField, "Obstacles");
% New canonical fields carry their own original geometry and construction
% margin. Explicit display options remain supported for older callers.
[storedOriginalField, storedSafetyMargin_deg, hasStoredOriginal] = ...
    recoverOriginalAzElObstacleField(obstacleField);
if ~hasOriginalObstacleField && hasStoredOriginal
    originalObstacleField = storedOriginalField;
    hasOriginalObstacleField = true;
end
if options.SafetyMarginDeg == 0 && storedSafetyMargin_deg > 0
    options.SafetyMarginDeg = storedSafetyMargin_deg;
end
if ~hasOriginalObstacleField
    originalObstacleField = obstacleField;
end
if numel(originalObstacleField.Obstacles) ~= ...
        numel(obstacleField.Obstacles)
    error("visualizeAzElTimeSpace:OriginalFieldSizeMismatch", ...
        "OriginalObstacleField must contain the same obstacle count.");
end
startPoint = normalizedStatePoint(startState, "startState");
goalPoint = normalizedStatePoint(goalState, "goalState");
if goalPoint(3) <= startPoint(3)
    error("visualizeAzElTimeSpace:InvalidTime", ...
        "goalState.time_s must follow startState.time_s.");
end

%% Section 2: Create The Three-Dimensional Axes
figureHandle = figure( ...
    "Name", "Az/el/time obstacle-space explorer", ...
    "Color", "w", ...
    "Visible", options.FigureVisible);
axesHandle = axes(figureHandle);
hold(axesHandle, "on");
grid(axesHandle, "on");
box(axesHandle, "on");
xlabel(axesHandle, "Azimuth (deg)");
ylabel(axesHandle, "Elevation (deg)");
zlabel(axesHandle, "Time (s)");
displayTitle = options.Title;
if options.SafetyMarginDeg > 0
    displayTitle = displayTitle + sprintf( ...
        " | safety margin = %.2f deg", options.SafetyMarginDeg);
end
title(axesHandle, displayTitle);
colors = lines(max(1, obstacleField.ObstacleCount));
slicePatches = gobjects(0, 1);
sweptSurfaces = gobjects(0, 1);
originalBoundaryHandles = gobjects(0, 1);
inflatedBoundaryHandles = gobjects(0, 1);
safetyMarginDiagnostics = repmat(struct( ...
    "ObstacleIndex", 0, ...
    "SampleIndex", 0, ...
    "RawRegionIndex", 0, ...
    "InflatedRegionIndex", 0, ...
    "RawBounds_deg", nan(1, 4), ...
    "InflatedBounds_deg", nan(1, 4), ...
    "BoundsExpansion_deg", nan(1, 4), ...
    "RawArea_deg2", NaN, ...
    "InflatedArea_deg2", NaN, ...
    "AreaIncrease_deg2", NaN), 0, 1);
skippedSurfaceCount = 0;
candidatePoints = zeros(0, 3);
candidateTypes = strings(0, 1);
candidateObstacleIndex = zeros(0, 1);
candidateSampleIndex = zeros(0, 1);
candidateRegionIndex = zeros(0, 1);
candidateBoundaryGeometry = cell(0, 1);
candidateStartVisible = false(0, 1);
candidateGoalVisible = false(0, 1);
boundarySelections = repmat(emptyBoundarySelection(), 0, 1);
allAzimuth_deg = [startPoint(1); goalPoint(1)];
allElevation_deg = [startPoint(2); goalPoint(2)];
allTime_s = [startPoint(3); goalPoint(3)];
appliedSafetyMargin_deg = options.SafetyMarginDeg;

%% Section 3: Draw Polygon Slices & Their Swept Surfaces
for obstacleIndex = 1:obstacleField.ObstacleCount
    obstacle = obstacleField.Obstacles(obstacleIndex);
    availableSamples = find(all(isfinite(double(obstacle.BoundsDeg)), 2));
    if isempty(availableSamples)
        continue;
    end
    maximumSliceCount = options.MaximumDisplayedSlicesPerObstacle;
    if numel(availableSamples) > maximumSliceCount
        retainedPositions = unique(round(linspace( ...
            1, numel(availableSamples), maximumSliceCount)));
        displayedSamples = availableSamples(retainedPositions);
    else
        displayedSamples = availableSamples;
    end
    obstacleColor = colors(obstacleIndex, :);
    displayedRegions = cell(numel(displayedSamples), 1);
    for displayedIndex = 1:numel(displayedSamples)
        sampleIndex = displayedSamples(displayedIndex);
        sampleTime_s = double(obstacle.TimeSeconds(sampleIndex));
        rawRegions = unpackSliceRegions(obstacle, sampleIndex);
        originalObstacle = originalObstacleField.Obstacles(obstacleIndex);
        [~, originalSampleIndex] = min(abs( ...
            double(originalObstacle.TimeSeconds(:)) - sampleTime_s));
        originalRegions = unpackSliceRegions( ...
            originalObstacle, originalSampleIndex);
        originalSliceRegions = cell(0, 1);
        inflatedRegionCount = 0;
        for rawRegionIndex = 1:numel(rawRegions)
            rawRegion_deg = rawRegions{rawRegionIndex};
            originalRegion_deg = rawRegion_deg;
            if rawRegionIndex <= numel(originalRegions)
                originalRegion_deg = originalRegions{rawRegionIndex};
            end
            if options.SafetyMarginDeg > 0
                closedRawRegion_deg = [ ...
                    originalRegion_deg; originalRegion_deg(1, :)];
                rawLegendVisibility = "off";
                rawDisplayName = "";
                if isempty(originalBoundaryHandles)
                    rawLegendVisibility = "on";
                    rawDisplayName = "Original obstacle boundary";
                end
                originalBoundaryHandles(end + 1, 1) = plot3( ... %#ok<AGROW>
                    axesHandle, closedRawRegion_deg(:, 1), ...
                    closedRawRegion_deg(:, 2), repmat(sampleTime_s, ...
                    size(closedRawRegion_deg, 1), 1), "-", ...
                    "Color", [0.12 0.12 0.12], ...
                    "LineWidth", 1.6, ...
                    "DisplayName", rawDisplayName, ...
                    "HandleVisibility", rawLegendVisibility);
            end
            % obstacleField already contains the safety-inflated polygons.
            % Do not add a second query or display margin after packing.
            inflatedRegions = {rawRegion_deg};
            for localRegionIndex = 1:numel(inflatedRegions)
                inflatedRegionCount = inflatedRegionCount + 1;
                regionIndex = inflatedRegionCount;
                region_deg = inflatedRegions{localRegionIndex};
                originalSliceRegions{regionIndex, 1} = originalRegion_deg;
                inflatedEdgeColor = 0.65 .* obstacleColor;
                isFirstVisibleObstacle = isempty(slicePatches);
                legendVisibility = "off";
                displayName = "";
                if isFirstVisibleObstacle
                    legendVisibility = "on";
                    displayName = "Obstacle time slices";
                    if options.SafetyMarginDeg > 0
                        displayName = "Original obstacle slices";
                    end
                end
                slicePatches(end + 1, 1) = patch(axesHandle, ... %#ok<AGROW>
                    originalRegion_deg(:, 1), originalRegion_deg(:, 2), ...
                    repmat(sampleTime_s, ...
                    size(originalRegion_deg, 1), 1), ...
                    obstacleColor, ...
                    "FaceAlpha", options.SliceFaceAlpha, ...
                    "EdgeColor", inflatedEdgeColor, ...
                    "LineWidth", 0.7, ...
                    "DisplayName", displayName, ...
                    "HandleVisibility", legendVisibility);
                if options.SafetyMarginDeg > 0
                    closedInflatedRegion_deg = [region_deg; region_deg(1, :)];
                    inflatedLegendVisibility = "off";
                    inflatedDisplayName = "";
                    if isempty(inflatedBoundaryHandles)
                        inflatedLegendVisibility = "on";
                        inflatedDisplayName = "Inflated safety boundary";
                    end
                    inflatedBoundaryHandles(end + 1, 1) = plot3( ... %#ok<AGROW>
                        axesHandle, closedInflatedRegion_deg(:, 1), ...
                        closedInflatedRegion_deg(:, 2), ...
                        repmat(sampleTime_s, ...
                        size(closedInflatedRegion_deg, 1), 1), ":", ...
                        "Color", [0.92 0.18 0.08], ...
                        "LineWidth", 2.2, ...
                        "DisplayName", inflatedDisplayName, ...
                        "HandleVisibility", inflatedLegendVisibility);
                    rawBounds_deg = [min(originalRegion_deg(:, 1)), ...
                        max(originalRegion_deg(:, 1)), ...
                        min(originalRegion_deg(:, 2)), ...
                        max(originalRegion_deg(:, 2))];
                    inflatedBounds_deg = [min(region_deg(:, 1)), ...
                        max(region_deg(:, 1)), ...
                        min(region_deg(:, 2)), ...
                        max(region_deg(:, 2))];
                    rawArea_deg2 = abs(polyarea( ...
                        originalRegion_deg(:, 1), ...
                        originalRegion_deg(:, 2)));
                    inflatedArea_deg2 = abs(polyarea( ...
                        region_deg(:, 1), region_deg(:, 2)));
                    safetyMarginDiagnostics(end + 1, 1) = struct( ... %#ok<AGROW>
                        "ObstacleIndex", obstacleIndex, ...
                        "SampleIndex", sampleIndex, ...
                        "RawRegionIndex", rawRegionIndex, ...
                        "InflatedRegionIndex", localRegionIndex, ...
                        "RawBounds_deg", rawBounds_deg, ...
                        "InflatedBounds_deg", inflatedBounds_deg, ...
                        "BoundsExpansion_deg", inflatedBounds_deg - ...
                        rawBounds_deg, ...
                        "RawArea_deg2", rawArea_deg2, ...
                        "InflatedArea_deg2", inflatedArea_deg2, ...
                        "AreaIncrease_deg2", ...
                        inflatedArea_deg2 - rawArea_deg2);
                end
                allAzimuth_deg = [allAzimuth_deg; ...
                    region_deg(:, 1); originalRegion_deg(:, 1)]; %#ok<AGROW>
                allElevation_deg = [allElevation_deg; ...
                    region_deg(:, 2); originalRegion_deg(:, 2)]; %#ok<AGROW>
                allTime_s = [allTime_s; repmat( ...
                    sampleTime_s, size(region_deg, 1) + ...
                    size(originalRegion_deg, 1), 1)]; %#ok<AGROW>
                if options.ShowBoundaryCandidates
                    [regionCandidates_deg, regionCandidateTypes] = ...
                        boundaryCandidates(region_deg, ...
                        startPoint(1:2), goalPoint(1:2), options);
                    candidateCount = size(regionCandidates_deg, 1);
                    candidatePoints = [candidatePoints; ...
                        regionCandidates_deg, repmat( ...
                        sampleTime_s, candidateCount, 1)]; %#ok<AGROW>
                    candidateTypes = [candidateTypes; ...
                        regionCandidateTypes]; %#ok<AGROW>
                    candidateObstacleIndex = [candidateObstacleIndex; ...
                        repmat(obstacleIndex, candidateCount, 1)]; %#ok<AGROW>
                    candidateSampleIndex = [candidateSampleIndex; ...
                        repmat(sampleIndex, candidateCount, 1)]; %#ok<AGROW>
                    candidateRegionIndex = [candidateRegionIndex; ...
                        repmat(regionIndex, candidateCount, 1)]; %#ok<AGROW>
                    candidateBoundaryGeometry = [ ...
                        candidateBoundaryGeometry; ...
                        repmat({region_deg}, candidateCount, 1)]; %#ok<AGROW>
                    selection = selectBoundaryConnection( ...
                        obstacleField, region_deg, regionCandidates_deg, ...
                        regionCandidateTypes, startPoint(1:2), ...
                        goalPoint(1:2), sampleTime_s, options);
                    selection.ObstacleIndex = obstacleIndex;
                    selection.SampleIndex = sampleIndex;
                    selection.RegionIndex = regionIndex;
                    boundarySelections(end + 1, 1) = selection; %#ok<AGROW>
                    candidateStartVisible = [candidateStartVisible; ...
                        selection.StartVisibleMask]; %#ok<AGROW>
                    candidateGoalVisible = [candidateGoalVisible; ...
                        selection.GoalVisibleMask]; %#ok<AGROW>
                end
            end
        end
        displayedRegions{displayedIndex} = originalSliceRegions;
    end

    if ~options.ShowSweptSurfaces
        continue;
    end
    for displayedIndex = 1:numel(displayedSamples) - 1
        firstRegions = displayedRegions{displayedIndex};
        secondRegions = displayedRegions{displayedIndex + 1};
        if numel(firstRegions) ~= numel(secondRegions)
            skippedSurfaceCount = skippedSurfaceCount + 1;
            continue;
        end
        firstTime_s = double(obstacle.TimeSeconds( ...
            displayedSamples(displayedIndex)));
        secondTime_s = double(obstacle.TimeSeconds( ...
            displayedSamples(displayedIndex + 1)));
        for regionIndex = 1:numel(firstRegions)
            firstRegion_deg = firstRegions{regionIndex};
            secondRegion_deg = secondRegions{regionIndex};
            if size(firstRegion_deg, 1) ~= size(secondRegion_deg, 1)
                skippedSurfaceCount = skippedSurfaceCount + 1;
                continue;
            end
            firstRegion_deg(end + 1, :) = firstRegion_deg(1, :);
            secondRegion_deg(end + 1, :) = secondRegion_deg(1, :);
            isFirstSweptSurface = isempty(sweptSurfaces);
            legendVisibility = "off";
            displayName = "";
            if isFirstSweptSurface
                legendVisibility = "on";
                displayName = "Swept obstacle surfaces";
            end
            sweptSurfaces(end + 1, 1) = surface(axesHandle, ...
                "XData", [firstRegion_deg(:, 1), ...
                secondRegion_deg(:, 1)], ...
                "YData", [firstRegion_deg(:, 2), ...
                secondRegion_deg(:, 2)], ...
                "ZData", [repmat(firstTime_s, ...
                size(firstRegion_deg, 1), 1), ...
                repmat(secondTime_s, ...
                size(secondRegion_deg, 1), 1)], ...
                "FaceColor", obstacleColor, ...
                "FaceAlpha", options.SweptSurfaceAlpha, ...
                "EdgeColor", "none", ...
                "DisplayName", displayName, ...
                "HandleVisibility", legendVisibility);
        end
    end
end

% Keep every per-slice result for inspection and also publish one stable
% overall winner. Edge count is primary, then boundary distance, slice
% time, and source indices make symmetric ties reproducible.
selectedBoundaryConnection = emptyBoundarySelection();
successfulBoundaryIndex = find([boundarySelections.Success]);
if ~isempty(successfulBoundaryIndex)
    successfulBoundary = boundarySelections(successfulBoundaryIndex);
    boundaryRanking = [ ...
        reshape([successfulBoundary.BoundaryEdgeCount], [], 1), ...
        reshape([successfulBoundary.BoundaryDistance_deg], [], 1), ...
        reshape([successfulBoundary.Time_s], [], 1), ...
        reshape([successfulBoundary.ObstacleIndex], [], 1), ...
        reshape([successfulBoundary.SampleIndex], [], 1), ...
        reshape([successfulBoundary.RegionIndex], [], 1)];
    [~, rankedBoundaryIndex] = sortrows(boundaryRanking, 1:6);
    selectedBoundaryConnection = successfulBoundary( ...
        rankedBoundaryIndex(1));
end

visibilityGraphs = buildSnapshotVisibilityGraphs( ...
    obstacleField, candidatePoints, candidateTypes, ...
    candidateObstacleIndex, candidateSampleIndex, ...
    candidateRegionIndex, candidateBoundaryGeometry, ...
    startPoint(1:2), goalPoint(1:2), options);
selectedVisibilityPath = emptyVisibilityGraph();
successfulGraphIndex = find([visibilityGraphs.Success]);
if ~isempty(successfulGraphIndex)
    successfulGraph = visibilityGraphs(successfulGraphIndex);
    graphRanking = [ ...
        reshape([successfulGraph.PathCost_deg], [], 1), ...
        reshape([successfulGraph.PathEdgeCount], [], 1), ...
        reshape([successfulGraph.Time_s], [], 1)];
    [~, rankedGraphIndex] = sortrows(graphRanking, 1:3);
    selectedVisibilityPath = successfulGraph(rankedGraphIndex(1));
end

%% Section 4: Draw Candidate Nodes & The Direct Vector
candidateHandles = struct( ...
    "StartTangents", gobjects(0, 1), ...
    "GoalTangents", gobjects(0, 1), ...
    "Corners", gobjects(0, 1));
isStartTangent = candidateTypes == "startTangent";
isGoalTangent = candidateTypes == "goalTangent";
isCorner = candidateTypes == "corner";
if any(isStartTangent)
    candidateHandles.StartTangents = plot3(axesHandle, ...
        candidatePoints(isStartTangent, 1), ...
        candidatePoints(isStartTangent, 2), ...
        candidatePoints(isStartTangent, 3), "^", ...
        "LineStyle", "none", ...
        "MarkerSize", 7, ...
        "MarkerFaceColor", [0.05 0.72 0.86], ...
        "MarkerEdgeColor", "k", ...
        "DisplayName", "Start-side tangencies");
end
if any(isGoalTangent)
    candidateHandles.GoalTangents = plot3(axesHandle, ...
        candidatePoints(isGoalTangent, 1), ...
        candidatePoints(isGoalTangent, 2), ...
        candidatePoints(isGoalTangent, 3), "v", ...
        "LineStyle", "none", ...
        "MarkerSize", 7, ...
        "MarkerFaceColor", [0.88 0.24 0.72], ...
        "MarkerEdgeColor", "k", ...
        "DisplayName", "Goal-side tangencies");
end
if any(isCorner)
    candidateHandles.Corners = plot3(axesHandle, ...
        candidatePoints(isCorner, 1), ...
        candidatePoints(isCorner, 2), ...
        candidatePoints(isCorner, 3), "s", ...
        "LineStyle", "none", ...
        "MarkerSize", 6, ...
        "MarkerFaceColor", [0.98 0.72 0.08], ...
        "MarkerEdgeColor", "k", ...
        "DisplayName", "Polygon corner candidates");
end
visibilityHandles = struct( ...
    "StartVisible", gobjects(0, 1), ...
    "GoalVisible", gobjects(0, 1));
if any(candidateStartVisible)
    visibilityHandles.StartVisible = plot3(axesHandle, ...
        candidatePoints(candidateStartVisible, 1), ...
        candidatePoints(candidateStartVisible, 2), ...
        candidatePoints(candidateStartVisible, 3), "o", ...
        "LineStyle", "none", ...
        "MarkerSize", 10, ...
        "MarkerFaceColor", "none", ...
        "MarkerEdgeColor", [0.08 0.58 0.18], ...
        "LineWidth", 1.5, ...
        "DisplayName", "Visible from start");
end
if any(candidateGoalVisible)
    visibilityHandles.GoalVisible = plot3(axesHandle, ...
        candidatePoints(candidateGoalVisible, 1), ...
        candidatePoints(candidateGoalVisible, 2), ...
        candidatePoints(candidateGoalVisible, 3), "d", ...
        "LineStyle", "none", ...
        "MarkerSize", 10, ...
        "MarkerFaceColor", "none", ...
        "MarkerEdgeColor", [0.78 0.08 0.08], ...
        "LineWidth", 1.5, ...
        "DisplayName", "Visible from goal");
end
connectionHandles = struct( ...
    "StartLinks", gobjects(0, 1), ...
    "BoundaryRoutes", gobjects(0, 1), ...
    "GoalLinks", gobjects(0, 1));
visibilityGraphHandles = drawVisibilityGraphs(axesHandle, ...
    visibilityGraphs, options);
directDelta = goalPoint - startPoint;
directLine = plot3(axesHandle, ...
    [startPoint(1) goalPoint(1)], ...
    [startPoint(2) goalPoint(2)], ...
    [startPoint(3) goalPoint(3)], "--", ...
    "Color", [0.12 0.30 0.82], ...
    "LineWidth", 2.0, ...
    "DisplayName", "Direct start-to-goal line");
directVector = quiver3(axesHandle, ...
    startPoint(1), startPoint(2), startPoint(3), ...
    directDelta(1), directDelta(2), directDelta(3), 0, ...
    "Color", [0.02 0.16 0.55], ...
    "LineWidth", 1.8, ...
    "MaxHeadSize", 0.12, ...
    "HandleVisibility", "off");
startHandle = plot3(axesHandle, ...
    startPoint(1), startPoint(2), startPoint(3), "o", ...
    "MarkerSize", 9, ...
    "MarkerFaceColor", [0.15 0.68 0.30], ...
    "MarkerEdgeColor", "k", ...
    "DisplayName", "Start");
goalHandle = plot3(axesHandle, ...
    goalPoint(1), goalPoint(2), goalPoint(3), "d", ...
    "MarkerSize", 9, ...
    "MarkerFaceColor", [0.84 0.18 0.18], ...
    "MarkerEdgeColor", "k", ...
    "DisplayName", "Goal");

%% Section 5: Apply One Equal Three-Dimensional Scale
if ~isempty(candidatePoints)
    allAzimuth_deg = [allAzimuth_deg; candidatePoints(:, 1)];
    allElevation_deg = [allElevation_deg; candidatePoints(:, 2)];
    allTime_s = [allTime_s; candidatePoints(:, 3)];
end
equalLimits = equalCubeLimits( ...
    allAzimuth_deg, allElevation_deg, allTime_s);
xlim(axesHandle, equalLimits(1, :));
ylim(axesHandle, equalLimits(2, :));
zlim(axesHandle, equalLimits(3, :));
goalTimeLine = plot3(axesHandle, ...
    [goalPoint(1) goalPoint(1)], ...
    [goalPoint(2) goalPoint(2)], ...
    equalLimits(3, :), ":", ...
    "Color", [0.72 0.10 0.62], ...
    "LineWidth", 2.0, ...
    "DisplayName", "Goal time line");
daspect(axesHandle, [1 1 1]);
pbaspect(axesHandle, [1 1 1]);
camproj(axesHandle, "orthographic");
view(axesHandle, 38, 25);
axis(axesHandle, "vis3d");
legend(axesHandle, "Location", "best");

spaceView = struct( ...
    "ObstacleField", obstacleField, ...
    "OriginalObstacleField", originalObstacleField, ...
    "StartPointAzElTime", startPoint, ...
    "GoalPointAzElTime", goalPoint, ...
