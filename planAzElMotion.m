function timedSlopePath = retimePolylineMotion( ...
        pathPosition_deg, initialState, goalState, limits, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = retimePolylineMotion()
%   timedSlopePath = retimePolylineMotion( ...
%       pathPosition_deg, initialState, goalState, limits)
%   timedSlopePath = retimePolylineMotion( ...
%       pathPosition_deg, initialState, goalState, limits, options)
%**************************************************************************
% PURPOSE
%   - Retime an azimuth/elevation visibility polyline subject to independent
%     azimuth and elevation velocity and acceleration limits.
%   - Follow every straight path segment exactly and stop at geometric
%     corners, avoiding any corner rounding that could enter an obstacle.
%   - Use a minimum-time triangular or trapezoidal scalar speed profile on
%     each segment, including compatible nonzero endpoint velocities.
%**************************************************************************
% INPUTS
%   - pathPosition_deg (N-by-2 finite numeric matrix, N >= 2)
%       Ordered [azimuth elevation] visibility-path waypoints.
%   - initialState, goalState (scalar structs)
%       Required fields: time_s, position_deg, and velocity_deg_s.
%       acceleration_deg_s2 is optional and defaults to [0 0]. This
%       retimer currently requires zero endpoint acceleration.
%   - limits (scalar struct)
%       .maxVelocity_deg_s      positive scalar or 1-by-2 vector
%       .maxAcceleration_deg_s2 positive scalar or 1-by-2 vector. When
%           omitted, acceleration is unconstrained for compatibility with
%           older velocity-only calls.
%   - options (scalar struct, optional)
%       .GoalTimeMode      "earliestArrival" (default) or "fixedArrival"
%       .SampleTime_s      maximum nominal output sample spacing (0.05)
%       .PositionTolerance_deg endpoint/duplicate tolerance (1e-8)
%       .KinematicTolerance     numeric constraint tolerance (1e-9)
%**************************************************************************
% OUTPUTS
%   - timedSlopePath (scalar struct)
%       Success, Message, time_s, position_deg, velocity_deg_s,
%       acceleration_deg_s2, WaypointTime_s, SegmentProfiles, Limits,
%       ConstraintDiagnostics, and GoalLineInterceptTime_s.
%**************************************************************************
% UNITS
%   - Position is degrees, time is seconds, velocity is deg/s, and
%     acceleration is deg/s^2.

%% Section 1: Defaults & Input Validation
defaultOptions = struct( ...
    "GoalTimeMode", "earliestArrival", ...
    "SampleTime_s", 0.05, ...
    "PositionTolerance_deg", 1e-8, ...
    "KinematicTolerance", 1e-9);
if nargin == 0
    timedSlopePath = defaultOptions;
    return;
end
if nargin < 5 || isempty(optionOverrides)
    optionOverrides = struct();
end
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("retimePolylineMotion:InvalidOptions", ...
        "Options must be a scalar struct.");
end
options = defaultOptions;
optionNames = string(fieldnames(optionOverrides));
knownOptionNames = string(fieldnames(defaultOptions));
unknownOptionNames = setdiff(optionNames, knownOptionNames);
if ~isempty(unknownOptionNames)
    warning("retimePolylineMotion:UnknownOptions", ...
        "Ignoring unknown option(s): %s.", ...
        strjoin(unknownOptionNames, ", "));
end
for optionIndex = 1:numel(optionNames)
    optionName = optionNames(optionIndex);
    if isfield(defaultOptions, optionName)
        options.(optionName) = optionOverrides.(optionName);
    end
end
options.GoalTimeMode = lower(string(options.GoalTimeMode));
if ~isscalar(options.GoalTimeMode) || ~ismember( ...
        options.GoalTimeMode, ["earliestarrival", "fixedarrival"])
    error("retimePolylineMotion:InvalidGoalTimeMode", ...
        "GoalTimeMode must be earliestArrival or fixedArrival.");
end
validateattributes(options.SampleTime_s, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.PositionTolerance_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'nonnegative'});
validateattributes(options.KinematicTolerance, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'nonnegative'});

validateattributes(pathPosition_deg, {'numeric'}, ...
    {'real', 'finite', '2d', 'ncols', 2});
pathPosition_deg = double(pathPosition_deg);
if size(pathPosition_deg, 1) < 2
    error("retimePolylineMotion:InvalidPath", ...
        "pathPosition_deg must contain at least two points.");
end
initialState = normalizedPolylineState(initialState, "initialState");
goalState = normalizedPolylineState(goalState, "goalState");
maxVelocity_deg_s = normalizedPolylineAxisLimit( ...
    limits, "maxVelocity_deg_s", false);
maxAcceleration_deg_s2 = normalizedPolylineAxisLimit( ...
    limits, "maxAcceleration_deg_s2", true);
resolvedLimits = struct( ...
    "maxVelocity_deg_s", maxVelocity_deg_s, ...
    "maxAcceleration_deg_s2", maxAcceleration_deg_s2);

positionTolerance_deg = options.PositionTolerance_deg;
if norm(pathPosition_deg(1, :) - initialState.position_deg) > ...
        positionTolerance_deg
    error("retimePolylineMotion:InitialPositionMismatch", ...
        "The path must start at initialState.position_deg.");
end
if norm(pathPosition_deg(end, :) - goalState.position_deg) > ...
        positionTolerance_deg
    error("retimePolylineMotion:GoalPositionMismatch", ...
        "The path must end at goalState.position_deg.");
end
if goalState.time_s <= initialState.time_s
    error("retimePolylineMotion:InvalidTimeWindow", ...
        "goalState.time_s must be later than initialState.time_s.");
end
if any(abs(initialState.velocity_deg_s) > ...
        maxVelocity_deg_s + options.KinematicTolerance) || ...
        any(abs(goalState.velocity_deg_s) > ...
        maxVelocity_deg_s + options.KinematicTolerance)
    error("retimePolylineMotion:EndpointVelocityLimit", ...
        "An endpoint velocity exceeds maxVelocity_deg_s.");
end
finiteAccelerationAxis = isfinite(maxAcceleration_deg_s2);
if any(abs(initialState.acceleration_deg_s2(finiteAccelerationAxis)) > ...
        maxAcceleration_deg_s2(finiteAccelerationAxis) + ...
        options.KinematicTolerance) || ...
        any(abs(goalState.acceleration_deg_s2(finiteAccelerationAxis)) > ...
        maxAcceleration_deg_s2(finiteAccelerationAxis) + ...
        options.KinematicTolerance)
    error("retimePolylineMotion:EndpointAccelerationLimit", ...
        "An endpoint acceleration exceeds maxAcceleration_deg_s2.");
end
if norm(initialState.acceleration_deg_s2) > ...
        options.KinematicTolerance || ...
        norm(goalState.acceleration_deg_s2) > options.KinematicTolerance
    error("retimePolylineMotion:NonzeroEndpointAcceleration", ...
        "This polyline retimer requires zero endpoint acceleration; " + ...
        "jerk-constrained boundary acceleration is not yet supported.");
end

% Remove only zero-length edges. Real corners are deliberately retained
% because stopping there is what makes the acceleration bound compatible
% with exact obstacle-avoiding polyline geometry.
pathStep_deg = diff(pathPosition_deg, 1, 1);
keepPoint = [true; hypot(pathStep_deg(:, 1), pathStep_deg(:, 2)) > ...
    positionTolerance_deg];
pathPosition_deg = pathPosition_deg(keepPoint, :);
if size(pathPosition_deg, 1) < 2
    error("retimePolylineMotion:ZeroLengthPath", ...
        "The path has no nonzero-length segment.");
end

%% Section 2: Resolve Directional Segment Limits & Minimum Times
segmentDelta_deg = diff(pathPosition_deg, 1, 1);
segmentLength_deg = hypot(segmentDelta_deg(:, 1), segmentDelta_deg(:, 2));
segmentDirection = segmentDelta_deg ./ segmentLength_deg;
segmentCount = numel(segmentLength_deg);
segmentTemplate = struct( ...
    "StartPosition_deg", zeros(1, 2), ...
    "EndPosition_deg", zeros(1, 2), ...
    "Direction", zeros(1, 2), ...
    "Length_deg", 0, ...
    "StartSpeed_deg_s", 0, ...
    "EndSpeed_deg_s", 0, ...
    "MaxSpeed_deg_s", 0, ...
    "MaxAcceleration_deg_s2", 0, ...
    "PeakSpeed_deg_s", 0, ...
    "AccelerationTime_s", 0, ...
    "CruiseTime_s", 0, ...
    "DecelerationTime_s", 0, ...
    "Duration_s", 0, ...
    "StartTime_s", NaN, ...
    "EndTime_s", NaN, ...
    "PeakVelocityByAxis_deg_s", zeros(1, 2), ...
    "PeakAccelerationByAxis_deg_s2", zeros(1, 2));
segmentProfiles = repmat(segmentTemplate, segmentCount, 1);

initialSpeed_deg_s = polylineBoundaryScalarSpeed( ...
    initialState.velocity_deg_s, segmentDirection(1, :), ...
    "initialState.velocity_deg_s", options.KinematicTolerance);
goalSpeed_deg_s = polylineBoundaryScalarSpeed( ...
    goalState.velocity_deg_s, segmentDirection(end, :), ...
    "goalState.velocity_deg_s", options.KinematicTolerance);

for segmentIndex = 1:segmentCount
    direction = segmentDirection(segmentIndex, :);
    maxSegmentSpeed_deg_s = polylineDirectionalLimit( ...
        maxVelocity_deg_s, direction);
    maxSegmentAcceleration_deg_s2 = polylineDirectionalLimit( ...
        maxAcceleration_deg_s2, direction);
    startSpeed_deg_s = 0;
    endSpeed_deg_s = 0;
    if segmentIndex == 1
        startSpeed_deg_s = initialSpeed_deg_s;
    end
    if segmentIndex == segmentCount
        endSpeed_deg_s = goalSpeed_deg_s;
    end
    [profile, feasible, failureMessage] = polylineMinimumTimeProfile( ...
        segmentLength_deg(segmentIndex), startSpeed_deg_s, ...
        endSpeed_deg_s, maxSegmentSpeed_deg_s, ...
        maxSegmentAcceleration_deg_s2, options.KinematicTolerance);
    if ~feasible
        timedSlopePath = failedPolylinePath( ...
            "Segment " + segmentIndex + ": " + failureMessage, ...
            resolvedLimits, options);
        return;
    end
    segmentProfiles(segmentIndex).StartPosition_deg = ...
        pathPosition_deg(segmentIndex, :);
    segmentProfiles(segmentIndex).EndPosition_deg = ...
        pathPosition_deg(segmentIndex + 1, :);
    segmentProfiles(segmentIndex).Direction = direction;
    segmentProfiles(segmentIndex).Length_deg = ...
        segmentLength_deg(segmentIndex);
    segmentProfiles(segmentIndex).StartSpeed_deg_s = startSpeed_deg_s;
    segmentProfiles(segmentIndex).EndSpeed_deg_s = endSpeed_deg_s;
    segmentProfiles(segmentIndex).MaxSpeed_deg_s = ...
        maxSegmentSpeed_deg_s;
    segmentProfiles(segmentIndex).MaxAcceleration_deg_s2 = ...
        maxSegmentAcceleration_deg_s2;
    segmentProfiles(segmentIndex).PeakSpeed_deg_s = profile.PeakSpeed_deg_s;
    segmentProfiles(segmentIndex).AccelerationTime_s = ...
        profile.AccelerationTime_s;
    segmentProfiles(segmentIndex).CruiseTime_s = profile.CruiseTime_s;
    segmentProfiles(segmentIndex).DecelerationTime_s = ...
        profile.DecelerationTime_s;
    segmentProfiles(segmentIndex).Duration_s = profile.Duration_s;
    segmentProfiles(segmentIndex).PeakVelocityByAxis_deg_s = ...
        abs(direction) * profile.PeakSpeed_deg_s;
    if isfinite(maxSegmentAcceleration_deg_s2)
        segmentProfiles(segmentIndex).PeakAccelerationByAxis_deg_s2 = ...
            abs(direction) * maxSegmentAcceleration_deg_s2;
    end
end

minimumMotionDuration_s = sum([segmentProfiles.Duration_s]);
minimumArrivalTime_s = initialState.time_s + minimumMotionDuration_s;
timeTolerance_s = options.KinematicTolerance * max( ...
    1, abs(goalState.time_s));
if minimumArrivalTime_s > goalState.time_s + timeTolerance_s
    timedSlopePath = failedPolylinePath(sprintf( ...
        "Earliest feasible arrival %.9g s exceeds goal time %.9g s.", ...
        minimumArrivalTime_s, goalState.time_s), resolvedLimits, options);
    return;
end

waitDuration_s = 0;
if options.GoalTimeMode == "fixedarrival"
    waitDuration_s = max(0, goalState.time_s - minimumArrivalTime_s);
    if waitDuration_s > timeTolerance_s && ...
            norm(initialState.velocity_deg_s) > options.KinematicTolerance
        timedSlopePath = failedPolylinePath( ...
            "fixedArrival needs a start hold, but the initial velocity " + ...
            "is nonzero.", resolvedLimits, options);
        return;
    end
end
motionStartTime_s = initialState.time_s + waitDuration_s;
segmentStartTime_s = motionStartTime_s + ...
    [0, cumsum([segmentProfiles(1:end - 1).Duration_s])];
for segmentIndex = 1:segmentCount
    segmentProfiles(segmentIndex).StartTime_s = ...
        segmentStartTime_s(segmentIndex);
    segmentProfiles(segmentIndex).EndTime_s = ...
        segmentStartTime_s(segmentIndex) + ...
        segmentProfiles(segmentIndex).Duration_s;
end

%% Section 3: Sample The Analytic Profiles
time_s = zeros(0, 1);
position_deg = zeros(0, 2);
velocity_deg_s = zeros(0, 2);
acceleration_deg_s2 = zeros(0, 2);
if waitDuration_s > timeTolerance_s
    waitLocalTime_s = polylineRegularAndEventTimes( ...
        waitDuration_s, options.SampleTime_s, []);
    time_s = initialState.time_s + waitLocalTime_s;
    position_deg = repmat(initialState.position_deg, numel(time_s), 1);
    velocity_deg_s = zeros(numel(time_s), 2);
    acceleration_deg_s2 = zeros(numel(time_s), 2);
end

for segmentIndex = 1:segmentCount
    profile = segmentProfiles(segmentIndex);
    candidateEventTime_s = [ ...
        profile.AccelerationTime_s; ...
        profile.AccelerationTime_s + profile.CruiseTime_s; ...
        profile.AccelerationTime_s / 2; ...
        profile.AccelerationTime_s + profile.CruiseTime_s / 2; ...
        profile.AccelerationTime_s + profile.CruiseTime_s + ...
            profile.DecelerationTime_s / 2];
    activeEvent = [true; true; ...
        profile.AccelerationTime_s > 0; ...
        profile.CruiseTime_s > 0; ...
        profile.DecelerationTime_s > 0];
    eventTime_s = candidateEventTime_s(activeEvent);
    localTime_s = polylineRegularAndEventTimes( ...
        profile.Duration_s, options.SampleTime_s, eventTime_s);
    [scalarPosition_deg, scalarVelocity_deg_s, ...
        scalarAcceleration_deg_s2] = samplePolylineMinimumTimeProfile( ...
        localTime_s, profile, options.KinematicTolerance);
    segmentPosition_deg = profile.StartPosition_deg + ...
        scalarPosition_deg .* profile.Direction;
    segmentVelocity_deg_s = ...
        scalarVelocity_deg_s .* profile.Direction;
    segmentAcceleration_deg_s2 = ...
        scalarAcceleration_deg_s2 .* profile.Direction;
    segmentTime_s = profile.StartTime_s + localTime_s;

    % Define acceleration as zero at switch instants and waypoints. The
    % one-sided values remain bounded; jerk is intentionally unconstrained.
    switchTime_s = [0; profile.AccelerationTime_s; ...
        profile.AccelerationTime_s + profile.CruiseTime_s; ...
        profile.Duration_s];
    for switchIndex = 1:numel(switchTime_s)
        atSwitch = abs(localTime_s - switchTime_s(switchIndex)) <= ...
            timeTolerance_s;
        segmentAcceleration_deg_s2(atSwitch, :) = 0;
    end
    segmentPosition_deg(1, :) = profile.StartPosition_deg;
    segmentPosition_deg(end, :) = profile.EndPosition_deg;
    segmentVelocity_deg_s(1, :) = ...
        profile.StartSpeed_deg_s * profile.Direction;
    segmentVelocity_deg_s(end, :) = ...
        profile.EndSpeed_deg_s * profile.Direction;

    if ~isempty(time_s) && abs(segmentTime_s(1) - time_s(end)) <= ...
            timeTolerance_s
        segmentTime_s(1) = [];
        segmentPosition_deg(1, :) = [];
        segmentVelocity_deg_s(1, :) = [];
        segmentAcceleration_deg_s2(1, :) = [];
    end
    time_s = [time_s; segmentTime_s]; %#ok<AGROW>
    position_deg = [position_deg; segmentPosition_deg]; %#ok<AGROW>
    velocity_deg_s = [velocity_deg_s; segmentVelocity_deg_s]; %#ok<AGROW>
    acceleration_deg_s2 = [ ...
        acceleration_deg_s2; segmentAcceleration_deg_s2]; %#ok<AGROW>
end

position_deg(1, :) = initialState.position_deg;
velocity_deg_s(1, :) = initialState.velocity_deg_s;
acceleration_deg_s2(1, :) = initialState.acceleration_deg_s2;
position_deg(end, :) = goalState.position_deg;
velocity_deg_s(end, :) = goalState.velocity_deg_s;
acceleration_deg_s2(end, :) = goalState.acceleration_deg_s2;

peakVelocity_deg_s = max(abs(velocity_deg_s), [], 1);
peakAcceleration_deg_s2 = max(abs(acceleration_deg_s2), [], 1);
velocityMargin_deg_s = maxVelocity_deg_s - peakVelocity_deg_s;
accelerationMargin_deg_s2 = ...
    maxAcceleration_deg_s2 - peakAcceleration_deg_s2;
constraintsSatisfied = all(velocityMargin_deg_s >= ...
    -options.KinematicTolerance) && all( ...
    accelerationMargin_deg_s2 >= -options.KinematicTolerance);
constraintDiagnostics = struct( ...
    "PeakVelocity_deg_s", peakVelocity_deg_s, ...
    "PeakAcceleration_deg_s2", peakAcceleration_deg_s2, ...
    "VelocityMargin_deg_s", velocityMargin_deg_s, ...
    "AccelerationMargin_deg_s2", accelerationMargin_deg_s2, ...
    "VelocitySatisfied", all(velocityMargin_deg_s >= ...
        -options.KinematicTolerance), ...
    "AccelerationSatisfied", all(accelerationMargin_deg_s2 >= ...
        -options.KinematicTolerance), ...
    "Satisfied", constraintsSatisfied);
waypointTime_s = [motionStartTime_s; ...
    motionStartTime_s + cumsum([segmentProfiles.Duration_s]).'];
goalLineInterceptTime_s = time_s(end);
timedSlopePath = struct( ...
    "Success", constraintsSatisfied, ...
    "Message", "Acceleration- and velocity-constrained retiming succeeded.", ...
    "time_s", time_s, ...
    "position_deg", position_deg, ...
    "velocity_deg_s", velocity_deg_s, ...
    "acceleration_deg_s2", acceleration_deg_s2, ...
    "PathPosition_deg", pathPosition_deg, ...
    "WaypointTime_s", waypointTime_s, ...
    "MotionStartTime_s", motionStartTime_s, ...
    "WaitDuration_s", waitDuration_s, ...
    "MinimumMotionDuration_s", minimumMotionDuration_s, ...
    "GoalLineInterceptTime_s", goalLineInterceptTime_s, ...
    "SegmentProfiles", segmentProfiles, ...
    "Limits", resolvedLimits, ...
    "Options", options, ...
    "ConstraintDiagnostics", constraintDiagnostics);
if ~constraintsSatisfied
    timedSlopePath.Message = ...
        "Internal constraint verification failed after sampling.";
end
end

