function options = resolveOptions(defaults, overrides)
% PURPOSE
%   - Merge partial overrides, warn once, normalize, and validate.
if ~isstruct(overrides) || ~isscalar(overrides)
    error("planAzElMotion:InvalidOptions", ...
        "optionOverrides must be a scalar struct.");
end
movedMarginNames = intersect(fieldnames(overrides), ...
    {'SafetyMarginDeg', 'RoundingClearance_deg'}, "stable");
if ~isempty(movedMarginNames)
    error("planAzElMotion:SafetyMarginMoved", ...
        "Safety margins belong to obstacle data. Remove %s and use " + ...
        "makeAzElObstacleData.", ...
        strjoin(string(movedMarginNames), ", "));
end
[options, unknown] = azElInternal.resolveOptions(defaults, overrides);
if ~isempty(unknown)
    warning("planAzElMotion:UnknownOptions", ...
        "Ignored unknown option fields: %s. No behavior changed.", ...
        strjoin(unknown, ", "));
end
options.GoalTimeMode = lower(string(options.GoalTimeMode));
if ~isscalar(options.GoalTimeMode) || ~any( ...
        options.GoalTimeMode == ["earliestarrival" "fixedarrival"])
    error("planAzElMotion:InvalidGoalTimeMode", ...
        "GoalTimeMode must be earliestArrival or fixedArrival.");
end
options.RpAgentFile = string(options.RpAgentFile);
if ~isscalar(options.RpAgentFile) || strlength(options.RpAgentFile) == 0
    error("planAzElMotion:InvalidRpAgentFile", ...
        "RpAgentFile must be nonempty scalar text.");
end
validateattributes(options.RpTurnRadius_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
options.UseParallel = azElInternal.normalizeParallelMode( ...
    options.UseParallel, "planAzElMotion:InvalidUseParallel");
logicalNames = ["AllowAzimuthWrapping" "DetectSnapshotEvents" ...
    "UseSpaceTimeVisibilityGraph" "AllowSippWaiting" "Verbose"];
for optionIndex = 1:numel(logicalNames)
    name = logicalNames(optionIndex);
    options.(name) = azElInternal.normalizeLogicalScalar( ...
        options.(name), name, "planAzElMotion:InvalidLogicalOption");
end
positiveNames = ["SampleTime_s" "VisibilitySampleStep_deg" ...
    "SafeIntervalTimeTolerance_s" "MaximumSippWallTime_s" ...
    "SippMaximumEdgeLength_deg" ...
    "RlDurationTolerance_s" "KinematicValidationTolerance" ...
    "MaximumPlanningTime_s" ...
    "MaximumSippPlanningFraction" ...
    "MinimumRlPolicySeedTime_s"];
for optionIndex = 1:numel(positiveNames)
    validateattributes(options.(positiveNames(optionIndex)), ...
        {'numeric'}, {'real', 'scalar', 'positive'});
end
nonnegativeNames = ["SnapshotCountChangeThreshold" ...
    "SnapshotEdgeRotationThreshold_deg" ...
    "SnapshotBoundaryMotionThreshold_deg" ...
    "VisibilityGraphCostChangeThreshold" ...
    "SpaceTimeNodeMergeTolerance_deg" ...
    "ArrivalTimeTieTolerance_s"];
for optionIndex = 1:numel(nonnegativeNames)
    validateattributes(options.(nonnegativeNames(optionIndex)), ...
        {'numeric'}, {'real', 'finite', 'scalar', 'nonnegative'});
end
if options.MaximumSippPlanningFraction > 1
    error("planAzElMotion:InvalidSippPlanningFraction", ...
        "MaximumSippPlanningFraction must be in the interval (0, 1].");
end
integerNames = ["MaximumVisibilitySnapshotsPerObstacle" ...
    "SnapshotProbeEdgeCount" "MaximumRlPolicySeeds" ...
    "SpaceTimeLayerCount" "MaximumSpaceTimeCandidateCount" ...
    "MaximumSippCandidates" "MaximumSippExpansions" ...
    "SippKNearestNeighbors" "RlDurationTrialCount"];
for optionIndex = 1:numel(integerNames)
    name = integerNames(optionIndex);
    validateattributes(options.(name), {'numeric'}, ...
        {'real', 'scalar', 'positive'});
    if isfinite(options.(name)) && fix(options.(name)) ~= options.(name)
        error("planAzElMotion:InvalidIntegerOption", ...
            "%s must be a positive integer or Inf.", name);
    end
end
if options.SpaceTimeLayerCount < 3
    error("planAzElMotion:InvalidSpaceTimeLayerCount", ...
        "SpaceTimeLayerCount must be at least 3.");
end
nonnegativeIntegerNames = ["CollisionTimePaddingSamples" ...
    "MaximumSafeIntervalRefinements" ...
    "MaximumSpaceTimeDiagnosticEdgeCount"];
for optionIndex = 1:numel(nonnegativeIntegerNames)
    validateattributes(options.(nonnegativeIntegerNames(optionIndex)), ...
        {'numeric'}, ...
        {'real', 'finite', 'scalar', 'integer', 'nonnegative'});
end
validateattributes(options.AzimuthInterval_deg, {'numeric'}, ...
    {'real', 'finite', 'vector', 'numel', 2, 'increasing'});
validateattributes(options.ElevationInterval_deg, {'numeric'}, ...
    {'real', 'finite', 'vector', 'numel', 2, 'increasing'});
validateattributes(options.TemporalSeedSampleTimes_s, {'numeric'}, ...
    {'real', 'finite', 'vector'});
options.AzimuthInterval_deg = ...
    reshape(double(options.AzimuthInterval_deg), 1, 2);
options.ElevationInterval_deg = ...
    reshape(double(options.ElevationInterval_deg), 1, 2);
options.TemporalSeedSampleTimes_s = unique(double( ...
    options.TemporalSeedSampleTimes_s(:)));
end

function state = normalizeState(state, label)
% PURPOSE
%   - Normalize one endpoint to scalar time and two-axis state rows.
if ~isstruct(state) || ~isscalar(state) || ...
        ~all(isfield(state, ["time_s" "position_deg"]))
    error("planAzElMotion:InvalidState", ...
        "%s must contain time_s and position_deg.", label);
end
if ~isfield(state, "velocity_deg_s") || isempty(state.velocity_deg_s)
    state.velocity_deg_s = [0 0];
end
if ~isfield(state, "acceleration_deg_s2") || ...
        isempty(state.acceleration_deg_s2)
    state.acceleration_deg_s2 = [0 0];
end
validateattributes(state.time_s, {'numeric'}, ...
    {'real', 'finite', 'scalar'});
names = ["position_deg" "velocity_deg_s" "acceleration_deg_s2"];
for fieldIndex = 1:numel(names)
    name = names(fieldIndex);
    validateattributes(state.(name), {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 2});
    state.(name) = reshape(double(state.(name)), 1, 2);
end
state.time_s = double(state.time_s);
end

function limits = normalizeLimits(limits)
% PURPOSE
%   - Normalize finite positive per-axis motion limits.
names = ["maxVelocity_deg_s" "maxAcceleration_deg_s2" ...
    "maxJerk_deg_s3"];
if ~isstruct(limits) || ~isscalar(limits) || ...
        ~all(isfield(limits, names))
    error("planAzElMotion:InvalidLimits", ...
        "limits must contain velocity, acceleration, and jerk limits.");
end
for fieldIndex = 1:numel(names)
    name = names(fieldIndex);
    value = limits.(name);
    validateattributes(value, {'numeric'}, ...
        {'real', 'finite', 'vector', 'nonempty', 'positive'});
    if ~(isscalar(value) || numel(value) == 2)
        error("planAzElMotion:InvalidLimits", ...
            "%s must be scalar or two-element.", name);
    end
    value = reshape(double(value), 1, []);
    if isscalar(value)
        value = repmat(value, 1, 2);
    end
    limits.(name) = value;
end
end

function [feasible, message] = endpointDynamicsAreFeasible( ...
        initialState, goalState, limits, options)
% PURPOSE
%   - Return stable expected failure for endpoint limit violations.
tolerance = options.KinematicValidationTolerance;
velocityFeasible = all(abs([initialState.velocity_deg_s; ...
    goalState.velocity_deg_s]) <= limits.maxVelocity_deg_s + tolerance, ...
    "all");
accelerationFeasible = all(abs([initialState.acceleration_deg_s2; ...
    goalState.acceleration_deg_s2]) <= ...
    limits.maxAcceleration_deg_s2 + tolerance, "all");
feasible = velocityFeasible && accelerationFeasible;
message = "Endpoint motion states satisfy their limits.";
if ~feasible
    message = "An endpoint velocity or acceleration exceeds its limit.";
end
end

function [feasible, message] = endpointWorkspaceIsFeasible( ...
        initialState, goalState, options)
% PURPOSE
%   - Return stable expected failure for endpoint workspace violations.
positions_deg = [initialState.position_deg; goalState.position_deg];
elevationFeasible = all(positions_deg(:, 2) >= ...
    options.ElevationInterval_deg(1) & positions_deg(:, 2) <= ...
    options.ElevationInterval_deg(2));
azimuthFeasible = true;
if ~options.AllowAzimuthWrapping
    azimuthFeasible = all(positions_deg(:, 1) >= ...
        options.AzimuthInterval_deg(1) & positions_deg(:, 1) <= ...
        options.AzimuthInterval_deg(2));
end
feasible = elevationFeasible && azimuthFeasible;
message = "Endpoint positions satisfy the workspace policy.";
if ~feasible
    message = "An endpoint position lies outside the configured workspace.";
end
end

