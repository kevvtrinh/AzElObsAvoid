function result = planAzElMotion( ...
        obstacles, initialState, goalState, limits, optionOverrides)
%PLANAZELMOTION Plan, retime, validate, and display az/el motion.
%   RESULT = PLANAZELMOTION(OBSTACLES, INITIALSTATE, GOALSTATE, LIMITS, OPTIONS)
%   is the single high-level entry point. OBSTACLES is canonical az/el data
%   from makeAzElObstacleData. OPTIONS.MotionType is either "exactStop" or
%   "velocityCarrying". Angles are degrees and time is seconds.
%
%   OPTIONS.SafetyMarginDeg is the required final clearance. Rounded mode
%   plans on that margin plus OPTIONS.RoundingClearance_deg so a fillet can
%   carry velocity without consuming the requested safety buffer.
%
%   Expected planning failures return Success=false after plotting the
%   environment, best attempted route, collision markers, and best-attempt
%   kinematics. Invalid API inputs still throw immediately.
%
%   A zero-input call returns the default options.

defaultOptions = struct( ...
    "MotionType", "velocityCarrying", ...
    "SafetyMarginDeg", 0, ...
    "RoundingClearance_deg", 0.02, ...
    "GoalTimeMode", "earliestArrival", ...
    "SampleTime_s", 0.05, ...
    "TurnRadius_deg", 1.0, ...
    "CollisionTimePaddingSamples", 1, ...
    "AllowAzimuthWrapping", false, ...
    "AzimuthInterval_deg", [-180 180], ...
    "MaximumVerticesPerRegion", Inf, ...
    "VisibilitySampleStep_deg", 0.10, ...
    "CandidateClearance_deg", 0, ...
    "CornerAngleThreshold_deg", 15, ...
    "FigureVisible", "on", ...
    "ShowAnimation", true, ...
    "ShowKinematicPlot", true, ...
    "AnimationFrameStride", 5, ...
    "AnimationPause_s", 0.005, ...
    "ShowSweptSurfaces", true, ...
    "MaximumDisplayedSlicesPerObstacle", 60, ...
    "Title", "Azimuth/elevation motion plan");
if nargin == 0
    result = defaultOptions;
    return;
end
if nargin < 5 || isempty(optionOverrides)
    optionOverrides = struct();
end
options = resolvePlannerOptions(defaultOptions, optionOverrides);
initialState = normalizedPlannerState(initialState, "initialState");
goalState = normalizedPlannerState(goalState, "goalState");
validatePlannerLimits(limits);

%% Build original and safety-inflated obstacle fields.
originalAzElData = combineAzElObstacles(obstacles);
planningSafetyMargin_deg = options.SafetyMarginDeg;
if lower(options.MotionType) == "velocitycarrying"
    planningSafetyMargin_deg = planningSafetyMargin_deg + ...
        options.RoundingClearance_deg;
end
planningAzElData = inflateAzElObstacleData( ...
    originalAzElData, planningSafetyMargin_deg);
fieldOptions = struct( ...
    "MaximumVerticesPerRegion", options.MaximumVerticesPerRegion);
originalObstacleField = buildAzElTimeObstacleField( ...
    originalAzElData, fieldOptions);
obstacleField = buildAzElTimeObstacleField( ...
    planningAzElData, fieldOptions);
marginTolerance_deg = max(1e-6, ...
    1e-3 * max(1, options.SafetyMarginDeg));
validationSafetyMargin_deg = max( ...
    0, options.SafetyMarginDeg - marginTolerance_deg);

startBlocked = queryAzElTimeObstacle(obstacleField, ...
    initialState.position_deg(1), initialState.position_deg(2), ...
    initialState.time_s);
goalBlocked = queryAzElTimeObstacle(obstacleField, ...
    goalState.position_deg(1), goalState.position_deg(2), ...
    goalState.time_s);
endpointBlocked = logical(startBlocked || goalBlocked);

%% Let the visibility graph generate routes; callers provide no waypoints.
viewOptions = struct( ...
    "FigureVisible", options.FigureVisible, ...
    "Title", options.Title, ...
    "ShowSweptSurfaces", options.ShowSweptSurfaces, ...
    "MaximumDisplayedSlicesPerObstacle", ...
    options.MaximumDisplayedSlicesPerObstacle, ...
    "ShowBoundaryCandidates", true, ...
    "ShowBoundaryConnections", true, ...
    "ShowVisibilityGraph", true, ...
    "CandidateClearance_deg", options.CandidateClearance_deg, ...
    "CornerAngleThreshold_deg", options.CornerAngleThreshold_deg, ...
    "VisibilitySampleStep_deg", options.VisibilitySampleStep_deg, ...
    "OriginalObstacleField", originalObstacleField);
spaceView = visualizeAzElTimeSpace( ...
    obstacleField, initialState, goalState, viewOptions);

routePosition_deg = { ...
    [initialState.position_deg; goalState.position_deg]};
routeName = "direct";
routeSnapshotTime_s = initialState.time_s;
routeGraphIndex = 0;
for graphIndex = 1:numel(spaceView.VisibilityGraphs)
    graph = spaceView.VisibilityGraphs(graphIndex);
    if ~graph.Success || size(graph.PathPosition_deg, 1) < 2
        continue;
    end
    if routeAlreadyPresent(routePosition_deg, graph.PathPosition_deg)
        continue;
    end
    routePosition_deg{end + 1, 1} = graph.PathPosition_deg; %#ok<AGROW>
    routeName(end + 1, 1) = "visibilityGraph"; %#ok<AGROW>
    routeSnapshotTime_s(end + 1, 1) = graph.Time_s; %#ok<AGROW>
    routeGraphIndex(end + 1, 1) = graphIndex; %#ok<AGROW>
end
routeCount = numel(routePosition_deg);
timedCandidates = cell(routeCount, 1);
smoothCandidates = cell(routeCount, 1);
blockedCandidates = cell(routeCount, 1);
candidateSuccess = false(routeCount, 1);
candidateCollisionFree = false(routeCount, 1);
candidateArrivalTime_s = inf(routeCount, 1);
candidateAttemptArrivalTime_s = inf(routeCount, 1);
candidateMessage = strings(routeCount, 1);
candidatePathLength_deg = zeros(routeCount, 1);
for routeIndex = 1:routeCount
    route_deg = routePosition_deg{routeIndex};
    candidatePathLength_deg(routeIndex) = sum(vecnorm( ...
        diff(route_deg, 1, 1), 2, 2));
    if ~routeRespectsAzimuthPolicy(route_deg, options)
        candidateMessage(routeIndex) = ...
            "Route violates the configured non-wrapping interval.";
        blockedCandidates{routeIndex} = false(0, 1);
        continue;
    end
    retimeOptions = struct( ...
        "GoalTimeMode", options.GoalTimeMode, ...
        "SampleTime_s", options.SampleTime_s);
    if lower(options.MotionType) == "exactstop"
        timedPath = retimePolylineMotion( ...
            route_deg, initialState, goalState, limits, retimeOptions);
        smoothPath = emptyPlannerSmoothPath(route_deg);
    else
        collisionTime_s = routeSnapshotTime_s(routeIndex);
        smoothPath = smoothRoundedMotion( ...
            route_deg, originalObstacleField, struct( ...
            "TurnRadius_deg", options.TurnRadius_deg, ...
            "CollisionCheckTimes_s", collisionTime_s, ...
            "TimePaddingSamples", ...
            options.CollisionTimePaddingSamples));
        timedPath = retimeRoundedMotion( ...
            smoothPath, initialState, goalState, limits, retimeOptions);
    end
    smoothCandidates{routeIndex} = smoothPath;
    timedCandidates{routeIndex} = timedPath;
    candidateSuccess(routeIndex) = timedPath.Success;
    candidateMessage(routeIndex) = timedPath.Message;
    if ~timedPath.Success
        canConservativelyScale = ...
            isUsableTimedPathIgnoringSuccess(timedPath) && ...
            isfield(timedPath, "ConstraintDiagnostics") && ...
            isfield(timedPath.ConstraintDiagnostics, ...
            "PeakAcceleration_deg_s2");
        if canConservativelyScale
            timedPath = conservativelyScaleTimedPath( ...
                timedPath, initialState, goalState, limits, options);
            timedCandidates{routeIndex} = timedPath;
            candidateSuccess(routeIndex) = timedPath.Success;
            candidateMessage(routeIndex) = timedPath.Message;
        end
        if ~timedPath.Success
            blockedCandidates{routeIndex} = false(0, 1);
            continue;
        end
    end
    candidateAttemptArrivalTime_s(routeIndex) = ...
        timedPath.GoalLineInterceptTime_s;
    if ~routeRespectsAzimuthPolicy(timedPath.position_deg, options)
        candidateMessage(routeIndex) = ...
            "Retiming violated the configured non-wrapping interval.";
        blockedCandidates{routeIndex} = false(0, 1);
        continue;
    end
    % The visibility graph was built on inflated geometry. Collision
    % validation uses the original polygons so boundary contacts retain the
    % requested construction clearance instead of self-blocking.
    blocked = queryAzElTimeObstacle( ...
        originalObstacleField, timedPath.position_deg(:, 1), ...
        timedPath.position_deg(:, 2), timedPath.time_s, struct( ...
        "CollisionMode", "polygon", ...
        "TimePaddingSamples", ...
        options.CollisionTimePaddingSamples, ...
        "SafetyMarginDeg", validationSafetyMargin_deg));
    blockedCandidates{routeIndex} = logical(blocked(:));
    candidateCollisionFree(routeIndex) = ~any(blocked);
    if candidateCollisionFree(routeIndex)
        candidateArrivalTime_s(routeIndex) = ...
            timedPath.GoalLineInterceptTime_s;
    else
        candidateMessage(routeIndex) = ...
            "The retimed route intersects an obstacle.";
    end
end

directFraction = linspace(0, 1, 501).';
directPosition_deg = initialState.position_deg + directFraction .* ...
    (goalState.position_deg - initialState.position_deg);
directTime_s = initialState.time_s + directFraction .* ...
    (goalState.time_s - initialState.time_s);
directBlocked = queryAzElTimeObstacle(obstacleField, ...
    directPosition_deg(:, 1), directPosition_deg(:, 2), directTime_s, ...
    struct("CollisionMode", "polygon", ...
    "TimePaddingSamples", options.CollisionTimePaddingSamples));
candidateDiagnostics = table( ...
    (1:routeCount).', routeName, routeSnapshotTime_s, routeGraphIndex, ...
    candidatePathLength_deg, candidateSuccess, candidateCollisionFree, ...
    candidateAttemptArrivalTime_s, candidateArrivalTime_s, ...
    candidateMessage, ...
    'VariableNames', {'Index', 'Source', 'SnapshotTime_s', ...
    'GraphIndex', 'PathLength_deg', 'Retimed', 'CollisionFree', ...
    'AttemptArrivalTime_s', 'ArrivalTime_s', 'Message'});

%% Select either the winning plan or the most informative failed attempt.
feasibleCandidateIndex = find( ...
    isfinite(candidateArrivalTime_s) & ~endpointBlocked);
planningSucceeded = ~isempty(feasibleCandidateIndex);
if planningSucceeded
    ranking = [ ...
        candidateArrivalTime_s(feasibleCandidateIndex), ...
        candidatePathLength_deg(feasibleCandidateIndex), ...
        feasibleCandidateIndex];
    [~, rankedIndex] = sortrows(ranking, [1 2 3]);
    selectedCandidateIndex = ...
        feasibleCandidateIndex(rankedIndex(1));
    resultMessage = ...
        "Automatic visibility planning and retiming succeeded.";
else
    selectedCandidateIndex = selectBestAttemptCandidate( ...
        candidateSuccess, blockedCandidates, ...
        candidateAttemptArrivalTime_s, candidatePathLength_deg, ...
        routeGraphIndex);
    if endpointBlocked
        resultMessage = ...
            "Planning failed because the safety margin contains the " + ...
            "start or goal. The best attempted route is plotted.";
    else
        failureSummary = strjoin( ...
            "route " + string((1:routeCount).') + ": " + ...
            candidateMessage, " | ");
        resultMessage = ...
            "No automatically generated route satisfies the motion " + ...
            "and obstacle constraints. Best attempt is plotted. " + ...
            failureSummary;
    end
end

selectedRoute_deg = routePosition_deg{selectedCandidateIndex};
[timedSlopePath, smoothPath, usedDiagnosticRetiming] = ...
    ensureDiagnosticTimedPath( ...
    timedCandidates{selectedCandidateIndex}, ...
    smoothCandidates{selectedCandidateIndex}, selectedRoute_deg, ...
    originalObstacleField, initialState, goalState, limits, options, ...
    routeSnapshotTime_s(selectedCandidateIndex));
selectedGraphIndex = routeGraphIndex(selectedCandidateIndex);
selectedPath = emptySelectedGraph();
if selectedGraphIndex > 0
    selectedPath = spaceView.VisibilityGraphs(selectedGraphIndex);
end

bestAttemptBlocked = queryAzElTimeObstacle( ...
    originalObstacleField, timedSlopePath.position_deg(:, 1), ...
    timedSlopePath.position_deg(:, 2), timedSlopePath.time_s, struct( ...
    "CollisionMode", "polygon", ...
    "TimePaddingSamples", options.CollisionTimePaddingSamples));
bestAttemptMarginBlocked = queryAzElTimeObstacle( ...
    originalObstacleField, timedSlopePath.position_deg(:, 1), ...
    timedSlopePath.position_deg(:, 2), timedSlopePath.time_s, struct( ...
    "CollisionMode", "polygon", ...
    "TimePaddingSamples", options.CollisionTimePaddingSamples, ...
    "SafetyMarginDeg", validationSafetyMargin_deg));

validation = validatePlannerResult( ...
    planningSucceeded, endpointBlocked, timedSlopePath, ...
    bestAttemptMarginBlocked, goalState, limits, options);
displaySucceeded = validation.Passed;
if planningSucceeded && ~displaySucceeded
    resultMessage = "Planner post-validation failed: " + ...
        validation.Message;
end

%% Draw the selected route or failed best attempt and its diagnostics.
pathColor = [0.05 0.70 0.82];
pathLabel = "Selected timed path";
if ~displaySucceeded
    pathColor = [0.95 0.45 0.05];
    pathLabel = "Best failed attempt";
    title(spaceView.Axes, options.Title + " | PLANNING FAILED");
end
timedSlopeHandle = plot3(spaceView.Axes, ...
    timedSlopePath.position_deg(:, 1), ...
    timedSlopePath.position_deg(:, 2), timedSlopePath.time_s, "-", ...
    "Color", pathColor, "LineWidth", 4.0, ...
    "DisplayName", pathLabel);
failureCollisionHandles = gobjects(0, 1);
if ~displaySucceeded
    if any(bestAttemptBlocked)
        failureCollisionHandles(end + 1, 1) = scatter3( ...
            spaceView.Axes, ...
            timedSlopePath.position_deg(bestAttemptBlocked, 1), ...
            timedSlopePath.position_deg(bestAttemptBlocked, 2), ...
            timedSlopePath.time_s(bestAttemptBlocked), 28, ...
            [0.75 0 0], "filled", ...
            "DisplayName", "Obstacle collision");
    end
    marginOnlyBlocked = bestAttemptMarginBlocked & ~bestAttemptBlocked;
    if any(marginOnlyBlocked)
        failureCollisionHandles(end + 1, 1) = scatter3( ...
            spaceView.Axes, ...
            timedSlopePath.position_deg(marginOnlyBlocked, 1), ...
            timedSlopePath.position_deg(marginOnlyBlocked, 2), ...
            timedSlopePath.time_s(marginOnlyBlocked), 22, ...
            [0.85 0.10 0.75], "filled", ...
            "DisplayName", "Safety-margin conflict");
    end
end
drawnow;

animation = struct();
if displaySucceeded && options.ShowAnimation
    animationPause_s = options.AnimationPause_s;
    if options.FigureVisible == "off"
        animationPause_s = 0;
    end
    animation = animateAzElTimedSlopePath( ...
        timedSlopePath, obstacleField, struct( ...
        "FigureVisible", options.FigureVisible, ...
        "FrameStride", options.AnimationFrameStride, ...
        "Pause_s", animationPause_s, ...
        "Title", options.Title + " animation"));
end
kinematicPlot = struct();
if options.ShowKinematicPlot || ~displaySucceeded
    kinematicTitle = options.Title + " kinematics";
    if ~displaySucceeded
        kinematicTitle = options.Title + ...
            " best-attempt kinematics (planning failed)";
    end
    kinematicPlot = plotPlannerKinematics(timedSlopePath, struct( ...
        "FigureVisible", options.FigureVisible, ...
        "Title", kinematicTitle));
end

result = struct( ...
    "Success", validation.Passed, ...
    "Message", resultMessage, ...
    "MotionType", options.MotionType, ...
    "Options", options, ...
    "azElData", planningAzElData, ...
    "originalAzElData", originalAzElData, ...
    "inflatedAzElData", planningAzElData, ...
    "obstacleField", obstacleField, ...
    "originalObstacleField", originalObstacleField, ...
    "initialState", initialState, ...
    "goalState", goalState, ...
    "limits", limits, ...
    "safetyMargin_deg", options.SafetyMarginDeg, ...
    "planningSafetyMargin_deg", planningSafetyMargin_deg, ...
    "validationSafetyMargin_deg", validationSafetyMargin_deg, ...
    "safetyMarginDiagnostics", spaceView.SafetyMarginDiagnostics, ...
    "directPosition_deg", directPosition_deg, ...
    "directTime_s", directTime_s, ...
    "directBlocked", logical(directBlocked(:)), ...
    "candidateRoutes_deg", {routePosition_deg}, ...
    "candidateTimedPaths", {timedCandidates}, ...
    "candidateSmoothPaths", {smoothCandidates}, ...
    "candidateBlocked", {blockedCandidates}, ...
    "candidateDiagnostics", candidateDiagnostics, ...
    "selectedCandidateIndex", selectedCandidateIndex, ...
    "selectedRoute_deg", selectedRoute_deg, ...
    "selectedPath", selectedPath, ...
    "selectedVisibilityPath", selectedPath, ...
    "smoothPath", smoothPath, ...
    "timedSlopePath", timedSlopePath, ...
    "goalLineInterceptTime_s", ...
    timedSlopePath.GoalLineInterceptTime_s, ...
    "timedSlopeHandle", timedSlopeHandle, ...
    "bestAttemptBlocked", logical(bestAttemptBlocked(:)), ...
    "bestAttemptMarginBlocked", ...
    logical(bestAttemptMarginBlocked(:)), ...
    "failureCollisionHandles", failureCollisionHandles, ...
    "usedDiagnosticRetiming", usedDiagnosticRetiming, ...
    "spaceView", spaceView, ...
    "animation", animation, ...
    "kinematicPlot", kinematicPlot, ...
    "Validation", validation);
if displaySucceeded
    fprintf( ...
        "Az/el planner: %s motion, %.2f deg safety margin, " + ...
        "%d automatic routes tested, selected route %d, " + ...
        "arrival %.3f s.\n", options.MotionType, ...
        options.SafetyMarginDeg, routeCount, selectedCandidateIndex, ...
        timedSlopePath.GoalLineInterceptTime_s);
else
    fprintf(2, ...
        "Az/el planner FAILED after %d automatic routes. " + ...
        "Best attempt is route %d; diagnostics were plotted.\n", ...
        routeCount, selectedCandidateIndex);
end
end

function options = resolvePlannerOptions(defaultOptions, overrides)
if ~isstruct(overrides) || ~isscalar(overrides)
    error("planAzElMotion:InvalidOptions", ...
        "options must be a scalar struct.");
end
unknown = setdiff(fieldnames(overrides), fieldnames(defaultOptions));
if ~isempty(unknown)
    error("planAzElMotion:UnknownOption", ...
        "Unknown option fields: %s.", strjoin(string(unknown), ", "));
end
options = defaultOptions;
names = fieldnames(overrides);
for index = 1:numel(names)
    if ~isempty(overrides.(names{index}))
        options.(names{index}) = overrides.(names{index});
    end
end
options.MotionType = lower(string(options.MotionType));
if ~any(options.MotionType == ["exactstop" "velocitycarrying"])
    error("planAzElMotion:InvalidMotionType", ...
        "MotionType must be exactStop or velocityCarrying.");
end
if options.MotionType == "exactstop"
    options.MotionType = "exactStop";
else
    options.MotionType = "velocityCarrying";
end
options.GoalTimeMode = lower(string(options.GoalTimeMode));
options.FigureVisible = lower(string(options.FigureVisible));
options.Title = string(options.Title);
validateattributes(options.SafetyMarginDeg, {'numeric'}, ...
    {'real','finite','scalar','nonnegative'});
validateattributes(options.RoundingClearance_deg, {'numeric'}, ...
    {'real','finite','scalar','nonnegative'});
validateattributes(options.TurnRadius_deg, {'numeric'}, ...
    {'real','finite','scalar','positive'});
validateattributes(options.SampleTime_s, {'numeric'}, ...
    {'real','finite','scalar','positive'});
validateattributes(options.CollisionTimePaddingSamples, {'numeric'}, ...
    {'real','finite','scalar','integer','nonnegative'});
validateattributes(options.AzimuthInterval_deg, {'numeric'}, ...
    {'real','finite','vector','numel',2,'increasing'});
validateattributes(options.AnimationFrameStride, {'numeric'}, ...
    {'real','finite','scalar','integer','positive'});
validateattributes(options.AnimationPause_s, {'numeric'}, ...
    {'real','finite','scalar','nonnegative'});
if ~any(options.FigureVisible == ["on" "off"])
    error("planAzElMotion:InvalidFigureVisible", ...
        "FigureVisible must be on or off.");
end
options.AllowAzimuthWrapping = logical(options.AllowAzimuthWrapping);
options.ShowAnimation = logical(options.ShowAnimation);
options.ShowKinematicPlot = logical(options.ShowKinematicPlot);
options.ShowSweptSurfaces = logical(options.ShowSweptSurfaces);
end

function state = normalizedPlannerState(state, label)
required = ["time_s" "position_deg"];
if ~isstruct(state) || ~isscalar(state) || ~all(isfield(state, required))
    error("planAzElMotion:InvalidState", ...
        "%s must contain time_s and position_deg.", label);
end
if ~isfield(state, "velocity_deg_s") || isempty(state.velocity_deg_s)
    state.velocity_deg_s = [0 0];
end
if ~isfield(state, "acceleration_deg_s2") || ...
        isempty(state.acceleration_deg_s2)
    state.acceleration_deg_s2 = [0 0];
end
validateattributes(state.time_s, {'numeric'}, ...
    {'real','finite','scalar'});
validateattributes(state.position_deg, {'numeric'}, ...
    {'real','finite','vector','numel',2});
validateattributes(state.velocity_deg_s, {'numeric'}, ...
    {'real','finite','vector','numel',2});
validateattributes(state.acceleration_deg_s2, {'numeric'}, ...
    {'real','finite','vector','numel',2});
state.position_deg = reshape(double(state.position_deg), 1, 2);
state.velocity_deg_s = reshape(double(state.velocity_deg_s), 1, 2);
state.acceleration_deg_s2 = reshape( ...
    double(state.acceleration_deg_s2), 1, 2);
state.time_s = double(state.time_s);
end

function validatePlannerLimits(limits)
if ~isstruct(limits) || ~isscalar(limits) || ...
        ~isfield(limits, "maxVelocity_deg_s")
    error("planAzElMotion:InvalidLimits", ...
        "limits must contain maxVelocity_deg_s.");
end
validateattributes(limits.maxVelocity_deg_s, {'numeric'}, ...
    {'real','finite','vector','positive'});
if isfield(limits, "maxAcceleration_deg_s2")
    validateattributes(limits.maxAcceleration_deg_s2, {'numeric'}, ...
        {'real','finite','vector','positive'});
end
end

function duplicate = routeAlreadyPresent(routes, candidate)
duplicate = false;
for routeIndex = 1:numel(routes)
    route = routes{routeIndex};
    if isequal(size(route), size(candidate)) && ...
            max(abs(route - candidate), [], "all") <= 1e-9
        duplicate = true;
        return;
    end
end
end

function respects = routeRespectsAzimuthPolicy(position_deg, options)
if options.AllowAzimuthWrapping
    respects = true;
    return;
end
azimuth_deg = position_deg(:, 1);
respects = all(azimuth_deg >= options.AzimuthInterval_deg(1) - 1e-10) && ...
    all(azimuth_deg <= options.AzimuthInterval_deg(2) + 1e-10) && ...
    all(abs(diff(azimuth_deg)) < 180 - 1e-10);
end

function selectedIndex = selectBestAttemptCandidate( ...
        candidateSuccess, blockedCandidates, attemptArrivalTime_s, ...
        pathLength_deg, routeGraphIndex)
% Prefer retimed attempts, then the least collision, then a graph route.
candidateCount = numel(candidateSuccess);
blockedCount = inf(candidateCount, 1);
blockedFraction = inf(candidateCount, 1);
for candidateIndex = 1:candidateCount
    blocked = blockedCandidates{candidateIndex};
    if candidateSuccess(candidateIndex) && ~isempty(blocked)
        blockedCount(candidateIndex) = nnz(blocked);
        blockedFraction(candidateIndex) = ...
            blockedCount(candidateIndex) / numel(blocked);
    end
end
isDirectRoute = routeGraphIndex(:) == 0;
ranking = [ ...
    ~candidateSuccess(:), blockedFraction, blockedCount, ...
    isDirectRoute, attemptArrivalTime_s(:), pathLength_deg(:), ...
    (1:candidateCount).'];
[~, order] = sortrows(ranking, 1:size(ranking, 2));
selectedIndex = order(1);
end

function [timedPath, smoothPath, usedDiagnosticRetiming] = ...
        ensureDiagnosticTimedPath( ...
        timedPath, smoothPath, route_deg, originalObstacleField, ...
        initialState, goalState, limits, options, snapshotTime_s)
% Produce kinematics for a failed attempt without changing its geometry.
usedDiagnosticRetiming = false;
if isUsableTimedPath(timedPath)
    return;
end
usedDiagnosticRetiming = true;
pathLength_deg = sum(vecnorm(diff(route_deg, 1, 1), 2, 2));
maximumVelocity_deg_s = plannerAxisLimit( ...
    limits, "maxVelocity_deg_s", false);
minimumVelocity_deg_s = min(maximumVelocity_deg_s(isfinite( ...
    maximumVelocity_deg_s)));
if isempty(minimumVelocity_deg_s)
    minimumVelocity_deg_s = 1;
end
diagnosticGoalState = goalState;
diagnosticGoalState.time_s = initialState.time_s + max( ...
    3600, 100 * max(pathLength_deg, 1) / minimumVelocity_deg_s);
retimeOptions = struct( ...
    "GoalTimeMode", "earliestArrival", ...
    "SampleTime_s", options.SampleTime_s);
if lower(options.MotionType) == "velocitycarrying"
    if ~isstruct(smoothPath) || ~isscalar(smoothPath) || ...
            ~isfield(smoothPath, "Success") || ~smoothPath.Success
        smoothPath = smoothRoundedMotion( ...
            route_deg, originalObstacleField, struct( ...
            "TurnRadius_deg", options.TurnRadius_deg, ...
            "CollisionCheckTimes_s", snapshotTime_s, ...
            "TimePaddingSamples", ...
            options.CollisionTimePaddingSamples));
    end
    timedPath = retimeRoundedMotion( ...
        smoothPath, initialState, diagnosticGoalState, ...
        limits, retimeOptions);
else
    smoothPath = emptyPlannerSmoothPath(route_deg);
    timedPath = retimePolylineMotion( ...
        route_deg, initialState, diagnosticGoalState, ...
        limits, retimeOptions);
end
if isUsableTimedPath(timedPath)
    return;
end

% Incompatible requested endpoint velocities should not suppress a useful
% failure plot. The final diagnostic fallback uses rest-to-rest motion and
% is explicitly marked through usedDiagnosticRetiming.
diagnosticInitialState = initialState;
diagnosticInitialState.velocity_deg_s = [0 0];
diagnosticInitialState.acceleration_deg_s2 = [0 0];
diagnosticGoalState.velocity_deg_s = [0 0];
diagnosticGoalState.acceleration_deg_s2 = [0 0];
smoothPath = emptyPlannerSmoothPath(route_deg);
timedPath = retimePolylineMotion( ...
    route_deg, diagnosticInitialState, diagnosticGoalState, ...
    limits, retimeOptions);
if ~isUsableTimedPath(timedPath)
    error("planAzElMotion:DiagnosticRetimingFailed", ...
        "The best route could not be retimed even for diagnostics: %s", ...
        timedPath.Message);
end
end

function usable = isUsableTimedPath(timedPath)
usable = isstruct(timedPath) && isscalar(timedPath) && ...
    isfield(timedPath, "Success") && timedPath.Success && ...
    isfield(timedPath, "time_s") && ~isempty(timedPath.time_s) && ...
    isfield(timedPath, "position_deg") && ...
    size(timedPath.position_deg, 1) == numel(timedPath.time_s);
end

function usable = isUsableTimedPathIgnoringSuccess(timedPath)
usable = isstruct(timedPath) && isscalar(timedPath) && ...
    isfield(timedPath, "time_s") && numel(timedPath.time_s) >= 2 && ...
    isfield(timedPath, "position_deg") && ...
    size(timedPath.position_deg, 1) == numel(timedPath.time_s) && ...
    isfield(timedPath, "velocity_deg_s") && ...
    isfield(timedPath, "acceleration_deg_s2");
end

function timedPath = conservativelyScaleTimedPath( ...
        timedPath, initialState, goalState, limits, options)
% Uniform time scaling preserves geometry while reducing v and a exactly.
maxVelocity_deg_s = plannerAxisLimit( ...
    limits, "maxVelocity_deg_s", false);
maxAcceleration_deg_s2 = plannerAxisLimit( ...
    limits, "maxAcceleration_deg_s2", true);
peakVelocity_deg_s = max(abs(timedPath.velocity_deg_s), [], 1);
peakAcceleration_deg_s2 = max( ...
    abs(timedPath.acceleration_deg_s2), [], 1);
velocityScale = max([1, ...
    peakVelocity_deg_s ./ maxVelocity_deg_s]);
accelerationScale = sqrt(max([1, ...
    peakAcceleration_deg_s2 ./ maxAcceleration_deg_s2]));
timeScale = 1.002 * max(velocityScale, accelerationScale);
if lower(options.GoalTimeMode) ~= "earliestarrival" || ...
        norm(initialState.velocity_deg_s) > 1e-10 || ...
        norm(goalState.velocity_deg_s) > 1e-10
    return;
end
motionStartTime_s = initialState.time_s;
if isfield(timedPath, "MotionStartTime_s")
    motionStartTime_s = timedPath.MotionStartTime_s;
end
scaledTime_s = motionStartTime_s + ...
    (timedPath.time_s - motionStartTime_s) * timeScale;
scaledArrivalTime_s = motionStartTime_s + ...
    (timedPath.GoalLineInterceptTime_s - motionStartTime_s) * timeScale;
if scaledArrivalTime_s > goalState.time_s + 1e-8
    return;
end
timedPath.time_s = scaledTime_s;
timedPath.velocity_deg_s = timedPath.velocity_deg_s / timeScale;
timedPath.acceleration_deg_s2 = ...
    timedPath.acceleration_deg_s2 / timeScale^2;
timedPath.GoalLineInterceptTime_s = scaledArrivalTime_s;
timedPath.MinimumMotionDuration_s = ...
    timedPath.MinimumMotionDuration_s * timeScale;
timeFields = ["WaypointTime_s" "CurveNodeTime_s"];
for fieldName = timeFields
    if isfield(timedPath, fieldName)
        timedPath.(fieldName) = motionStartTime_s + ...
            (timedPath.(fieldName) - motionStartTime_s) * timeScale;
    end
end
speedFields = ["CurveSpeed_deg_s" "SampleSpeed_deg_s"];
for fieldName = speedFields
    if isfield(timedPath, fieldName)
        timedPath.(fieldName) = timedPath.(fieldName) / timeScale;
    end
end
if isfield(timedPath, "CurveSpeedSquared_deg2_s2")
    timedPath.CurveSpeedSquared_deg2_s2 = ...
        timedPath.CurveSpeedSquared_deg2_s2 / timeScale^2;
end
accelerationFields = ["CurveTangentialAcceleration_deg_s2" ...
    "SampleTangentialAcceleration_deg_s2"];
for fieldName = accelerationFields
    if isfield(timedPath, fieldName)
        timedPath.(fieldName) = ...
            timedPath.(fieldName) / timeScale^2;
    end
end
if isfield(timedPath, "SegmentProfiles")
    for segmentIndex = 1:numel(timedPath.SegmentProfiles)
        profile = timedPath.SegmentProfiles(segmentIndex);
        profile.Duration_s = profile.Duration_s * timeScale;
        profile.StartTime_s = motionStartTime_s + ...
            (profile.StartTime_s - motionStartTime_s) * timeScale;
        profile.EndTime_s = motionStartTime_s + ...
            (profile.EndTime_s - motionStartTime_s) * timeScale;
        profile.StartSpeed_deg_s = ...
            profile.StartSpeed_deg_s / timeScale;
        profile.EndSpeed_deg_s = profile.EndSpeed_deg_s / timeScale;
        profile.TangentialAcceleration_deg_s2 = ...
            profile.TangentialAcceleration_deg_s2 / timeScale^2;
        timedPath.SegmentProfiles(segmentIndex) = profile;
    end
end
if isfield(timedPath, "MotionStartTime_s")
    timedPath.MotionStartTime_s = motionStartTime_s;
end
peakVelocity_deg_s = max(abs(timedPath.velocity_deg_s), [], 1);
peakAcceleration_deg_s2 = max( ...
    abs(timedPath.acceleration_deg_s2), [], 1);
velocitySatisfied = all(peakVelocity_deg_s <= ...
    maxVelocity_deg_s + options.SampleTime_s * eps);
accelerationSatisfied = all(peakAcceleration_deg_s2 <= ...
    maxAcceleration_deg_s2 + options.SampleTime_s * eps);
timedPath.ConstraintDiagnostics.PeakVelocity_deg_s = ...
    peakVelocity_deg_s;
timedPath.ConstraintDiagnostics.PeakAcceleration_deg_s2 = ...
    peakAcceleration_deg_s2;
timedPath.ConstraintDiagnostics.VelocityMargin_deg_s = ...
    maxVelocity_deg_s - peakVelocity_deg_s;
timedPath.ConstraintDiagnostics.AccelerationMargin_deg_s2 = ...
    maxAcceleration_deg_s2 - peakAcceleration_deg_s2;
timedPath.ConstraintDiagnostics.VelocitySatisfied = velocitySatisfied;
timedPath.ConstraintDiagnostics.AccelerationSatisfied = ...
    accelerationSatisfied;
timedPath.ConstraintDiagnostics.Satisfied = ...
    velocitySatisfied && accelerationSatisfied;
if isfield(timedPath.ConstraintDiagnostics, "MinimumArcSpeed_deg_s")
    timedPath.ConstraintDiagnostics.MinimumArcSpeed_deg_s = ...
        timedPath.ConstraintDiagnostics.MinimumArcSpeed_deg_s / timeScale;
end
timedPath.ConstraintDiagnostics.UniformTimeScale = timeScale;
timedPath.Success = timedPath.ConstraintDiagnostics.Satisfied;
if timedPath.Success
    timedPath.Message = ...
        "Retiming succeeded after conservative uniform time scaling.";
    timedPath.RetimerType = ...
        string(timedPath.RetimerType) + "UniformTimeScaled";
end
end

function validation = validatePlannerResult( ...
        planningSucceeded, endpointBlocked, timedPath, ...
        marginBlocked, goalState, limits, options)
% Publish stable checks so examples only need to validate this contract.
hasTimedPath = isUsableTimedPath(timedPath);
endpointClear = ~endpointBlocked;
requestedMarginClear = hasTimedPath && ~any(marginBlocked);
azimuthPolicySatisfied = hasTimedPath && ...
    routeRespectsAzimuthPolicy(timedPath.position_deg, options);
goalReached = hasTimedPath && norm( ...
    timedPath.position_deg(end, :) - goalState.position_deg) <= 1e-7;
arrivalWithinGoalTime = hasTimedPath && ...
    timedPath.GoalLineInterceptTime_s <= goalState.time_s + 1e-8;
velocityLimit_deg_s = plannerAxisLimit( ...
    limits, "maxVelocity_deg_s", false);
accelerationLimit_deg_s2 = plannerAxisLimit( ...
    limits, "maxAcceleration_deg_s2", true);
velocityWithinLimits = hasTimedPath && all(max( ...
    abs(timedPath.velocity_deg_s), [], 1) <= ...
    velocityLimit_deg_s + 1e-7);
accelerationWithinLimits = hasTimedPath && all(max( ...
    abs(timedPath.acceleration_deg_s2), [], 1) <= ...
    accelerationLimit_deg_s2 + 1e-7);
passed = planningSucceeded && endpointClear && requestedMarginClear && ...
    azimuthPolicySatisfied && goalReached && arrivalWithinGoalTime && ...
    velocityWithinLimits && accelerationWithinLimits;
checkNames = ["planning" "endpointClear" "requestedMarginClear" ...
    "azimuthPolicy" "goalReached" "arrivalWithinGoalTime" ...
    "velocityLimits" "accelerationLimits"];
checkValues = [planningSucceeded endpointClear requestedMarginClear ...
    azimuthPolicySatisfied goalReached arrivalWithinGoalTime ...
    velocityWithinLimits accelerationWithinLimits];
failedChecks = checkNames(~checkValues);
message = "All planner validations passed.";
if ~passed
    message = "Failed checks: " + strjoin(failedChecks, ", ") + ".";
end
validation = struct( ...
    "Passed", passed, ...
    "Message", message, ...
    "PlanningSucceeded", planningSucceeded, ...
    "EndpointClear", endpointClear, ...
    "RequestedMarginClear", requestedMarginClear, ...
    "AzimuthPolicySatisfied", azimuthPolicySatisfied, ...
    "GoalReached", goalReached, ...
    "ArrivalWithinGoalTime", arrivalWithinGoalTime, ...
    "VelocityWithinLimits", velocityWithinLimits, ...
    "AccelerationWithinLimits", accelerationWithinLimits);
end

