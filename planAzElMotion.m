function derivativeBounds = roundedRunDerivativeBounds( ...
        smoothPath, startS_deg, endS_deg, runIndex)
%% Section 0: Header & Readme
% Form analytic global bounds on q', q'', and q''' for one smooth run.
% For a quintic, Bernstein control-polygon bounds give global maxima of
% parameter derivatives. The symmetric blend also gives the exact positive
% lower bound (25/16)*d*cos(theta/2) on ||dB/du||. Combining them yields
% conservative arc-length derivative bounds without output-grid dependence.
tangentBound = zeros(1, 2);
secondDerivativeBound = zeros(1, 2);
thirdDerivativeBound = zeros(1, 2);
coveredPrimitiveCount = 0;
for primitiveIndex = 1:numel(smoothPath.Primitives)
    primitive = smoothPath.Primitives(primitiveIndex);
    if primitive.EndArcLength_deg < startS_deg || ...
            primitive.StartArcLength_deg > endS_deg
        continue;
    end
    coveredPrimitiveCount = coveredPrimitiveCount + 1;
    primitiveType = string(primitive.Type);
    if primitiveType == "line"
        primitiveTangentBound = abs(primitive.Direction);
        primitiveSecondBound = [0 0];
        primitiveThirdBound = [0 0];
    elseif primitiveType == "arc"
        primitiveTangentBound = [1 1];
        primitiveSecondBound = repmat(1 / primitive.Radius_deg, 1, 2);
        primitiveThirdBound = repmat(1 / primitive.Radius_deg^2, 1, 2);
    else
        controlPoints_deg = primitive.ControlPoints_deg;
        incomingDirection = controlPoints_deg(2, :) - ...
            controlPoints_deg(1, :);
        outgoingDirection = controlPoints_deg(end, :) - ...
            controlPoints_deg(end - 1, :);
        halfTrimDistance_deg = norm(incomingDirection);
        incomingDirection = incomingDirection / halfTrimDistance_deg;
        outgoingDirection = outgoingDirection / norm(outgoingDirection);
        trimDistance_deg = 2 * halfTrimDistance_deg;
        halfAngleCosine = sqrt(max(0, ...
            0.5 * (1 + dot(incomingDirection, outgoingDirection))));
        parameterSpeedLowerBound_deg = ...
            (25 / 16) * trimDistance_deg * halfAngleCosine;
        if parameterSpeedLowerBound_deg <= 0
            error("retimeJerkContinuousRoundedMotion:DegenerateQuintic", ...
                "A quintic blend lacks a positive derivative lower bound.");
        end
        secondControl = 20 * diff(controlPoints_deg, 2, 1);
        thirdControl = 60 * diff(controlPoints_deg, 3, 1);
        parameterSecondBound_deg = max(vecnorm( ...
            secondControl, 2, 2));
        parameterThirdBound_deg = max(vecnorm( ...
            thirdControl, 2, 2));
        curvatureNormBound_deg_inv = parameterSecondBound_deg / ...
            parameterSpeedLowerBound_deg^2;
        thirdDerivativeNormBound_deg_inv2 = ...
            2 * parameterThirdBound_deg / ...
            parameterSpeedLowerBound_deg^3 + ...
            8 * parameterSecondBound_deg^2 / ...
            parameterSpeedLowerBound_deg^4;
        primitiveTangentBound = [1 1];
        primitiveSecondBound = repmat( ...
            curvatureNormBound_deg_inv, 1, 2);
        primitiveThirdBound = repmat( ...
            thirdDerivativeNormBound_deg_inv2, 1, 2);
    end
    tangentBound = max(tangentBound, primitiveTangentBound);
    secondDerivativeBound = max( ...
        secondDerivativeBound, primitiveSecondBound);
    thirdDerivativeBound = max( ...
        thirdDerivativeBound, primitiveThirdBound);
end
diagnosticStep_deg = 0.002;
diagnosticS_deg = (startS_deg:diagnosticStep_deg:endS_deg).';
diagnosticS_deg = unique([diagnosticS_deg; endS_deg]);
diagnosticSamples = sampleRoundedMotion(smoothPath, diagnosticS_deg);
numericalTangentBound = max(abs(diagnosticSamples.tangent), [], 1);
numericalSecondBound = max(abs( ...
    diagnosticSamples.secondDerivative_deg_inv), [], 1);
numericalThirdBound = max(abs( ...
    diagnosticSamples.thirdDerivative_deg_inv2), [], 1);
derivativeBounds = struct( ...
    "RunIndex", runIndex, ...
    "StartArcLength_deg", startS_deg, ...
    "EndArcLength_deg", endS_deg, ...
    "TangentByAxis", tangentBound, ...
    "SecondDerivativeByAxis_deg_inv", secondDerivativeBound, ...
    "ThirdDerivativeByAxis_deg_inv2", thirdDerivativeBound, ...
    "NumericalTangentByAxis", numericalTangentBound, ...
    "NumericalSecondDerivativeByAxis_deg_inv", numericalSecondBound, ...
    "NumericalThirdDerivativeByAxis_deg_inv2", numericalThirdBound, ...
    "EnvelopeInflationFactor", 1.0, ...
    "SampleCount", coveredPrimitiveCount, ...
    "Method", "analyticBezierControlPolygon");
end

function [maxSpeed_deg_s, maxAcceleration_deg_s2, maxJerk_deg_s3] = ...
        roundedRunScalarLimits(bounds, limits, tolerance)
%% Section 0: Header & Readme
% Allocate separate tangential, curvature, and curvature-rate budgets.
tangentBound = bounds.NumericalTangentByAxis;
secondBound = bounds.NumericalSecondDerivativeByAxis_deg_inv;
thirdBound = bounds.NumericalThirdDerivativeByAxis_deg_inv2;
velocityLimit_deg_s = limits.maxVelocity_deg_s;
accelerationLimit_deg_s2 = limits.maxAcceleration_deg_s2;
jerkLimit_deg_s3 = limits.maxJerk_deg_s3;
maxSpeed_deg_s = Inf;
maxAcceleration_deg_s2 = Inf;
maxJerk_deg_s3 = Inf;
for axisIndex = 1:2
    if tangentBound(axisIndex) > tolerance
        maxSpeed_deg_s = min(maxSpeed_deg_s, ...
            velocityLimit_deg_s(axisIndex) / tangentBound(axisIndex));
    end
    if isfinite(accelerationLimit_deg_s2(axisIndex))
        if tangentBound(axisIndex) > tolerance
            maxAcceleration_deg_s2 = min(maxAcceleration_deg_s2, ...
                0.55 * accelerationLimit_deg_s2(axisIndex) / ...
                tangentBound(axisIndex));
        end
        if secondBound(axisIndex) > tolerance
            maxSpeed_deg_s = min(maxSpeed_deg_s, sqrt( ...
                0.45 * accelerationLimit_deg_s2(axisIndex) / ...
                secondBound(axisIndex)));
        end
    end
    if isfinite(jerkLimit_deg_s3(axisIndex))
        if tangentBound(axisIndex) > tolerance
            maxJerk_deg_s3 = min(maxJerk_deg_s3, ...
                jerkLimit_deg_s3(axisIndex) / ...
                (3 * tangentBound(axisIndex)));
        end
        if thirdBound(axisIndex) > tolerance
            maxSpeed_deg_s = min(maxSpeed_deg_s, nthroot( ...
                jerkLimit_deg_s3(axisIndex) / ...
                (3 * thirdBound(axisIndex)), 3));
        end
    end
end
finiteJerkLimit_deg_s3 = jerkLimit_deg_s3(isfinite(jerkLimit_deg_s3));
if ~isfinite(maxJerk_deg_s3)
    % A finite constraint can be geometrically inactive on this run. Keep
    % the scalar S-curve well conditioned without claiming that axis moves.
    maxJerk_deg_s3 = min(finiteJerkLimit_deg_s3);
end
for axisIndex = 1:2
    if isfinite(jerkLimit_deg_s3(axisIndex)) && ...
            secondBound(axisIndex) > tolerance
        crossAccelerationLimit_deg_s2 = ...
            jerkLimit_deg_s3(axisIndex) / ...
            (9 * secondBound(axisIndex) * max(maxSpeed_deg_s, eps));
        maxAcceleration_deg_s2 = min(maxAcceleration_deg_s2, ...
            crossAccelerationLimit_deg_s2);
    end
end
if ~isfinite(maxSpeed_deg_s) || maxSpeed_deg_s <= 0 || ...
        maxAcceleration_deg_s2 <= 0 || ...
        ~isfinite(maxJerk_deg_s3) || maxJerk_deg_s3 <= 0
    error("retimeJerkContinuousRoundedMotion:InvalidScalarLimits", ...
        "The rounded geometry produced unusable scalar kinematic limits.");
end
end

function [velocityBound_deg_s, accelerationBound_deg_s2, ...
        jerkBound_deg_s3] = roundedRunKinematicBounds(bounds, profile)
%% Section 0: Header & Readme
% Convert scalar S-curve peaks into conservative per-axis Cartesian peaks
% using the same guarded numerical envelope used by the retimer.
tangentBound = bounds.NumericalTangentByAxis;
secondBound = bounds.NumericalSecondDerivativeByAxis_deg_inv;
thirdBound = bounds.NumericalThirdDerivativeByAxis_deg_inv2;
velocityBound_deg_s = tangentBound * profile.PeakSpeed_deg_s;
accelerationBound_deg_s2 = ...
    tangentBound * profile.PeakAcceleration_deg_s2 + ...
    secondBound * profile.PeakSpeed_deg_s^2;
jerkBound_deg_s3 = tangentBound * profile.PeakJerk_deg_s3 + ...
    3 * secondBound * profile.PeakSpeed_deg_s * ...
    profile.PeakAcceleration_deg_s2 + ...
    thirdBound * profile.PeakSpeed_deg_s^3;
end

function time_s = jerkProfileTimeAtDistance(profile, distance_deg, tolerance)
%% Section 0: Header & Readme
% Invert the monotone analytic S-curve with safeguarded bisection.
distance_deg = min(max(double(distance_deg(:)), 0), profile.Length_deg);
time_s = zeros(size(distance_deg));
for distanceIndex = 1:numel(distance_deg)
    targetDistance_deg = distance_deg(distanceIndex);
    if targetDistance_deg <= tolerance
        time_s(distanceIndex) = 0;
        continue;
    end
    if targetDistance_deg >= profile.Length_deg - tolerance
        time_s(distanceIndex) = profile.Duration_s;
        continue;
    end
    lowerTime_s = 0;
    upperTime_s = profile.Duration_s;
    for iteration = 1:70
        middleTime_s = 0.5 * (lowerTime_s + upperTime_s);
        middleDistance_deg = sampleJerkProfile( ...
            middleTime_s, profile, tolerance);
        if middleDistance_deg < targetDistance_deg
            lowerTime_s = middleTime_s;
        else
            upperTime_s = middleTime_s;
        end
    end
    time_s(distanceIndex) = 0.5 * (lowerTime_s + upperTime_s);
end
end

function timedPath = retimeJerkLimitedPrimitives( ...
        primitives, pathPosition_deg, initialState, goalState, ...
        limits, options, motionType)
%% Section 0: Header & Readme
% Retime exact line/circle primitives with analytic bounded-jerk S-curves.
% Acceleration is zero at every primitive boundary. This is automatically
% compatible with exact-stop corners and prevents curvature jumps in the
% current G1 rounded geometry from creating impulsive jerk.
primitiveCount = numel(primitives);
if primitiveCount < 1
    timedPath = failedJerkLimitedPath( ...
        "The path has no nonzero primitive.", limits, options, motionType);
    return;
end
maxVelocity_deg_s = limits.maxVelocity_deg_s;
maxAcceleration_deg_s2 = limits.maxAcceleration_deg_s2;
maxJerk_deg_s3 = limits.maxJerk_deg_s3;

[startPosition_deg, startTangent, startSecondDerivative_deg_inv] = ...
    sampleJerkPrimitive(primitives(1), 0);
[goalPosition_deg, goalTangent, goalSecondDerivative_deg_inv] = ...
    sampleJerkPrimitive( ...
    primitives(end), primitives(end).Length_deg);
if norm(startPosition_deg - initialState.position_deg) > ...
        options.PositionTolerance_deg || ...
        norm(goalPosition_deg - goalState.position_deg) > ...
        options.PositionTolerance_deg
    error("retimeJerkLimitedPrimitives:EndpointMismatch", ...
        "Primitive endpoints must match the requested endpoint states.");
end
initialSpeed_deg_s = roundedBoundaryScalarSpeed( ...
    initialState.velocity_deg_s, startTangent, ...
    "initialState.velocity_deg_s", options.KinematicTolerance);
goalSpeed_deg_s = roundedBoundaryScalarSpeed( ...
    goalState.velocity_deg_s, goalTangent, ...
    "goalState.velocity_deg_s", options.KinematicTolerance);
requiredInitialAcceleration_deg_s2 = ...
    startSecondDerivative_deg_inv * initialSpeed_deg_s^2;
requiredGoalAcceleration_deg_s2 = ...
    goalSecondDerivative_deg_inv * goalSpeed_deg_s^2;
if norm(requiredInitialAcceleration_deg_s2 - ...
        initialState.acceleration_deg_s2) > options.KinematicTolerance || ...
        norm(requiredGoalAcceleration_deg_s2 - ...
        goalState.acceleration_deg_s2) > options.KinematicTolerance
    timedPath = failedJerkLimitedPath( ...
        "A nonzero endpoint speed on a curved primitive requires the " + ...
        "matching normal acceleration boundary state.", ...
        limits, options, motionType);
    return;
end

