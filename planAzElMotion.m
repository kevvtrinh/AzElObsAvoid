function length_deg = routeLength(route_deg)
% PURPOSE
%   - Compute polyline length for deterministic seed diagnostics.
if size(route_deg, 1) < 2
    length_deg = 0;
    return;
end
step_deg = diff(route_deg, 1, 1);
length_deg = sum(hypot(step_deg(:, 1), step_deg(:, 2)));
end
