    "SnapshotProbeEdgeCount", options.SnapshotProbeEdgeCount, ...
    "SnapshotCountChangeThreshold", ...
    options.SnapshotCountChangeThreshold, ...
    "SnapshotEdgeRotationThreshold_deg", ...
    options.SnapshotEdgeRotationThreshold_deg, ...
    "SnapshotBoundaryMotionThreshold_deg", ...
    options.SnapshotBoundaryMotionThreshold_deg, ...
    "VisibilitySampleStep_deg", options.VisibilitySampleStep_deg, ...
    "ConnectivityPathCostChangeThreshold", ...
    options.VisibilityGraphCostChangeThreshold, ...
    "BuildFullVisibilityGraphs", true, ...
    "BuildMergedVisibilityGraph", true, ...
    "BuildAlternativeTopologyRoute", true, ...
    "BuildSpaceTimeVisibilityGraph", ...
    options.UseSpaceTimeVisibilityGraph && ...
    ~isObstacleGeometryTimeInvariant, ...
    "GoalTimeMode", options.GoalTimeMode, ...
    "MaximumVelocity_deg_s", limits.maxVelocity_deg_s, ...
    "MaximumAcceleration_deg_s2", limits.maxAcceleration_deg_s2, ...
    "MaximumJerk_deg_s3", limits.maxJerk_deg_s3, ...
    "SpaceTimeLayerCount", options.SpaceTimeLayerCount, ...
    "MaximumSpaceTimeCandidateCount", ...
