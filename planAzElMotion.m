function kinematicPlot = plotPlannerKinematics( ...
        timedSlopePath, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = plotPlannerKinematics()
%   kinematicPlot = plotPlannerKinematics(timedSlopePath)
%   kinematicPlot = plotPlannerKinematics( ...
%       timedSlopePath, optionOverrides)
%**************************************************************************
% PURPOSE
%   - Plot position, velocity, acceleration, and jerk for a retimed path.
%   - Overlay the configured per-axis velocity, acceleration, and jerk limits so
%     constraint compliance is visible without inspecting numeric arrays.
%**************************************************************************
% INPUTS
%   - timedSlopePath (successful planAzElMotion timed-path output)
%   - optionOverrides (scalar struct, optional)
%       .FigureVisible "on" (default) or "off"
%       .ShowLimits    true (default)
%       .Title         scalar text
%**************************************************************************
% OUTPUTS
%   - kinematicPlot (scalar struct)
%       Figure, Axes, PositionLines, VelocityLines, AccelerationLines,
%       JerkLines,
%       LimitLines, Diagnostics, and Options.
%**************************************************************************
% UNITS
%   - Position is degrees, time is seconds, velocity is deg/s,
%     acceleration is deg/s^2, and jerk is deg/s^3.

%% Section 1: Resolve Options & Validate The Path
defaultOptions = struct( ...
    "FigureVisible", "on", ...
    "ShowLimits", true, ...
    "Title", "Azimuth/elevation timed-path kinematics");
if nargin == 0
    kinematicPlot = defaultOptions;
    return;
end
if nargin < 2 || isempty(optionOverrides)
    optionOverrides = struct();
end
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("plotPlannerKinematics:InvalidOptions", ...
        "Options must be a scalar struct.");
end
options = defaultOptions;
overrideNames = string(fieldnames(optionOverrides));
knownNames = string(fieldnames(defaultOptions));
unknownNames = setdiff(overrideNames, knownNames);
if ~isempty(unknownNames)
    warning("plotPlannerKinematics:UnknownOptions", ...
        "Ignoring unknown option(s): %s.", strjoin(unknownNames, ", "));
end
for optionIndex = 1:numel(overrideNames)
    optionName = overrideNames(optionIndex);
    if isfield(defaultOptions, optionName)
        options.(optionName) = optionOverrides.(optionName);
    end
end
options.FigureVisible = lower(string(options.FigureVisible));
if ~isscalar(options.FigureVisible) || ...
        ~any(options.FigureVisible == ["on", "off"])
    error("plotPlannerKinematics:InvalidFigureVisible", ...
        "FigureVisible must be on or off.");
end
if ~islogical(options.ShowLimits) || ~isscalar(options.ShowLimits)
    error("plotPlannerKinematics:InvalidShowLimits", ...
        "ShowLimits must be a logical scalar.");
end
options.Title = string(options.Title);
if ~isscalar(options.Title)
    error("plotPlannerKinematics:InvalidTitle", ...
        "Title must be scalar text.");
end

requiredFields = ["time_s", "position_deg", "velocity_deg_s", ...
    "acceleration_deg_s2"];
if ~isstruct(timedSlopePath) || ~isscalar(timedSlopePath) || ...
        ~all(isfield(timedSlopePath, requiredFields)) || ...
        (isfield(timedSlopePath, "Success") && ~timedSlopePath.Success)
    error("plotPlannerKinematics:InvalidTimedSlopePath", ...
        "Input must be a successful acceleration-aware timed path.");
end
time_s = double(timedSlopePath.time_s(:));
position_deg = double(timedSlopePath.position_deg);
velocity_deg_s = double(timedSlopePath.velocity_deg_s);
acceleration_deg_s2 = double(timedSlopePath.acceleration_deg_s2);
jerk_deg_s3 = NaN(size(acceleration_deg_s2));
if isfield(timedSlopePath, "jerk_deg_s3")
    jerk_deg_s3 = double(timedSlopePath.jerk_deg_s3);
end
validateattributes(time_s, {'numeric'}, ...
    {'real', 'finite', 'vector', 'increasing'});
validateattributes(position_deg, {'numeric'}, ...
    {'real', 'finite', '2d', 'ncols', 2});
validateattributes(velocity_deg_s, {'numeric'}, ...
    {'real', 'finite', '2d', 'ncols', 2});
validateattributes(acceleration_deg_s2, {'numeric'}, ...
    {'real', 'finite', '2d', 'ncols', 2});
validateattributes(jerk_deg_s3, {'numeric'}, ...
    {'real', '2d', 'ncols', 2});
sampleCount = numel(time_s);
if size(position_deg, 1) ~= sampleCount || ...
        size(velocity_deg_s, 1) ~= sampleCount || ...
        size(acceleration_deg_s2, 1) ~= sampleCount || ...
        size(jerk_deg_s3, 1) ~= sampleCount
    error("plotPlannerKinematics:PathSizeMismatch", ...
        "Every kinematic array must have one row per time sample.");
end

maxVelocity_deg_s = [Inf Inf];
maxAcceleration_deg_s2 = [Inf Inf];
maxJerk_deg_s3 = [Inf Inf];
if isfield(timedSlopePath, "Limits") && ...
        isstruct(timedSlopePath.Limits)
    if isfield(timedSlopePath.Limits, "maxVelocity_deg_s")
        maxVelocity_deg_s = reshape( ...
            double(timedSlopePath.Limits.maxVelocity_deg_s), 1, 2);
    end
    if isfield(timedSlopePath.Limits, "maxAcceleration_deg_s2")
        maxAcceleration_deg_s2 = reshape( ...
            double(timedSlopePath.Limits.maxAcceleration_deg_s2), 1, 2);
    end
    if isfield(timedSlopePath.Limits, "maxJerk_deg_s3")
        maxJerk_deg_s3 = reshape( ...
            double(timedSlopePath.Limits.maxJerk_deg_s3), 1, 2);
    end
end

%% Section 2: Draw Position, Velocity, Acceleration & Jerk With Bounds
axisColors = [0.10 0.35 0.85; 0.90 0.30 0.15];
figureHandle = figure( ...
    "Name", char(options.Title), ...
    "Color", "w", ...
    "Visible", options.FigureVisible);
axesHandles = gobjects(4, 1);
positionLines = gobjects(2, 1);
velocityLines = gobjects(2, 1);
accelerationLines = gobjects(2, 1);
jerkLines = gobjects(2, 1);
limitLines = gobjects(0, 1);

axesHandles(1) = subplot(4, 1, 1, "Parent", figureHandle);
hold(axesHandles(1), "on");
positionLines(1) = plot(axesHandles(1), time_s, position_deg(:, 1), ...
    "-", "Color", axisColors(1, :), "LineWidth", 1.8, ...
    "DisplayName", "Azimuth");
positionLines(2) = plot(axesHandles(1), time_s, position_deg(:, 2), ...
    "-", "Color", axisColors(2, :), "LineWidth", 1.8, ...
    "DisplayName", "Elevation");
ylabel(axesHandles(1), "Position (deg)");
title(axesHandles(1), options.Title);
legend(axesHandles(1), "Location", "best");

axesHandles(2) = subplot(4, 1, 2, "Parent", figureHandle);
hold(axesHandles(2), "on");
velocityLines(1) = plot(axesHandles(2), time_s, velocity_deg_s(:, 1), ...
    "-", "Color", axisColors(1, :), "LineWidth", 1.8, ...
    "DisplayName", "Azimuth velocity");
velocityLines(2) = plot(axesHandles(2), time_s, velocity_deg_s(:, 2), ...
    "-", "Color", axisColors(2, :), "LineWidth", 1.8, ...
    "DisplayName", "Elevation velocity");
if options.ShowLimits
    limitLines = [limitLines; drawAxisBounds( ...
        axesHandles(2), maxVelocity_deg_s, axisColors, "velocity")];
end
ylabel(axesHandles(2), "Velocity (deg/s)");
legend(axesHandles(2), "Location", "best");

axesHandles(3) = subplot(4, 1, 3, "Parent", figureHandle);
hold(axesHandles(3), "on");
accelerationLines(1) = plot(axesHandles(3), time_s, ...
    acceleration_deg_s2(:, 1), "-", "Color", axisColors(1, :), ...
    "LineWidth", 1.8, "DisplayName", "Azimuth acceleration");
accelerationLines(2) = plot(axesHandles(3), time_s, ...
    acceleration_deg_s2(:, 2), "-", "Color", axisColors(2, :), ...
    "LineWidth", 1.8, "DisplayName", "Elevation acceleration");
if options.ShowLimits
    limitLines = [limitLines; drawAxisBounds( ...
        axesHandles(3), maxAcceleration_deg_s2, axisColors, ...
        "acceleration")];
end
ylabel(axesHandles(3), "Acceleration (deg/s^2)");
legend(axesHandles(3), "Location", "best");

axesHandles(4) = subplot(4, 1, 4, "Parent", figureHandle);
hold(axesHandles(4), "on");
jerkLines(1) = plot(axesHandles(4), time_s, jerk_deg_s3(:, 1), ...
    "-", "Color", axisColors(1, :), "LineWidth", 1.8, ...
    "DisplayName", "Azimuth jerk");
jerkLines(2) = plot(axesHandles(4), time_s, jerk_deg_s3(:, 2), ...
    "-", "Color", axisColors(2, :), "LineWidth", 1.8, ...
    "DisplayName", "Elevation jerk");
if options.ShowLimits
    limitLines = [limitLines; drawAxisBounds( ...
        axesHandles(4), maxJerk_deg_s3, axisColors, "jerk")];
end
xlabel(axesHandles(4), "Time (s)");
ylabel(axesHandles(4), "Jerk (deg/s^3)");
legend(axesHandles(4), "Location", "best");

for axesIndex = 1:numel(axesHandles)
    grid(axesHandles(axesIndex), "on");
    box(axesHandles(axesIndex), "on");
    xlim(axesHandles(axesIndex), [time_s(1), time_s(end)]);
end
linkaxes(axesHandles, "x");

if isfield(timedSlopePath, "ConstraintDiagnostics")
    diagnostics = timedSlopePath.ConstraintDiagnostics;
else
    diagnostics = struct( ...
        "PeakVelocity_deg_s", max(abs(velocity_deg_s), [], 1), ...
        "PeakAcceleration_deg_s2", ...
        max(abs(acceleration_deg_s2), [], 1));
end
kinematicPlot = struct( ...
    "Figure", figureHandle, ...
    "Axes", axesHandles, ...
    "PositionLines", positionLines, ...
    "VelocityLines", velocityLines, ...
    "AccelerationLines", accelerationLines, ...
    "JerkLines", jerkLines, ...
    "LimitLines", limitLines, ...
    "Diagnostics", diagnostics, ...
    "Options", options);
end

function handles = drawAxisBounds(axesHandle, limits, colors, quantity)
%% Section 0: Header & Readme
% Draw finite positive/negative component bounds without crowding legends.
handles = gobjects(0, 1);
axisNames = ["Azimuth", "Elevation"];
for axisIndex = 1:2
    if ~isfinite(limits(axisIndex))
        continue;
    end
    positiveBound = yline(axesHandle, limits(axisIndex), "--", ...
        "Color", colors(axisIndex, :), "LineWidth", 1.0, ...
        "HandleVisibility", "off");
    negativeBound = yline(axesHandle, -limits(axisIndex), "--", ...
        "Color", colors(axisIndex, :), "LineWidth", 1.0, ...
        "HandleVisibility", "off");
    positiveBound.DisplayName = sprintf("%s %s limit", ...
        axisNames(axisIndex), quantity);
    handles = [handles; positiveBound; negativeBound]; %#ok<AGROW>
end
end
