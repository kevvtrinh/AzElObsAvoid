function smoothPath = smoothRoundedMotion( ...
        pathPosition_deg, obstacleField, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = smoothRoundedMotion()
%   smoothPath = smoothRoundedMotion(pathPosition_deg)
%   smoothPath = smoothRoundedMotion( ...
%       pathPosition_deg, obstacleField, options)
%**************************************************************************
% PURPOSE
%   - Replace visibility-polyline corners with tangent circular fillets so
%     velocity can remain nonzero while its direction changes.
%   - Shrink each requested fillet until it clears supplied obstacle
%     geometry. A corner that cannot be rounded is explicitly marked as a
%     mandatory stop for the curve retimer.
%**************************************************************************
% INPUTS
%   - pathPosition_deg (N-by-2 finite numeric matrix, N >= 2)
%   - obstacleField (scalar struct or [], optional)
%       Packed field checked at CollisionCheckTimes_s. For visibility paths
%       built on safety-inflated geometry, pass the original obstacle field
%       so a fillet may safely use part of the planning buffer.
%   - options (scalar struct, optional)
%       .TurnRadius_deg              requested radius (1.0)
%       .MinimumTurnRadius_deg       smallest useful fillet (0.02)
%       .RadiusBackoffFactor         retry scale in (0,1) (0.65)
%       .MaximumTangentFraction      per-end edge usage (0.45)
%       .SampleSpacing_deg           output curve spacing (0.05)
%       .CollisionCheckSpacing_deg   fillet check spacing (0.02)
%       .CollisionCheckTimes_s       obstacle times to check ([])
%       .CollisionSafetyMargin_deg   extra edge clearance (0)
%       .TimePaddingSamples          collision time padding (0)
%**************************************************************************
% OUTPUTS
%   - smoothPath (scalar struct)
%       Exact line/arc primitives, sampled geometry, corner diagnostics,
%       curvature, and mandatory-stop locations.

defaultOptions = struct( ...
    "TurnRadius_deg", 1.0, ...
    "MinimumTurnRadius_deg", 0.02, ...
    "RadiusBackoffFactor", 0.65, ...
    "MaximumTangentFraction", 0.45, ...
    "SampleSpacing_deg", 0.05, ...
    "CollisionCheckSpacing_deg", 0.02, ...
    "CollisionCheckTimes_s", zeros(0, 1), ...
    "CollisionSafetyMargin_deg", 0, ...
    "TimePaddingSamples", 0, ...
    "PositionTolerance_deg", 1e-9, ...
    "StraightAngleTolerance_rad", 1e-6);
if nargin == 0
    smoothPath = defaultOptions;
    return;
end
if nargin < 2
    obstacleField = [];
end
if nargin < 3 || isempty(optionOverrides)
    optionOverrides = struct();
end
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("smoothRoundedMotion:InvalidOptions", ...
        "optionOverrides must be a scalar struct.");
end
options = defaultOptions;
overrideNames = fieldnames(optionOverrides);
for overrideIndex = 1:numel(overrideNames)
    optionName = overrideNames{overrideIndex};
    if ~isfield(options, optionName)
        error("smoothRoundedMotion:UnknownOption", ...
            "Unknown option %s.", optionName);
    end
    options.(optionName) = optionOverrides.(optionName);
end

validateattributes(pathPosition_deg, {'numeric'}, ...
    {'real', 'finite', '2d', 'ncols', 2});
if size(pathPosition_deg, 1) < 2
    error("smoothRoundedMotion:TooFewPoints", ...
        "pathPosition_deg must contain at least two points.");
end
validateattributes(options.TurnRadius_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.MinimumTurnRadius_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.RadiusBackoffFactor, {'numeric'}, ...
    {'real', 'finite', 'scalar', '>', 0, '<', 1});
validateattributes(options.MaximumTangentFraction, {'numeric'}, ...
    {'real', 'finite', 'scalar', '>', 0, '<', 0.5});
validateattributes(options.SampleSpacing_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.CollisionCheckSpacing_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.CollisionCheckTimes_s, {'numeric'}, ...
    {'real', 'finite', 'vector'});
validateattributes(options.CollisionSafetyMargin_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'nonnegative'});
validateattributes(options.TimePaddingSamples, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', 'nonnegative'});
validateattributes(options.PositionTolerance_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.StraightAngleTolerance_rad, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
if options.MinimumTurnRadius_deg > options.TurnRadius_deg
    error("smoothRoundedMotion:RadiusOrder", ...
        "MinimumTurnRadius_deg cannot exceed TurnRadius_deg.");
end
if ~isempty(obstacleField) && ...
        (~isstruct(obstacleField) || ~isscalar(obstacleField))
    error("smoothRoundedMotion:InvalidObstacleField", ...
        "obstacleField must be a scalar packed field or empty.");
end

%% Section 1: Normalize The Polyline & Fit Each Corner
pathPosition_deg = double(pathPosition_deg);
pathStep_deg = diff(pathPosition_deg, 1, 1);
keepPoint = [true; hypot(pathStep_deg(:, 1), pathStep_deg(:, 2)) > ...
    options.PositionTolerance_deg];
pathPosition_deg = pathPosition_deg(keepPoint, :);
if size(pathPosition_deg, 1) < 2
    error("smoothRoundedMotion:ZeroLengthPath", ...
        "The path has no nonzero-length edge.");
end

pointCount = size(pathPosition_deg, 1);
cornerCount = max(0, pointCount - 2);
cornerTemplate = struct( ...
    "PathPointIndex", 0, ...
    "Position_deg", zeros(1, 2), ...
    "DeflectionAngle_rad", 0, ...
    "TurnSign", 0, ...
    "RequestedRadius_deg", options.TurnRadius_deg, ...
    "AppliedRadius_deg", 0, ...
    "EntryPosition_deg", zeros(1, 2), ...
    "ExitPosition_deg", zeros(1, 2), ...
    "Center_deg", [NaN NaN], ...
    "StartAngle_rad", NaN, ...
    "SweepAngle_rad", 0, ...
    "Smoothed", false, ...
    "MandatoryStop", false, ...
    "Reason", "");
cornerDiagnostics = repmat(cornerTemplate, cornerCount, 1);

for cornerNumber = 1:cornerCount
    pointIndex = cornerNumber + 1;
    previousPoint_deg = pathPosition_deg(pointIndex - 1, :);
    cornerPoint_deg = pathPosition_deg(pointIndex, :);
    nextPoint_deg = pathPosition_deg(pointIndex + 1, :);
    incomingVector_deg = cornerPoint_deg - previousPoint_deg;
    outgoingVector_deg = nextPoint_deg - cornerPoint_deg;
    incomingLength_deg = norm(incomingVector_deg);
    outgoingLength_deg = norm(outgoingVector_deg);
    incomingDirection = incomingVector_deg / incomingLength_deg;
    outgoingDirection = outgoingVector_deg / outgoingLength_deg;
    directionDot = min(1, max(-1, dot( ...
        incomingDirection, outgoingDirection)));
    deflectionAngle_rad = acos(directionDot);
    turnCross = incomingDirection(1) * outgoingDirection(2) - ...
        incomingDirection(2) * outgoingDirection(1);
    turnSign = sign(turnCross);

    diagnostic = cornerTemplate;
    diagnostic.PathPointIndex = pointIndex;
    diagnostic.Position_deg = cornerPoint_deg;
    diagnostic.DeflectionAngle_rad = deflectionAngle_rad;
    diagnostic.TurnSign = turnSign;
    diagnostic.EntryPosition_deg = cornerPoint_deg;
    diagnostic.ExitPosition_deg = cornerPoint_deg;

    if deflectionAngle_rad <= options.StraightAngleTolerance_rad
        diagnostic.Reason = "collinear";
        cornerDiagnostics(cornerNumber) = diagnostic;
        continue;
    end
    if pi - deflectionAngle_rad <= options.StraightAngleTolerance_rad || ...
            turnSign == 0
        diagnostic.MandatoryStop = true;
        diagnostic.Reason = "reversal";
        cornerDiagnostics(cornerNumber) = diagnostic;
        continue;
    end

    tangentScale = tan(0.5 * deflectionAngle_rad);
    maximumTangentDistance_deg = options.MaximumTangentFraction * ...
        min(incomingLength_deg, outgoingLength_deg);
    maximumRadius_deg = maximumTangentDistance_deg / tangentScale;
    requestedRadius_deg = min(options.TurnRadius_deg, maximumRadius_deg);
    if requestedRadius_deg < options.MinimumTurnRadius_deg
        diagnostic.MandatoryStop = true;
        diagnostic.Reason = "adjacent edges are too short";
        cornerDiagnostics(cornerNumber) = diagnostic;
        continue;
    end

    trialRadii_deg = requestedRadius_deg * ...
        options.RadiusBackoffFactor .^ (0:60);
    trialRadii_deg = trialRadii_deg( ...
        trialRadii_deg >= options.MinimumTurnRadius_deg);
    if isempty(trialRadii_deg) || ...
            trialRadii_deg(end) > options.MinimumTurnRadius_deg * (1 + eps)
        trialRadii_deg(end + 1) = ...
            options.MinimumTurnRadius_deg; %#ok<AGROW>
    end
    filletAccepted = false;
    for trialIndex = 1:numel(trialRadii_deg)
        radius_deg = trialRadii_deg(trialIndex);
        tangentDistance_deg = radius_deg * tangentScale;
        entryPosition_deg = cornerPoint_deg - ...
            tangentDistance_deg * incomingDirection;
        exitPosition_deg = cornerPoint_deg + ...
            tangentDistance_deg * outgoingDirection;
        turnNormal = turnSign * ...
            [-incomingDirection(2), incomingDirection(1)];
        center_deg = entryPosition_deg + radius_deg * turnNormal;
        startAngle_rad = atan2( ...
            entryPosition_deg(2) - center_deg(2), ...
            entryPosition_deg(1) - center_deg(1));
        arcLength_deg = radius_deg * deflectionAngle_rad;
        checkCount = max(5, ceil( ...
            arcLength_deg / options.CollisionCheckSpacing_deg) + 1);
        checkS_deg = linspace(0, arcLength_deg, checkCount).';
        checkAngle_rad = startAngle_rad + ...
            turnSign * checkS_deg / radius_deg;
        checkPosition_deg = center_deg + radius_deg * ...
            [cos(checkAngle_rad), sin(checkAngle_rad)];
        if filletCollides(checkPosition_deg, obstacleField, options)
            continue;
        end
        diagnostic.AppliedRadius_deg = radius_deg;
        diagnostic.EntryPosition_deg = entryPosition_deg;
        diagnostic.ExitPosition_deg = exitPosition_deg;
        diagnostic.Center_deg = center_deg;
        diagnostic.StartAngle_rad = startAngle_rad;
        diagnostic.SweepAngle_rad = turnSign * deflectionAngle_rad;
        diagnostic.Smoothed = true;
        diagnostic.Reason = "collision-free fillet";
        filletAccepted = true;
        break;
    end
    if ~filletAccepted
        diagnostic.MandatoryStop = true;
        diagnostic.Reason = "no collision-free fillet radius";
    end
    cornerDiagnostics(cornerNumber) = diagnostic;
end

%% Section 2: Assemble Exact Line/Arc Primitives
primitiveTemplate = struct( ...
    "Type", "", ...
    "StartPosition_deg", zeros(1, 2), ...
    "EndPosition_deg", zeros(1, 2), ...
    "Direction", zeros(1, 2), ...
    "Length_deg", 0, ...
    "StartArcLength_deg", 0, ...
    "EndArcLength_deg", 0, ...
    "Center_deg", [NaN NaN], ...
    "Radius_deg", NaN, ...
    "StartAngle_rad", NaN, ...
    "TurnSign", 0, ...
    "CornerPathPointIndex", 0);
primitives = repmat(primitiveTemplate, 0, 1);
mandatoryStopArcLength_deg = zeros(0, 1);
currentPosition_deg = pathPosition_deg(1, :);
currentArcLength_deg = 0;

for cornerNumber = 1:cornerCount
    diagnostic = cornerDiagnostics(cornerNumber);
    [primitives, currentArcLength_deg] = appendLinePrimitive( ...
        primitives, primitiveTemplate, currentPosition_deg, ...
        diagnostic.EntryPosition_deg, currentArcLength_deg, ...
        options.PositionTolerance_deg);
    if diagnostic.Smoothed
        arcPrimitive = primitiveTemplate;
        arcPrimitive.Type = "arc";
        arcPrimitive.StartPosition_deg = diagnostic.EntryPosition_deg;
        arcPrimitive.EndPosition_deg = diagnostic.ExitPosition_deg;
        arcPrimitive.Direction = zeros(1, 2);
        arcPrimitive.Radius_deg = diagnostic.AppliedRadius_deg;
        arcPrimitive.Center_deg = diagnostic.Center_deg;
        arcPrimitive.StartAngle_rad = diagnostic.StartAngle_rad;
        arcPrimitive.TurnSign = diagnostic.TurnSign;
        arcPrimitive.Length_deg = diagnostic.AppliedRadius_deg * ...
            diagnostic.DeflectionAngle_rad;
        arcPrimitive.StartArcLength_deg = currentArcLength_deg;
        currentArcLength_deg = currentArcLength_deg + ...
            arcPrimitive.Length_deg;
        arcPrimitive.EndArcLength_deg = currentArcLength_deg;
        arcPrimitive.CornerPathPointIndex = diagnostic.PathPointIndex;
        primitives(end + 1, 1) = arcPrimitive; %#ok<AGROW>
        currentPosition_deg = diagnostic.ExitPosition_deg;
    else
        currentPosition_deg = diagnostic.Position_deg;
        if diagnostic.MandatoryStop
            mandatoryStopArcLength_deg(end + 1, 1) = ...
                currentArcLength_deg; %#ok<AGROW>
        end
    end
end
[primitives, currentArcLength_deg] = appendLinePrimitive( ...
    primitives, primitiveTemplate, currentPosition_deg, ...
    pathPosition_deg(end, :), currentArcLength_deg, ...
    options.PositionTolerance_deg);
if isempty(primitives) || currentArcLength_deg <= options.PositionTolerance_deg
    error("smoothRoundedMotion:EmptyCurve", ...
        "Smoothing produced no nonzero-length curve primitives.");
end

%% Section 3: Sample The Curve & Publish Diagnostics
primitiveBoundaryS_deg = [primitives.EndArcLength_deg].';
regularS_deg = (0:options.SampleSpacing_deg:currentArcLength_deg).';
sampleS_deg = unique([0; regularS_deg; primitiveBoundaryS_deg; ...
    mandatoryStopArcLength_deg; currentArcLength_deg]);
curveDefinition = struct( ...
    "Primitives", primitives, ...
    "TotalLength_deg", currentArcLength_deg);
samples = sampleRoundedMotion(curveDefinition, sampleS_deg);
mandatoryStop = false(size(sampleS_deg));
for stopIndex = 1:numel(mandatoryStopArcLength_deg)
    [~, sampleIndex] = min(abs( ...
        sampleS_deg - mandatoryStopArcLength_deg(stopIndex)));
    mandatoryStop(sampleIndex) = true;
end

smoothPath = struct( ...
    "Success", true, ...
    "Message", sprintf( ...
        "Rounded %d of %d geometric corners; %d mandatory stops remain.", ...
        nnz([cornerDiagnostics.Smoothed]), ...
        nnz([cornerDiagnostics.DeflectionAngle_rad] > ...
        options.StraightAngleTolerance_rad), ...
        nnz([cornerDiagnostics.MandatoryStop])), ...
    "OriginalPathPosition_deg", pathPosition_deg, ...
    "Primitives", primitives, ...
    "TotalLength_deg", currentArcLength_deg, ...
    "SampleArcLength_deg", sampleS_deg, ...
    "position_deg", samples.position_deg, ...
    "tangent", samples.tangent, ...
    "secondDerivative_deg_inv", samples.secondDerivative_deg_inv, ...
    "curvature_deg_inv", samples.curvature_deg_inv, ...
    "PrimitiveIndex", samples.PrimitiveIndex, ...
    "PrimitiveType", samples.PrimitiveType, ...
    "MandatoryStop", mandatoryStop, ...
    "MandatoryStopArcLength_deg", mandatoryStopArcLength_deg, ...
    "CornerDiagnostics", cornerDiagnostics, ...
    "RoundedCornerCount", nnz([cornerDiagnostics.Smoothed]), ...
    "MandatoryStopCount", nnz([cornerDiagnostics.MandatoryStop]), ...
    "Options", options);
end

function blocked = filletCollides(position_deg, obstacleField, options)
% Check the complete fillet at every caller-selected obstacle time.
blocked = false;
if isempty(obstacleField) || isempty(options.CollisionCheckTimes_s)
    return;
end
queryOptions = struct( ...
    "CollisionMode", "polygon", ...
    "TimePaddingSamples", options.TimePaddingSamples, ...
    "SafetyMarginDeg", options.CollisionSafetyMargin_deg);
checkTimes_s = options.CollisionCheckTimes_s(:);
for timeIndex = 1:numel(checkTimes_s)
    isOccupied = queryAzElTimeObstacle( ...
        obstacleField, position_deg(:, 1), position_deg(:, 2), ...
        checkTimes_s(timeIndex), queryOptions);
    if any(isOccupied)
        blocked = true;
        return;
    end
end
end

function [primitives, endArcLength_deg] = appendLinePrimitive( ...
        primitives, primitiveTemplate, startPosition_deg, endPosition_deg, ...
        startArcLength_deg, positionTolerance_deg)
% Append one nonzero line with exact cumulative arc-length metadata.
delta_deg = endPosition_deg - startPosition_deg;
length_deg = norm(delta_deg);
endArcLength_deg = startArcLength_deg;
if length_deg <= positionTolerance_deg
    return;
end
linePrimitive = primitiveTemplate;
linePrimitive.Type = "line";
linePrimitive.StartPosition_deg = startPosition_deg;
linePrimitive.EndPosition_deg = endPosition_deg;
linePrimitive.Direction = delta_deg / length_deg;
linePrimitive.Length_deg = length_deg;
linePrimitive.StartArcLength_deg = startArcLength_deg;
endArcLength_deg = startArcLength_deg + length_deg;
linePrimitive.EndArcLength_deg = endArcLength_deg;
primitives(end + 1, 1) = linePrimitive;
end

function samples = sampleRoundedMotion(smoothPath, arcLength_deg)
%% Section 0: Header & Readme
% SYNTAX
%   samples = sampleRoundedMotion(smoothPath, arcLength_deg)
%**************************************************************************
% PURPOSE
%   - Evaluate a piecewise line/circular-arc azimuth/elevation path by arc
%     length.
%   - Return the unit tangent and arc-length second derivative required by
%     a curvature-aware time parameterization.
%**************************************************************************
% INPUTS
%   - smoothPath (scalar struct)
%       Rounded-path structure created by this planner.
%   - arcLength_deg (finite numeric array)
%       Distance along the path in degrees.
%**************************************************************************
% OUTPUTS
%   - samples (scalar struct)
%       position_deg, tangent, secondDerivative_deg_inv,
%       curvature_deg_inv, PrimitiveIndex, and PrimitiveType. Every array
%       follows arcLength_deg(:).

if ~isstruct(smoothPath) || ~isscalar(smoothPath) || ...
        ~isfield(smoothPath, "Primitives") || ...
        ~isfield(smoothPath, "TotalLength_deg")
    error("sampleRoundedMotion:InvalidSmoothPath", ...
        "smoothPath must be produced by the rounded-motion stage.");
end
validateattributes(arcLength_deg, {'numeric'}, {'real', 'finite'});
queryS_deg = double(arcLength_deg(:));
totalLength_deg = double(smoothPath.TotalLength_deg);
coordinateTolerance_deg = 1e-10 * max(1, totalLength_deg);
if any(queryS_deg < -coordinateTolerance_deg) || ...
        any(queryS_deg > totalLength_deg + coordinateTolerance_deg)
    error("sampleRoundedMotion:ArcLengthOutsidePath", ...
        "arcLength_deg must remain within [0, TotalLength_deg].");
end
queryS_deg = min(max(queryS_deg, 0), totalLength_deg);

queryCount = numel(queryS_deg);
position_deg = zeros(queryCount, 2);
tangent = zeros(queryCount, 2);
secondDerivative_deg_inv = zeros(queryCount, 2);
primitiveIndex = zeros(queryCount, 1);
primitiveType = strings(queryCount, 1);
primitives = smoothPath.Primitives;
primitiveCount = numel(primitives);

for currentPrimitiveIndex = 1:primitiveCount
    primitive = primitives(currentPrimitiveIndex);
    if currentPrimitiveIndex < primitiveCount
        belongsToPrimitive = queryS_deg >= ...
            primitive.StartArcLength_deg - coordinateTolerance_deg & ...
            queryS_deg < primitive.EndArcLength_deg - ...
            coordinateTolerance_deg;
    else
        belongsToPrimitive = queryS_deg >= ...
            primitive.StartArcLength_deg - coordinateTolerance_deg & ...
            queryS_deg <= primitive.EndArcLength_deg + ...
            coordinateTolerance_deg;
    end
    % At a shared primitive endpoint, assign the sample to the following
    % primitive. Its tangent is identical for a rounded join, while its
    % curvature correctly activates at a line-to-arc transition.
    belongsToPrimitive = belongsToPrimitive & primitiveIndex == 0;
    if ~any(belongsToPrimitive)
        continue;
    end
    localS_deg = queryS_deg(belongsToPrimitive) - ...
        primitive.StartArcLength_deg;
    localS_deg = min(max(localS_deg, 0), primitive.Length_deg);
    if primitive.Type == "line"
        position_deg(belongsToPrimitive, :) = ...
            primitive.StartPosition_deg + ...
            localS_deg .* primitive.Direction;
        tangent(belongsToPrimitive, :) = repmat( ...
            primitive.Direction, nnz(belongsToPrimitive), 1);
    else
        angle_rad = primitive.StartAngle_rad + ...
            primitive.TurnSign * localS_deg / primitive.Radius_deg;
        radialDirection = [cos(angle_rad), sin(angle_rad)];
        position_deg(belongsToPrimitive, :) = ...
            primitive.Center_deg + primitive.Radius_deg * radialDirection;
        tangent(belongsToPrimitive, :) = primitive.TurnSign * ...
            [-sin(angle_rad), cos(angle_rad)];
        secondDerivative_deg_inv(belongsToPrimitive, :) = ...
            -radialDirection / primitive.Radius_deg;
    end
    primitiveIndex(belongsToPrimitive) = currentPrimitiveIndex;
    primitiveType(belongsToPrimitive) = primitive.Type;
end

if any(primitiveIndex == 0)
    error("sampleRoundedMotion:PrimitiveCoverage", ...
        "The smooth-path primitives do not cover the requested arc lengths.");
end

samples = struct( ...
    "arcLength_deg", queryS_deg, ...
    "position_deg", position_deg, ...
    "tangent", tangent, ...
    "secondDerivative_deg_inv", secondDerivative_deg_inv, ...
    "curvature_deg_inv", hypot( ...
        secondDerivative_deg_inv(:, 1), ...
        secondDerivative_deg_inv(:, 2)), ...
    "PrimitiveIndex", primitiveIndex, ...
    "PrimitiveType", primitiveType);
end

function timedSlopePath = retimeRoundedMotion( ...
        smoothPath, initialState, goalState, limits, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = retimeRoundedMotion()
%   timedSlopePath = retimeRoundedMotion( ...
%       smoothPath, initialState, goalState, limits)
%   timedSlopePath = retimeRoundedMotion( ...
%       smoothPath, initialState, goalState, limits, options)
%**************************************************************************
% PURPOSE
%   - Carry velocity through tangent-continuous line/arc joins while
%     respecting independent azimuth/elevation velocity and acceleration
%     limits.
%   - Apply a conservative global forward/backward pass to squared path
%     speed. The acceleration model includes both tangential acceleration
%     and curvature acceleration:
%           qDDot = qPrime * sDDot + qDoublePrime * sDot^2.
%   - Preserve explicit mandatory stops where the smoother could not fit a
%     collision-free fillet.
%**************************************************************************
% INPUTS
%   - smoothPath (scalar struct)
%       Rounded-path structure created by this planner.
%   - initialState, goalState (scalar structs)
%       time_s, position_deg, velocity_deg_s, and optional
%       acceleration_deg_s2. Endpoint acceleration must currently be zero.
%   - limits (scalar struct)
%       .maxVelocity_deg_s      positive scalar or 1-by-2 vector
%       .maxAcceleration_deg_s2 positive scalar or 1-by-2 vector; optional
%   - options (scalar struct, optional)
%       .GoalTimeMode                 earliestArrival or fixedArrival
%       .SampleTime_s                 maximum nominal output spacing (0.05)
%       .SpatialStep_deg              retiming grid spacing (0.025)
%       .NormalAccelerationFraction   curvature allocation (0.80)
%       .AccelerationSafetyFactor     grid conservatism (0.95)
%**************************************************************************
% OUTPUTS
%   - timedSlopePath (scalar struct)
%       Compatible timed-path fields plus SmoothPath, CurveArcLength_deg,
%       CurveSpeed_deg_s, CurveTangentialAcceleration_deg_s2, and
%       curvature-aware diagnostics.

defaultOptions = struct( ...
    "GoalTimeMode", "earliestArrival", ...
    "SampleTime_s", 0.05, ...
    "SpatialStep_deg", 0.025, ...
    "NormalAccelerationFraction", 0.80, ...
    "AccelerationSafetyFactor", 0.95, ...
    "PositionTolerance_deg", 1e-8, ...
    "KinematicTolerance", 1e-9);
if nargin == 0
    timedSlopePath = defaultOptions;
    return;
end
if nargin < 5 || isempty(optionOverrides)
    optionOverrides = struct();
end
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("retimeRoundedMotion:InvalidOptions", ...
        "optionOverrides must be a scalar struct.");
end
options = defaultOptions;
overrideNames = fieldnames(optionOverrides);
for overrideIndex = 1:numel(overrideNames)
    optionName = overrideNames{overrideIndex};
    if ~isfield(options, optionName)
        error("retimeRoundedMotion:UnknownOption", ...
            "Unknown option %s.", optionName);
    end
    options.(optionName) = optionOverrides.(optionName);
end
options.GoalTimeMode = lower(string(options.GoalTimeMode));
if ~isscalar(options.GoalTimeMode) || ...
        ~any(options.GoalTimeMode == ["earliestarrival" "fixedarrival"])
    error("retimeRoundedMotion:InvalidGoalTimeMode", ...
        "GoalTimeMode must be earliestArrival or fixedArrival.");
end
validateattributes(options.SampleTime_s, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.SpatialStep_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.NormalAccelerationFraction, {'numeric'}, ...
    {'real', 'finite', 'scalar', '>', 0, '<', 1});
validateattributes(options.AccelerationSafetyFactor, {'numeric'}, ...
    {'real', 'finite', 'scalar', '>', 0, '<=', 1});
validateattributes(options.PositionTolerance_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.KinematicTolerance, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});

if ~isstruct(smoothPath) || ~isscalar(smoothPath) || ...
        ~isfield(smoothPath, "Primitives") || ...
        ~isfield(smoothPath, "TotalLength_deg") || ...
        ~isfield(smoothPath, "MandatoryStopArcLength_deg")
    error("retimeRoundedMotion:InvalidSmoothPath", ...
        "smoothPath must be produced by the rounded-motion stage.");
end
initialState = normalizedRoundedState(initialState, "initialState");
goalState = normalizedRoundedState(goalState, "goalState");
maxVelocity_deg_s = normalizedRoundedAxisLimit( ...
    limits, "maxVelocity_deg_s", false);
maxAcceleration_deg_s2 = normalizedRoundedAxisLimit( ...
    limits, "maxAcceleration_deg_s2", true);
resolvedLimits = struct( ...
    "maxVelocity_deg_s", maxVelocity_deg_s, ...
    "maxAcceleration_deg_s2", maxAcceleration_deg_s2);
if goalState.time_s <= initialState.time_s
    error("retimeRoundedMotion:InvalidTimeWindow", ...
        "goalState.time_s must be later than initialState.time_s.");
end
if any(abs(initialState.velocity_deg_s) > ...
        maxVelocity_deg_s + options.KinematicTolerance) || ...
        any(abs(goalState.velocity_deg_s) > ...
        maxVelocity_deg_s + options.KinematicTolerance)
    error("retimeRoundedMotion:EndpointVelocityLimit", ...
        "An endpoint velocity exceeds maxVelocity_deg_s.");
end
finiteAccelerationAxis = isfinite(maxAcceleration_deg_s2);
if any(abs(initialState.acceleration_deg_s2(finiteAccelerationAxis)) > ...
        maxAcceleration_deg_s2(finiteAccelerationAxis) + ...
        options.KinematicTolerance) || ...
        any(abs(goalState.acceleration_deg_s2(finiteAccelerationAxis)) > ...
        maxAcceleration_deg_s2(finiteAccelerationAxis) + ...
        options.KinematicTolerance)
    error("retimeRoundedMotion:EndpointAccelerationLimit", ...
        "An endpoint acceleration exceeds maxAcceleration_deg_s2.");
end
if norm(initialState.acceleration_deg_s2) > ...
        options.KinematicTolerance || ...
        norm(goalState.acceleration_deg_s2) > options.KinematicTolerance
    error("retimeRoundedMotion:NonzeroEndpointAcceleration", ...
        "This retimer currently requires zero endpoint acceleration.");
end

%% Section 1: Discretize Arc Length & Resolve Local Speed Ceilings
totalLength_deg = double(smoothPath.TotalLength_deg);
primitiveBoundaryS_deg = [smoothPath.Primitives.EndArcLength_deg].';
regularS_deg = (0:options.SpatialStep_deg:totalLength_deg).';
curveArcLength_deg = unique([0; regularS_deg; primitiveBoundaryS_deg; ...
    smoothPath.MandatoryStopArcLength_deg(:); totalLength_deg]);
curveSamples = sampleRoundedMotion(smoothPath, curveArcLength_deg);
positionTolerance_deg = options.PositionTolerance_deg;
if norm(curveSamples.position_deg(1, :) - ...
        initialState.position_deg) > positionTolerance_deg
    error("retimeRoundedMotion:InitialPositionMismatch", ...
        "The smooth path must start at initialState.position_deg.");
end
if norm(curveSamples.position_deg(end, :) - ...
        goalState.position_deg) > positionTolerance_deg
    error("retimeRoundedMotion:GoalPositionMismatch", ...
        "The smooth path must end at goalState.position_deg.");
end

initialSpeed_deg_s = roundedBoundaryScalarSpeed( ...
    initialState.velocity_deg_s, curveSamples.tangent(1, :), ...
    "initialState.velocity_deg_s", options.KinematicTolerance);
goalSpeed_deg_s = roundedBoundaryScalarSpeed( ...
    goalState.velocity_deg_s, curveSamples.tangent(end, :), ...
    "goalState.velocity_deg_s", options.KinematicTolerance);
nodeCount = numel(curveArcLength_deg);
maximumSpeedSquared_deg2_s2 = inf(nodeCount, 1);
for axisIndex = 1:2
    tangentMagnitude = abs(curveSamples.tangent(:, axisIndex));
    activeTangent = tangentMagnitude > 1e-12;
    axisVelocityCeilingSquared = inf(nodeCount, 1);
    axisVelocityCeilingSquared(activeTangent) = ( ...
        maxVelocity_deg_s(axisIndex) ./ ...
        tangentMagnitude(activeTangent)).^2;
    maximumSpeedSquared_deg2_s2 = min( ...
        maximumSpeedSquared_deg2_s2, axisVelocityCeilingSquared);

    curvatureMagnitude = abs( ...
        curveSamples.secondDerivative_deg_inv(:, axisIndex));
    activeCurvature = curvatureMagnitude > 1e-12 & ...
        isfinite(maxAcceleration_deg_s2(axisIndex));
    axisCurvatureCeilingSquared = inf(nodeCount, 1);
    axisCurvatureCeilingSquared(activeCurvature) = ...
        options.NormalAccelerationFraction * ...
        maxAcceleration_deg_s2(axisIndex) ./ ...
        curvatureMagnitude(activeCurvature);
    maximumSpeedSquared_deg2_s2 = min( ...
        maximumSpeedSquared_deg2_s2, axisCurvatureCeilingSquared);
end

mandatoryStop = false(nodeCount, 1);
for stopIndex = 1:numel(smoothPath.MandatoryStopArcLength_deg)
    [stopError_deg, nodeIndex] = min(abs(curveArcLength_deg - ...
        smoothPath.MandatoryStopArcLength_deg(stopIndex)));
    if stopError_deg <= options.PositionTolerance_deg
        mandatoryStop(nodeIndex) = true;
    end
end
maximumSpeedSquared_deg2_s2(mandatoryStop) = 0;
startSpeedSquared_deg2_s2 = initialSpeed_deg_s^2;
goalSpeedSquared_deg2_s2 = goalSpeed_deg_s^2;
speedSquaredTolerance = options.KinematicTolerance * max( ...
    1, max(maxVelocity_deg_s)^2);
if startSpeedSquared_deg2_s2 > ...
        maximumSpeedSquared_deg2_s2(1) + speedSquaredTolerance || ...
        goalSpeedSquared_deg2_s2 > ...
        maximumSpeedSquared_deg2_s2(end) + speedSquaredTolerance
    timedSlopePath = failedRoundedPath( ...
        "An endpoint speed exceeds the curve-local velocity or curvature limit.", ...
        resolvedLimits, options, smoothPath);
    return;
end

% Reserve the normal-acceleration share at every node before calculating a
% scalar tangential-acceleration ceiling. The triangle inequality then
% guarantees each per-axis total acceleration remains within its limit.
maximumTangentialAcceleration_deg_s2 = inf(nodeCount, 1);
for axisIndex = 1:2
    tangentMagnitude = abs(curveSamples.tangent(:, axisIndex));
    activeTangent = tangentMagnitude > 1e-12;
    if ~isfinite(maxAcceleration_deg_s2(axisIndex))
        continue;
    end
    normalAccelerationBudget_deg_s2 = abs( ...
        curveSamples.secondDerivative_deg_inv(:, axisIndex)) .* ...
        maximumSpeedSquared_deg2_s2;
    availableAxisAcceleration_deg_s2 = max(0, ...
        maxAcceleration_deg_s2(axisIndex) - ...
        normalAccelerationBudget_deg_s2);
    axisTangentialCeiling_deg_s2 = inf(nodeCount, 1);
    axisTangentialCeiling_deg_s2(activeTangent) = ...
        availableAxisAcceleration_deg_s2(activeTangent) ./ ...
        tangentMagnitude(activeTangent);
    maximumTangentialAcceleration_deg_s2 = min( ...
        maximumTangentialAcceleration_deg_s2, ...
        axisTangentialCeiling_deg_s2);
end
maximumTangentialAcceleration_deg_s2 = ...
    options.AccelerationSafetyFactor * ...
    maximumTangentialAcceleration_deg_s2;
segmentLength_deg = diff(curveArcLength_deg);
segmentTangentialAccelerationLimit_deg_s2 = min( ...
    maximumTangentialAcceleration_deg_s2(1:end - 1), ...
    maximumTangentialAcceleration_deg_s2(2:end));

%% Section 2: Forward/Backward Reachability Pass On Squared Speed
curveSpeedSquared_deg2_s2 = maximumSpeedSquared_deg2_s2;
curveSpeedSquared_deg2_s2(1) = startSpeedSquared_deg2_s2;
for segmentIndex = 1:nodeCount - 1
    reachableSpeedSquared = curveSpeedSquared_deg2_s2(segmentIndex) + ...
        2 * segmentTangentialAccelerationLimit_deg_s2(segmentIndex) * ...
        segmentLength_deg(segmentIndex);
    curveSpeedSquared_deg2_s2(segmentIndex + 1) = min( ...
        curveSpeedSquared_deg2_s2(segmentIndex + 1), ...
        reachableSpeedSquared);
end
if goalSpeedSquared_deg2_s2 > ...
        curveSpeedSquared_deg2_s2(end) + speedSquaredTolerance
    timedSlopePath = failedRoundedPath( ...
        "The requested goal velocity is not forward-reachable.", ...
        resolvedLimits, options, smoothPath);
    return;
end
curveSpeedSquared_deg2_s2(end) = goalSpeedSquared_deg2_s2;
for segmentIndex = nodeCount - 1:-1:1
    stoppableSpeedSquared = curveSpeedSquared_deg2_s2(segmentIndex + 1) + ...
        2 * segmentTangentialAccelerationLimit_deg_s2(segmentIndex) * ...
        segmentLength_deg(segmentIndex);
    curveSpeedSquared_deg2_s2(segmentIndex) = min( ...
        curveSpeedSquared_deg2_s2(segmentIndex), stoppableSpeedSquared);
end
if curveSpeedSquared_deg2_s2(1) < ...
        startSpeedSquared_deg2_s2 - speedSquaredTolerance
    timedSlopePath = failedRoundedPath( ...
        "The requested initial velocity cannot decelerate along the curve.", ...
        resolvedLimits, options, smoothPath);
    return;
end
curveSpeedSquared_deg2_s2(1) = startSpeedSquared_deg2_s2;
curveSpeedSquared_deg2_s2 = max(0, curveSpeedSquared_deg2_s2);
curveSpeed_deg_s = sqrt(curveSpeedSquared_deg2_s2);
curveTangentialAcceleration_deg_s2 = diff( ...
    curveSpeedSquared_deg2_s2) ./ (2 * segmentLength_deg);
segmentDuration_s = 2 * segmentLength_deg ./ ...
    (curveSpeed_deg_s(1:end - 1) + curveSpeed_deg_s(2:end));
if any(~isfinite(segmentDuration_s))
    timedSlopePath = failedRoundedPath( ...
        "Two adjacent zero-speed nodes make a curve interval infeasible.", ...
        resolvedLimits, options, smoothPath);
    return;
end

minimumMotionDuration_s = sum(segmentDuration_s);
minimumArrivalTime_s = initialState.time_s + minimumMotionDuration_s;
timeTolerance_s = options.KinematicTolerance * max( ...
    1, abs(goalState.time_s));
if minimumArrivalTime_s > goalState.time_s + timeTolerance_s
    timedSlopePath = failedRoundedPath(sprintf( ...
        "Earliest feasible arrival %.9g s exceeds goal time %.9g s.", ...
        minimumArrivalTime_s, goalState.time_s), ...
        resolvedLimits, options, smoothPath);
    return;
end
waitDuration_s = 0;
if options.GoalTimeMode == "fixedarrival"
    waitDuration_s = max(0, goalState.time_s - minimumArrivalTime_s);
    if waitDuration_s > timeTolerance_s && ...
            norm(initialState.velocity_deg_s) > options.KinematicTolerance
        timedSlopePath = failedRoundedPath( ...
            "fixedArrival needs a start hold, but initial velocity is nonzero.", ...
            resolvedLimits, options, smoothPath);
        return;
    end
end
motionStartTime_s = initialState.time_s + waitDuration_s;
curveNodeTime_s = motionStartTime_s + ...
    [0; cumsum(segmentDuration_s)];
goalLineInterceptTime_s = curveNodeTime_s(end);

%% Section 3: Sample The Piecewise-Constant Tangential Acceleration
regularTime_s = (initialState.time_s:options.SampleTime_s: ...
    goalLineInterceptTime_s).';
time_s = unique([initialState.time_s; regularTime_s; motionStartTime_s; ...
    curveNodeTime_s; goalLineInterceptTime_s]);
sampleCount = numel(time_s);
sampleArcLength_deg = zeros(sampleCount, 1);
sampleSpeed_deg_s = zeros(sampleCount, 1);
sampleTangentialAcceleration_deg_s2 = zeros(sampleCount, 1);
duringMotion = time_s >= motionStartTime_s - timeTolerance_s;

for segmentIndex = 1:nodeCount - 1
    if segmentIndex < nodeCount - 1
        belongsToSegment = duringMotion & ...
            time_s >= curveNodeTime_s(segmentIndex) - timeTolerance_s & ...
            time_s < curveNodeTime_s(segmentIndex + 1) - timeTolerance_s;
    else
        belongsToSegment = duringMotion & ...
            time_s >= curveNodeTime_s(segmentIndex) - timeTolerance_s & ...
            time_s <= curveNodeTime_s(segmentIndex + 1) + timeTolerance_s;
    end
    if ~any(belongsToSegment)
        continue;
    end
    localTime_s = time_s(belongsToSegment) - ...
        curveNodeTime_s(segmentIndex);
    startSpeed_deg_s = curveSpeed_deg_s(segmentIndex);
    tangentialAcceleration_deg_s2 = ...
        curveTangentialAcceleration_deg_s2(segmentIndex);
    localDistance_deg = startSpeed_deg_s * localTime_s + ...
        0.5 * tangentialAcceleration_deg_s2 * localTime_s.^2;
    localDistance_deg = min(max(localDistance_deg, 0), ...
        segmentLength_deg(segmentIndex));
    sampleArcLength_deg(belongsToSegment) = ...
        curveArcLength_deg(segmentIndex) + localDistance_deg;
    sampleSpeed_deg_s(belongsToSegment) = max(0, ...
        startSpeed_deg_s + tangentialAcceleration_deg_s2 * localTime_s);
    sampleTangentialAcceleration_deg_s2(belongsToSegment) = ...
        tangentialAcceleration_deg_s2;
end
sampleArcLength_deg(~duringMotion) = 0;
sampleSpeed_deg_s(~duringMotion) = 0;
sampleTangentialAcceleration_deg_s2(~duringMotion) = 0;
sampleArcLength_deg(end) = totalLength_deg;
sampleSpeed_deg_s(end) = goalSpeed_deg_s;

timedCurveSamples = sampleRoundedMotion( ...
    smoothPath, sampleArcLength_deg);
position_deg = timedCurveSamples.position_deg;
velocity_deg_s = timedCurveSamples.tangent .* sampleSpeed_deg_s;
acceleration_deg_s2 = timedCurveSamples.tangent .* ...
    sampleTangentialAcceleration_deg_s2 + ...
    timedCurveSamples.secondDerivative_deg_inv .* sampleSpeed_deg_s.^2;
if any(~duringMotion)
    position_deg(~duringMotion, :) = repmat( ...
        initialState.position_deg, nnz(~duringMotion), 1);
    velocity_deg_s(~duringMotion, :) = 0;
    acceleration_deg_s2(~duringMotion, :) = 0;
end
position_deg(1, :) = initialState.position_deg;
velocity_deg_s(1, :) = initialState.velocity_deg_s;
acceleration_deg_s2(1, :) = initialState.acceleration_deg_s2;
position_deg(end, :) = goalState.position_deg;
velocity_deg_s(end, :) = goalState.velocity_deg_s;
acceleration_deg_s2(end, :) = goalState.acceleration_deg_s2;

%% Section 4: Verify Constraints & Assemble A Compatible Result
peakVelocity_deg_s = max(abs(velocity_deg_s), [], 1);
peakAcceleration_deg_s2 = max(abs(acceleration_deg_s2), [], 1);
velocityMargin_deg_s = maxVelocity_deg_s - peakVelocity_deg_s;
accelerationMargin_deg_s2 = ...
    maxAcceleration_deg_s2 - peakAcceleration_deg_s2;
velocitySatisfied = all(velocityMargin_deg_s >= ...
    -options.KinematicTolerance);
accelerationSatisfied = all(accelerationMargin_deg_s2 >= ...
    -options.KinematicTolerance);
constraintsSatisfied = velocitySatisfied && accelerationSatisfied;
onRoundedArc = timedCurveSamples.PrimitiveType == "arc" & duringMotion;
minimumArcSpeed_deg_s = NaN;
if any(onRoundedArc)
    minimumArcSpeed_deg_s = min(sampleSpeed_deg_s(onRoundedArc));
end
constraintDiagnostics = struct( ...
    "PeakVelocity_deg_s", peakVelocity_deg_s, ...
    "PeakAcceleration_deg_s2", peakAcceleration_deg_s2, ...
    "VelocityMargin_deg_s", velocityMargin_deg_s, ...
    "AccelerationMargin_deg_s2", accelerationMargin_deg_s2, ...
    "VelocitySatisfied", velocitySatisfied, ...
    "AccelerationSatisfied", accelerationSatisfied, ...
    "Satisfied", constraintsSatisfied, ...
    "MinimumArcSpeed_deg_s", minimumArcSpeed_deg_s, ...
    "RoundedVelocityCarried", isempty(find(onRoundedArc, 1)) || ...
        minimumArcSpeed_deg_s > options.KinematicTolerance, ...
    "NormalAccelerationFraction", options.NormalAccelerationFraction);

segmentTemplate = struct( ...
    "StartArcLength_deg", 0, ...
    "EndArcLength_deg", 0, ...
    "StartSpeed_deg_s", 0, ...
    "EndSpeed_deg_s", 0, ...
    "TangentialAcceleration_deg_s2", 0, ...
    "Duration_s", 0, ...
    "StartTime_s", 0, ...
    "EndTime_s", 0);
segmentProfiles = repmat(segmentTemplate, nodeCount - 1, 1);
for segmentIndex = 1:nodeCount - 1
    segmentProfiles(segmentIndex).StartArcLength_deg = ...
        curveArcLength_deg(segmentIndex);
    segmentProfiles(segmentIndex).EndArcLength_deg = ...
        curveArcLength_deg(segmentIndex + 1);
    segmentProfiles(segmentIndex).StartSpeed_deg_s = ...
        curveSpeed_deg_s(segmentIndex);
    segmentProfiles(segmentIndex).EndSpeed_deg_s = ...
        curveSpeed_deg_s(segmentIndex + 1);
    segmentProfiles(segmentIndex).TangentialAcceleration_deg_s2 = ...
        curveTangentialAcceleration_deg_s2(segmentIndex);
    segmentProfiles(segmentIndex).Duration_s = segmentDuration_s(segmentIndex);
    segmentProfiles(segmentIndex).StartTime_s = curveNodeTime_s(segmentIndex);
    segmentProfiles(segmentIndex).EndTime_s = ...
        curveNodeTime_s(segmentIndex + 1);
end

timedSlopePath = struct( ...
    "Success", constraintsSatisfied, ...
    "Message", "Curvature-aware velocity-carrying retiming succeeded.", ...
    "time_s", time_s, ...
    "position_deg", position_deg, ...
    "velocity_deg_s", velocity_deg_s, ...
    "acceleration_deg_s2", acceleration_deg_s2, ...
    "PathPosition_deg", smoothPath.position_deg, ...
    "WaypointTime_s", curveNodeTime_s, ...
    "MotionStartTime_s", motionStartTime_s, ...
    "WaitDuration_s", waitDuration_s, ...
    "MinimumMotionDuration_s", minimumMotionDuration_s, ...
    "GoalLineInterceptTime_s", goalLineInterceptTime_s, ...
    "SegmentProfiles", segmentProfiles, ...
    "Limits", resolvedLimits, ...
    "Options", options, ...
    "ConstraintDiagnostics", constraintDiagnostics, ...
    "SmoothPath", smoothPath, ...
    "CurveArcLength_deg", curveArcLength_deg, ...
    "CurveNodeTime_s", curveNodeTime_s, ...
    "CurveSpeed_deg_s", curveSpeed_deg_s, ...
    "CurveSpeedSquared_deg2_s2", curveSpeedSquared_deg2_s2, ...
    "CurveTangentialAcceleration_deg_s2", ...
    curveTangentialAcceleration_deg_s2, ...
    "SampleArcLength_deg", sampleArcLength_deg, ...
    "SampleSpeed_deg_s", sampleSpeed_deg_s, ...
    "SampleTangentialAcceleration_deg_s2", ...
    sampleTangentialAcceleration_deg_s2, ...
    "RetimerType", "curvatureAwareForwardBackward");
if ~constraintsSatisfied
    timedSlopePath.Message = ...
        "Internal constraint verification failed after curve sampling.";
end
end

function state = normalizedRoundedState(state, label)
% Normalize one endpoint state to finite scalar/vector values.
requiredFields = ["time_s", "position_deg", "velocity_deg_s"];
if ~isstruct(state) || ~isscalar(state) || ...
        ~all(isfield(state, requiredFields))
    error("retimeRoundedMotion:InvalidState", ...
        "%s must contain time_s, position_deg, and velocity_deg_s.", label);
end
validateattributes(state.time_s, {'numeric'}, ...
    {'real', 'finite', 'scalar'});
validateattributes(state.position_deg, {'numeric'}, ...
    {'real', 'finite', 'vector', 'numel', 2});
validateattributes(state.velocity_deg_s, {'numeric'}, ...
    {'real', 'finite', 'vector', 'numel', 2});
state.time_s = double(state.time_s);
state.position_deg = reshape(double(state.position_deg), 1, 2);
state.velocity_deg_s = reshape(double(state.velocity_deg_s), 1, 2);
if ~isfield(state, "acceleration_deg_s2") || ...
        isempty(state.acceleration_deg_s2)
    state.acceleration_deg_s2 = zeros(1, 2);
else
    validateattributes(state.acceleration_deg_s2, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 2});
    state.acceleration_deg_s2 = reshape( ...
        double(state.acceleration_deg_s2), 1, 2);
end
end

function axisLimit = normalizedRoundedAxisLimit(limits, fieldName, optional)
% Expand one scalar/per-axis limit and validate positivity.
if ~isstruct(limits) || ~isscalar(limits)
    error("retimeRoundedMotion:InvalidLimits", ...
        "limits must be a scalar struct.");
end
if ~isfield(limits, fieldName) || isempty(limits.(fieldName))
    if optional
        axisLimit = [Inf Inf];
        return;
    end
    error("retimeRoundedMotion:MissingLimit", ...
        "limits.%s is required.", fieldName);
end
axisLimit = double(limits.(fieldName));
if isscalar(axisLimit)
    axisLimit = repmat(axisLimit, 1, 2);
elseif isvector(axisLimit) && numel(axisLimit) == 2
    axisLimit = reshape(axisLimit, 1, 2);
else
    error("retimeRoundedMotion:InvalidLimit", ...
        "limits.%s must be a scalar or two-element vector.", fieldName);
end
if any(isnan(axisLimit)) || any(axisLimit <= 0)
    error("retimeRoundedMotion:InvalidLimit", ...
        "limits.%s must contain positive values.", fieldName);
end
end

function scalarSpeed = roundedBoundaryScalarSpeed( ...
        velocity_deg_s, direction, label, tolerance)
% Require an endpoint velocity to point along the curve tangent.
scalarSpeed = dot(velocity_deg_s, direction);
perpendicularVelocity_deg_s = velocity_deg_s - scalarSpeed * direction;
scaledTolerance = tolerance * max(1, norm(velocity_deg_s));
if norm(perpendicularVelocity_deg_s) > scaledTolerance || ...
        scalarSpeed < -scaledTolerance
    error("retimeRoundedMotion:IncompatibleEndpointVelocity", ...
        "%s must point forward along the adjacent curve tangent.", label);
end
scalarSpeed = max(0, scalarSpeed);
end

