function [position_deg, velocity_deg_s, acceleration_deg_s2] = ...
        samplePolylineMinimumTimeProfile(time_s, profile, tolerance)
%% Section 0: Header & Readme
% Evaluate a scalar triangular/trapezoidal profile at arbitrary times.
accelerationTime_s = profile.AccelerationTime_s;
cruiseTime_s = profile.CruiseTime_s;
duration_s = profile.Duration_s;
startSpeed_deg_s = profile.StartSpeed_deg_s;
endSpeed_deg_s = profile.EndSpeed_deg_s;
peakSpeed_deg_s = profile.PeakSpeed_deg_s;
maxAcceleration_deg_s2 = profile.MaxAcceleration_deg_s2;
distance_deg = profile.Length_deg;

position_deg = zeros(size(time_s));
velocity_deg_s = zeros(size(time_s));
acceleration_deg_s2 = zeros(size(time_s));
if isinf(maxAcceleration_deg_s2)
    position_deg = min(distance_deg, peakSpeed_deg_s * time_s);
    velocity_deg_s(:) = peakSpeed_deg_s;
    velocity_deg_s(1) = startSpeed_deg_s;
    velocity_deg_s(end) = endSpeed_deg_s;
    position_deg(end) = distance_deg;
    return;
end

accelerationDistance_deg = startSpeed_deg_s * accelerationTime_s + ...
    0.5 * maxAcceleration_deg_s2 * accelerationTime_s^2;
cruiseDistance_deg = peakSpeed_deg_s * cruiseTime_s;
accelerationPhase = time_s < accelerationTime_s - tolerance;
cruisePhase = ~accelerationPhase & time_s < ...
    accelerationTime_s + cruiseTime_s - tolerance;
decelerationPhase = ~(accelerationPhase | cruisePhase);

phaseTime_s = time_s(accelerationPhase);
position_deg(accelerationPhase) = startSpeed_deg_s * phaseTime_s + ...
    0.5 * maxAcceleration_deg_s2 * phaseTime_s.^2;
velocity_deg_s(accelerationPhase) = startSpeed_deg_s + ...
    maxAcceleration_deg_s2 * phaseTime_s;
acceleration_deg_s2(accelerationPhase) = maxAcceleration_deg_s2;

phaseTime_s = time_s(cruisePhase) - accelerationTime_s;
position_deg(cruisePhase) = accelerationDistance_deg + ...
    peakSpeed_deg_s * phaseTime_s;
velocity_deg_s(cruisePhase) = peakSpeed_deg_s;

phaseTime_s = time_s(decelerationPhase) - ...
    accelerationTime_s - cruiseTime_s;
position_deg(decelerationPhase) = accelerationDistance_deg + ...
    cruiseDistance_deg + peakSpeed_deg_s * phaseTime_s - ...
    0.5 * maxAcceleration_deg_s2 * phaseTime_s.^2;
velocity_deg_s(decelerationPhase) = max(0, ...
    peakSpeed_deg_s - maxAcceleration_deg_s2 * phaseTime_s);
acceleration_deg_s2(decelerationPhase) = -maxAcceleration_deg_s2;

position_deg(time_s <= tolerance) = 0;
position_deg(time_s >= duration_s - tolerance) = distance_deg;
velocity_deg_s(time_s <= tolerance) = startSpeed_deg_s;
velocity_deg_s(time_s >= duration_s - tolerance) = endSpeed_deg_s;
end

