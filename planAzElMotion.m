profiles = repmat(profileTemplate, primitiveCount, 1);
for primitiveIndex = 1:primitiveCount
    primitive = primitives(primitiveIndex);
    startSpeed_deg_s = 0;
    endSpeed_deg_s = 0;
    if primitiveIndex == 1
        startSpeed_deg_s = initialSpeed_deg_s;
    end
    if primitiveIndex == primitiveCount
        endSpeed_deg_s = goalSpeed_deg_s;
    end
    [scalarVelocityLimit_deg_s, scalarAccelerationLimit_deg_s2, ...
        scalarJerkLimit_deg_s3] = primitiveScalarLimits( ...
        primitive, maxVelocity_deg_s, maxAcceleration_deg_s2, ...
        maxJerk_deg_s3);
    [profile, feasible, failureMessage] = jerkMinimumTimeProfile( ...
        primitive.Length_deg, startSpeed_deg_s, endSpeed_deg_s, ...
        scalarVelocityLimit_deg_s, scalarAccelerationLimit_deg_s2, ...
        scalarJerkLimit_deg_s3, options.KinematicTolerance);
    if ~feasible
        timedPath = failedJerkLimitedPath( ...
            "Primitive " + primitiveIndex + ": " + failureMessage, ...
            limits, options, motionType);
        return;
    end
    profile.PrimitiveType = string(primitive.Type);
    profile.StartPosition_deg = primitive.StartPosition_deg;
    profile.EndPosition_deg = primitive.EndPosition_deg;
    profile.Length_deg = primitive.Length_deg;
    profile.StartArcLength_deg = primitive.StartArcLength_deg;
    profile.EndArcLength_deg = primitive.EndArcLength_deg;
    profile.MaxSpeed_deg_s = scalarVelocityLimit_deg_s;
    profile.MaxAcceleration_deg_s2 = scalarAccelerationLimit_deg_s2;
    profile.MaxJerk_deg_s3 = scalarJerkLimit_deg_s3;
    [velocityBound, accelerationBound, jerkBound] = ...
        primitiveKinematicBounds(primitive, profile);
    profile.PeakVelocityByAxis_deg_s = velocityBound;
    profile.PeakAccelerationByAxis_deg_s2 = accelerationBound;
    profile.PeakJerkByAxis_deg_s3 = jerkBound;
    profiles(primitiveIndex) = orderfields(profile, profileTemplate);
end

minimumMotionDuration_s = sum([profiles.Duration_s]);
minimumArrivalTime_s = initialState.time_s + minimumMotionDuration_s;
timeTolerance_s = options.KinematicTolerance * ...
    max(1, abs(goalState.time_s));
if minimumArrivalTime_s > goalState.time_s + timeTolerance_s
    timedPath = failedJerkLimitedPath(sprintf( ...
        "Earliest jerk-limited arrival %.9g s exceeds goal time %.9g s.", ...
        minimumArrivalTime_s, goalState.time_s), ...
        limits, options, motionType);
    return;
end
waitDuration_s = 0;
if options.GoalTimeMode == "fixedarrival"
    waitDuration_s = max(0, goalState.time_s - minimumArrivalTime_s);
    if waitDuration_s > timeTolerance_s && ...
            (norm(initialState.velocity_deg_s) > ...
            options.KinematicTolerance || ...
            norm(initialState.acceleration_deg_s2) > ...
            options.KinematicTolerance)
        timedPath = failedJerkLimitedPath( ...
            "fixedArrival needs a start hold, but the initial velocity " + ...
            "or acceleration is nonzero.", limits, options, motionType);
        return;
    end
end
motionStartTime_s = initialState.time_s + waitDuration_s;
primitiveStartTime_s = motionStartTime_s + ...
    [0, cumsum([profiles(1:end - 1).Duration_s])];
for primitiveIndex = 1:primitiveCount
    profiles(primitiveIndex).StartTime_s = ...
        primitiveStartTime_s(primitiveIndex);
    profiles(primitiveIndex).EndTime_s = ...
        primitiveStartTime_s(primitiveIndex) + ...
        profiles(primitiveIndex).Duration_s;
end

time_s = zeros(0, 1);
position_deg = zeros(0, 2);
velocity_deg_s = zeros(0, 2);
acceleration_deg_s2 = zeros(0, 2);
jerk_deg_s3 = zeros(0, 2);
sampleArcLength_deg = zeros(0, 1);
sampleSpeed_deg_s = zeros(0, 1);
sampleTangentialAcceleration_deg_s2 = zeros(0, 1);
sampleTangentialJerk_deg_s3 = zeros(0, 1);
if waitDuration_s > timeTolerance_s
    waitLocalTime_s = polylineRegularAndEventTimes( ...
        waitDuration_s, options.SampleTime_s, []);
    waitSampleCount = numel(waitLocalTime_s);
    time_s = initialState.time_s + waitLocalTime_s;
    position_deg = repmat(initialState.position_deg, waitSampleCount, 1);
    velocity_deg_s = zeros(waitSampleCount, 2);
    acceleration_deg_s2 = zeros(waitSampleCount, 2);
    jerk_deg_s3 = zeros(waitSampleCount, 2);
    sampleArcLength_deg = zeros(waitSampleCount, 1);
    sampleSpeed_deg_s = zeros(waitSampleCount, 1);
    sampleTangentialAcceleration_deg_s2 = zeros(waitSampleCount, 1);
    sampleTangentialJerk_deg_s3 = zeros(waitSampleCount, 1);
end

for primitiveIndex = 1:primitiveCount
    profile = profiles(primitiveIndex);
    phaseEndTime_s = cumsum(profile.PhaseDuration_s);
    phaseStartTime_s = [0; phaseEndTime_s(1:end - 1)];
    phaseMidTime_s = phaseStartTime_s + 0.5 * profile.PhaseDuration_s;
    eventTime_s = unique([phaseStartTime_s; phaseMidTime_s; ...
        phaseEndTime_s]);
    localTime_s = polylineRegularAndEventTimes( ...
        profile.Duration_s, options.SampleTime_s, eventTime_s);
    [localDistance_deg, scalarVelocity_deg_s, ...
        scalarAcceleration_deg_s2, scalarJerk_deg_s3] = ...
        sampleJerkProfile(localTime_s, profile, ...
        options.KinematicTolerance);
    [primitivePosition_deg, tangent, secondDerivative_deg_inv, ...
        thirdDerivative_deg_inv2] = sampleJerkPrimitive( ...
        primitives(primitiveIndex), localDistance_deg);
    primitiveVelocity_deg_s = tangent .* scalarVelocity_deg_s;
    primitiveAcceleration_deg_s2 = tangent .* ...
        scalarAcceleration_deg_s2 + secondDerivative_deg_inv .* ...
        scalarVelocity_deg_s.^2;
    primitiveJerk_deg_s3 = tangent .* scalarJerk_deg_s3 + ...
        3 * secondDerivative_deg_inv .* scalarVelocity_deg_s .* ...
        scalarAcceleration_deg_s2 + thirdDerivative_deg_inv2 .* ...
        scalarVelocity_deg_s.^3;
    primitiveTime_s = profile.StartTime_s + localTime_s;
    primitiveArcLength_deg = primitive.StartArcLength_deg + ...
        localDistance_deg;
    if ~isempty(time_s) && abs(primitiveTime_s(1) - time_s(end)) <= ...
            timeTolerance_s
        primitiveTime_s(1) = [];
        primitivePosition_deg(1, :) = [];
        primitiveVelocity_deg_s(1, :) = [];
        primitiveAcceleration_deg_s2(1, :) = [];
        primitiveJerk_deg_s3(1, :) = [];
        primitiveArcLength_deg(1) = [];
        scalarVelocity_deg_s(1) = [];
        scalarAcceleration_deg_s2(1) = [];
        scalarJerk_deg_s3(1) = [];
    end
    time_s = [time_s; primitiveTime_s]; %#ok<AGROW>
    position_deg = [position_deg; primitivePosition_deg]; %#ok<AGROW>
    velocity_deg_s = [velocity_deg_s; primitiveVelocity_deg_s]; %#ok<AGROW>
    acceleration_deg_s2 = [acceleration_deg_s2; ...
        primitiveAcceleration_deg_s2]; %#ok<AGROW>
    jerk_deg_s3 = [jerk_deg_s3; primitiveJerk_deg_s3]; %#ok<AGROW>
    sampleArcLength_deg = [sampleArcLength_deg; ...
        primitiveArcLength_deg]; %#ok<AGROW>
    sampleSpeed_deg_s = [sampleSpeed_deg_s; ...
        scalarVelocity_deg_s]; %#ok<AGROW>
    sampleTangentialAcceleration_deg_s2 = [ ...
        sampleTangentialAcceleration_deg_s2; ...
        scalarAcceleration_deg_s2]; %#ok<AGROW>
    sampleTangentialJerk_deg_s3 = [sampleTangentialJerk_deg_s3; ...
        scalarJerk_deg_s3]; %#ok<AGROW>
end

position_deg(1, :) = initialState.position_deg;
velocity_deg_s(1, :) = initialState.velocity_deg_s;
acceleration_deg_s2(1, :) = initialState.acceleration_deg_s2;
jerk_deg_s3(1, :) = [0 0];
position_deg(end, :) = goalState.position_deg;
velocity_deg_s(end, :) = goalState.velocity_deg_s;
acceleration_deg_s2(end, :) = goalState.acceleration_deg_s2;
jerk_deg_s3(end, :) = [0 0];

peakVelocity_deg_s = max(vertcat( ...
    profiles.PeakVelocityByAxis_deg_s), [], 1);
peakAcceleration_deg_s2 = max(vertcat( ...
    profiles.PeakAccelerationByAxis_deg_s2), [], 1);
peakJerk_deg_s3 = max(vertcat( ...
    profiles.PeakJerkByAxis_deg_s3), [], 1);
velocityMargin_deg_s = maxVelocity_deg_s - peakVelocity_deg_s;
accelerationMargin_deg_s2 = ...
    maxAcceleration_deg_s2 - peakAcceleration_deg_s2;
jerkMargin_deg_s3 = maxJerk_deg_s3 - peakJerk_deg_s3;
velocitySatisfied = all(velocityMargin_deg_s >= ...
    -options.KinematicTolerance);
accelerationSatisfied = all(accelerationMargin_deg_s2 >= ...
    -options.KinematicTolerance);
jerkSatisfied = all(jerkMargin_deg_s3 >= ...
    -options.KinematicTolerance);
constraintsSatisfied = velocitySatisfied && accelerationSatisfied && ...
    jerkSatisfied;
curvatureStopCount = 0;
if motionType == "velocityCarrying"
    curvatureStopCount = max(0, primitiveCount - 1);
end
diagnostics = struct( ...
    "PeakVelocity_deg_s", peakVelocity_deg_s, ...
    "PeakAcceleration_deg_s2", peakAcceleration_deg_s2, ...
    "PeakJerk_deg_s3", peakJerk_deg_s3, ...
    "VelocityMargin_deg_s", velocityMargin_deg_s, ...
    "AccelerationMargin_deg_s2", accelerationMargin_deg_s2, ...
    "JerkMargin_deg_s3", jerkMargin_deg_s3, ...
    "VelocitySatisfied", velocitySatisfied, ...
    "AccelerationSatisfied", accelerationSatisfied, ...
    "JerkSatisfied", jerkSatisfied, ...
    "JerkConstrained", true, ...
    "FiniteJerkCertified", constraintsSatisfied, ...
    "ContinuousJerkCertified", false, ...
    "CurvatureDiscontinuityStopCount", curvatureStopCount, ...
    "RoundedVelocityCarried", curvatureStopCount == 0, ...
    "Satisfied", constraintsSatisfied);
primitiveNodeTime_s = [motionStartTime_s; ...
    motionStartTime_s + cumsum([profiles.Duration_s]).'];
timedPath = struct( ...
    "Success", constraintsSatisfied, ...
    "Message", "Velocity-, acceleration-, and jerk-constrained " + ...
        "analytic S-curve retiming succeeded.", ...
    "time_s", time_s, ...
    "position_deg", position_deg, ...
    "velocity_deg_s", velocity_deg_s, ...
    "acceleration_deg_s2", acceleration_deg_s2, ...
    "jerk_deg_s3", jerk_deg_s3, ...
    "PathPosition_deg", pathPosition_deg, ...
    "WaypointTime_s", primitiveNodeTime_s, ...
    "MotionStartTime_s", motionStartTime_s, ...
    "WaitDuration_s", waitDuration_s, ...
    "MinimumMotionDuration_s", minimumMotionDuration_s, ...
    "GoalLineInterceptTime_s", time_s(end), ...
    "SegmentProfiles", profiles, ...
    "Limits", limits, ...
    "Options", options, ...
    "ConstraintDiagnostics", diagnostics, ...
    "CurveArcLength_deg", [0; [primitives.EndArcLength_deg].'], ...
    "CurveNodeTime_s", primitiveNodeTime_s, ...
    "CurveSpeed_deg_s", [initialSpeed_deg_s; ...
        zeros(max(0, primitiveCount - 1), 1); goalSpeed_deg_s], ...
    "CurveSpeedSquared_deg2_s2", [initialSpeed_deg_s; ...
        zeros(max(0, primitiveCount - 1), 1); goalSpeed_deg_s].^2, ...
    "CurveTangentialAcceleration_deg_s2", zeros(primitiveCount + 1, 1), ...
    "CurveTangentialJerk_deg_s3", zeros(primitiveCount + 1, 1), ...
    "SampleArcLength_deg", sampleArcLength_deg, ...
    "SampleSpeed_deg_s", sampleSpeed_deg_s, ...
    "SampleTangentialAcceleration_deg_s2", ...
        sampleTangentialAcceleration_deg_s2, ...
    "SampleTangentialJerk_deg_s3", sampleTangentialJerk_deg_s3, ...
    "CurvatureDiscontinuityStopCount", curvatureStopCount, ...
    "RetimerType", "analyticJerkLimitedSCurve");
if ~constraintsSatisfied
    timedPath.Message = ...
        "Internal jerk-limited constraint verification failed.";
end
end

function [maxSpeed_deg_s, maxAcceleration_deg_s2, maxJerk_deg_s3] = ...
        primitiveScalarLimits(primitive, velocityLimit_deg_s, ...
        accelerationLimit_deg_s2, jerkLimit_deg_s3)
%% Section 0: Header & Readme
% Allocate conservative scalar budgets for one line or circular arc.
if string(primitive.Type) == "line"
    direction = primitive.Direction;
    maxSpeed_deg_s = polylineDirectionalLimit( ...
        velocityLimit_deg_s, direction);
    maxAcceleration_deg_s2 = polylineDirectionalLimit( ...
        accelerationLimit_deg_s2, direction);
    maxJerk_deg_s3 = polylineDirectionalLimit( ...
        jerkLimit_deg_s3, direction);
    finiteAxisJerk_deg_s3 = jerkLimit_deg_s3( ...
        isfinite(jerkLimit_deg_s3));
    if ~isempty(finiteAxisJerk_deg_s3)
        % Capping by the smallest active axis constraint is conservative
        % and avoids ill-conditioned scalar jerk when a constrained axis
        % has only a numerically tiny component along this line.
        maxJerk_deg_s3 = min(maxJerk_deg_s3, ...
            min(finiteAxisJerk_deg_s3));
    end
    return;
end
radius_deg = primitive.Radius_deg;
maxSpeed_deg_s = min(velocityLimit_deg_s);
minimumAcceleration_deg_s2 = min(accelerationLimit_deg_s2);
minimumJerk_deg_s3 = min(jerkLimit_deg_s3);
if isfinite(minimumAcceleration_deg_s2)
    maxAcceleration_deg_s2 = 0.45 * minimumAcceleration_deg_s2;
    maxSpeed_deg_s = min(maxSpeed_deg_s, sqrt( ...
        0.45 * minimumAcceleration_deg_s2 * radius_deg));
else
    maxAcceleration_deg_s2 = Inf;
end
maxJerk_deg_s3 = minimumJerk_deg_s3 / 3;
maxSpeed_deg_s = min(maxSpeed_deg_s, nthroot( ...
    minimumJerk_deg_s3 * radius_deg^2 / 3, 3));
if isfinite(maxAcceleration_deg_s2)
    maxSpeed_deg_s = min(maxSpeed_deg_s, ...
        minimumJerk_deg_s3 * radius_deg / ...
        (9 * maxAcceleration_deg_s2));
else
    maxAcceleration_deg_s2 = minimumJerk_deg_s3 * radius_deg / ...
        (9 * max(maxSpeed_deg_s, eps));
end
end

function [profile, feasible, message] = jerkMinimumTimeProfile( ...
        distance_deg, startSpeed_deg_s, endSpeed_deg_s, ...
        maxSpeed_deg_s, maxAcceleration_deg_s2, maxJerk_deg_s3, tolerance)
%% Section 0: Header & Readme
% Solve one minimum-time zero-boundary-acceleration S-curve profile.
profile = struct( ...
    "PrimitiveType", "", ...
    "StartPosition_deg", zeros(1, 2), ...
    "EndPosition_deg", zeros(1, 2), ...
    "Length_deg", distance_deg, ...
    "StartArcLength_deg", 0, ...
    "EndArcLength_deg", distance_deg, ...
    "StartSpeed_deg_s", startSpeed_deg_s, ...
    "EndSpeed_deg_s", endSpeed_deg_s, ...
    "MaxSpeed_deg_s", maxSpeed_deg_s, ...
    "MaxAcceleration_deg_s2", maxAcceleration_deg_s2, ...
    "MaxJerk_deg_s3", maxJerk_deg_s3, ...
    "PeakSpeed_deg_s", NaN, ...
    "PeakAcceleration_deg_s2", NaN, ...
    "PeakJerk_deg_s3", NaN, ...
    "PeakVelocityByAxis_deg_s", zeros(1, 2), ...
    "PeakAccelerationByAxis_deg_s2", zeros(1, 2), ...
    "PeakJerkByAxis_deg_s3", zeros(1, 2), ...
    "PhaseDuration_s", zeros(0, 1), ...
    "PhaseJerk_deg_s3", zeros(0, 1), ...
    "PhaseStartTime_s", zeros(0, 1), ...
    "PhaseStartPosition_deg", zeros(0, 1), ...
    "PhaseStartSpeed_deg_s", zeros(0, 1), ...
    "PhaseStartAcceleration_deg_s2", zeros(0, 1), ...
    "CruiseTime_s", 0, ...
    "Duration_s", NaN, ...
    "StartTime_s", NaN, ...
    "EndTime_s", NaN, ...
    "TangentialAcceleration_deg_s2", 0);
feasible = false;
message = "";
speedTolerance = tolerance * max(1, maxSpeed_deg_s);
if startSpeed_deg_s > maxSpeed_deg_s + speedTolerance || ...
        endSpeed_deg_s > maxSpeed_deg_s + speedTolerance
    message = "An endpoint speed exceeds the primitive speed limit.";
    return;
end
if ~isfinite(maxJerk_deg_s3) || maxJerk_deg_s3 <= 0
    message = "A finite positive directional jerk limit is required.";
    return;
end
lowerPeakSpeed_deg_s = max(startSpeed_deg_s, endSpeed_deg_s);
minimumDistance_deg = jerkTransitionDistance( ...
    startSpeed_deg_s, endSpeed_deg_s, ...
    maxAcceleration_deg_s2, maxJerk_deg_s3);
distanceTolerance_deg = tolerance * max(1, distance_deg);
if distance_deg < minimumDistance_deg - distanceTolerance_deg
    message = "The primitive is too short for its endpoint-speed " + ...
        "transition within the acceleration and jerk limits.";
    return;
end
distanceAtSpeedLimit_deg = jerkTransitionDistance( ...
    startSpeed_deg_s, maxSpeed_deg_s, ...
    maxAcceleration_deg_s2, maxJerk_deg_s3) + ...
    jerkTransitionDistance(maxSpeed_deg_s, endSpeed_deg_s, ...
    maxAcceleration_deg_s2, maxJerk_deg_s3);
if distanceAtSpeedLimit_deg <= distance_deg + distanceTolerance_deg
    peakSpeed_deg_s = maxSpeed_deg_s;
    cruiseDistance_deg = max(0, distance_deg - distanceAtSpeedLimit_deg);
    cruiseTime_s = cruiseDistance_deg / max(peakSpeed_deg_s, eps);
else
    lowerSpeed_deg_s = lowerPeakSpeed_deg_s;
    upperSpeed_deg_s = maxSpeed_deg_s;
    for iteration = 1:80
        middleSpeed_deg_s = 0.5 * ...
            (lowerSpeed_deg_s + upperSpeed_deg_s);
        middleDistance_deg = jerkTransitionDistance( ...
            startSpeed_deg_s, middleSpeed_deg_s, ...
            maxAcceleration_deg_s2, maxJerk_deg_s3) + ...
            jerkTransitionDistance(middleSpeed_deg_s, endSpeed_deg_s, ...
            maxAcceleration_deg_s2, maxJerk_deg_s3);
        if middleDistance_deg <= distance_deg
            lowerSpeed_deg_s = middleSpeed_deg_s;
        else
            upperSpeed_deg_s = middleSpeed_deg_s;
        end
    end
    peakSpeed_deg_s = lowerSpeed_deg_s;
    cruiseTime_s = 0;
end
[accelerationDuration_s, accelerationJerk_deg_s3] = ...
    jerkTransitionPhases(startSpeed_deg_s, peakSpeed_deg_s, ...
    maxAcceleration_deg_s2, maxJerk_deg_s3);
[decelerationDuration_s, decelerationJerk_deg_s3] = ...
    jerkTransitionPhases(peakSpeed_deg_s, endSpeed_deg_s, ...
    maxAcceleration_deg_s2, maxJerk_deg_s3);
phaseDuration_s = accelerationDuration_s;
phaseJerk_deg_s3 = accelerationJerk_deg_s3;
if cruiseTime_s > tolerance
    phaseDuration_s(end + 1, 1) = cruiseTime_s;
    phaseJerk_deg_s3(end + 1, 1) = 0;
end
phaseDuration_s = [phaseDuration_s; decelerationDuration_s];
phaseJerk_deg_s3 = [phaseJerk_deg_s3; decelerationJerk_deg_s3];
activePhase = phaseDuration_s > tolerance;
phaseDuration_s = phaseDuration_s(activePhase);
phaseJerk_deg_s3 = phaseJerk_deg_s3(activePhase);
phaseCount = numel(phaseDuration_s);
phaseStartTime_s = zeros(phaseCount, 1);
phaseStartPosition_deg = zeros(phaseCount, 1);
phaseStartSpeed_deg_s = zeros(phaseCount, 1);
phaseStartAcceleration_deg_s2 = zeros(phaseCount, 1);
currentTime_s = 0;
currentPosition_deg = 0;
currentSpeed_deg_s = startSpeed_deg_s;
currentAcceleration_deg_s2 = 0;
peakAcceleration_deg_s2 = 0;
for phaseIndex = 1:phaseCount
    phaseStartTime_s(phaseIndex) = currentTime_s;
    phaseStartPosition_deg(phaseIndex) = currentPosition_deg;
    phaseStartSpeed_deg_s(phaseIndex) = currentSpeed_deg_s;
    phaseStartAcceleration_deg_s2(phaseIndex) = ...
        currentAcceleration_deg_s2;
    duration_s = phaseDuration_s(phaseIndex);
    jerk_deg_s3 = phaseJerk_deg_s3(phaseIndex);
    currentPosition_deg = currentPosition_deg + ...
        currentSpeed_deg_s * duration_s + ...
        0.5 * currentAcceleration_deg_s2 * duration_s^2 + ...
        jerk_deg_s3 * duration_s^3 / 6;
    currentSpeed_deg_s = currentSpeed_deg_s + ...
        currentAcceleration_deg_s2 * duration_s + ...
        0.5 * jerk_deg_s3 * duration_s^2;
    currentAcceleration_deg_s2 = currentAcceleration_deg_s2 + ...
        jerk_deg_s3 * duration_s;
    currentTime_s = currentTime_s + duration_s;
    peakAcceleration_deg_s2 = max(peakAcceleration_deg_s2, ...
        abs(currentAcceleration_deg_s2));
end
profile.PeakSpeed_deg_s = peakSpeed_deg_s;
profile.PeakAcceleration_deg_s2 = peakAcceleration_deg_s2;
profile.PeakJerk_deg_s3 = max([0; abs(phaseJerk_deg_s3(:))]);
profile.PhaseDuration_s = phaseDuration_s;
profile.PhaseJerk_deg_s3 = phaseJerk_deg_s3;
profile.PhaseStartTime_s = phaseStartTime_s;
profile.PhaseStartPosition_deg = phaseStartPosition_deg;
profile.PhaseStartSpeed_deg_s = phaseStartSpeed_deg_s;
profile.PhaseStartAcceleration_deg_s2 = ...
    phaseStartAcceleration_deg_s2;
profile.CruiseTime_s = cruiseTime_s;
profile.Duration_s = currentTime_s;
if abs(currentPosition_deg - distance_deg) > ...
        1e-7 * max(1, distance_deg) || ...
        abs(currentSpeed_deg_s - endSpeed_deg_s) > ...
        1e-7 * max(1, endSpeed_deg_s) || ...
        abs(currentAcceleration_deg_s2) > 1e-7
    message = "Internal S-curve integration did not reach its boundary state.";
    return;
end
feasible = true;
end

function distance_deg = jerkTransitionDistance( ...
        startSpeed_deg_s, endSpeed_deg_s, maxAcceleration_deg_s2, ...
        maxJerk_deg_s3)
%% Section 0: Header & Readme
% Symmetric zero-acceleration speed-transition distance.
[duration_s, ~] = jerkTransitionPhases( ...
    startSpeed_deg_s, endSpeed_deg_s, ...
    maxAcceleration_deg_s2, maxJerk_deg_s3);
distance_deg = 0.5 * (startSpeed_deg_s + endSpeed_deg_s) * ...
    sum(duration_s);
end

function [duration_s, jerk_deg_s3] = jerkTransitionPhases( ...
        startSpeed_deg_s, endSpeed_deg_s, maxAcceleration_deg_s2, ...
        maxJerk_deg_s3)
%% Section 0: Header & Readme
% Return the three constant-jerk phases for one scalar speed transition.
deltaSpeed_deg_s = abs(endSpeed_deg_s - startSpeed_deg_s);
if deltaSpeed_deg_s <= 1e-14
    duration_s = zeros(0, 1);
    jerk_deg_s3 = zeros(0, 1);
    return;
end
if isfinite(maxAcceleration_deg_s2)
    jerkRampTime_s = min(maxAcceleration_deg_s2 / maxJerk_deg_s3, ...
        sqrt(deltaSpeed_deg_s / maxJerk_deg_s3));
else
    jerkRampTime_s = sqrt(deltaSpeed_deg_s / maxJerk_deg_s3);
end
constantAccelerationTime_s = max(0, ...
    deltaSpeed_deg_s / (maxJerk_deg_s3 * jerkRampTime_s) - ...
    jerkRampTime_s);
transitionSign = sign(endSpeed_deg_s - startSpeed_deg_s);
duration_s = [jerkRampTime_s; constantAccelerationTime_s; ...
    jerkRampTime_s];
jerk_deg_s3 = transitionSign * maxJerk_deg_s3 * [1; 0; -1];
end

function [position_deg, speed_deg_s, acceleration_deg_s2, jerk_deg_s3] = ...
        sampleJerkProfile(time_s, profile, tolerance)
%% Section 0: Header & Readme
% Integrate the containing constant-jerk phase exactly at each query time.
time_s = double(time_s(:));
sampleCount = numel(time_s);
position_deg = zeros(sampleCount, 1);
speed_deg_s = zeros(sampleCount, 1);
acceleration_deg_s2 = zeros(sampleCount, 1);
jerk_deg_s3 = zeros(sampleCount, 1);
phaseEndTime_s = profile.PhaseStartTime_s + profile.PhaseDuration_s;
for sampleIndex = 1:sampleCount
    queryTime_s = min(max(time_s(sampleIndex), 0), profile.Duration_s);
    phaseIndex = find(queryTime_s < phaseEndTime_s - tolerance, 1);
    if isempty(phaseIndex)
        phaseIndex = numel(phaseEndTime_s);
    end
    localTime_s = queryTime_s - profile.PhaseStartTime_s(phaseIndex);
    localTime_s = min(max(localTime_s, 0), ...
        profile.PhaseDuration_s(phaseIndex));
    phaseJerk_deg_s3 = profile.PhaseJerk_deg_s3(phaseIndex);
    phaseAcceleration_deg_s2 = ...
        profile.PhaseStartAcceleration_deg_s2(phaseIndex);
    phaseSpeed_deg_s = profile.PhaseStartSpeed_deg_s(phaseIndex);
    position_deg(sampleIndex) = ...
        profile.PhaseStartPosition_deg(phaseIndex) + ...
        phaseSpeed_deg_s * localTime_s + ...
        0.5 * phaseAcceleration_deg_s2 * localTime_s^2 + ...
        phaseJerk_deg_s3 * localTime_s^3 / 6;
    speed_deg_s(sampleIndex) = phaseSpeed_deg_s + ...
        phaseAcceleration_deg_s2 * localTime_s + ...
        0.5 * phaseJerk_deg_s3 * localTime_s^2;
    acceleration_deg_s2(sampleIndex) = ...
        phaseAcceleration_deg_s2 + phaseJerk_deg_s3 * localTime_s;
    jerk_deg_s3(sampleIndex) = phaseJerk_deg_s3;
end
atStart = time_s <= tolerance;
atEnd = time_s >= profile.Duration_s - tolerance;
position_deg(atStart) = 0;
speed_deg_s(atStart) = profile.StartSpeed_deg_s;
acceleration_deg_s2(atStart) = 0;
jerk_deg_s3(atStart) = 0;
position_deg(atEnd) = profile.Length_deg;
speed_deg_s(atEnd) = profile.EndSpeed_deg_s;
acceleration_deg_s2(atEnd) = 0;
jerk_deg_s3(atEnd) = 0;
end

function [position_deg, tangent, secondDerivative_deg_inv, ...
        thirdDerivative_deg_inv2] = sampleJerkPrimitive(primitive, distance_deg)
%% Section 0: Header & Readme
% Evaluate q, q', q'', and q''' with respect to primitive arc length.
distance_deg = min(max(double(distance_deg(:)), 0), primitive.Length_deg);
if string(primitive.Type) == "line"
    tangent = repmat(primitive.Direction, numel(distance_deg), 1);
    position_deg = primitive.StartPosition_deg + ...
        distance_deg .* primitive.Direction;
    secondDerivative_deg_inv = zeros(numel(distance_deg), 2);
    thirdDerivative_deg_inv2 = zeros(numel(distance_deg), 2);
    return;
end
angle_rad = primitive.StartAngle_rad + ...
    primitive.TurnSign * distance_deg / primitive.Radius_deg;
radialDirection = [cos(angle_rad), sin(angle_rad)];
position_deg = primitive.Center_deg + ...
    primitive.Radius_deg * radialDirection;
tangent = primitive.TurnSign * [-sin(angle_rad), cos(angle_rad)];
secondDerivative_deg_inv = ...
    -radialDirection / primitive.Radius_deg;
thirdDerivative_deg_inv2 = -tangent / primitive.Radius_deg^2;
end

function [velocityBound_deg_s, accelerationBound_deg_s2, ...
        jerkBound_deg_s3] = primitiveKinematicBounds(primitive, profile)
%% Section 0: Header & Readme
% Publish analytic per-axis certificates independent of output sampling.
if string(primitive.Type) == "line"
    componentMagnitude = abs(primitive.Direction);
    velocityBound_deg_s = ...
        componentMagnitude * profile.PeakSpeed_deg_s;
    accelerationBound_deg_s2 = ...
        componentMagnitude * profile.PeakAcceleration_deg_s2;
    jerkBound_deg_s3 = componentMagnitude * profile.PeakJerk_deg_s3;
    return;
end
radius_deg = primitive.Radius_deg;
velocityBound_deg_s = repmat(profile.PeakSpeed_deg_s, 1, 2);
accelerationBound_deg_s2 = repmat( ...
    profile.PeakAcceleration_deg_s2 + ...
    profile.PeakSpeed_deg_s^2 / radius_deg, 1, 2);
jerkBound_deg_s3 = repmat(profile.PeakJerk_deg_s3 + ...
    3 * profile.PeakSpeed_deg_s * ...
    profile.PeakAcceleration_deg_s2 / radius_deg + ...
    profile.PeakSpeed_deg_s^3 / radius_deg^2, 1, 2);
end

