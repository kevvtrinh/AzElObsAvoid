function policyOptions = seedPolicyOptions( ...
        options, seed, initialState, obstacleGeometryTimeInvariant)
% PURPOSE
%   - Pass one space-time route law to direct policy-motion generation.
policyOptions = options;
policyOptions.ObstacleGeometryTimeInvariant = ...
    logical(obstacleGeometryTimeInvariant);
policyOptions.SeedSnapshotTime_s = seed.SnapshotTime_s;
policyOptions.SeedRouteTimeFraction = zeros(0, 1);
policyOptions.SeedRouteProgress = zeros(0, 1);
policyOptions.SeedRouteDuration_s = NaN;
if obstacleGeometryTimeInvariant
    % Static geometry does not require a SIPP wait law. The policy motion
    % can use its fastest certified analytic time scale.
    return;
end
if isfield(seed, "RpSeedRouteTimeFraction") && ...
        isfield(seed, "RpSeedRouteProgress") && ...
        numel(seed.RpSeedRouteTimeFraction) >= 2
    policyOptions.SeedRouteTimeFraction = ...
        seed.RpSeedRouteTimeFraction;
    policyOptions.SeedRouteProgress = seed.RpSeedRouteProgress;
    policyOptions.SeedRouteDuration_s = seed.RpSeedRouteDuration_s;
    return;
end
routeTime_s = double(seed.RouteTime_s(:));
route_deg = double(seed.Route_deg);
hasTimedRoute = numel(routeTime_s) == size(route_deg, 1) && ...
    numel(routeTime_s) >= 2 && all(isfinite(routeTime_s)) && ...
    all(diff(routeTime_s) > 0) && ...
    routeTime_s(1) >= initialState.time_s && ...
    routeTime_s(end) > initialState.time_s;
if ~hasTimedRoute
    return;
end
routeStep_deg = diff(route_deg, 1, 1);
routeArc_deg = [0; cumsum(hypot( ...
    routeStep_deg(:, 1), routeStep_deg(:, 2)))];
if routeArc_deg(end) <= eps
    return;
end
% SIPP-IP arrival times define the collision-checked progress law. The
% analytic reconstruction must not replace that law with uniform timing
% because doing so changes obstacle phase.
policyOptions.SeedRouteTimeFraction = ...
    (routeTime_s - initialState.time_s) / ...
    (routeTime_s(end) - initialState.time_s);
policyOptions.SeedRouteProgress = routeArc_deg / routeArc_deg(end);
policyOptions.SeedRouteDuration_s = ...
    routeTime_s(end) - initialState.time_s;
end

function allocatedTime_s = fairCandidateTimeAllocation( ...
        remainingTime_s, remainingCandidateCount)
% PURPOSE
%   - Prevent one candidate from consuming another candidate's finite share.
if ~isfinite(remainingTime_s)
    allocatedTime_s = Inf;
    return;
end
allocatedTime_s = max(0, remainingTime_s) / ...
    max(1, remainingCandidateCount);
end

function [useParallel, diagnostics] = ...
        resolvePolicyParallelExecution(requestedMode, taskCount)
% PURPOSE
%   - Start or reuse a pool for independent RL policy routes.
toolboxAvailable = license("test", "Distrib_Computing_Toolbox") && ...
    exist("parpool", "file") == 2 && exist("gcp", "file") == 2;
useParallel = false;
workerCount = 0;
if taskCount <= 1
    message = "One or fewer RL policy routes; serial execution selected.";
elseif requestedMode == "off"
    message = "UseParallel is off; serial RL policy generation selected.";
elseif ~toolboxAvailable
    message = "Parallel Computing Toolbox is unavailable; serial fallback selected.";
    if requestedMode == "on"
        warning("planAzElMotion:ParallelUnavailable", "%s", message);
    end
else
    try
        pool = gcp("nocreate");
        if isempty(pool)
            pool = parpool;
        end
        workerCount = pool.NumWorkers;
        useParallel = workerCount > 0;
        message = sprintf( ...
            "Parallel RL policy generation enabled with %d workers.", ...
            workerCount);
    catch parallelException
        message = "Parallel pool startup failed; serial fallback selected. " + ...
            string(parallelException.message);
        if requestedMode == "on"
            warning("planAzElMotion:ParallelUnavailable", "%s", message);
        end
    end
end
diagnostics = struct( ...
    "RequestedMode", requestedMode, ...
    "ToolboxAvailable", toolboxAvailable, ...
    "Enabled", useParallel, ...
    "WorkerCount", workerCount, ...
    "TaskCount", taskCount, ...
    "Message", string(message));
end

function [plausible, seedRoute_deg, seedRouteTime_s] = ...
        directSeedIsPlausible(obstacleField, ...
        initialState, goalState, options, horizonCollisionMask, ...
        isObstacleGeometryTimeInvariant)
% PURPOSE
%   - Retain a straight seed if a valid deterministic time law is clear.
seedRoute_deg = [initialState.position_deg; goalState.position_deg];
seedRouteTime_s = zeros(0, 1);
plausible = obstacleField.ObstacleCount == 0 || ...
    ~any(horizonCollisionMask);
preserveClearHorizonTimeLaw = plausible && ...
    obstacleField.ObstacleCount > 0 && ...
    ~isObstacleGeometryTimeInvariant;
if plausible && (options.GoalTimeMode == "fixedarrival" || ...
        preserveClearHorizonTimeLaw)
    seedRouteTime_s = [initialState.time_s; goalState.time_s];
end
if plausible || isObstacleGeometryTimeInvariant
    return;
end
pathFraction = linspace(0, 1, 201).';
position_deg = initialState.position_deg + pathFraction .* ...
    (goalState.position_deg - initialState.position_deg);
if options.GoalTimeMode == "fixedarrival"
    timeFraction = linspace(0, 1, 201).';
    exponent = [0.25; 0.5; 2; 4];
    progressLaw = zeros(numel(timeFraction), 0);
    for exponentIndex = 1:numel(exponent)
        progressLaw(:, end + 1) = ...
            timeFraction .^ exponent(exponentIndex); %#ok<AGROW>
    end
    waitFraction = [0.25; 0.5; 0.75];
    for waitIndex = 1:numel(waitFraction)
        wait = waitFraction(waitIndex);
        progressLaw(:, end + 1) = max(0, ...
            (timeFraction - wait) / (1 - wait)); %#ok<AGROW>
        progressLaw(:, end + 1) = min(1, ...
            timeFraction / (1 - wait)); %#ok<AGROW>
    end
    horizon_s = goalState.time_s - initialState.time_s;
    time_s = initialState.time_s + horizon_s * timeFraction;
    for lawIndex = 1:size(progressLaw, 2)
        lawPosition_deg = initialState.position_deg + ...
            progressLaw(:, lawIndex) .* ...
            (goalState.position_deg - initialState.position_deg);
        collisionMask = queryAzElTimedPathCollision(obstacleField, ...
            time_s, lawPosition_deg, struct( ...
            "TimePaddingSamples", options.CollisionTimePaddingSamples, ...
            "BoundaryIsOccupied", false, "StopAtFirstCollision", true));
        if ~any(collisionMask)
            plausible = true;
            anchorIndex = unique(round(linspace( ...
                1, numel(time_s), 9)));
            seedRoute_deg = lawPosition_deg(anchorIndex, :);
            seedRouteTime_s = time_s(anchorIndex);
            return;
        end
    end
    return;
end
horizon_s = goalState.time_s - initialState.time_s;
arrivalTime_s = initialState.time_s + horizon_s * ...
    linspace(0.1, 1, 10).';
obstacleSampleTime_s = zeros(0, 1);
for obstacleIndex = 1:numel(obstacleField.Obstacles)
    obstacleSampleTime_s = [obstacleSampleTime_s; ...
        obstacleField.Obstacles(obstacleIndex).TimeSeconds(:)]; %#ok<AGROW>
end
midpointAlignedArrival_s = initialState.time_s + 2 * ...
    (obstacleSampleTime_s - initialState.time_s);
arrivalTime_s = unique([arrivalTime_s; midpointAlignedArrival_s]);
arrivalTime_s = arrivalTime_s(arrivalTime_s > initialState.time_s & ...
    arrivalTime_s <= goalState.time_s);
for arrivalIndex = 1:numel(arrivalTime_s)
    time_s = initialState.time_s + pathFraction * ...
        (arrivalTime_s(arrivalIndex) - initialState.time_s);
    collisionMask = queryAzElTimedPathCollision(obstacleField, ...
        time_s, position_deg, struct( ...
        "TimePaddingSamples", options.CollisionTimePaddingSamples, ...
        "BoundaryIsOccupied", false, "StopAtFirstCollision", true));
    if ~any(collisionMask)
        plausible = true;
        seedRouteTime_s = [initialState.time_s; ...
            arrivalTime_s(arrivalIndex)];
        return;
    end
end
end

function [seeds, routes_deg, reduction] = collectSeeds( ...
        initialState, goalState, search, options, includeDirectSeed, ...
        isObstacleGeometryTimeInvariant, directSeedRoute_deg, ...
        directSeedRouteTime_s)
% PURPOSE
%   - Use a plausible direct seed, then deterministic topology/time seeds.
template = struct( ...
    "Source", "direct", ...
    "SnapshotTime_s", initialState.time_s, ...
    "GraphIndex", 0, ...
    "RouteCost_deg", 0, ...
    "Route_deg", zeros(0, 2), ...
    "RouteTime_s", zeros(0, 1), ...
    "RouteSignature", "");
directSeed = template;
directSeed.Route_deg = directSeedRoute_deg;
directSeed.RouteTime_s = directSeedRouteTime_s;
directSeed.RouteCost_deg = routeLength(directSeedRoute_deg);
seeds = repmat(template, 0, 1);
if includeDirectSeed
    seeds = directSeed;
end
graphSources = {search.VisibilityGraphs, search.MergedVisibilityGraphs};
sourceNames = ["visibilityGraph" "mergedObstacleGraph"];
collectedVisibilitySeeds = repmat(template, 0, 1);
spaceTimeGraph = search.SpaceTimeVisibilityGraph;
timedCandidates = repmat(struct( ...
    "Position_deg", zeros(0, 2), ...
    "Time_s", zeros(0, 1), ...
    "AngularLength_deg", Inf, ...
    "WaitDuration_s", 0, ...
    "RouteSignature", ""), 0, 1);
primaryTimedRouteAddsDecision = spaceTimeGraph.Success && ...
    timedRouteAddsDecision(spaceTimeGraph.PathPosition_deg, ...
    spaceTimeGraph.PathTime_s, goalState.position_deg);
if primaryTimedRouteAddsDecision && ...
        isfield(spaceTimeGraph, "DiverseCandidates")
    timedCandidates = spaceTimeGraph.DiverseCandidates;
elseif primaryTimedRouteAddsDecision
    timedCandidates = struct( ...
        "Position_deg", spaceTimeGraph.PathPosition_deg, ...
        "Time_s", spaceTimeGraph.PathTime_s, ...
        "AngularLength_deg", spaceTimeGraph.PathCost_deg, ...
        "WaitDuration_s", spaceTimeGraph.WaitDuration_s, ...
        "RouteSignature", "legacySpaceTimeRoute");
end
if ~isempty(timedCandidates) && primaryTimedRouteAddsDecision
    primaryTimedCandidateIndex = 0;
    for timedCandidateIndex = 1:numel(timedCandidates)
        candidatePosition_deg = ...
            timedCandidates(timedCandidateIndex).Position_deg;
        candidateTime_s = timedCandidates(timedCandidateIndex).Time_s;
        samePosition = routesHaveSameGeometry( ...
            candidatePosition_deg, spaceTimeGraph.PathPosition_deg);
        sameTime = isequal(size(candidateTime_s), ...
            size(spaceTimeGraph.PathTime_s)) && ...
            max(abs(candidateTime_s - ...
            spaceTimeGraph.PathTime_s), [], "all") <= 1e-10;
        if samePosition && sameTime
            primaryTimedCandidateIndex = timedCandidateIndex;
            break;
        end
    end
    if primaryTimedCandidateIndex > 1
        timedCandidateOrder = [primaryTimedCandidateIndex, ...
            1:primaryTimedCandidateIndex - 1, ...
            primaryTimedCandidateIndex + 1:numel(timedCandidates)];
        timedCandidates = timedCandidates(timedCandidateOrder);
    end
end
for timedCandidateIndex = 1:numel(timedCandidates)
    timedCandidate = timedCandidates(timedCandidateIndex);
    candidateAddsDecision = timedRouteAddsDecision( ...
        timedCandidate.Position_deg, timedCandidate.Time_s, ...
        goalState.position_deg);
    if ~candidateAddsDecision
        continue;
    end
    seed = template;
    seed.Source = "spaceTimeVisibilityGraph";
    seed.SnapshotTime_s = mean(timedCandidate.Time_s);
    seed.GraphIndex = timedCandidateIndex;
    seed.RouteCost_deg = timedCandidate.AngularLength_deg;
    seed.Route_deg = timedCandidate.Position_deg;
    seed.RouteTime_s = timedCandidate.Time_s;
    seed.RouteSignature = timedCandidate.RouteSignature;
    collectedVisibilitySeeds(end + 1, 1) = seed; %#ok<AGROW>
end
for sourceIndex = 1:numel(graphSources)
    graphs = graphSources{sourceIndex};
    for graphIndex = 1:numel(graphs)
        if ~graphs(graphIndex).Success || ...
                isempty(graphs(graphIndex).PathPosition_deg)
            continue;
        end
        seed = template;
        seed.Source = sourceNames(sourceIndex);
        seed.SnapshotTime_s = graphs(graphIndex).Time_s;
        seed.GraphIndex = graphIndex;
        seed.RouteCost_deg = graphs(graphIndex).PathCost_deg;
        seed.Route_deg = graphs(graphIndex).PathPosition_deg;
        % The visibility search retains few snapshots, so bounded growth
        % keeps the original stable insertion index for later tie breaks.
        collectedVisibilitySeeds(end + 1, 1) = seed; %#ok<AGROW>
        if ~isempty(graphs(graphIndex).AlternativePathPosition_deg)
            alternativeSeed = template;
            alternativeSeed.Source = sourceNames(sourceIndex) + ...
                "Alternative";
            alternativeSeed.SnapshotTime_s = graphs(graphIndex).Time_s;
            alternativeSeed.GraphIndex = graphIndex;
            alternativeSeed.RouteCost_deg = ...
                graphs(graphIndex).AlternativePathCost_deg;
            alternativeSeed.Route_deg = ...
                graphs(graphIndex).AlternativePathPosition_deg;
            collectedVisibilitySeeds(end + 1, 1) = ...
                alternativeSeed; %#ok<AGROW>
        end
    end
end
if ~isempty(collectedVisibilitySeeds)
    isSpaceTimeSeed = [collectedVisibilitySeeds.Source].' == ...
        "spaceTimeVisibilityGraph";
    hasDelayedDirectSeed = ~isempty(seeds) && ...
        any([seeds.Source] == "direct");
    % A successful primary SIPP-IP route contains collision-checked
    % temporal decisions that an untimed snapshot route does not preserve.
    % Retain one primary timed route, then prefer spatial fallback evidence
    % before extra SIPP diversity variants consume a bounded seed budget.
    isPrimarySpaceTimeSeed = isSpaceTimeSeed & ...
        [collectedVisibilitySeeds.GraphIndex].' == 1;
    timedSeedClass = ones(numel(collectedVisibilitySeeds), 1);
    availableVisibilitySeedSlotCount = max(0, ...
        options.MaximumRlPolicySeeds - numel(seeds));
    canReserveTimedEvidence = hasDelayedDirectSeed || ...
        availableVisibilitySeedSlotCount >= 2;
    if canReserveTimedEvidence
        timedSeedClass(isPrimarySpaceTimeSeed) = 0;
    end
    if hasDelayedDirectSeed
        timedSeedClass(isSpaceTimeSeed) = 0;
    end
    isReducedMergedSeed = contains( ...
        [collectedVisibilitySeeds.Source].', "mergedObstacleGraph");
    repeatsDirectGeometryWithoutTiming = false( ...
        numel(collectedVisibilitySeeds), 1);
    if hasDelayedDirectSeed
        directRoute_deg = seeds(find( ...
            [seeds.Source] == "direct", 1, "first")).Route_deg;
        for candidateIndex = 1:numel(collectedVisibilitySeeds)
            candidate = collectedVisibilitySeeds(candidateIndex);
            repeatsDirectGeometryWithoutTiming(candidateIndex) = ...
                ~isSpaceTimeSeed(candidateIndex) && ...
                routesHaveSameGeometry( ...
                candidate.Route_deg, directRoute_deg);
        end
    end
    % Full protected-field topology is stronger evidence than a route from
    % a reduced merged graph. Cost ranks only after this fidelity class.
    ranking = [isReducedMergedSeed, timedSeedClass, ...
        repeatsDirectGeometryWithoutTiming, ...
        [collectedVisibilitySeeds.RouteCost_deg].', ...
        [collectedVisibilitySeeds.SnapshotTime_s].', ...
        (1:numel(collectedVisibilitySeeds)).'];
    [~, order] = sortrows(ranking, 1:size(ranking, 2));
    collectedVisibilitySeeds = collectedVisibilitySeeds(order);
end
collectedCandidateSeedCount = ...
    numel(seeds) + numel(collectedVisibilitySeeds);

% Sort before deduplication so equal static routes keep the cheapest,
% earliest, and then earliest-inserted graph source deterministically.
visibilitySeeds = repmat(template, 0, 1);
for seedIndex = 1:numel(collectedVisibilitySeeds)
    seed = collectedVisibilitySeeds(seedIndex);
    if routeDuplicatesAny(seed.Route_deg, seed.SnapshotTime_s, ...
            [seeds; visibilitySeeds], ...
            isObstacleGeometryTimeInvariant)
        continue;
    end
    visibilitySeeds(end + 1, 1) = seed; %#ok<AGROW>
end
maximumVisibilitySeedCount = max(0, ...
    options.MaximumRlPolicySeeds - numel(seeds));
deduplicatedCandidateSeedCount = numel(seeds) + numel(visibilitySeeds);
visibilitySeeds = selectBoundedTemporalSeeds( ...
    visibilitySeeds, maximumVisibilitySeedCount, seeds, ...
    options.GoalTimeMode == "earliestarrival" && ...
    maximumVisibilitySeedCount >= 4 && ...
    ~isObstacleGeometryTimeInvariant);
seeds = [seeds; visibilitySeeds];
routes_deg = reshape({seeds.Route_deg}, [], 1);
reduction = struct( ...
    "CollectedCandidateSeedCount", collectedCandidateSeedCount, ...
    "DeduplicatedCandidateSeedCount", ...
    deduplicatedCandidateSeedCount, ...
    "SeedCapDroppedCount", ...
    deduplicatedCandidateSeedCount - numel(seeds));
end

function duplicates = routeDuplicatesAny( ...
        route_deg, snapshotTime_s, seeds, ...
        isObstacleGeometryTimeInvariant)
% PURPOSE
%   - Collapse cross-time route copies only for a fully static field.
duplicates = false;
for seedIndex = 1:numel(seeds)
    sameTemporalSeed = isObstacleGeometryTimeInvariant || ...
        abs(snapshotTime_s - seeds(seedIndex).SnapshotTime_s) <= 1e-10;
    if sameTemporalSeed && routesHaveSameGeometry( ...
            route_deg, seeds(seedIndex).Route_deg)
        duplicates = true;
        return;
    end
end
end

function matches = routesHaveSameGeometry(firstRoute_deg, secondRoute_deg)
% PURPOSE
%   - Compare route geometry without attaching snapshot-time meaning.
firstRoute_deg = removeConsecutiveRoutePoints(firstRoute_deg);
secondRoute_deg = removeConsecutiveRoutePoints(secondRoute_deg);
matches = isequal(size(firstRoute_deg), size(secondRoute_deg)) && ...
    max(abs(firstRoute_deg - secondRoute_deg), [], "all") <= 1e-10;
end

function route_deg = removeConsecutiveRoutePoints(route_deg)
% PURPOSE
%   - Compare spatial topology without treating waiting as new geometry.
if size(route_deg, 1) < 2
    return;
end
keepRow = [true; any(abs(diff(route_deg, 1, 1)) > 1e-10, 2)];
route_deg = route_deg(keepRow, :);
end

function addsDecision = timedRouteAddsDecision( ...
        route_deg, routeTime_s, goalPosition_deg)
% PURPOSE
%   - Ignore a direct route whose only wait is at the fixed-arrival goal.
addsDecision = false;
if size(route_deg, 1) < 2 || numel(routeTime_s) ~= size(route_deg, 1)
    return;
end
compressedRoute_deg = removeConsecutiveRoutePoints(route_deg);
if size(compressedRoute_deg, 1) > 2
    addsDecision = true;
    return;
end
routeStep_deg = diff(route_deg, 1, 1);
waitEdge = hypot(routeStep_deg(:, 1), routeStep_deg(:, 2)) <= 1e-10 & ...
    diff(routeTime_s(:)) > 1e-10;
waitPosition_deg = route_deg(1:end - 1, :);
waitGoalOffset_deg = waitPosition_deg - goalPosition_deg;
waitsAwayFromGoal = waitEdge & ...
    hypot(waitGoalOffset_deg(:, 1), waitGoalOffset_deg(:, 2)) > 1e-10;
addsDecision = any(waitsAwayFromGoal);
end

function selectedSeeds = selectBoundedTemporalSeeds( ...
        seeds, maximumCount, preselectedSeeds, reserveLateSnapshot)
% PURPOSE
%   - Keep the cheapest topology seed, then spread retained seed times.
if maximumCount <= 0 || isempty(seeds)
    selectedSeeds = seeds([]);
    return;
end
maximumCount = min(maximumCount, numel(seeds));
if numel(seeds) <= maximumCount
    selectedSeeds = seeds;
    return;
end

selectedIndex = zeros(maximumCount, 1);
isSelected = false(numel(seeds), 1);
snapshotTime_s = [seeds.SnapshotTime_s].';
finiteSnapshotTime_s = snapshotTime_s(isfinite(snapshotTime_s));
reserveLateSnapshotSlot = reserveLateSnapshot && ...
    numel(unique(finiteSnapshotTime_s)) >= 3;
distinctTopologyLimit = maximumCount - reserveLateSnapshotSlot;
% Distinct geometry must survive before extra time laws for an already
% retained route. This prevents moving snapshots of one route from removing
% a valid alternative topology.
selectedCount = 0;
while selectedCount < distinctTopologyLimit
    remainingIndex = find(~isSelected);
    selectedSeedPool = [preselectedSeeds; seeds(isSelected)];
    chosenIndex = 0;
    for remainingPosition = 1:numel(remainingIndex)
        seedIndex = remainingIndex(remainingPosition);
        geometryAlreadySelected = routeDuplicatesAny( ...
            seeds(seedIndex).Route_deg, ...
            seeds(seedIndex).SnapshotTime_s, selectedSeedPool, true);
        if ~geometryAlreadySelected
            chosenIndex = seedIndex;
            break;
        end
    end
    if chosenIndex == 0
        break;
    end
    selectedCount = selectedCount + 1;
    selectedIndex(selectedCount) = chosenIndex;
    isSelected(chosenIndex) = true;
end
if selectedCount == 0
    selectedCount = 1;
    selectedIndex(selectedCount) = 1;
    isSelected(1) = true;
end
routeCost_deg = [seeds.RouteCost_deg].';
distinctTimeTolerance_s = 1e-10;
if reserveLateSnapshotSlot && selectedCount < maximumCount
    finalSnapshotTime_s = max(finiteSnapshotTime_s);
    interiorTime_s = finiteSnapshotTime_s( ...
        finiteSnapshotTime_s < finalSnapshotTime_s - ...
        distinctTimeTolerance_s);
    latestInteriorTime_s = max(interiorTime_s);
    lateSnapshotIndex = find(~isSelected & abs(snapshotTime_s - ...
        latestInteriorTime_s) <= distinctTimeTolerance_s);
    if ~isempty(lateSnapshotIndex)
        ranking = [routeCost_deg(lateSnapshotIndex), lateSnapshotIndex];
        [~, order] = sortrows(ranking, [1 2]);
        selectedCount = selectedCount + 1;
        chosenIndex = lateSnapshotIndex(order(1));
        selectedIndex(selectedCount) = chosenIndex;
        isSelected(chosenIndex) = true;
    end
end
preselectedTime_s = [preselectedSeeds.SnapshotTime_s].';
preselectedTime_s = preselectedTime_s(isfinite(preselectedTime_s));

while selectedCount < maximumCount
    remainingIndex = find(~isSelected);
    selectedTime_s = [preselectedTime_s; ...
        snapshotTime_s(isSelected & isfinite(snapshotTime_s))];
    if isempty(selectedTime_s)
        break;
    end
    minimumSeparation_s = -inf(numel(remainingIndex), 1);
    for remainingPosition = 1:numel(remainingIndex)
        seedIndex = remainingIndex(remainingPosition);
        if isfinite(snapshotTime_s(seedIndex))
            minimumSeparation_s(remainingPosition) = min(abs( ...
                snapshotTime_s(seedIndex) - selectedTime_s));
        end
    end
    distinctTime = minimumSeparation_s > distinctTimeTolerance_s;
    if ~any(distinctTime)
        break;
    end
    distinctIndex = remainingIndex(distinctTime);
    distinctSeparation_s = minimumSeparation_s(distinctTime);
    ranking = [-distinctSeparation_s, routeCost_deg(distinctIndex), ...
        snapshotTime_s(distinctIndex), distinctIndex];
    [~, order] = sortrows(ranking, [1 2 3 4]);
    selectedCount = selectedCount + 1;
    chosenIndex = distinctIndex(order(1));
    selectedIndex(selectedCount) = chosenIndex;
    isSelected(chosenIndex) = true;
end

% The remaining input order is already the stable cost ranking.
remainingSlotCount = maximumCount - selectedCount;
if remainingSlotCount > 0
    costFillIndex = find(~isSelected, remainingSlotCount, "first");
    selectedIndex(selectedCount + (1:remainingSlotCount)) = ...
        costFillIndex;
end
selectedSeeds = seeds(selectedIndex);
end

function diagnostic = emptyCandidateDiagnostic()
% PURPOSE
%   - Define planner-level diagnostics for one RL projection seed.
diagnostic = struct( ...
    "Index", 0, "SeedIndex", 0, "SeedSource", "", ...
    "SeedSnapshotTime_s", NaN, "SeedGraphIndex", 0, ...
    "SeedRouteCost_deg", Inf, "SeedRoute_deg", zeros(0, 2), ...
    "SeedRouteTime_s", zeros(0, 1), ...
    "TimedSeedLawUsed", false, ...
    "SeedRouteTimeFraction", zeros(0, 1), ...
    "SeedRouteProgress", zeros(0, 1), ...
    "Success", false, ...
    "TerminationReason", "notEvaluated", "SolverExitFlag", NaN, ...
