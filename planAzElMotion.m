    options.MaximumSpaceTimeDiagnosticEdgeCount, ...
    "MaximumSafeIntervalRefinements", ...
    options.MaximumSafeIntervalRefinements, ...
    "SafeIntervalTimeTolerance_s", ...
    options.SafeIntervalTimeTolerance_s, ...
    "MaximumSippCandidates", options.MaximumSippCandidates, ...
    "MaximumSippExpansions", options.MaximumSippExpansions, ...
    "MaximumSippWallTime_s", options.MaximumSippWallTime_s, ...
    "SippKNearestNeighbors", options.SippKNearestNeighbors, ...
    "SippMaximumEdgeLength_deg", ...
    options.SippMaximumEdgeLength_deg, ...
    "AllowSippWaiting", options.AllowSippWaiting, ...
    "SpaceTimeNodeMergeTolerance_deg", ...
    options.SpaceTimeNodeMergeTolerance_deg, ...
    "CollisionTimePaddingSamples", ...
    options.CollisionTimePaddingSamples, ...
