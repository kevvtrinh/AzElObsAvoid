function [selectedIndex, success] = selectCandidate( ...
        diagnostics, timeTieTolerance_s)
% PURPOSE
%   - Select validated earliest arrival, then jerk, then stable seed index.
selectedIndex = 0;
success = false;
if isempty(diagnostics)
    return;
end
feasibleIndex = find([diagnostics.Success]);
if ~isempty(feasibleIndex)
    arrivalTime_s = [diagnostics(feasibleIndex).ObjectiveArrivalTime_s].';
    bestArrival_s = min(arrivalTime_s);
    nearBest = feasibleIndex(arrivalTime_s <= ...
        bestArrival_s + timeTieTolerance_s);
    ranking = [[diagnostics(nearBest).IntegratedSquaredJerk].', ...
        nearBest(:)];
    [~, order] = sortrows(ranking, [1 2]);
    selectedIndex = nearBest(order(1));
    success = true;
    return;
end
finiteIndex = find(isfinite([diagnostics.ObjectiveArrivalTime_s]));
if isempty(finiteIndex)
    selectedIndex = 1;
else
    ranking = [[diagnostics(finiteIndex).ObjectiveArrivalTime_s].', ...
        finiteIndex(:)];
    [~, order] = sortrows(ranking, [1 2]);
    selectedIndex = finiteIndex(order(1));
end
end

