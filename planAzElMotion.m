function timedPath = retimeJerkContinuousRoundedMotion( ...
        smoothPath, initialState, goalState, limits, options)
%% Section 0: Header & Readme
% Retime each uninterrupted G3 geometric run with one analytic S-curve.
% The quintic corner construction has q''=q'''=0 at every line join, so a
% shared nonzero scalar speed crosses those joins without an acceleration
% or jerk impulse. Only explicitly unsmoothed corners split the path into
% separate zero-speed runs.
totalLength_deg = double(smoothPath.TotalLength_deg);
endpointSamples = sampleRoundedMotion(smoothPath, [0; totalLength_deg]);
if norm(endpointSamples.position_deg(1, :) - initialState.position_deg) > ...
        options.PositionTolerance_deg || ...
        norm(endpointSamples.position_deg(2, :) - goalState.position_deg) > ...
        options.PositionTolerance_deg
    error("retimeJerkContinuousRoundedMotion:EndpointMismatch", ...
        "Smooth-path endpoints must match the requested endpoint states.");
end
initialSpeed_deg_s = roundedBoundaryScalarSpeed( ...
    initialState.velocity_deg_s, endpointSamples.tangent(1, :), ...
    "initialState.velocity_deg_s", options.KinematicTolerance);
goalSpeed_deg_s = roundedBoundaryScalarSpeed( ...
    goalState.velocity_deg_s, endpointSamples.tangent(2, :), ...
    "goalState.velocity_deg_s", options.KinematicTolerance);
requiredInitialAcceleration_deg_s2 = ...
    endpointSamples.secondDerivative_deg_inv(1, :) * initialSpeed_deg_s^2;
requiredGoalAcceleration_deg_s2 = ...
    endpointSamples.secondDerivative_deg_inv(2, :) * goalSpeed_deg_s^2;
if norm(requiredInitialAcceleration_deg_s2 - ...
        initialState.acceleration_deg_s2) > options.KinematicTolerance || ...
        norm(requiredGoalAcceleration_deg_s2 - ...
        goalState.acceleration_deg_s2) > options.KinematicTolerance
    timedPath = failedJerkLimitedPath( ...
        "A nonzero endpoint speed on curved geometry requires the " + ...
        "matching normal acceleration boundary state.", ...
        limits, options, "velocityCarrying");
    return;
end

%% Section 1: Split Only At Genuine Mandatory Stops
coordinateTolerance_deg = options.KinematicTolerance * ...
    max(1, totalLength_deg);
mandatoryStopArcLength_deg = unique(double( ...
    smoothPath.MandatoryStopArcLength_deg(:)));
mandatoryStopArcLength_deg = mandatoryStopArcLength_deg( ...
    mandatoryStopArcLength_deg > coordinateTolerance_deg & ...
    mandatoryStopArcLength_deg < totalLength_deg - ...
    coordinateTolerance_deg);
runBoundaryS_deg = [0; mandatoryStopArcLength_deg; totalLength_deg];
runCount = numel(runBoundaryS_deg) - 1;
runNodeSpeed_deg_s = [initialSpeed_deg_s; ...
    zeros(max(0, runCount - 1), 1); goalSpeed_deg_s];
profileTemplate = jerkMinimumTimeProfile(1, 0, 0, 1, 1, 1, ...
    options.KinematicTolerance);
profileTemplate = profileTemplate(1);
profiles = repmat(profileTemplate, runCount, 1);
boundTemplate = struct( ...
    "RunIndex", 0, ...
    "StartArcLength_deg", 0, ...
    "EndArcLength_deg", 0, ...
    "TangentByAxis", zeros(1, 2), ...
    "SecondDerivativeByAxis_deg_inv", zeros(1, 2), ...
    "ThirdDerivativeByAxis_deg_inv2", zeros(1, 2), ...
    "NumericalTangentByAxis", zeros(1, 2), ...
    "NumericalSecondDerivativeByAxis_deg_inv", zeros(1, 2), ...
    "NumericalThirdDerivativeByAxis_deg_inv2", zeros(1, 2), ...
    "EnvelopeInflationFactor", 1.0, ...
    "SampleCount", 0, ...
    "Method", "analyticBezierControlPolygon");
geometryDerivativeBounds = repmat(boundTemplate, runCount, 1);

for runIndex = 1:runCount
    runStartS_deg = runBoundaryS_deg(runIndex);
    runEndS_deg = runBoundaryS_deg(runIndex + 1);
    runLength_deg = runEndS_deg - runStartS_deg;
    derivativeBounds = roundedRunDerivativeBounds( ...
        smoothPath, runStartS_deg, runEndS_deg, runIndex);
    geometryDerivativeBounds(runIndex) = derivativeBounds;
    [scalarVelocityLimit_deg_s, scalarAccelerationLimit_deg_s2, ...
        scalarJerkLimit_deg_s3] = roundedRunScalarLimits( ...
        derivativeBounds, limits, options.KinematicTolerance);
    [profile, feasible, failureMessage] = jerkMinimumTimeProfile( ...
        runLength_deg, runNodeSpeed_deg_s(runIndex), ...
        runNodeSpeed_deg_s(runIndex + 1), ...
        scalarVelocityLimit_deg_s, scalarAccelerationLimit_deg_s2, ...
        scalarJerkLimit_deg_s3, options.KinematicTolerance);
    if ~feasible
        timedPath = failedJerkLimitedPath( ...
            "Smooth run " + runIndex + ": " + failureMessage, ...
            limits, options, "velocityCarrying");
        return;
    end
    runEndpoints = sampleRoundedMotion( ...
        smoothPath, [runStartS_deg; runEndS_deg]);
    profile.PrimitiveType = "smoothRun";
    profile.StartPosition_deg = runEndpoints.position_deg(1, :);
    profile.EndPosition_deg = runEndpoints.position_deg(2, :);
    profile.Length_deg = runLength_deg;
    profile.StartArcLength_deg = runStartS_deg;
    profile.EndArcLength_deg = runEndS_deg;
    profile.MaxSpeed_deg_s = scalarVelocityLimit_deg_s;
    profile.MaxAcceleration_deg_s2 = scalarAccelerationLimit_deg_s2;
    profile.MaxJerk_deg_s3 = scalarJerkLimit_deg_s3;
    [velocityBound, accelerationBound, jerkBound] = ...
        roundedRunKinematicBounds(derivativeBounds, profile);
    profile.PeakVelocityByAxis_deg_s = velocityBound;
    profile.PeakAccelerationByAxis_deg_s2 = accelerationBound;
    profile.PeakJerkByAxis_deg_s3 = jerkBound;
    profiles(runIndex) = profile;
end

%% Section 2: Resolve Arrival Time And Optional Initial Hold
minimumMotionDuration_s = sum([profiles.Duration_s]);
minimumArrivalTime_s = initialState.time_s + minimumMotionDuration_s;
timeTolerance_s = options.KinematicTolerance * ...
    max(1, abs(goalState.time_s));
if minimumArrivalTime_s > goalState.time_s + timeTolerance_s
    timedPath = failedJerkLimitedPath(sprintf( ...
        "Earliest jerk-limited arrival %.9g s exceeds goal time %.9g s.", ...
        minimumArrivalTime_s, goalState.time_s), ...
        limits, options, "velocityCarrying");
    return;
end
waitDuration_s = 0;
if options.GoalTimeMode == "fixedarrival"
    waitDuration_s = max(0, goalState.time_s - minimumArrivalTime_s);
    if waitDuration_s > timeTolerance_s && ...
            (norm(initialState.velocity_deg_s) > ...
            options.KinematicTolerance || ...
            norm(initialState.acceleration_deg_s2) > ...
            options.KinematicTolerance)
        timedPath = failedJerkLimitedPath( ...
            "fixedArrival needs a start hold, but the initial velocity " + ...
            "or acceleration is nonzero.", ...
            limits, options, "velocityCarrying");
        return;
    end
end
motionStartTime_s = initialState.time_s + waitDuration_s;
runStartTime_s = motionStartTime_s + ...
