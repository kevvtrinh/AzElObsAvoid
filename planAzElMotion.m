function result = planAzElMotion(obstacles, initialState, goalState, ...
        limits, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = planAzElMotion()
%   result = planAzElMotion(obstacles, initialState, goalState, limits)
%   result = planAzElMotion(obstacles, initialState, goalState, limits, ...
%       optionOverrides)
%**************************************************************************
% PURPOSE
%   - Find the earliest independently validated azimuth/elevation motion.
%   - Use the checked-in RL agent to shape every topology route.
%   - Generate the final motion directly from the policy route without a
%     numerical motion optimizer.
%**************************************************************************
% INPUTS
%   - obstacles (canonical obstacle data, nested cell array, or [])
%       Static or time-varying already-protected polygon geometry.
%   - initialState, goalState (scalar structs)
%       time_s, position_deg, velocity_deg_s, and acceleration_deg_s2.
%       goalState.time_s is the horizon or fixed arrival time.
%   - limits (scalar struct)
%       Finite positive two-axis velocity, acceleration, and jerk limits.
%   - optionOverrides (scalar struct, optional; default struct())
%       Partial RL policy, visibility, and validation
%       options. RpAgentFile selects the required checked-in policy.
%**************************************************************************
% OUTPUTS
%   - result (scalar struct)
%       Stable success/failure record with trajectory, topology seed,
%       independent validation, and diagnostics. Expected infeasibility
%       returns Success=false; invalid input throws.
%**************************************************************************
% UNITS
%   - Angles use degrees and time uses seconds. Histories are N-by-2
%     [azimuth elevation] with derivative units stated in field names.
%**************************************************************************

%% Section 1: Validate Inputs And Apply Defaults

defaults = plannerDefaults();
if nargin == 0
    result = defaults;
    return;
end
if nargin < 5 || isempty(optionOverrides)
    optionOverrides = struct();
end
planningTimer = tic;
options = resolveOptions(defaults, optionOverrides);
initialState = normalizeState(initialState, "initialState");
goalState = normalizeState(goalState, "goalState");
limits = normalizeLimits(limits);
if goalState.time_s <= initialState.time_s
    error("planAzElMotion:InvalidTimeWindow", ...
        "goalState.time_s must be greater than initialState.time_s.");
end

%% Section 2: Build Protected Geometry And Validate Endpoints

protectedAzElData = combineAzElObstacles(obstacles);
obstacleField = buildAzElTimeObstacleField(protectedAzElData, ...
    struct("Verbose", options.Verbose));
isObstacleGeometryTimeInvariant = ...
    azElInternal.packedAzElGeometryIsTimeInvariant(obstacleField);
[originalObstacleField, obstacleSafetyMargins_deg] = ...
    recoverOriginalAzElObstacleField(obstacleField);
startBlocked = queryAzElTimeObstacle(obstacleField, ...
    initialState.position_deg(1), initialState.position_deg(2), ...
    initialState.time_s);
goalBlockedAtHorizon = queryAzElTimeObstacle(obstacleField, ...
    goalState.position_deg(1), goalState.position_deg(2), ...
    goalState.time_s);
goalBlocked = options.GoalTimeMode == "fixedarrival" && ...
    goalBlockedAtHorizon;
endpointBlocked = logical(startBlocked || goalBlocked);
[endpointDynamicsFeasible, endpointDynamicsMessage] = ...
    endpointDynamicsAreFeasible(initialState, goalState, limits, options);
[endpointWorkspaceFeasible, endpointWorkspaceMessage] = ...
    endpointWorkspaceIsFeasible(initialState, goalState, options);

directFraction = linspace(0, 1, 501).';
directPosition_deg = initialState.position_deg + directFraction .* ...
    (goalState.position_deg - initialState.position_deg);
directTime_s = initialState.time_s + directFraction .* ...
    (goalState.time_s - initialState.time_s);
directBlocked = queryAzElTimedPathCollision(obstacleField, ...
    directTime_s, directPosition_deg, struct( ...
    "TimePaddingSamples", options.CollisionTimePaddingSamples, ...
    "BoundaryIsOccupied", false));
[includeDirectSeed, directSeedRoute_deg, directSeedRouteTime_s] = ...
    directSeedIsPlausible(obstacleField, ...
    initialState, goalState, options, directBlocked, ...
    isObstacleGeometryTimeInvariant);

%% Section 3: Generate Direct And Visibility Topology Seeds

searchOptions = visibilitySearchOptions( ...
    options, limits, isObstacleGeometryTimeInvariant);
remainingPlanningTime_s = max(0, ...
    options.MaximumPlanningTime_s - toc(planningTimer));
if isfinite(remainingPlanningTime_s)
    reservedOptimizerTime_s = min( ...
        options.MinimumRlPolicySeedTime_s, ...
        0.75 * remainingPlanningTime_s);
    reservedSippTime_s = options.MaximumSippPlanningFraction * ...
        remainingPlanningTime_s;
    searchBudget_s = max( ...
        remainingPlanningTime_s - reservedOptimizerTime_s, ...
        reservedSippTime_s);
    searchOptions.MaximumPlanningTime_s = max(eps, min( ...
        remainingPlanningTime_s, searchBudget_s));
    searchOptions.MaximumSippWallTime_s = min( ...
        searchOptions.MaximumSippWallTime_s, ...
        max(eps, reservedSippTime_s));
end
search = emptyVisibilitySearch(searchOptions);
canSearch = ~endpointBlocked && endpointDynamicsFeasible && ...
    endpointWorkspaceFeasible;
if canSearch && obstacleField.ObstacleCount > 0
    search = buildAzElVisibilityRoutes( ...
        obstacleField, initialState, goalState, searchOptions);
end
[seeds, ~, seedReductionDiagnostics] = collectSeeds( ...
    initialState, goalState, search, options, includeDirectSeed, ...
    isObstacleGeometryTimeInvariant, directSeedRoute_deg, ...
    directSeedRouteTime_s);
topologySeedCount = numel(seeds);
[seeds, rpSeedDiagnostics, rpSeedReduction] = ...
    azElInternal.buildAzElRlPolicySeeds( ...
    seeds, obstacleField, limits, options);
seedReductionDiagnostics.CollectedCandidateSeedCount = ...
    seedReductionDiagnostics.CollectedCandidateSeedCount + ...
    rpSeedReduction.GeneratedWarmStartCount - topologySeedCount;
seedReductionDiagnostics.DeduplicatedCandidateSeedCount = ...
    seedReductionDiagnostics.DeduplicatedCandidateSeedCount + ...
    rpSeedReduction.GeneratedWarmStartCount - topologySeedCount;
seedReductionDiagnostics.SeedCapDroppedCount = ...
    seedReductionDiagnostics.SeedCapDroppedCount + ...
    rpSeedReduction.SeedCapDroppedWarmStartCount;
seedRoutes_deg = reshape({seeds.Route_deg}, [], 1);

%% Section 4: Generate And Independently Validate Every Policy Motion

[useParallelPolicy, parallelPolicyExecution] = ...
    resolvePolicyParallelExecution(options.UseParallel, numel(seeds));
candidateResults = repmat(emptyCandidateDiagnostic(), 0, 1);
rawCandidates = cell(0, 1);
if canSearch && useParallelPolicy
    seedCount = numel(seeds);
    candidateResults = repmat(emptyCandidateDiagnostic(), seedCount, 1);
    rawCandidates = cell(seedCount, 1);
    remainingPlanningTime_s = max(0, ...
        options.MaximumPlanningTime_s - toc(planningTimer));
    perSeedTime_s = fairCandidateTimeAllocation( ...
        remainingPlanningTime_s, seedCount);
    parfor seedIndex = 1:seedCount
        policyOptions = seedPolicyOptions( ...
            options, seeds(seedIndex), initialState, ...
            isObstacleGeometryTimeInvariant);
        policyOptions.UseParallel = false;
        policyOptions.RemainingPlanningTime_s = perSeedTime_s;
        rawCandidate = azElInternal.generateAzElRlMotion( ...
            seeds(seedIndex).Route_deg, obstacleField, initialState, ...
            goalState, limits, policyOptions);
        rawCandidates{seedIndex} = rawCandidate;
        candidateResults(seedIndex) = candidateDiagnostic( ...
            seedIndex, seeds(seedIndex), rawCandidate);
    end
elseif canSearch
    for seedIndex = 1:numel(seeds)
        elapsedPlanningTime_s = toc(planningTimer);
        if elapsedPlanningTime_s >= options.MaximumPlanningTime_s
            break;
        end
        policyOptions = seedPolicyOptions( ...
            options, seeds(seedIndex), initialState, ...
            isObstacleGeometryTimeInvariant);
        remainingSeedCount = numel(seeds) - seedIndex + 1;
        remainingPlanningTime_s = ...
            options.MaximumPlanningTime_s - elapsedPlanningTime_s;
        policyOptions.RemainingPlanningTime_s = ...
            fairCandidateTimeAllocation( ...
            remainingPlanningTime_s, remainingSeedCount);
        rawCandidate = azElInternal.generateAzElRlMotion( ...
            seeds(seedIndex).Route_deg, obstacleField, initialState, ...
            goalState, limits, policyOptions);
        rawCandidates{end + 1, 1} = rawCandidate; %#ok<AGROW>
        candidateResults(end + 1, 1) = candidateDiagnostic( ...
            seedIndex, seeds(seedIndex), rawCandidate); %#ok<AGROW>
    end
end
[selectedCandidateIndex, success] = selectCandidate( ...
    candidateResults, options.ArrivalTimeTieTolerance_s);
selectedRoute_deg = [initialState.position_deg; goalState.position_deg];
selectedRouteTime_s = zeros(0, 1);
selectedRawCandidate = [];
if selectedCandidateIndex > 0
    selectedRoute_deg = seeds(selectedCandidateIndex).Route_deg;
    selectedRouteTime_s = seeds(selectedCandidateIndex).RouteTime_s;
    selectedRawCandidate = rawCandidates{selectedCandidateIndex};
end

%% Section 5: Assemble Stable Trajectory And Result Schemas

timedSlopePath = emptyTimedPath();
validation = emptyValidation();
message = "No direct RL policy motion was evaluated.";
terminationReason = "noFeasibleCandidate";
if endpointBlocked
    message = "The protected geometry contains the start or goal.";
    terminationReason = "endpointBlocked";
elseif ~endpointDynamicsFeasible
    message = endpointDynamicsMessage;
    terminationReason = "dynamicEndpointInfeasible";
elseif ~endpointWorkspaceFeasible
    message = endpointWorkspaceMessage;
    terminationReason = "endpointOutsideWorkspace";
elseif selectedCandidateIndex > 0
    timedSlopePath = compatibilityTimedPath( ...
        selectedRawCandidate, initialState);
    validation = selectedRawCandidate.Validation;
    message = selectedRawCandidate.Message;
    terminationReason = selectedRawCandidate.TerminationReason;
end
if success
    message = "Best direct RL policy motion passed validation.";
    terminationReason = "goalReached";
end
candidateDiagnostics = candidateDiagnosticTable(candidateResults);
seedRouteTimes_s = reshape({seeds.RouteTime_s}, [], 1);
elapsedPlanningTime_s = toc(planningTimer);
searchDiagnostics = assembleSearchDiagnostics( ...
    search, seeds, candidateResults, selectedCandidateIndex, ...
    elapsedPlanningTime_s, options, terminationReason, ...
    parallelPolicyExecution, ...
    isObstacleGeometryTimeInvariant, seedReductionDiagnostics);
searchDiagnostics.RpSeedDiagnostics = rpSeedDiagnostics;
searchDiagnostics.RpSeedReduction = rpSeedReduction;
searchDiagnostics.RpAgentFile = options.RpAgentFile;
searchDiagnostics.RpSeedMethod = "requiredRlCornerPolicy";
trajectory = trajectoryView(timedSlopePath);
goalLineInterceptTime_s = NaN;
if ~isempty(timedSlopePath.time_s)
    goalLineInterceptTime_s = timedSlopePath.time_s(end);
end
result = struct( ...
    "Success", success, ...
    "Message", message, ...
    "TerminationReason", terminationReason, ...
    "Options", options, ...
    "azElData", protectedAzElData, ...
    "originalAzElData", originalObstacleField.SourceAzElData, ...
    "obstacleField", obstacleField, ...
    "initialState", initialState, ...
    "goalState", goalState, ...
    "limits", limits, ...
    "obstacleSafetyMargins_deg", obstacleSafetyMargins_deg, ...
    "candidateReductionDiagnostics", ...
    search.CandidateReductionDiagnostics, ...
    "directPosition_deg", directPosition_deg, ...
    "directTime_s", directTime_s, ...
    "directBlocked", logical(directBlocked(:)), ...
    "candidateRoutes_deg", {seedRoutes_deg}, ...
    "candidateRouteTimes_s", {seedRouteTimes_s}, ...
    "candidateDiagnostics", candidateDiagnostics, ...
    "selectedCandidateIndex", selectedCandidateIndex, ...
    "selectedRoute_deg", selectedRoute_deg, ...
    "selectedRouteTime_s", selectedRouteTime_s, ...
    "smoothPath", [], ...
    "timedSlopePath", timedSlopePath, ...
    "time_s", trajectory.time_s, ...
    "position_deg", trajectory.position_deg, ...
    "velocity_deg_s", trajectory.velocity_deg_s, ...
    "acceleration_deg_s2", trajectory.acceleration_deg_s2, ...
    "jerk_deg_s3", trajectory.jerk_deg_s3, ...
    "goalLineInterceptTime_s", goalLineInterceptTime_s, ...
    "SearchDiagnostics", searchDiagnostics, ...
    "ElapsedPlanningTime_s", elapsedPlanningTime_s, ...
    "Validation", validation);
if options.Verbose
    fprintf("[AzEl RL policy] %s Routes %d, feasible %d, " + ...
        "elapsed %.3f s.\n", message, numel(candidateResults), ...
        nnz([candidateResults.Success]), elapsedPlanningTime_s);
end
end

