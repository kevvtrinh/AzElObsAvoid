function testRandomizedCoefficientAndTerminalParity(testCase)
% Cover requested mesh sizes, randomized jerk, and nonzero endpoint bases.
rng(325, "twister");
for segmentCount = [1 2 5 10]
    duration_s = 1.7 + 0.31 * segmentCount;
    evaluationTau = unique([linspace(0, 1, 47).'; ...
        (0:segmentCount).' / segmentCount]);
    model = azElPlannerMethods.hs3.internal.motion.hs3AffineSensitivity( ...
        segmentCount, duration_s, evaluationTau);
    initialState = struct( ...
        "position", -2.3 + rand(), ...
        "velocity", 0.7 + rand(), ...
        "acceleration", -0.4 + 0.8 * rand());
    jerk = 0.6 * randn(model.ControlCount, 1);
    zeroPolynomial = directReconstruction( ...
        zeros(model.ControlCount, 1), initialState, duration_s, segmentCount);
    jerkPolynomial = directReconstruction( ...
        jerk, initialState, duration_s, segmentCount);
    verifyCoefficientDelta(testCase, model, zeroPolynomial, jerkPolynomial, jerk);
    expectedTerminalDelta = model.terminalStateMap * jerk;
    actualTerminalDelta = jerkPolynomial.terminalState - ...
        zeroPolynomial.terminalState;
    verifyEqual(testCase, actualTerminalDelta, expectedTerminalDelta, ...
        "AbsTol", 2e-12, "RelTol", 2e-12);
    [zeroPosition, zeroVelocity] = evaluateDirect(zeroPolynomial, evaluationTau);
    [jerkPosition, jerkVelocity] = evaluateDirect(jerkPolynomial, evaluationTau);
    verifyEqual(testCase, jerkPosition - zeroPosition, ...
        model.positionAtTauMap * jerk, "AbsTol", 2e-12, "RelTol", 2e-12);
    verifyEqual(testCase, jerkVelocity - zeroVelocity, ...
        model.velocityAtTauMap * jerk, "AbsTol", 2e-12, "RelTol", 2e-12);
end
end

function testDirectionalFiniteDifferenceParity(testCase)
% Verify every coefficient and sampled map as a decision-space derivative.
rng(1325, "twister");
for segmentCount = [1 2 5 10]
    duration_s = 2.1 + 0.19 * segmentCount;
    evaluationTau = unique([linspace(0, 1, 53).'; ...
        ((0:segmentCount - 1).' + 0.5) / segmentCount]);
    model = azElPlannerMethods.hs3.internal.motion.hs3AffineSensitivity( ...
        segmentCount, duration_s, evaluationTau);
    initialState = struct("position", 1.4, "velocity", -0.8, ...
        "acceleration", 0.35);
    jerk = randn(model.ControlCount, 1);
    direction = randn(model.ControlCount, 1);
    direction = direction / norm(direction);
    differenceStep = 1e-5;
    lowerPolynomial = directReconstruction( ...
        jerk - differenceStep * direction, initialState, duration_s, segmentCount);
    upperPolynomial = directReconstruction( ...
        jerk + differenceStep * direction, initialState, duration_s, segmentCount);
    verifyDirectionalCoefficient(testCase, model, lowerPolynomial, ...
        upperPolynomial, direction, differenceStep);
    [lowerPosition, lowerVelocity] = evaluateDirect( ...
        lowerPolynomial, evaluationTau);
    [upperPosition, upperVelocity] = evaluateDirect( ...
        upperPolynomial, evaluationTau);
    verifyEqual(testCase, (upperPosition - lowerPosition) / ...
        (2 * differenceStep), model.positionAtTauMap * direction, ...
        "AbsTol", 2e-9, "RelTol", 2e-10);
    verifyEqual(testCase, (upperVelocity - lowerVelocity) / ...
        (2 * differenceStep), model.velocityAtTauMap * direction, ...
        "AbsTol", 2e-9, "RelTol", 2e-10);
    verifyEqual(testCase, (upperPolynomial.terminalState - ...
        lowerPolynomial.terminalState) / (2 * differenceStep), ...
        model.terminalStateMap * direction, ...
        "AbsTol", 2e-9, "RelTol", 2e-10);
end
end

