function [inequality, equality] = directConstraintValues( ...
        decision, initialState, duration_s, segmentCount, ...
        seedCorridor, corridor, corridorTau)
% Reconstruct raw fixed-time constraints independently of production maps.
controlCount = 2 * segmentCount + 1;
azimuthInitial = struct( ...
    "position", initialState.position(1), ...
    "velocity", initialState.velocity(1), ...
    "acceleration", initialState.acceleration(1));
elevationInitial = struct( ...
    "position", initialState.position(2), ...
    "velocity", initialState.velocity(2), ...
    "acceleration", initialState.acceleration(2));
azimuthPolynomial = directReconstruction( ...
    decision(1:controlCount), azimuthInitial, duration_s, segmentCount);
elevationPolynomial = directReconstruction( ...
    decision(controlCount + 1:end), elevationInitial, duration_s, segmentCount);
polynomial = combineScalarPolynomials( ...
    azimuthPolynomial, elevationPolynomial, segmentCount);
continuousInequality = directContinuousBounds(polynomial);
seedInequality = azElInternal.seedCorridorInequality( ...
    polynomial, seedCorridor);
[azimuthPosition, ~] = evaluateDirect(azimuthPolynomial, corridorTau);
[elevationPosition, ~] = evaluateDirect(elevationPolynomial, corridorTau);
position_deg = [azimuthPosition, elevationPosition];
controlIndex = [corridor.ControlIndex].';
normal = vertcat(corridor.FixedNormal);
offset_deg = [corridor.FixedBoundaryOffset_deg].' + ...
    [corridor.Clearance_deg].';
corridorInequality = offset_deg - sum( ...
    position_deg(controlIndex, :) .* normal, 2);
inequality = [continuousInequality; seedInequality; corridorInequality];
equality = [ ...
    azimuthPolynomial.terminalState(1); ...
    elevationPolynomial.terminalState(1); ...
    azimuthPolynomial.terminalState(2); ...
    elevationPolynomial.terminalState(2); ...
    azimuthPolynomial.terminalState(3); ...
    elevationPolynomial.terminalState(3)];
end

function polynomial = combineScalarPolynomials(azimuth, elevation, segmentCount)
% Assemble the two-axis coefficient shape consumed by shared constraints.
polynomial = struct( ...
    "SegmentCount", segmentCount, ...
    "positionPower_deg", cat(2, ...
    reshape(azimuth.positionPower, segmentCount, 1, 6), ...
    reshape(elevation.positionPower, segmentCount, 1, 6)), ...
    "velocityPower_deg_s", cat(2, ...
    reshape(azimuth.velocityPower, segmentCount, 1, 5), ...
    reshape(elevation.velocityPower, segmentCount, 1, 5)), ...
    "accelerationPower_deg_s2", cat(2, ...
    reshape(azimuth.accelerationPower, segmentCount, 1, 4), ...
    reshape(elevation.accelerationPower, segmentCount, 1, 4)), ...
    "jerkPower_deg_s3", cat(2, ...
    reshape(azimuth.jerkPower, segmentCount, 1, 3), ...
    reshape(elevation.jerkPower, segmentCount, 1, 3)));
end

function inequality = directContinuousBounds(polynomial)
% Reproduce the non-wrapped continuous Bernstein constraint value order.
positionViolation = directBernsteinViolations( ...
    polynomial.positionPower_deg, [-10 -10], [10 10]);
velocityViolation = directBernsteinViolations( ...
    polynomial.velocityPower_deg_s, [-3 -3], [3 3]);
accelerationViolation = directBernsteinViolations( ...
    polynomial.accelerationPower_deg_s2, [-2 -2], [2 2]);
jerkViolation = directBernsteinViolations( ...
    polynomial.jerkPower_deg_s3, [-3 -3], [3 3]);
firstAxis = [positionViolation(:, 1, :); velocityViolation(:, 1, :); ...
    accelerationViolation(:, 1, :); jerkViolation(:, 1, :)];
secondAxis = [positionViolation(:, 2, :); velocityViolation(:, 2, :); ...
    accelerationViolation(:, 2, :); jerkViolation(:, 2, :)];
segmentCount = polynomial.SegmentCount;
inequalityBySegment = [reshape(firstAxis, [], segmentCount); ...
    reshape(secondAxis, [], segmentCount)];
inequality = inequalityBySegment(:);
end

function violation = directBernsteinViolations( ...
        powerCoefficient, lowerBound, upperBound)
% Convert independent coefficient values through the shared exact basis.
segmentCount = size(powerCoefficient, 1);
coefficientCount = size(powerCoefficient, 3);
coefficientMatrix = reshape(permute( ...
    powerCoefficient, [3 1 2]), coefficientCount, []);
bernstein = azElInternal.powerToBernstein(coefficientMatrix);
bernstein = permute(reshape( ...
    bernstein, coefficientCount, segmentCount, 2), [1 3 2]);
violation = [bernstein - reshape(upperBound, 1, 2, 1); ...
    reshape(lowerBound, 1, 2, 1) - bernstein];
end

function verifyCoefficientDelta(testCase, model, zeroPolynomial, ...
        jerkPolynomial, jerk)
% Apply every coefficient tensor to one randomized control vector.
names = ["positionPower", "velocityPower", ...
    "accelerationPower", "jerkPower"];
for name = names
    coefficientMap = model.(name + "Map");
    predictedDelta = applyMap(coefficientMap, jerk);
    actualDelta = jerkPolynomial.(name) - zeroPolynomial.(name);
    verifyEqual(testCase, actualDelta, predictedDelta, ...
        "AbsTol", 2e-12, "RelTol", 2e-12);
end
end

function verifyDirectionalCoefficient(testCase, model, lowerPolynomial, ...
        upperPolynomial, direction, differenceStep)
% Compare centered directional differences for every polynomial field.
names = ["positionPower", "velocityPower", ...
    "accelerationPower", "jerkPower"];
for name = names
    actualDerivative = (upperPolynomial.(name) - ...
        lowerPolynomial.(name)) / (2 * differenceStep);
    expectedDerivative = applyMap(model.(name + "Map"), direction);
    verifyEqual(testCase, actualDerivative, expectedDerivative, ...
        "AbsTol", 2e-9, "RelTol", 2e-10);
end
end

function value = applyMap(coefficientMap, control)
% Contract a segment-by-power-by-control map with one control column.
value = reshape(sum(coefficientMap .* ...
    reshape(control, 1, 1, []), 3), ...
    size(coefficientMap, 1), size(coefficientMap, 2));
end

function polynomial = directReconstruction( ...
        jerk, initialState, duration_s, segmentCount)
% Independently propagate scalar states through exact local integrations.
segmentDuration_s = duration_s / segmentCount;
positionPower = zeros(segmentCount, 6);
velocityPower = zeros(segmentCount, 5);
accelerationPower = zeros(segmentCount, 4);
jerkPower = zeros(segmentCount, 3);
position = initialState.position;
velocity = initialState.velocity;
acceleration = initialState.acceleration;
for segmentIndex = 1:segmentCount
    startJerk = jerk(2 * segmentIndex - 1);
    midpointJerk = jerk(2 * segmentIndex);
    endJerk = jerk(2 * segmentIndex + 1);
    jerkLinear = -3 * startJerk + 4 * midpointJerk - endJerk;
    jerkQuadratic = 2 * startJerk - 4 * midpointJerk + 2 * endJerk;
    jerkPower(segmentIndex, :) = [startJerk, jerkLinear, jerkQuadratic];
    accelerationPower(segmentIndex, :) = [acceleration, ...
        segmentDuration_s * startJerk, ...
        segmentDuration_s * jerkLinear / 2, ...
        segmentDuration_s * jerkQuadratic / 3];
    velocityPower(segmentIndex, :) = [velocity, ...
        segmentDuration_s * acceleration, ...
        segmentDuration_s^2 * startJerk / 2, ...
        segmentDuration_s^2 * jerkLinear / 6, ...
        segmentDuration_s^2 * jerkQuadratic / 12];
    positionPower(segmentIndex, :) = [position, ...
        segmentDuration_s * velocity, ...
        segmentDuration_s^2 * acceleration / 2, ...
        segmentDuration_s^3 * startJerk / 6, ...
        segmentDuration_s^3 * jerkLinear / 24, ...
        segmentDuration_s^3 * jerkQuadratic / 60];
    position = sum(positionPower(segmentIndex, :));
    velocity = sum(velocityPower(segmentIndex, :));
    acceleration = sum(accelerationPower(segmentIndex, :));
end
polynomial = struct( ...
    "positionPower", positionPower, ...
    "velocityPower", velocityPower, ...
    "accelerationPower", accelerationPower, ...
    "jerkPower", jerkPower, ...
    "terminalState", [position; velocity; acceleration]);
end

function [position, velocity] = evaluateDirect(polynomial, evaluationTau)
% Evaluate ascending local powers using a test-owned Horner loop.
segmentCount = size(polynomial.positionPower, 1);
scaledTau = segmentCount * evaluationTau;
segmentIndex = min(segmentCount, floor(scaledTau) + 1);
localTau = scaledTau - segmentIndex + 1;
position = evaluatePower(polynomial.positionPower, segmentIndex, localTau);
velocity = evaluatePower(polynomial.velocityPower, segmentIndex, localTau);
end

function value = evaluatePower(coefficient, segmentIndex, localTau)
% Apply Horner evaluation independently of production polynomial helpers.
value = zeros(size(localTau));
for powerIndex = size(coefficient, 2):-1:1
    selectedCoefficient = coefficient(sub2ind( ...
        size(coefficient), segmentIndex, ...
        powerIndex * ones(size(segmentIndex))));
    selectedCoefficient = selectedCoefficient(:);
    value = selectedCoefficient + localTau .* value;
end
end
