function verifyConstraintDirection(testCase, decision, direction, step, ...
        inequality, equality, inequalityGradient, equalityGradient, ...
        initialState, goalState, limits, options, obstacles, corridor, ...
        corridorTau, seedCorridor, segmentCount, minimumFinalTime_s, ...
        reconstructFunction, differenceMode, tolerance)
% Compare the returned fmincon-oriented Jacobians with raw value differences.
upperDecision = decision + step * direction;
[upperInequality, upperEquality] = ...
    azElPlannerMethods.hs3.internal.motion.evaluateHs3TrajectoryConstraints( ...
    upperDecision, true, goalState.time_s, minimumFinalTime_s, ...
    goalState.time_s, segmentCount, initialState, goalState, limits, ...
    options, obstacles, corridor, corridorTau, seedCorridor, ...
    reconstructFunction);
if differenceMode == "central"
    lowerDecision = decision - step * direction;
    [lowerInequality, lowerEquality] = ...
        azElPlannerMethods.hs3.internal.motion.evaluateHs3TrajectoryConstraints( ...
        lowerDecision, true, goalState.time_s, minimumFinalTime_s, ...
        goalState.time_s, segmentCount, initialState, goalState, limits, ...
        options, obstacles, corridor, corridorTau, seedCorridor, ...
        reconstructFunction);
    inequalityDifference = (upperInequality - lowerInequality) / (2 * step);
    equalityDifference = (upperEquality - lowerEquality) / (2 * step);
else
    inequalityDifference = (upperInequality - inequality) / step;
    equalityDifference = (upperEquality - equality) / step;
end
verifyEqual(testCase, inequalityDifference, ...
    inequalityGradient.' * direction, "AbsTol", tolerance, ...
    "RelTol", tolerance);
verifyEqual(testCase, equalityDifference, ...
    equalityGradient.' * direction, "AbsTol", tolerance, ...
    "RelTol", tolerance);
end

function polynomial = reconstructHs3Polynomial( ...
        jerk_deg_s3, initialState, finalTime_s, segmentCount)
% Build the two-axis test polynomial through independent scalar propagation.
duration_s = finalTime_s - initialState.time_s;
azimuthInitial = struct( ...
    "position", initialState.position_deg(1), ...
    "velocity", initialState.velocity_deg_s(1), ...
    "acceleration", initialState.acceleration_deg_s2(1));
elevationInitial = struct( ...
    "position", initialState.position_deg(2), ...
    "velocity", initialState.velocity_deg_s(2), ...
    "acceleration", initialState.acceleration_deg_s2(2));
azimuth = directReconstruction( ...
    jerk_deg_s3(:, 1), azimuthInitial, duration_s, segmentCount);
elevation = directReconstruction( ...
    jerk_deg_s3(:, 2), elevationInitial, duration_s, segmentCount);
polynomial = combineScalarPolynomials(azimuth, elevation, segmentCount);
polynomial.SegmentStartTime_s = initialState.time_s + ...
    (0:segmentCount - 1).' * duration_s / segmentCount;
polynomial.SegmentDuration_s = duration_s / segmentCount;
polynomial.FinalTime_s = finalTime_s;
polynomial.TerminalState = struct( ...
    "position_deg", [azimuth.terminalState(1), elevation.terminalState(1)], ...
    "velocity_deg_s", [azimuth.terminalState(2), elevation.terminalState(2)], ...
    "acceleration_deg_s2", ...
    [azimuth.terminalState(3), elevation.terminalState(3)]);
end

