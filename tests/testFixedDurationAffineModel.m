function testSimpleKnotModelMatchesDirectConversion(testCase)
% Cover the route-sized quintic with simple interior knots.
spanDuration_s = [0.7; 1.1; 0.9];
controlPointCount = numel(spanDuration_s) + 5;
verifyModelIdentity( ...
    testCase, controlPointCount, 2.5, spanDuration_s);
end

function testDoubledKnotCompactModelMatchesDirectConversion(testCase)
% Cover the compact C3 eight-span, twenty-control representation.
