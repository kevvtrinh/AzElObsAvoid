function tests = testBmtpWarmStartConversion
%% Section 0: Header & Readme
% SYNTAX
%   tests = testBmtpWarmStartConversion
%**************************************************************************
% PURPOSE
%   - Verify standalone equal-span conversion of Ruckig switching motions.
%**************************************************************************
% INPUTS
%   - None.
%**************************************************************************
% OUTPUTS
%   - tests (matlab.unittest function test array)
%**************************************************************************
% UNITS
%   - Fixture position is in degrees and time is seconds.
%**************************************************************************
tests = functiontests(localfunctions);
end

function setupOnce(~)
% Add only the independent trajectory-engine parent for isolated tests.
repositoryRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(fullfile(repositoryRoot, "trajectory"));
end

function testSinglePhaseSpanIsReproducedToRoundoff(testCase)
% Anchor the fit on a span that contains one constant-jerk polynomial.
initialState = struct( ...
    "time_s", 2, "position_deg", [1 -2], ...
    "velocity_deg_s", [0.2 -0.1], ...
    "acceleration_deg_s2", [0.05 0.03]);
motion = bmtpEngine.createMotionRecord( ...
    struct(), initialState, [0; 3], [0.1 -0.2], 0.05, ...
    "singleJerkPhaseFixture");
[warmStart, diagnostics] = ...
    bmtpEngine.convertPolynomialToWarmStart(motion.Polynomial, 1, 7);

verifySize(testCase, warmStart.ControlPoint_deg, [1 8 2]);
verifyEqual(testCase, warmStart.SegmentTime_s, 3, "AbsTol", 1e-14);
verifyEqual(testCase, diagnostics.InteriorSourceBreakCount, 0);
verifyLessThanOrEqual(testCase, ...
    diagnostics.MaximumPositionDeviation_deg, 1e-12);
end

function testRuckigProfileReportsSingleAndMultiPhaseErrors(testCase)
% Measure both exact single-phase spans and approximate switch-crossing spans.
[ruckigResult, sharedPolynomial] = createRuckigPolynomial();
fineSegmentCount = 64;
[~, fineDiagnostics] = bmtpEngine.convertPolynomialToWarmStart( ...
    sharedPolynomial, fineSegmentCount, 7);
singlePhaseSpan = fineDiagnostics.InteriorSourceBreakCount == 0;
verifyTrue(testCase, any(singlePhaseSpan));
verifyLessThanOrEqual(testCase, max( ...
    fineDiagnostics.SpanMaximumPositionDeviation_deg(singlePhaseSpan)), ...
    1e-12);

coarseSegmentCount = 2;
[warmStart, coarseDiagnostics] = ...
    bmtpEngine.convertPolynomialToWarmStart( ...
    sharedPolynomial, coarseSegmentCount, 7);
verifyTrue(testCase, any(coarseDiagnostics.InteriorSourceBreakCount > 0));
verifySize(testCase, warmStart.ControlPoint_deg, [2 8 2]);
verifyEqual(testCase, warmStart.SegmentTime_s, ...
    ruckigResult.Duration / coarseSegmentCount, "AbsTol", 1e-12);
verifyTrue(testCase, isfinite( ...
    coarseDiagnostics.MaximumPositionDeviation_deg));
end

function [result, polynomial] = createRuckigPolynomial()
% Reconstruct the shared record directly from an exact Ruckig jerk profile.
initialState = struct( ...
    "time", 0, "position", [0 0], ...
    "velocity", [0 0], "acceleration", [0 0]);
terminalState = struct( ...
    "position", [4 2], "velocity", [0 0], ...
    "acceleration", [0 0], "maximumTime", 20);
limits = struct( ...
    "maximumVelocity", [2 2], ...
    "maximumAcceleration", [1 1], ...
    "maximumJerk", [2 2], ...
    "positionLower", [-10 -10], ...
    "positionUpper", [10 10]);
result = ruckigEngine.solve( ...
    initialState, terminalState, limits, struct());
assert(result.Success, result.Message);
sharedInitialState = struct( ...
    "time_s", initialState.time, ...
    "position_deg", initialState.position, ...
    "velocity_deg_s", initialState.velocity, ...
    "acceleration_deg_s2", initialState.acceleration);
switchTime_s = [result.Polynomial.SegmentStartTime; result.FinalTime];
motion = bmtpEngine.createMotionRecord( ...
    struct(), sharedInitialState, switchTime_s, result.ControlJerk, ...
    0.05, "ruckigConversionFixture");
polynomial = motion.Polynomial;
end
