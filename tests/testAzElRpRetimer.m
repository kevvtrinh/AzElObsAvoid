function testNinetyDegreeCornerIsRoundedAndFaster(testCase)
% The selected equal-leg turn must beat the evaluated sharp-stop member.
route_deg = [0 0; 10 0; 10 10];
[initialState, goalState, limits, options] = requestForRoute(route_deg);
obstacleField = buildAzElTimeObstacleField([]);

[smoothPath, timedPath] = azElInternal.retimeAzElSpatialPath( ...
    route_deg, obstacleField, initialState, goalState, limits, ...
    options, initialState.time_s);

testCase.verifyTrue(timedPath.Success, timedPath.Message);
testCase.verifyEqual(smoothPath.RoundedCornerCount, 1);
testCase.verifyEqual(timedPath.TerminationReason, ...
    "certifiedUnconstrainedOptimum");
testCase.verifyGreaterThan( ...
    smoothPath.CornerDiagnostics. ...
    CertifiedMinimumCurvatureRadius_deg, 0);
candidates = smoothPath.GeometryOptimizationDiagnostics.Candidates;
sharpIndex = [];
for candidateIndex = 1:numel(candidates)
    if all(candidates(candidateIndex).RadiusScaleByCorner == 0)
        sharpIndex = candidateIndex;
        break;
    end
end
testCase.assertNotEmpty(sharpIndex);
testCase.verifyLessThan(timedPath.MinimumMotionDuration_s, ...
    candidates(sharpIndex).MinimumMotionDuration_s);
testCase.verifyTrue( ...
    timedPath.RetimerDiagnostics.FinalCollisionCertificate.Resolved);
testCase.verifyTrue(timedPath.RetimerDiagnostics.FinalCollisionFree);
end

function testStaticCollisionUsesNondecreasingRadiusRepair(testCase)
% A protected corner obstruction must produce an outward certified bulge.
route_deg = [0 0; 10 0; 10 10];
[initialState, goalState, limits, options] = requestForRoute(route_deg);
obstacle = makeAzElObstacleData( ...
    "protected region", [0; 100], ...
    [9.4; 9.7; 9.7; 9.4], [0.3; 0.3; 0.7; 0.7], 0.02);
obstacleField = buildAzElTimeObstacleField(obstacle);

[smoothPath, timedPath] = azElInternal.retimeAzElSpatialPath( ...
    route_deg, obstacleField, initialState, goalState, limits, ...
    options, initialState.time_s);

diagnostics = timedPath.RetimerDiagnostics;
testCase.verifyTrue(timedPath.Success, timedPath.Message);
testCase.verifyEqual(timedPath.TerminationReason, ...
    "certifiedAfterLocalRepair");
testCase.verifyFalse(diagnostics.UnconstrainedCollisionFree);
testCase.verifyTrue(diagnostics.FinalCollisionFree);
testCase.verifyGreaterThan(diagnostics.RepairAttemptCount, 0);
testCase.verifyTrue(diagnostics.SafetyMarginPreserved);
testCase.verifyEqual(diagnostics.OriginalSafetyMargins_deg, 0.02, ...
    "AbsTol", 1e-12);
testCase.verifyGreaterThanOrEqual(diagnostics.FinalRadius_deg, ...
    diagnostics.UnconstrainedRadius_deg - 1e-10);
testCase.verifyGreaterThan(norm( ...
    diagnostics.CornerRepairDiagnostics(1).Displacement_deg), 0);
blocked = queryAzElTimedCurveCollision( ...
    obstacleField, timedPath, struct( ...
        "MaximumNumericalEnvelope_deg", ...
            options.RpCollisionCurveTolerance_deg, ...
        "TimePaddingSamples", 0));
testCase.verifyFalse(any(blocked));
testCase.verifyEqual(smoothPath.OriginalPathPosition_deg, route_deg);
end

function testLineCollisionReturnsRepairExhaustion(testCase)
% A colliding line has no same-route curve repair and must fail honestly.
route_deg = [0 0; 10 0];
[initialState, goalState, limits, options] = requestForRoute(route_deg);
obstacle = makeAzElObstacleData( ...
    "line blocker", [0; 100], [4; 6; 6; 4], [-1; -1; 1; 1], 0.05);
obstacleField = buildAzElTimeObstacleField(obstacle);

[~, timedPath] = azElInternal.retimeAzElSpatialPath( ...
    route_deg, obstacleField, initialState, goalState, limits, ...
    options, initialState.time_s);

testCase.verifyFalse(timedPath.Success);
testCase.verifyTrue(timedPath.HasTimedAttempt);
testCase.verifyEqual(timedPath.TerminationReason, ...
    "collisionRepairExhausted");
testCase.verifyTrue(timedPath.RetimerDiagnostics.RepairExhausted);
testCase.verifyFalse(timedPath.RetimerDiagnostics.FinalCollisionFree);
testCase.verifyNotEmpty(timedPath.RetimerDiagnostics. ...
    InitialCollisionSegmentIndex);
end

function testStructurallyDifferentTurnsAreDeterministic(testCase)
% Unequal oblique turns exercise a different corner family and repeatability.
route_deg = [0 0; 6 0; 8 3; 12 4];
[initialState, goalState, limits, options] = requestForRoute(route_deg);
obstacleField = buildAzElTimeObstacleField([]);

[firstSmoothPath, firstTimedPath] = ...
    azElInternal.retimeAzElSpatialPath( ...
        route_deg, obstacleField, initialState, goalState, limits, ...
        options, initialState.time_s);
[secondSmoothPath, secondTimedPath] = ...
    azElInternal.retimeAzElSpatialPath( ...
        route_deg, obstacleField, initialState, goalState, limits, ...
        options, initialState.time_s);

testCase.verifyTrue(firstTimedPath.Success, firstTimedPath.Message);
testCase.verifyGreaterThanOrEqual(firstSmoothPath.RoundedCornerCount, 1);
testCase.verifyEqual(firstTimedPath.MinimumMotionDuration_s, ...
    secondTimedPath.MinimumMotionDuration_s, "AbsTol", 1e-12);
testCase.verifyEqual(firstSmoothPath.position_deg, ...
    secondSmoothPath.position_deg, "AbsTol", 1e-12);
testCase.verifyGreaterThan( ...
    firstSmoothPath.GeometryOptimizationDiagnostics.CandidateCount, 6);
end

function testCurveEnvelopeDetectsBetweenSampleHazard(testCase)
% Clear endpoints must not hide a parabolic mid-interval obstacle crossing.
obstacle = makeAzElObstacleData( ...
    "between samples", [0; 1], ...
    [0.45; 0.55; 0.55; 0.45], [0.9; 0.9; 1.1; 1.1], 0);
obstacleField = buildAzElTimeObstacleField(obstacle);
profile = struct( ...
    "StartTime_s", 0, ...
    "EndTime_s", 1, ...
    "Duration_s", 1, ...
    "PhaseStartTime_s", 0, ...
    "PhaseDuration_s", 1);
timedPath = struct( ...
    "Success", true, ...
    "time_s", [0; 1], ...
    "position_deg", [0 0; 1 0], ...
    "ConstraintDiagnostics", struct( ...
        "PeakAcceleration_deg_s2", [0 8]), ...
    "SegmentProfiles", profile);
sampleBlocked = queryAzElTimeObstacle( ...
    obstacleField, timedPath.position_deg(:, 1), ...
    timedPath.position_deg(:, 2), timedPath.time_s);

[blocked, certificate] = queryAzElTimedCurveCollision( ...
    obstacleField, timedPath, struct( ...
        "MaximumNumericalEnvelope_deg", 1.01, ...
        "TimePaddingSamples", 0));

testCase.verifyFalse(any(sampleBlocked));
testCase.verifyTrue(certificate.Resolved);
testCase.verifyEqual(certificate.MaximumEnvelope_deg, 1, ...
    "AbsTol", 1e-10);
testCase.verifyTrue(any(blocked));
testCase.verifyFalse(certificate.CollisionFree);
end

function testMovingLineCollisionIsLocalizedAfterRetiming(testCase)
% A moving protected region must be checked at the retimed crossing time.
route_deg = [0 0; 10 0];
[initialState, goalState, limits, options] = requestForRoute(route_deg);
azimuthBySlice_deg = { ...
    [4.8; 5.2; 5.2; 4.8]; ...
    [4.8; 5.2; 5.2; 4.8]};
elevationBySlice_deg = { ...
    [0.7; 0.7; 1.3; 1.3]; ...
    [-1.3; -1.3; -0.7; -0.7]};
obstacle = makeAzElObstacleData( ...
    "moving blocker", [0; 3.66], ...
    azimuthBySlice_deg, elevationBySlice_deg, 0.02);
obstacleField = buildAzElTimeObstacleField(obstacle);

[~, timedPath] = azElInternal.retimeAzElSpatialPath( ...
    route_deg, obstacleField, initialState, goalState, limits, ...
    options, initialState.time_s);

testCase.verifyFalse(timedPath.Success);
