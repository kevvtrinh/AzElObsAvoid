function testPlannerUsesAnotherRouteAfterDirectRepairExhaustion(testCase)
% A failed direct retimer candidate must not stop visibility-route search.
obstacle = makeAzElObstacleData( ...
    "central blocker", [0; 100], ...
    [-0.5; 0.5; 0.5; -0.5], [-0.5; -0.5; 0.5; 0.5], 0.1);
initialState = struct( ...
    "time_s", 0, "position_deg", [-3 0], ...
    "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", 30, "position_deg", [3 0], ...
    "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
limits = struct( ...
    "maxVelocity_deg_s", [3 3], ...
    "maxAcceleration_deg_s2", [2 2], ...
    "maxJerk_deg_s3", [Inf Inf]);
options = planAzElMotion();
options.UseRpAgent = false;
options.CollisionTimePaddingSamples = 0;
options.MaximumTemporalRefinementSteps = 0;

result = planAzElMotion( ...
    obstacle, initialState, goalState, limits, options);

testCase.verifyTrue(result.Success, result.Message);
testCase.verifyGreaterThan(result.selectedCandidateIndex, 1);
testCase.verifyFalse(result.candidateDiagnostics.Retimed(1));
testCase.verifyTrue(contains( ...
    result.candidateDiagnostics.Message(1), ...
    "equal-or-larger-radius", "IgnoreCase", true));
testCase.verifyTrue(result.timedSlopePath. ...
    RetimerDiagnostics.FinalCollisionFree);
end

