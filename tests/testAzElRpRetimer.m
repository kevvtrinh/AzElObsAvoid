testCase.verifyLessThan(max(collisionTime_s), 2.0);
end

function testRepairPreservesUnrelatedCurveControls(testCase)
% Repair at the first turn must not alter the second turn control polygon.
route_deg = [0 0; 10 0; 10 10; 20 10];
[initialState, goalState, limits, options] = requestForRoute(route_deg);
obstacle = makeAzElObstacleData( ...
    "first turn blocker", [0; 100], ...
    [9.4; 9.7; 9.7; 9.4], [0.3; 0.3; 0.7; 0.7], 0.02);
obstacleField = buildAzElTimeObstacleField(obstacle);

[smoothPath, timedPath] = azElInternal.retimeAzElSpatialPath( ...
    route_deg, obstacleField, initialState, goalState, limits, ...
    options, initialState.time_s);

diagnostics = timedPath.RetimerDiagnostics;
testCase.verifyTrue(timedPath.Success, timedPath.Message);
testCase.verifyEqual(timedPath.TerminationReason, ...
    "certifiedAfterLocalRepair");
testCase.verifyGreaterThan(norm( ...
    diagnostics.CornerRepairDiagnostics(1).Displacement_deg), 0);
testCase.verifyEqual( ...
    diagnostics.CornerRepairDiagnostics(2).Displacement_deg, [0 0]);
testCase.verifyEqual( ...
    smoothPath.CornerDiagnostics(2).ControlPoints_deg, ...
    diagnostics.UnconstrainedControlPointsByCorner_deg{2}, ...
    "AbsTol", 0);
unrelatedCurvePrimitiveIndex = find( ...
    [smoothPath.Primitives.CornerPathPointIndex] == 3);
testCase.verifyFalse(any(ismember(unrelatedCurvePrimitiveIndex, ...
    diagnostics.ContinuityUpdatedPrimitiveIndex)));
end

function testEachCollidingCornerReceivesRepairBudget(testCase)
% Two blocked turns must each receive local proposals before exhaustion.
route_deg = [0 0; 10 0; 10 10; 20 10];
[initialState, goalState, limits, options] = requestForRoute(route_deg);
firstObstacle = makeAzElObstacleData( ...
    "first turn blocker", [0; 100], ...
    [9.4; 9.7; 9.7; 9.4], [0.3; 0.3; 0.7; 0.7], 0.02);
secondObstacle = makeAzElObstacleData( ...
    "second turn blocker", [0; 100], ...
    [10.3; 10.7; 10.7; 10.3], [9.4; 9.4; 9.7; 9.7], 0.02);
obstacleField = buildAzElTimeObstacleField( ...
    [firstObstacle; secondObstacle]);

[~, timedPath] = azElInternal.retimeAzElSpatialPath( ...
    route_deg, obstacleField, initialState, goalState, limits, ...
    options, initialState.time_s);

diagnostics = timedPath.RetimerDiagnostics;
testCase.verifyTrue(timedPath.Success, timedPath.Message);
testCase.verifyGreaterThan(diagnostics.RepairAttemptCountByCorner(1), 0);
testCase.verifyGreaterThan(diagnostics.RepairAttemptCountByCorner(2), 0);
testCase.verifyTrue(all(diagnostics.FinalRadius_deg + 1e-10 >= ...
    diagnostics.UnconstrainedRadius_deg));
testCase.verifyTrue(diagnostics.FinalCollisionFree);
end

