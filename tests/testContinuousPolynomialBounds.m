function setupOnce(testCase)
% Add production and shared trajectory packages for public validation.
repositoryRoot = fileparts(fileparts(mfilename("fullpath")));
addpath(repositoryRoot);
addpath(fullfile(repositoryRoot, "trajectory"));
testCase.TestData.RepositoryRoot = repositoryRoot;
end

function testOutsideControlDoesNotRejectTouchingCurve(testCase)
% Do not reject one outside Bernstein control when the curve stays in range.
validation = validateArch(4, 1);

verifyTrue(testCase, validation.PositionWithinLimits);
verifyTrue(testCase, validation.Passed, validation.Message);
end

function testInteriorOvershootIsRejected(testCase)
% Reject a structurally identical curve whose true interior exceeds the limit.
validation = validateArch(5, 1);

verifyFalse(testCase, validation.PositionWithinLimits);
verifyFalse(testCase, validation.Passed);
verifyTrue(testCase, any(validation.Issues == "continuous limits"));
end

function validation = validateArch(amplitudeCoefficient, upperLimit_deg)
% Validate p(t)=a*t*(1-t) with exact derivative histories on [0, 1].
positionPower_deg = zeros(1, 2, 4);
positionPower_deg(1, 1, 2:3) = ...
    [amplitudeCoefficient, -amplitudeCoefficient];
velocityPower_deg_s = zeros(1, 2, 3);
velocityPower_deg_s(1, 1, 1:2) = ...
    [amplitudeCoefficient, -2 * amplitudeCoefficient];
accelerationPower_deg_s2 = zeros(1, 2, 2);
accelerationPower_deg_s2(1, 1, 1) = -2 * amplitudeCoefficient;
polynomial = struct( ...
    "SegmentCount", 1, ...
    "SegmentStartTime_s", 0, ...
    "SegmentDuration_s", 1, ...
    "FinalTime_s", 1, ...
    "positionPower_deg", positionPower_deg, ...
    "velocityPower_deg_s", velocityPower_deg_s, ...
    "accelerationPower_deg_s2", accelerationPower_deg_s2, ...
    "jerkPower_deg_s3", zeros(1, 2, 1), ...
    "TerminalState", struct());
sampleTime_s = [0; 0.5; 1];
[~, position_deg, velocity_deg_s, acceleration_deg_s2, jerk_deg_s3] = ...
    bmtpEngine.evaluatePolynomial(polynomial, sampleTime_s);
trajectory = struct( ...
    "time_s", sampleTime_s, ...
    "position_deg", position_deg, ...
    "velocity_deg_s", velocity_deg_s, ...
    "acceleration_deg_s2", acceleration_deg_s2, ...
    "jerk_deg_s3", jerk_deg_s3, ...
    "Polynomial", polynomial);
initialState = struct( ...
    "time_s", 0, ...
    "position_deg", position_deg(1, :), ...
    "velocity_deg_s", velocity_deg_s(1, :), ...
    "acceleration_deg_s2", acceleration_deg_s2(1, :));
goalState = struct( ...
    "time_s", 1, ...
    "position_deg", position_deg(end, :), ...
    "velocity_deg_s", velocity_deg_s(end, :), ...
    "acceleration_deg_s2", acceleration_deg_s2(end, :));
limits = struct( ...
    "maxVelocity_deg_s", [6 1], ...
    "maxAcceleration_deg_s2", [12 1], ...
    "maxJerk_deg_s3", [1 1], ...
    "azimuthInterval_deg", [-1 upperLimit_deg], ...
    "elevationInterval_deg", [-1 1]);
options = obstacleAvoidance.planTrajectory();
options.GoalTimeMode = "fixedArrival";
validation = obstacleAvoidance.validateTrajectory( ...
    trajectory, [], initialState, goalState, limits, options);
end
