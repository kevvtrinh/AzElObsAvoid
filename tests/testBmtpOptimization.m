function travelRefinementAddsNewCollisionPlanes(testCase)
    box_units = [-0.5, -0.5; 0.5, -0.5; 0.5, 0.5; -0.5, 0.5];
    waypoints_units = [-3, 0; -3, 3; 3, 3; 3, 0];
    controls_units = zeros(3, 9, 2);
    for span = 1:3
        points_units = [repmat(waypoints_units(span, :), 4, 1); ...
            mean(waypoints_units(span:span + 1, :), 1); ...
            repmat(waypoints_units(span + 1, :), 4, 1)];
        controls_units(span, :, :) = reshape(points_units, 1, 9, 2);
    end
    plane = struct( ...
        'Active',          false, ...
        'Verified',        false, ...
        'ExitFlag',        NaN, ...
        'Normal',          zeros(2), ...
        'Offset_units',    zeros(1, 2), ...
        'SignedGap_units', NaN, ...
        'TimeFraction',    [0, 1]);
    initial = struct( ...
        'time_s',                0, ...
        'position_units',        waypoints_units(1, :), ...
        'velocity_units_s',      [0, 0], ...
        'acceleration_units_s2', [0, 0]);
    goal = struct( ...
        'time_s',                12, ...
        'position_units',        waypoints_units(end, :), ...
        'velocity_units_s',      [0, 0], ...
        'acceleration_units_s2', [0, 0]);
    limits = struct( ...
        'xInterval_units',          [-10, 10], ...
        'yInterval_units',          [-10, 10], ...
        'maxVelocity_units_s',      [5, 5], ...
        'maxAcceleration_units_s2', [10, 10], ...
        'maxJerk_units_s3',         [20, 20]);
    normalized = planner([], initial, goal, limits, ...
        struct('GoalTimeMode', "earliestArrival"));
    edgeLength_units = vecnorm(diff(waypoints_units), 2, 2);
    seed = struct( ...
        'position_units',    waypoints_units, ...
        'tau',               [0; cumsum(edgeLength_units)] / sum(edgeLength_units), ...
        'UsesVariableClock', true);
    request = bmtpEngine.prepareRequest(seed, ...
        struct('regions_units', {{box_units}}, ...
        'coverage', struct('Passed', true, 'ExactRegionCount', 1, ...
        'BreakTime_s', [initial.time_s; goal.time_s])), ...
        struct('initialState', normalized.Inputs.initialState, ...
        'goalState', normalized.Inputs.goalState, ...
        'limits', normalized.Diagnostics.Limits, ...
        'options', normalized.Options));
    alternating = bmtpEngine.optimization.createOptimizationResult( ...
        "A complete time-scoped feasible iterate was retained.", "", "", false, ...
        controls_units, [4; 4; 4], repmat(plane, 3, 1), false(3, 1));
    diagnostics = struct('ConicSolver', bmtpEngine.optimization.accumulateConicDiagnostics());
    roundoffReserve_units = normalized.Diagnostics.SeparationProof.RoundoffReserve_units;
    target_units  = normalized.Diagnostics.SeparationProof.RequiredGap_units - roundoffReserve_units;
    [refined, diagnostics] = bmtpEngine.optimization.refineTravel( ...
        request, alternating, [], [], diagnostics, target_units, roundoffReserve_units);
    verifyTrue(testCase, diagnostics.TravelRefinementAccepted);
    verifyGreaterThan(testCase, diagnostics.TaggedPairCount, 0);
    verifyLessThan(testCase, diagnostics.TravelRefinementFinalLength_units, ...
        diagnostics.TravelRefinementInitialLength_units);
    prepared = struct('ControlPoint_units', refined.ControlPoint_units, ...
        'SegmentTime_s', refined.SegmentTime_s(:), ...
        'FinalTime_s', request.InitialState.time_s + sum(refined.SegmentTime_s));
    verifyTrue(testCase, bmtpEngine.validation.checkFinalMotion( ...
        request, prepared, roundoffReserve_units, target_units).Passed);
end

