function differentTimeWindowsDoNotConflict(testCase, limits, options)
    initial = struct('time_s',0,'position_units',[-1,0],'velocity_units_s',[0,0],'acceleration_units_s2',[0,0]);
    goal = initial; goal.time_s = 6; goal.position_units = [1,0];
    planes = repmat(struct('Active',true,'Normal',[1,0;1,0],'Offset_units',[0.5,0.5], ...
        'TimeFraction',[0,0.1]),1,2);
    planes(2).Normal = -planes(1).Normal; planes(2).TimeFraction = [0.9,1];
    request = stepRequest(5,initial,goal,limits,options);
    [controls,durations,flag,output,constraintBase] = ...
        bmtpEngine.optimization.solveTrajectoryStep(request, ...
        trajectoryStep(1,planes,1e-8,6));
    verifyTrue(testCase,flag>0 || flag==-7);
    verifyEqual(testCase,durations,6);
    verifyLessThan(testCase,output.MaximumClearanceSlack_units,1e-6);
    first = bmtpEngine.motion.restrictBezier(squeeze(controls),[0,0.1]);
    last = bmtpEngine.motion.restrictBezier(squeeze(controls),[0.9,1]);
    verifyLessThan(testCase,max(first(:,1)),-0.5);
    verifyGreaterThan(testCase,min(last(:,1)),0.5);
    % The same two exclusions overlap in time and are genuinely incompatible.
    planes(1).TimeFraction = [0,1]; planes(2).TimeFraction = [0,1];
    [~,~,flag,output] = bmtpEngine.optimization.solveTrajectoryStep(request, ...
        trajectoryStep(1,planes,1e-8,6));
    verifyTrue(testCase,flag<=0 || output.MaximumClearanceSlack_units>0.4);
    verifyTrue(testCase,output.ConstraintGenerationApplied);
    verifyGreaterThan(testCase,output.SolveCount,1);
    verifyEqual(testCase,output.LoadedPlanePairCount,2);

    reducedStep = trajectoryStep(1,planes(1),1e-8,6);
    reducedStep.ConstraintBase = constraintBase;
    [~,~,~,~,reducedConstraintBase] = ...
        bmtpEngine.optimization.solveTrajectoryStep(request,reducedStep);
    verifyNotEqual(testCase,reducedConstraintBase.Key.VariableCount, ...
        constraintBase.Key.VariableCount);
    verifyEqual(testCase,size(reducedConstraintBase.A,2), ...
        reducedConstraintBase.Key.VariableCount);
end

function singleSpanTimedInfeasibilityReturnsNoMotion(testCase, limits, options)
    planes = repmat(struct('Active',false),1,0);
    % Two units in 0.1 s exceeds the two-units/s velocity bound alone.
    request = stepRequest(8,struct('position_units',[-1,0]),struct('position_units',[1,0.5]),limits,options);
    [controls,duration_s,flag] = bmtpEngine.optimization.solveTrajectoryStep( ...
        request,timedStep(1,planes,1e-8,0.1));
    verifyLessThanOrEqual(testCase,flag,0);
    verifyEmpty(testCase,controls);
    verifyTrue(testCase,isnan(duration_s));
end

function singleSpanTimedMotionIsIndependentlyValid(testCase, limits, options)
    planes = repmat(struct('Active',false),1,0);
    for degree = [5,8]
        for horizon_s = [5,6,8,10]
            request = stepRequest(degree,struct('position_units',[-1,0]), ...
                struct('position_units',[1,0.5]),limits,options);
            [controls,duration_s,flag,output] = bmtpEngine.optimization.solveTrajectoryStep( ...
                request,timedStep(1,planes,1e-8,horizon_s));
            assertNotEmpty(testCase,controls);
            verifyTrue(testCase,flag>0 || flag==-7);
            verifyEqual(testCase,output.OptimizationConverged,flag>0);
            verifyEqual(testCase,duration_s,horizon_s,'AbsTol',1e-12);
            initial = struct('time_s',0,'position_units',[-1,0]);
            goal = struct('time_s',horizon_s,'position_units',[1,0.5]);
            result = planner([],initial,goal,limits,struct('GoalTimeMode','fixedArrival'));
            seed = struct('position_units',[-1,0;1,0.5],'tau',[0;1]);
            request = bmtpEngine.prepareRequest(seed, ...
                struct('regions_units', {cell(0,1)}, ...
                'coverage', struct('Passed',true,'ExactRegionCount',0)), ...
                struct('initialState', result.Inputs.initialState, ...
                'goalState', result.Inputs.goalState, ...
                'limits', result.Diagnostics.Limits, ...
                'options', result.Options));
            prepared = bmtpEngine.motion.createMotion(request,controls,duration_s);
            [~,roundoffReserve_units] = bmtpEngine.validation.createCoordinateTolerances( ...
                controls,limits.xInterval_units,limits.yInterval_units);
