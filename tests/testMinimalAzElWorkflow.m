function testStaticBlockerCarriesSpeedThroughTurn(testCase)
% PURPOSE
%   - Verify that the RL route carries speed through a certified turn.
obstacle = makeAzElObstacleData("static blocker", [0; 20], ...
    [-0.5; 0.5; 0.5; -0.5], [-1; -1; 1; 1], 0.1);
[initialState, goalState, limits] = standardRequest( ...
    [-3 0], [3 0], 20);
options = fastOptions(3);
options.UseParallel = "on";
result = planAzElMotion( ...
    obstacle, initialState, goalState, limits, options);
testCase.verifyTrue(result.Success, result.Message);
testCase.verifyTrue(any(result.directBlocked));
testCase.verifyGreaterThan(size(result.selectedRoute_deg, 1), 2);
blocked = queryAzElTimedPathCollision(result.obstacleField, ...
    result.time_s, result.position_deg);
testCase.verifyFalse(any(blocked));

speed_deg_s = vecnorm(result.velocity_deg_s, 2, 2);
curvatureNumerator = abs(result.velocity_deg_s(:, 1) .* ...
    result.acceleration_deg_s2(:, 2) - ...
    result.velocity_deg_s(:, 2) .* ...
    result.acceleration_deg_s2(:, 1));
curvature = curvatureNumerator ./ max(speed_deg_s .^ 3, 1e-8);
turnMask = abs(result.position_deg(:, 1)) < 1.5 & ...
    result.time_s > result.time_s(1) + 0.1 * ...
    (result.time_s(end) - result.time_s(1)) & ...
    result.time_s < result.time_s(1) + 0.9 * ...
    (result.time_s(end) - result.time_s(1));
curvature(~turnMask) = -Inf;
[~, maximumCurvatureIndex] = max(curvature);
testCase.verifyGreaterThan(speed_deg_s(maximumCurvatureIndex), 0.05);
testCase.verifyGreaterThan(min(speed_deg_s(turnMask)), 1e-3);
interiorSeed_deg = result.selectedRoute_deg(2:end - 1, :);
minimumSeedDistance_deg = Inf;
for seedIndex = 1:size(interiorSeed_deg, 1)
    minimumSeedDistance_deg = min(minimumSeedDistance_deg, min(vecnorm( ...
        result.position_deg - interiorSeed_deg(seedIndex, :), 2, 2)));
end
testCase.verifyLessThanOrEqual(minimumSeedDistance_deg, 1e-7);
stopBaseline_s = deliberateStopBaseline( ...
    result.selectedRoute_deg, limits);
testCase.verifyLessThanOrEqual(result.time_s(end) - result.time_s(1), ...
    stopBaseline_s);
exampleValidation = validateAzElExampleResult( ...
    result, "static blocker regression");
testCase.verifyTrue(exampleValidation.SafetyMarginPolicySatisfied);
testCase.verifyTrue(exampleValidation.BufferedChordQueryClear);
tamperedResult = result;
tamperedResult.azElData(1).az_deg{1}(1) = ...
    tamperedResult.azElData(1).az_deg{1}(1) + 1e-4;
tamperedValidation = validateAzElExampleResult( ...
    tamperedResult, "tampered margin provenance");
testCase.verifyFalse(tamperedValidation.SafetyMarginPolicySatisfied);
selectedDiagnostic = result.SearchDiagnostics.CandidatePolicyMotions( ...
    result.selectedCandidateIndex);
testCase.verifyEqual(selectedDiagnostic.SeedRoute_deg, ...
    result.selectedRoute_deg);
testCase.verifyTrue(selectedDiagnostic.CollisionFree);
testCase.verifyTrue(selectedDiagnostic.BufferedChordQueryClear);
testCase.verifyTrue(selectedDiagnostic.CollisionSafetyProven);
testCase.verifyTrue(selectedDiagnostic.Validation.Passed);
testCase.verifyTrue(result.candidateDiagnostics. ...
    BufferedChordQueryClear(result.selectedCandidateIndex));
testCase.verifyTrue(contains(result.SearchDiagnostics. ...
    CollisionValidationMethod, "quintic curve tube"));
testCase.verifyEqual(selectedDiagnostic.MaximumVelocity_deg_s, ...
    result.Validation.MaximumVelocity_deg_s, "AbsTol", 1e-12);
testCase.verifyEqual(result.SearchDiagnostics. ...
    RlPolicyParallelExecution.RequestedMode, "on");
testCase.verifyGreaterThanOrEqual(result.SearchDiagnostics. ...
    RlPolicyParallelExecution.TaskCount, 2);
end

