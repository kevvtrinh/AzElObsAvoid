function testStaticSeedCopiesCollapseButMovingCopiesRemain(testCase)
% PURPOSE
%   - Remove static time copies while retaining moving-obstacle time laws.
squareAzimuth_deg = [-0.5; 0.5; 0.5; -0.5];
squareElevation_deg = [-3; -3; -2; -2];
staticObstacle = makeAzElObstacleData( ...
    "static seed field", [0; 10], ...
    {squareAzimuth_deg; squareAzimuth_deg}, ...
    {squareElevation_deg; squareElevation_deg}, 0);
movingTime_s = [0; 2.5; 5; 7.5; 10];
movingAzimuth_deg = cell(numel(movingTime_s), 1);
movingElevation_deg = repmat( ...
    {squareElevation_deg}, numel(movingTime_s), 1);
for sampleIndex = 1:numel(movingTime_s)
    movingAzimuth_deg{sampleIndex} = squareAzimuth_deg + ...
        5e-11 * (sampleIndex - 1) / (numel(movingTime_s) - 1);
end
movingObstacle = makeAzElObstacleData( ...
    "moving seed field", movingTime_s, movingAzimuth_deg, ...
    movingElevation_deg, 0);
[initialState, goalState, limits] = standardRequest( ...
    [-3 2], [3 2], 10);
options = fastOptions(8);
options.GoalTimeMode = "fixedArrival";
options.MaximumVisibilitySnapshotsPerObstacle = 2;
options.DetectSnapshotEvents = false;
options.TemporalSeedSampleTimes_s = [0; 10];
options.MaximumPlanningTime_s = 5;

staticResult = planAzElMotion( ...
    staticObstacle, initialState, goalState, limits, options);
movingResult = planAzElMotion( ...
    movingObstacle, initialState, goalState, limits, options);

testCase.verifyTrue(staticResult.SearchDiagnostics. ...
    ObstacleGeometryTimeInvariant);
testCase.verifyFalse(movingResult.SearchDiagnostics. ...
    ObstacleGeometryTimeInvariant);
testCase.verifyEqual(staticResult.SearchDiagnostics.CandidateSeedCount, 1);
movingSeeds = movingResult.SearchDiagnostics.CandidateSeeds;
testCase.verifyGreaterThanOrEqual(numel(movingSeeds), 2);
hasCrossTimeRouteCopy = false;
for firstSeedIndex = 1:numel(movingSeeds) - 1
    for secondSeedIndex = firstSeedIndex + 1:numel(movingSeeds)
        firstRoute_deg = movingSeeds(firstSeedIndex).Route_deg;
        secondRoute_deg = movingSeeds(secondSeedIndex).Route_deg;
        sameRoute = isequal(size(firstRoute_deg), size(secondRoute_deg)) && ...
            max(abs(firstRoute_deg - secondRoute_deg), [], "all") <= 1e-10;
        differentTime = abs(movingSeeds(firstSeedIndex).SnapshotTime_s - ...
            movingSeeds(secondSeedIndex).SnapshotTime_s) > 1e-10;
        hasCrossTimeRouteCopy = hasCrossTimeRouteCopy || ...
            (sameRoute && differentTime);
    end
end
testCase.verifyTrue(hasCrossTimeRouteCopy);

cappedOptions = options;
cappedOptions.MaximumVisibilitySnapshotsPerObstacle = 5;
cappedOptions.TemporalSeedSampleTimes_s = movingTime_s;
cappedOptions.MaximumRlPolicySeeds = 3;
cappedResult = planAzElMotion( ...
    movingObstacle, initialState, goalState, limits, cappedOptions);
cappedSeeds = cappedResult.SearchDiagnostics.CandidateSeeds;
cappedSnapshotTime_s = [cappedSeeds.SnapshotTime_s];
testCase.verifyEqual(numel(cappedSeeds), 3);
testCase.verifyEqual(cappedSnapshotTime_s, [0 2.5 10], ...
    "AbsTol", 1e-12);
testCase.verifyGreaterThan( ...
    cappedResult.SearchDiagnostics.SeedCapDroppedCount, 0);
testCase.verifyGreaterThan( ...
    cappedResult.SearchDiagnostics.DeduplicatedCandidateSeedCount, ...
    cappedResult.SearchDiagnostics.CandidateSeedCount);

uncappedTemporalOptions = cappedOptions;
uncappedTemporalOptions.MaximumRlPolicySeeds = 8;
uncappedTemporalResult = planAzElMotion( ...
    movingObstacle, initialState, goalState, limits, ...
    uncappedTemporalOptions);
uncappedTemporalSeeds = ...
    uncappedTemporalResult.SearchDiagnostics.CandidateSeeds;
testCase.verifyGreaterThanOrEqual(numel(uncappedTemporalSeeds), 2);
cheapestTopologyTime_s = uncappedTemporalSeeds(2).SnapshotTime_s;

twoSeedOptions = cappedOptions;
twoSeedOptions.MaximumRlPolicySeeds = 2;
twoSeedResult = planAzElMotion( ...
    movingObstacle, initialState, goalState, limits, twoSeedOptions);
twoSeedSnapshotTime_s = [twoSeedResult.SearchDiagnostics. ...
    CandidateSeeds.SnapshotTime_s];
testCase.verifyEqual(twoSeedSnapshotTime_s, ...
    [0 cheapestTopologyTime_s], ...
    "AbsTol", 1e-12);
end

