    [], successInitial, successGoal, successLimits, successOptions);
[initialState, goalState, limits] = standardRequest([0 0], [1 0], 10);
initialState.velocity_deg_s = [3 0];
[dynamicFailure, dynamicDiagnostics] = planAzElMotion( ...
    [], initialState, goalState, limits, fastOptions(1));

obstacle = makeAzElObstacleData( ...
    "goal blocker", [0; 10], ...
    [0.5; 1.5; 1.5; 0.5], [-1; -1; 1; 1], 0);
[initialState, goalState, limits] = standardRequest([0 0], [1 0], 10);
[blockedFailure, blockedDiagnostics] = planAzElMotion( ...
    obstacle, initialState, goalState, limits, fastOptions(1));
[candidateFailureInitial, candidateFailureGoal, ...
    candidateFailureLimits] = standardRequest([0 0], [10 0], 1);
[~, candidateFailureDiagnostics] = planAzElMotion( ...
    [], candidateFailureInitial, ...
    candidateFailureGoal, candidateFailureLimits, fastOptions(1));

testCase.verifyTrue(successResult.Success, successResult.Message);
testCase.verifyFalse(dynamicFailure.Success);
testCase.verifyFalse(blockedFailure.Success);
testCase.verifyEqual(fieldnames(successResult), ...
    fieldnames(dynamicFailure));
testCase.verifyEqual(fieldnames(dynamicFailure), ...
    fieldnames(blockedFailure));
testCase.verifyEqual(fieldnames(successDiagnostics.TimedPath), ...
    fieldnames(dynamicDiagnostics.TimedPath));
testCase.verifyEqual(fieldnames(dynamicDiagnostics.TimedPath), ...
    fieldnames(blockedDiagnostics.TimedPath));
testCase.verifyEqual( ...
    fieldnames(successDiagnostics.TimedPath.ConstraintDiagnostics), ...
    fieldnames(dynamicDiagnostics.TimedPath.ConstraintDiagnostics));
testCase.verifyEqual( ...
    fieldnames(dynamicDiagnostics.TimedPath.ConstraintDiagnostics), ...
    fieldnames(blockedDiagnostics.TimedPath.ConstraintDiagnostics));
testCase.verifyEqual(fieldnames(dynamicFailure.Validation), ...
    fieldnames(blockedFailure.Validation));
testCase.verifyEqual(fieldnames(successResult.Validation), ...
    fieldnames(dynamicFailure.Validation));
testCase.verifyEqual(fieldnames(successDiagnostics), ...
    fieldnames(dynamicDiagnostics));
testCase.verifyEqual(fieldnames(dynamicDiagnostics), ...
    fieldnames(blockedDiagnostics));
testCase.verifyEqual(fieldnames(successDiagnostics.Search), ...
    fieldnames(dynamicDiagnostics.Search));
testCase.verifyEqual(fieldnames(dynamicDiagnostics.Search), ...
    fieldnames(blockedDiagnostics.Search));
successCandidate = successDiagnostics.Search. ...
    CandidateOptimizations(successDiagnostics.SelectedCandidateIndex);
failureCandidate = candidateFailureDiagnostics.Search. ...
    CandidateOptimizations(1);
testCase.verifyEqual(fieldnames(successCandidate), ...
    fieldnames(failureCandidate));
testCase.verifyEqual(fieldnames(successCandidate.Validation), ...
    fieldnames(failureCandidate.Validation));
end

function [initialState, goalState, limits] = standardRequest( ...
        start_deg, goal_deg, horizon_s)
% PURPOSE
%   - Build neutral state and limit fixtures for planner tests.
initialState = struct( ...
    "time_s", 0, "position_deg", start_deg, ...
    "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", horizon_s, "position_deg", goal_deg, ...
    "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
limits = struct( ...
    "maxVelocity_deg_s", [2 2], ...
    "maxAcceleration_deg_s2", [1 1], ...
    "maxJerk_deg_s3", [2.5 2.5]);
end

function options = fastOptions(maximumSeedCount)
% PURPOSE
%   - Keep regression runtime bounded without changing physical inputs.
options = struct( ...
    "InitialCollocationSegmentCount", 6, ...
    "MaximumMeshRefinementPasses", 0, ...
    "MaximumCollocationSegmentCount", 6, ...
    "MaximumDirectCollocationSeeds", maximumSeedCount, ...
    "MaximumNlpIterations", 200, ...
    "EnableJerkTieBreak", false, ...
    "MaximumPlanningTime_s", 120, ...
    "UseParallel", "off", ...
    "Verbose", false);
end

function duration_s = deliberateStopBaseline(route_deg, limits)
% PURPOSE
%   - Compute a conservative stop-at-each-vertex comparison duration.
step_deg = diff(route_deg, 1, 1);
distance_deg = vecnorm(step_deg, 2, 2);
velocity_deg_s = min(limits.maxVelocity_deg_s);
acceleration_deg_s2 = min(limits.maxAcceleration_deg_s2);
jerk_deg_s3 = min(limits.maxJerk_deg_s3);
duration_s = sum(distance_deg / velocity_deg_s + ...
    velocity_deg_s / acceleration_deg_s2 + ...
    2 * acceleration_deg_s2 / jerk_deg_s3);
end

function closeMotionFigures(handles)
% PURPOSE
%   - Close all figures made by one plotAzElMotion test call.
figureHandles = handles.WorkspaceFigure;
if isstruct(handles.VisibilityGraphs) && ...
        isfield(handles.VisibilityGraphs, "Figure")
    figureHandles(end + 1) = handles.VisibilityGraphs.Figure;
end
