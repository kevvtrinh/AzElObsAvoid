    figureHandles(end + 1) = handles.KinematicsFigure;
end
if isstruct(handles.Animation) && isfield(handles.Animation, "Figure")
    figureHandles(end + 1) = handles.Animation.Figure;
end
close(figureHandles(isgraphics(figureHandles)));
end
