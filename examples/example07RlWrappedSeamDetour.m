function result = example07RlWrappedSeamDetour(showFigure)
%% Section 0: Header & Readme
% SYNTAX
%   result = example07RlWrappedSeamDetour()
%   result = example07RlWrappedSeamDetour(showFigure)
%**************************************************************************
% PURPOSE
%   - Replay the RL branch's disconnected blocker across the azimuth seam.
%**************************************************************************
% INPUTS
%   - showFigure (optional logical scalar, default false)
%**************************************************************************
% OUTPUTS
%   - result (scalar planner result)
%**************************************************************************
% UNITS
%   - Angles are degrees and time is seconds.

if nargin < 1
    showFigure = false;
end

%% Section 1: Build The Imported Seam Geometry
time_s = (0:0.5:30).';
azimuth_deg = [ ...
    174; 180; 180; 174; 174; NaN; ...
    -180; -174; -174; -180; -180];
elevation_deg = [ ...
    -5; -5; 5; 5; -5; NaN; ...
    -5; -5; 5; 5; -5];
azElData = makeAzElObstacleData( ...
    "Wrapped seam blocker", time_s, azimuth_deg, elevation_deg);

%% Section 2: Define The Imported Mission
initialState = struct( ...
    "time_s", 0, ...
    "position_deg", [170, 0], ...
    "velocity_deg_s", [0, 0], ...
    "acceleration_deg_s2", [0, 0]);
goal = struct( ...
    "type", "fixed", ...
    "time_s", 30, ...
    "position_deg", [-170, 0], ...
    "velocity_deg_s", [0, 0], ...
    "acceleration_deg_s2", [0, 0]);
limits = struct( ...
    "azimuth_deg", [-180, 180], ...
    "elevation_deg", [-20, 20], ...
    "maxVelocity_deg_s", [2, 2], ...
    "maxAcceleration_deg_s2", [2, 2]);
request = struct( ...
    "obstacles", azElData, ...
    "initialState", initialState, ...
    "goal", goal, ...
    "limits", limits, ...
    "options", struct( ...
        "safetyMargin_deg", 0.5, ...
        "azimuthWrap", true, ...
        "deadline_s", 30));

%% Section 3: Plan & Independently Validate
result = planAzElAvoidance(request);
assert(result.success, "%s", char(join(result.message)));
validation = validateAzElCommand( ...
    result.command, request, result.arrivalTime_s);
assert(validation.isValid, "%s", char(join(validation.message)));
assert(validation.seamIsValid, ...
    "The command is not continuous in unwrapped azimuth.");
assert(max(abs(result.command.unwrappedPosition_deg(:, 2))) > 5, ...
    "The command did not detour around the seam blocker.");

%% Section 4: Report & Optionally Display
fprintf("RL seam detour: %.6f s; clearance %.6f deg.\n", ...
    result.arrivalTime_s, validation.collision.minimumClearance_deg);
if showFigure
    visualizeAzElPlan(request, result);
end
end
