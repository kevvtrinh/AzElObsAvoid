function result = exampleExitConcavePocketEarliest(exampleOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   result = exampleExitConcavePocketEarliest()
%   result = exampleExitConcavePocketEarliest(exampleOverrides)
%**************************************************************************
% PURPOSE
%   - Start deep inside the pocket of one large C-shaped obstacle and reach
%     a goal far outside it as early as the limits allow.
%   - Reproduce the sandbox request saved in "Rogue Cases/notworking.json"
%     exactly, including its two identical obstacle keyframes.
%**************************************************************************
% INPUTS
%   - exampleOverrides (scalar struct, optional; default struct())
%       Display controls and public planner option overrides.
%**************************************************************************
% OUTPUTS
%   - result (scalar struct)
%       Unmodified public planner result. Ordinary planning failure returns
%       Success = false; invalid input throws an error.
%**************************************************************************
% UNITS
%   - Positions are 1-by-2 [x y] rows in coordinate units. Time is seconds;
%     velocity, acceleration, and jerk use units/s, units/s^2, and units/s^3.
%**************************************************************************

%% Section 1: Resolve Example Controls
if nargin < 1 || isempty(exampleOverrides)
    exampleOverrides = struct();
end
scenarioDefaults = struct( ...
    "GoalTimeMode", "earliestArrival", "WrapX", false, "WrapY", false, ...
    "Title", "Earliest exit from a concave pocket");
[options, displayOptions] = resolveExampleOptions( ...
    exampleOverrides, scenarioDefaults, [2.5 2.5]);

%% Section 2: Create Obstacles
% One 33-vertex C shape about 95 units wide and 90 units tall. Its pocket
% opens to the west between roughly (-130, 33) and (-132, -9). The saved
% request repeats the same outline at 0 s and 180 s, so the obstacle is
% stationary but is supplied as a two-sample history, exactly as recorded.
missionEndTime_s   = 180;
safetyMargin_units = 0.2;
pocketOutline_units = [ ...
    -130.4090863403357     32.61584078801889; ...
    -121.72479646195598    36.08955673937079; ...
    -113.04050658357623    37.82641471504674; ...
    -103.48778771735853    38.984320032164035; ...
     -94.51402150969946    38.69484370288471; ...
     -84.38234998492311    33.7737461051362; ...
     -81.48758669212987    30.010553824504974; ...
     -77.72439441149864    19.878882299728616; ...
     -77.72439441149864    16.405166348376724; ...
     -79.75072871645392    13.220926726304157; ...
     -87.27711327771635     8.878781787114278; ...
    -114.77736455925219     2.2208262136898185; ...
    -123.1721781083526     -1.831842396220722; ...
    -132.14594431601165    -9.358226957483165; ...
    -133.8828022916876    -15.147753543069651; ...
    -129.2511810232184    -19.20042215298019; ...
    -118.25108051060408   -21.516232787214786; ...
     -92.48768720474419   -21.805709116494125; ...
     -78.01387074077797   -19.77937481153884; ...
     -56.0136697155493     -9.937179616041814; ...
     -45.59252186149362     9.74721077495225; ...
     -45.88199819077295    20.457834958287265; ...
     -49.066237812845515   31.457935470901596; ...
     -57.171575032666595   42.1685596542366; ...
     -68.46115187456024    52.010754849733644; ...
     -79.46125238717458    59.537139410996076; ...
     -98.85616644888934    67.64247663081717; ...
    -117.38265152276611    67.9319529600965; ...
    -125.77746507186652    65.03718966730324; ...
    -137.64599457231884    54.037089154688914; ...
    -139.96180520655344    49.69494421549904; ...
    -140.54075786511208    41.010654337119306; ...
    -139.3828525479948     39.563272690722684];
obstacleTime_s = [0; missionEndTime_s];
obstacles = obstacleAvoidance.obstacles.createObstacle("Obstacle 1", ...
    obstacleTime_s, ...
    {pocketOutline_units(:, 1); pocketOutline_units(:, 1)}, ...
    {pocketOutline_units(:, 2); pocketOutline_units(:, 2)}, ...
    safetyMargin_units);

%% Section 3: Create Planner Inputs
% The start sits inside the pocket, about 25 units east of its mouth. The
% goal is about 95 units east of the obstacle, so every route must first
% leave the pocket westward and then pass around the outside of the shape.
initialState = struct("time_s", 0, ...
    "position_units", [-106.96150366871042 15.247261031259427], ...
    "velocity_units_s", [0 0], "acceleration_units_s2", [0 0]);
goalState    = struct("time_s", missionEndTime_s, ...
    "position_units", [50.22414312996281 31.16845914162227], ...
    "velocity_units_s", [0 0], "acceleration_units_s2", [0 0]);
limits       = struct( ...
    "maxVelocity_units_s",      [2 2], ...
    "maxAcceleration_units_s2", [0.75 0.75], ...
    "maxJerk_units_s3",         displayOptions.MaxJerk_units_s3, ...
    "xInterval_units",          [-180 180], ...
    "yInterval_units",          [-90 90]);

%% Section 4: Run Planner
result = planner(obstacles, initialState, goalState, limits, options);

%% Section 5: Validate Result
% Validate the full returned motion independently. The direct line from the
% start to the goal crosses the pocket wall, so it must be reported blocked.
exampleValidation = validateExampleResult(result, ...
    "earliest exit from a concave pocket", ...
    struct("RequireDirectBlocked", true));
if ~exampleValidation.Passed
    warning("exampleExitConcavePocketEarliest:ValidationFailed", ...
        "%s", exampleValidation.Message);
end

%% Section 6: Plot Diagnostics And Motion
if displayOptions.PlotOutputs
    obstacleAvoidance.plotting.plotTrajectory(result, displayOptions.PlotOptions);
end
end
