function report = example04RlBranchArrivalOracles()
%% Section 0: Header & Readme
% SYNTAX
%   report = example04RlBranchArrivalOracles()
%**************************************************************************
% PURPOSE
%   - Replay the four analytic free-space missions introduced on the
%     all-dijkstra-rl-parameter-auto-tune branch.
%   - Check independently validated arrival against each double-integrator
%     oracle without importing that branch's planner or learned settings.
%**************************************************************************
% INPUTS
%   - None.
%**************************************************************************
% OUTPUTS
%   - report (scalar struct)
%       Per-case requests, planner results, validations, and arrival ratios.
%**************************************************************************
% UNITS
%   - Angular quantities are degrees; temporal quantities are seconds.

%% Section 1: Define Mission Facts & Independent Oracles
caseData = [ ...
    makeCase("triangularAxis", [-2, 0], [2, 0], ...
        [-6, 6], [-4, 4], [10, 10], [1, 1], 10, false, 4)
    makeCase("trapezoidalAxis", [-8, 0], [8, 0], ...
        [-10, 10], [-4, 4], [2, 2], [1, 1], 16, false, 10)
    makeCase("synchronizedDiagonal", [-6, -3], [6, 3], ...
        [-8, 8], [-5, 5], [3, 2], [2, 1], 12, false, 5.5)
    makeCase("wrappedSeam", [170, 0], [-170, 0], ...
        [-180, 180], [-5, 5], [5, 5], [2, 2], 15, true, 6.5)];
maximumArrivalRatio = 1.03;

%% Section 2: Plan & Independently Validate Every Case
caseCount = numel(caseData);
caseReport = repmat(struct( ...
    "name", "", ...
    "request", struct(), ...
    "result", struct(), ...
    "validation", struct(), ...
    "trueMinimumDuration_s", NaN, ...
    "arrivalRatio", Inf), caseCount, 1);
for caseIndex = 1:caseCount
    request = buildRequest(caseData(caseIndex));
    result = planAzElAvoidance(request);
    assert(result.success, "%s failed: %s", ...
        caseData(caseIndex).name, result.message);
    validation = validateAzElCommand( ...
        result.command, request, result.arrivalTime_s);
    assert(validation.isValid, "%s failed validation: %s", ...
        caseData(caseIndex).name, validation.message);
    arrivalRatio = result.executionDuration_s ./ ...
        caseData(caseIndex).trueMinimumDuration_s;
    assert(arrivalRatio <= maximumArrivalRatio + 1e-12, ...
        "%s arrival ratio %.6f exceeds %.6f.", ...
        caseData(caseIndex).name, arrivalRatio, maximumArrivalRatio);
    caseReport(caseIndex) = struct( ...
        "name", caseData(caseIndex).name, ...
        "request", request, ...
        "result", result, ...
        "validation", validation, ...
        "trueMinimumDuration_s", ...
            caseData(caseIndex).trueMinimumDuration_s, ...
        "arrivalRatio", arrivalRatio);
end

%% Section 3: Assemble & Print Acceptance Evidence
report = struct( ...
    "sourceBranch", "all-dijkstra-rl-parameter-auto-tune", ...
    "acceptanceThreshold", maximumArrivalRatio, ...
    "cases", caseReport, ...
    "passedCount", nnz([caseReport.arrivalRatio] <= ...
        maximumArrivalRatio + 1e-12), ...
    "caseCount", caseCount, ...
    "maximumArrivalRatio", max([caseReport.arrivalRatio]));
fprintf("RL-branch analytic arrivals: %d/%d passed; max ratio %.6f.\n", ...
    report.passedCount, report.caseCount, report.maximumArrivalRatio);
end

function data = makeCase(name, startPosition_deg, goalPosition_deg, ...
        azimuthLimits_deg, elevationLimits_deg, maximumVelocity_deg_s, ...
        maximumAcceleration_deg_s2, deadline_s, azimuthWrap, ...
        trueMinimumDuration_s)
%% Section 0: Header & Readme
% SYNTAX
%   data = makeCase(name, startPosition_deg, goalPosition_deg, ...
%       azimuthLimits_deg, elevationLimits_deg, maximumVelocity_deg_s, ...
%       maximumAcceleration_deg_s2, deadline_s, azimuthWrap, ...
%       trueMinimumDuration_s)
%**************************************************************************
% PURPOSE
%   - Store one analytic mission using only physical inputs and its oracle.
%**************************************************************************
% INPUTS
%   - name (scalar string)
%   - positions, limits, deadline, wrap choice, and oracle (mission facts)
%**************************************************************************
% OUTPUTS
%   - data (scalar struct)
%**************************************************************************
% UNITS
%   - Angles are degrees and time is seconds.

data = struct( ...
    "name", name, ...
    "startPosition_deg", startPosition_deg, ...
    "goalPosition_deg", goalPosition_deg, ...
    "azimuthLimits_deg", azimuthLimits_deg, ...
    "elevationLimits_deg", elevationLimits_deg, ...
    "maximumVelocity_deg_s", maximumVelocity_deg_s, ...
    "maximumAcceleration_deg_s2", maximumAcceleration_deg_s2, ...
    "deadline_s", deadline_s, ...
    "azimuthWrap", azimuthWrap, ...
    "trueMinimumDuration_s", trueMinimumDuration_s);
end

function request = buildRequest(data)
%% Section 0: Header & Readme
% SYNTAX
%   request = buildRequest(data)
%**************************************************************************
% PURPOSE
%   - Translate one stored mission into the public greenfield request.
%**************************************************************************
% INPUTS
%   - data (scalar case-data struct)
%**************************************************************************
% OUTPUTS
%   - request (scalar public planner request)
%**************************************************************************
% UNITS
%   - Angles are degrees and time is seconds.

initialState = struct( ...
    "time_s", 0, ...
    "position_deg", data.startPosition_deg, ...
    "velocity_deg_s", [0, 0], ...
    "acceleration_deg_s2", [0, 0]);
goal = struct( ...
    "type", "fixed", ...
    "time_s", data.deadline_s, ...
    "position_deg", data.goalPosition_deg, ...
    "velocity_deg_s", [0, 0], ...
    "acceleration_deg_s2", [0, 0]);
limits = struct( ...
    "azimuth_deg", data.azimuthLimits_deg, ...
    "elevation_deg", data.elevationLimits_deg, ...
    "maxVelocity_deg_s", data.maximumVelocity_deg_s, ...
    "maxAcceleration_deg_s2", data.maximumAcceleration_deg_s2);
missionOptions = struct( ...
    "deadline_s", data.deadline_s, ...
    "azimuthWrap", data.azimuthWrap);
request = struct( ...
    "obstacles", [], ...
    "initialState", initialState, ...
    "goal", goal, ...
    "limits", limits, ...
    "options", missionOptions);
end
