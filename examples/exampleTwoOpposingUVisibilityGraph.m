function result = exampleTwoOpposingUVisibilityGraph(viewOptions)
%% Section 0: Header & Readme
% SYNTAX
%   result = exampleTwoOpposingUVisibilityGraph()
%   result = exampleTwoOpposingUVisibilityGraph(viewOptions)
%**************************************************************************
% PURPOSE
%   - Place the start and goal inside two offset U-shaped obstacles.
%   - Rotate the second U by 180 degrees so the openings face each other.
%   - Let a global visibility graph choose the central gap or an outside
%     route from all cross-obstacle corner connections.
%**************************************************************************
% OUTPUTS
%   - result (scalar struct)
%       Scenario data, packed obstacles, selected graph path, static 3-D
%       view, synchronized 3-D/2-D animation, and kinematic-profile plot.
%**************************************************************************
% UNITS
%   - Azimuth/elevation are degrees and time is seconds.

%% Section 1: Draw Two Static Offset, Opposing U Obstacles
if nargin < 1
    viewOptions = struct();
end
if ~isfield(viewOptions, "SafetyMarginDeg") || ...
        isempty(viewOptions.SafetyMarginDeg)
    viewOptions.SafetyMarginDeg = 1.5;
end
missionEndTime_s = 35;
time_s = [0; missionEndTime_s];

% U1 opens to the right. Its free cavity contains the start.
firstUBoundary_deg = [ ...
    -10,  8; ... % outer upper-left
      0,  8; ... % outer upper-right
      0,  5; ... % inner upper-right lip
     -7,  5; ... % inner upper-left
     -7, -5; ... % inner lower-left
      0, -5; ... % inner lower-right lip
      0, -8; ... % outer lower-right
    -10, -8];    % outer lower-left

% U2 is U1 rotated by 180 degrees, then offset right and upward. It opens
% to the left, and its free cavity contains the goal. The vertical offset
% leaves a diagonal passage between U1's top and U2's bottom.
secondUBoundary_deg = [ ...
     5, 28; ... % outer upper-left
    15, 28; ... % outer upper-right
    15, 12; ... % outer lower-right
     5, 12; ... % outer lower-left
     5, 15; ... % inner lower-left lip
    12, 15; ... % inner lower-right
    12, 25; ... % inner upper-right
     5, 25];    % inner upper-left lip

firstObstacle = makeAzElObstacleData( ...
    "Right-opening U around start", time_s, ...
    firstUBoundary_deg(:, 1), firstUBoundary_deg(:, 2), ...
    viewOptions.SafetyMarginDeg);
secondObstacle = makeAzElObstacleData( ...
    "Left-opening U around goal", time_s, ...
    secondUBoundary_deg(:, 1), secondUBoundary_deg(:, 2), ...
    viewOptions.SafetyMarginDeg);
azElData = [firstObstacle; secondObstacle];

%% Section 2: Put Start & Goal On Opposite Sides
initialState = struct( ...
    "time_s", 0, ...
    "position_deg", [-4 0], ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", missionEndTime_s, ...
    "position_deg", [9 20], ...
    "velocity_deg_s", [0 0], ... % resolved from the selected final edge
    "acceleration_deg_s2", [0 0]);

%% Section 3: Pack The Final Az/El Geometry Without Another Margin
% makeAzElObstacleData already produced the safety-inflated planning data.
% The separate original field remains available only for diagnostics.
obstacleField = buildAzElTimeObstacleField(azElData);
[originalObstacleField, ~, ~] = ...
    recoverOriginalAzElObstacleField(obstacleField);
originalAzElData = originalObstacleField.SourceAzElData;
directFraction = linspace(0, 1, 501).';
directPosition_deg = initialState.position_deg + directFraction .* ...
    (goalState.position_deg - initialState.position_deg);
directTime_s = initialState.time_s + directFraction .* ...
    (goalState.time_s - initialState.time_s);
directBlocked = queryAzElTimeObstacle(obstacleField, ...
    directPosition_deg(:, 1), directPosition_deg(:, 2), directTime_s, ...
    struct( ...
    "CollisionMode", "polygon", ...
    "TimePaddingSamples", 0));
if directBlocked(1) || directBlocked(end)
    error("exampleTwoOpposingUVisibilityGraph:BlockedEndpoint", ...
        "The start and goal must remain in their free U cavities.");
end
if ~any(directBlocked)
    error("exampleTwoOpposingUVisibilityGraph:DirectLineIsFree", ...
        "The direct line should cross an arm of the offset U obstacles.");
end

%% Section 4: Build & Draw The Global Candidate Graph
if ~isfield(viewOptions, "Title") || isempty(viewOptions.Title)
    viewOptions.Title = ...
        "Two opposing U obstacles: central gap versus outside route";
end
if ~isfield(viewOptions, "FigureVisible") || ...
        isempty(viewOptions.FigureVisible)
    viewOptions.FigureVisible = "on";
end
appliedSafetyMargin_deg = viewOptions.SafetyMarginDeg;
displayOptions = rmfield(viewOptions, "SafetyMarginDeg");
if isfield(displayOptions, "OriginalObstacleField")
    displayOptions = rmfield(displayOptions, "OriginalObstacleField");
end
spaceView = visualizeAzElTimeSpace( ...
    obstacleField, initialState, goalState, displayOptions);
if lower(string(viewOptions.FigureVisible)) == "on"
    set(spaceView.Figure, "Visible", "on");
    figure(spaceView.Figure);
    drawnow;
end
selectedPath = spaceView.SelectedVisibilityPath;
if ~selectedPath.Success
    error("exampleTwoOpposingUVisibilityGraph:NoGraphPath", ...
        "The global candidate visibility graph did not reach the goal.");
end

% Inflation rounds the two inner lips, so exact uninflated corner
% coordinates are no longer meaningful assertions. The selected central-gap
% route must still use candidate geometry from both obstacles.
usedObstacleIndex = unique(selectedPath.PathObstacleIndex);
usesBothObstacles = all(ismember([1 2], usedObstacleIndex));
selectedRouteClass = "outsideOrSingleObstacle";
if usesBothObstacles
    selectedRouteClass = "interObstacleGap";
end
limits = struct("maxVelocity_deg_s", [1 1]);
% The inflated lip changes the last edge direction. Resolve a compatible
% nonzero terminal velocity from that edge at its fastest allowed slope so
% earliest-arrival retiming does not weaken the terminal-state requirement.
finalEdge_deg = selectedPath.PathPosition_deg(end, :) - ...
    selectedPath.PathPosition_deg(end - 1, :);
finalEdgeDuration_s = max( ...
    abs(finalEdge_deg) ./ limits.maxVelocity_deg_s);
goalState.velocity_deg_s = finalEdge_deg / finalEdgeDuration_s;
timedSlopePath = retimeAzElVisibilityPath( ...
    selectedPath.PathPosition_deg, initialState, goalState, limits, struct( ...
    "GoalTimeMode", "earliestArrival"));
if ~timedSlopePath.Success
    error("exampleTwoOpposingUVisibilityGraph:SlopeRetimingFailed", ...
        "%s", timedSlopePath.Message);
end
timedSlopeHandle = plot3(spaceView.Axes, ...
    timedSlopePath.position_deg(:, 1), ...
    timedSlopePath.position_deg(:, 2), ...
    timedSlopePath.time_s, "-", ...
    "Color", [0.05 0.70 0.82], ...
    "LineWidth", 4.0, ...
    "DisplayName", "Velocity-limited timed slope path");
drawnow;

%% Section 5: Animate The Timed Slope In 3-D & 2-D By Default
animationOptions = struct( ...
    "FigureVisible", viewOptions.FigureVisible, ...
    "Title", "Two opposing U timed slope path");
if lower(string(viewOptions.FigureVisible)) == "off"
    animationOptions.Pause_s = 0;
end
animation = animateAzElTimedSlopePath( ...
    timedSlopePath, obstacleField, animationOptions);
kinematicPlot = plotAzElTimedSlopeKinematics(timedSlopePath, struct( ...
    "FigureVisible", viewOptions.FigureVisible, ...
    "Title", "Two opposing U timed slope kinematics"));

result = struct( ...
    "azElData", azElData, ...
    "originalAzElData", originalAzElData, ...
    "inflatedAzElData", azElData, ... % compatibility alias
    "originalObstacleField", originalObstacleField, ...
    "obstacleField", obstacleField, ...
    "initialState", initialState, ...
    "goalState", goalState, ...
    "firstUBoundary_deg", firstUBoundary_deg, ...
    "secondUBoundary_deg", secondUBoundary_deg, ...
    "directPosition_deg", directPosition_deg, ...
    "directTime_s", directTime_s, ...
    "directBlocked", directBlocked, ...
    "blockedDirectSampleCount", nnz(directBlocked), ...
    "selectedPath", selectedPath, ...
    "selectedRouteClass", selectedRouteClass, ...
    "safetyMargin_deg", appliedSafetyMargin_deg, ...
    "safetyMarginDiagnostics", spaceView.SafetyMarginDiagnostics, ...
    "limits", limits, ...
    "timedSlopePath", timedSlopePath, ...
    "goalLineInterceptTime_s", ...
    timedSlopePath.GoalLineInterceptTime_s, ...
    "timedSlopeHandle", timedSlopeHandle, ...
    "animation", animation, ...
    "kinematicPlot", kinematicPlot, ...
    "spaceView", spaceView);
fprintf([ ...
    "Two-U visibility graph: direct line blocked at %d/%d samples; " + ...
    "selected %d graph edges over %.3f deg (%s); " + ...
    "applied safety margin is %.2f deg; " + ...
    "earliest goal-line intercept is %.3f s.\n"], ...
    nnz(directBlocked), numel(directBlocked), ...
    selectedPath.PathEdgeCount, selectedPath.PathCost_deg, ...
    selectedRouteClass, appliedSafetyMargin_deg, ...
    timedSlopePath.GoalLineInterceptTime_s);
end
