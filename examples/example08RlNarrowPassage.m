function result = example08RlNarrowPassage(showFigure)
%% Section 0: Header & Readme
% SYNTAX
%   result = example08RlNarrowPassage()
%   result = example08RlNarrowPassage(showFigure)
%**************************************************************************
% PURPOSE
%   - Replay the RL branch's narrow training-style wall using the greenfield
%     planner and independent validator only.
%**************************************************************************
% INPUTS
%   - showFigure (optional logical scalar, default false)
%**************************************************************************
% OUTPUTS
%   - result (scalar planner result)
%**************************************************************************
% UNITS
%   - Angles are degrees and time is seconds.

if nargin < 1
    showFigure = false;
end

%% Section 1: Build The Imported Narrow Wall
sampleTime_s = (0:20).';
wallAzimuth_deg = [ ...
    -3.4; 2.4; 2.4; -3.4; -3.4; NaN; ...
    -3.4; 2.4; 2.4; -3.4; -3.4];
wallElevation_deg = [ ...
    -10; -10; -3.7; -3.7; -10; NaN; ...
    -2.3; -2.3; 10; 10; -2.3];
azElData = makeAzElObstacleData( ...
    "Narrow training-style wall", sampleTime_s, ...
    wallAzimuth_deg, wallElevation_deg);

%% Section 2: Define The Imported Mission
initialState = struct( ...
    "time_s", 0, ...
    "position_deg", [-10, 0], ...
    "velocity_deg_s", [0, 0], ...
    "acceleration_deg_s2", [0, 0]);
goal = struct( ...
    "type", "fixed", ...
    "time_s", 20, ...
    "position_deg", [10, 0], ...
    "velocity_deg_s", [0, 0], ...
    "acceleration_deg_s2", [0, 0]);
limits = struct( ...
    "azimuth_deg", [-12, 12], ...
    "elevation_deg", [-10, 10], ...
    "maxVelocity_deg_s", [5, 5], ...
    "maxAcceleration_deg_s2", [5, 5]);
request = struct( ...
    "obstacles", azElData, ...
    "initialState", initialState, ...
    "goal", goal, ...
    "limits", limits, ...
    "options", struct("deadline_s", 20));

%% Section 3: Plan & Independently Validate
result = planAzElAvoidance(request);
assert(result.success, "%s", char(join(result.message)));
validation = validateAzElCommand( ...
    result.command, request, result.arrivalTime_s);
assert(validation.isValid, "%s", char(join(validation.message)));
assert(validation.collision.minimumClearance_deg > 0.5, ...
    "The narrow-passage command did not clear the default margin.");

%% Section 4: Report & Optionally Display
fprintf("RL narrow passage: %.6f s; clearance %.6f deg.\n", ...
    result.arrivalTime_s, validation.collision.minimumClearance_deg);
if showFigure
    visualizeAzElPlan(request, result);
end
end
