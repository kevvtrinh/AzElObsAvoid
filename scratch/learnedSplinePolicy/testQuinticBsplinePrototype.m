function tests = testQuinticBsplinePrototype
%% Section 0: Header & Readme
% SYNTAX
%   tests = testQuinticBsplinePrototype
%**************************************************************************
% PURPOSE
%   - Verify the research quintic B-spline representation before planner
%     integration or any learned-policy experiment is considered.
%**************************************************************************
% INPUTS
%   - None.
%**************************************************************************
% OUTPUTS
%   - tests (matlab.unittest.Test array)
%       Deterministic function-based prototype tests.
%**************************************************************************
% UNITS
%   - Position is degrees; time is seconds; derivatives use deg/s, deg/s^2,
%     and deg/s^3.
%**************************************************************************
tests = functiontests(localfunctions);
end

function testRequiredGeometryFamily(testCase)
% Exercise structurally different route families without obstacle knowledge.
[routeNames, routes_deg] = requiredRoutes();
limits = prototypeLimits();
for routeIndex = 1:numel(routes_deg)
    route_deg = routes_deg{routeIndex};
    [initialState, goalState] = endpointStates(route_deg, 100);
    motion = buildQuinticBsplinePrototype( ...
        route_deg, initialState, goalState, limits);

    diagnostic = sprintf("Route family %s", routeNames(routeIndex));
    verifyTrue(testCase, motion.Success, diagnostic);
    verifyTrue(testCase, motion.Validation.Passed, diagnostic);
    verifyEqual(testCase, motion.Polynomial.SegmentCount, ...
        size(route_deg, 1) - 1, diagnostic);
    verifyEqual(testCase, size(motion.ControlPoint_deg, 1), ...
        size(route_deg, 1) + 4, diagnostic);
    verifyLessThanOrEqual(testCase, ...
        maximumContinuityResidual(motion), 1e-7, diagnostic);
    verifyEqual(testCase, motion.position_deg(1, :), route_deg(1, :), ...
        "AbsTol", 1e-10, diagnostic);
    verifyEqual(testCase, motion.position_deg(end, :), route_deg(end, :), ...
        "AbsTol", 1e-9, diagnostic);
    verifyLessThanOrEqual(testCase, ...
        max(abs([motion.velocity_deg_s(1, :), ...
        motion.velocity_deg_s(end, :)])), 1e-9, diagnostic);
    verifyLessThanOrEqual(testCase, ...
        max(abs([motion.acceleration_deg_s2(1, :), ...
        motion.acceleration_deg_s2(end, :)])), 1e-8, diagnostic);
end
end

function testOffsetsAndSpanWeightsAreDeterministic(testCase)
% Confirm the proposed low-dimensional controls affect only explicit inputs.
route_deg = [0 0; 3 2; 6 -2; 9 0];
[initialState, goalState] = endpointStates(route_deg, 100);
limits = prototypeLimits();
options = struct( ...
    "ControlPointOffsets_deg", [0.2 -0.1; -0.1 0.2], ...
    "SpanWeights", [1; 2; 1], ...
    "SampleTime_s", 0.1);
firstMotion = buildQuinticBsplinePrototype( ...
    route_deg, initialState, goalState, limits, options);
secondMotion = buildQuinticBsplinePrototype( ...
    route_deg, initialState, goalState, limits, options);

verifyTrue(testCase, firstMotion.Success);
verifyEqual(testCase, firstMotion.ControlPoint_deg, ...
    secondMotion.ControlPoint_deg, "AbsTol", 0);
verifyEqual(testCase, firstMotion.SpanDuration_s, ...
    secondMotion.SpanDuration_s, "AbsTol", 0);
verifyEqual(testCase, firstMotion.Polynomial.positionPower_deg, ...
    secondMotion.Polynomial.positionPower_deg, "AbsTol", 0);
verifyEqual(testCase, firstMotion.Options.ControlPointOffsets_deg, ...
    options.ControlPointOffsets_deg);
verifyEqual(testCase, firstMotion.Options.SpanWeights, options.SpanWeights);
end

function testContinuousLimitsBetweenSamples(testCase)
% Coarse samples must not be the only evidence for derivative feasibility.
route_deg = [0 0; 4 0; 4 4];
[initialState, goalState] = endpointStates(route_deg, 100);
limits = prototypeLimits();
options = struct("SampleTime_s", 10);
motion = buildQuinticBsplinePrototype( ...
    route_deg, initialState, goalState, limits, options);

verifyTrue(testCase, motion.Success);
verifyTrue(testCase, motion.Validation.Passed);
verifyLessThanOrEqual(testCase, ...
    max(motion.Validation.PeakVelocity_deg_s ./ ...
    limits.maxVelocity_deg_s), 1 + 1e-7);
verifyLessThanOrEqual(testCase, ...
    max(motion.Validation.PeakAcceleration_deg_s2 ./ ...
    limits.maxAcceleration_deg_s2), 1 + 1e-7);
verifyLessThanOrEqual(testCase, ...
    max(motion.Validation.PeakJerk_deg_s3 ./ ...
    limits.maxJerk_deg_s3), 1 + 1e-7);
end

function testNonzeroEndpointDerivativeIsRejected(testCase)
route_deg = [0 0; 5 0];
[initialState, goalState] = endpointStates(route_deg, 100);
initialState.velocity_deg_s = [0.1 0];
verifyError(testCase, @() buildQuinticBsplinePrototype( ...
    route_deg, initialState, goalState, prototypeLimits()), ...
    "buildQuinticBsplinePrototype:UnsupportedEndpointState");
end

function [routeNames, routes_deg] = requiredRoutes()
routeNames = ["straight", "turn45", "turn90", "sTurn", ...
    "horseshoe", "fiveAlternating"];
routes_deg = { ...
    [0 0; 6 0], ...
    [0 0; 4 0; 7 3], ...
    [0 0; 4 0; 4 4], ...
    [0 0; 3 2; 6 -2; 9 0], ...
    [0 0; 4 0; 4 4; 0 4; 0 1; 3 1], ...
    [0 0; 2 2; 4 -2; 6 2; 8 -2; 10 2; 12 0]};
end

function limits = prototypeLimits()
limits = struct( ...
    "maxVelocity_deg_s", [2 2], ...
    "maxAcceleration_deg_s2", [1 1], ...
    "maxJerk_deg_s3", [2 2], ...
    "azimuthInterval_deg", [-20 20], ...
    "elevationInterval_deg", [-20 20]);
end

function [initialState, goalState] = endpointStates(route_deg, horizon_s)
initialState = struct( ...
    "time_s", 0, ...
    "position_deg", route_deg(1, :), ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", horizon_s, ...
    "position_deg", route_deg(end, :), ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
end

function residual = maximumContinuityResidual(motion)
continuity = motion.Continuity;
residual = max([ ...
    continuity.MaximumPositionResidual_deg, ...
    continuity.MaximumVelocityResidual_deg_s, ...
    continuity.MaximumAccelerationResidual_deg_s2, ...
    continuity.MaximumJerkResidual_deg_s3]);
end
