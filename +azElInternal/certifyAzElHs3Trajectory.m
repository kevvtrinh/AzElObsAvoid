function certificate = certifyAzElHs3Trajectory( ...
        solution, meshTau, limits, options)
%% Section 0: Header & Readme
% SYNTAX
%   certificate = azElInternal.certifyAzElHs3Trajectory()
%   certificate = azElInternal.certifyAzElHs3Trajectory( ...
%       solution, meshTau, limits, options)
%**************************************************************************
% PURPOSE
%   - Certify continuous position, velocity, acceleration, jerk, dynamics,
%     and HS-3 collocation bounds from segment polynomials.
%**************************************************************************
% INPUTS
%   - solution (scalar propagated HS-3 solution struct)
%       Knot and midpoint states and controls for the complete motion.
%   - meshTau (increasing finite numeric vector)
%       Normalized knot locations from zero to one.
%   - limits (scalar struct)
%       Positive two-axis maxVelocity_deg_s, maxAcceleration_deg_s2, and
%       maxJerk_deg_s3 values.
%   - options (scalar resolved planner-option struct)
%       Workspace intervals, wrapping policy, and validation tolerances.
%**************************************************************************
% OUTPUTS
%   - certificate (scalar struct)
%       Continuous extrema, violations, dynamic defects, collocation
%       defects, and per-segment bounds. A zero-input call returns the
%       stable empty certificate schema.
%**************************************************************************
% UNITS
%   - Position is degrees. Derivatives use deg/s, deg/s^2, and deg/s^3.
%     Axis order is [azimuth elevation].
%**************************************************************************

%% Section 1: Return The Empty Schema When Requested

if nargin == 0
    certificate = emptyCertificate();
    return;
end

%% Section 2: Bound Every Segment Polynomial

segmentCount = numel(meshTau) - 1;
duration_s = solution.FinalTime_s - solution.InitialTime_s;
maximumVelocityBySegment_deg_s = zeros(segmentCount, 2);
maximumAccelerationBySegment_deg_s2 = zeros(segmentCount, 2);
maximumJerkBySegment_deg_s3 = zeros(segmentCount, 2);
minimumPositionBySegment_deg = zeros(segmentCount, 2);
maximumPositionBySegment_deg = zeros(segmentCount, 2);
segmentDynamicsDefect = zeros(segmentCount, 1);
segmentCollocationDefect = zeros(segmentCount, 1);
midpointAndEndpointPower = [ ...
    1 0.5 0.25 0.125 0.0625 0.03125; ...
    1 1 1 1 1 1];
for segmentIndex = 1:segmentCount
    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    [statePower, controlPower] = ...
        azElInternal.buildAzElHs3SegmentPolynomials( ...
        solution.KnotState(segmentIndex, :), ...
        solution.KnotControl(segmentIndex, :), ...
        solution.MidpointControl(segmentIndex, :), ...
        solution.KnotControl(segmentIndex + 1, :), ...
        segmentDuration_s);
    [minimumPositionBySegment_deg(segmentIndex, :), ...
        maximumPositionBySegment_deg(segmentIndex, :)] = ...
        polynomialRange(statePower(:, 1:2));
    maximumVelocityBySegment_deg_s(segmentIndex, :) = ...
        polynomialMaximumAbsolute(statePower(:, 3:4));
    maximumAccelerationBySegment_deg_s2(segmentIndex, :) = ...
        polynomialMaximumAbsolute(statePower(:, 5:6));
    maximumJerkBySegment_deg_s3(segmentIndex, :) = ...
        polynomialMaximumAbsolute(controlPower);

    derivativePower = (1:size(statePower, 1) - 1).' .* ...
        statePower(2:end, :) / segmentDuration_s;
    paddedControlPower = [controlPower; zeros(2, 2)];
    dynamicsPower = [statePower(1:end - 1, 3:6), ...
        paddedControlPower];
    segmentDynamicsDefect(segmentIndex) = max( ...
        polynomialMaximumAbsolute( ...
        derivativePower - dynamicsPower), [], "all");

    predictedState = midpointAndEndpointPower * statePower;
    midpointDefect = solution.MidpointState(segmentIndex, :) - ...
        predictedState(1, :);
    endpointDefect = solution.KnotState(segmentIndex + 1, :) - ...
        predictedState(2, :);
    segmentCollocationDefect(segmentIndex) = max( ...
        abs([midpointDefect endpointDefect]));
end

%% Section 3: Assemble Continuous Limits And Violations

maximumVelocity_deg_s = max(maximumVelocityBySegment_deg_s, [], 1);
maximumAcceleration_deg_s2 = max( ...
    maximumAccelerationBySegment_deg_s2, [], 1);
maximumJerk_deg_s3 = max(maximumJerkBySegment_deg_s3, [], 1);
azimuthLower = -Inf;
azimuthUpper = Inf;
if ~options.AllowAzimuthWrapping
    azimuthLower = options.AzimuthInterval_deg(1);
    azimuthUpper = options.AzimuthInterval_deg(2);
end
positionLower = [azimuthLower, options.ElevationInterval_deg(1)];
positionUpper = [azimuthUpper, options.ElevationInterval_deg(2)];
minimumPosition_deg = min(minimumPositionBySegment_deg, [], 1);
maximumPosition_deg = max(maximumPositionBySegment_deg, [], 1);
maximumPositionViolation_deg = max([ ...
    positionLower - minimumPosition_deg; ...
    maximumPosition_deg - positionUpper; zeros(1, 2)], [], 1);
maximumVelocityViolation_deg_s = max(0, ...
    maximumVelocity_deg_s - limits.maxVelocity_deg_s);
maximumAccelerationViolation_deg_s2 = max(0, ...
    maximumAcceleration_deg_s2 - limits.maxAcceleration_deg_s2);
maximumJerkViolation_deg_s3 = max(0, ...
    maximumJerk_deg_s3 - limits.maxJerk_deg_s3);
certificate = struct( ...
    "MaximumVelocity_deg_s", maximumVelocity_deg_s, ...
    "MaximumAcceleration_deg_s2", maximumAcceleration_deg_s2, ...
    "MaximumJerk_deg_s3", maximumJerk_deg_s3, ...
    "MaximumVelocityViolation_deg_s", ...
    maximumVelocityViolation_deg_s, ...
    "MaximumAccelerationViolation_deg_s2", ...
    maximumAccelerationViolation_deg_s2, ...
    "MaximumJerkViolation_deg_s3", maximumJerkViolation_deg_s3, ...
    "MaximumPositionViolation_deg", maximumPositionViolation_deg, ...
    "MaximumDynamicsDefect", max(segmentDynamicsDefect), ...
    "SegmentDynamicsDefect", segmentDynamicsDefect, ...
    "SegmentCollocationDefect", segmentCollocationDefect, ...
    "MaximumVelocityBySegment_deg_s", ...
    maximumVelocityBySegment_deg_s, ...
    "MaximumAccelerationBySegment_deg_s2", ...
    maximumAccelerationBySegment_deg_s2, ...
    "MaximumJerkBySegment_deg_s3", maximumJerkBySegment_deg_s3);
end

%% Section 4: Local Functions

function certificate = emptyCertificate()
% PURPOSE
%   - Define the stable continuous-certificate schema.
certificate = struct( ...
    "MaximumVelocity_deg_s", [Inf Inf], ...
    "MaximumAcceleration_deg_s2", [Inf Inf], ...
    "MaximumJerk_deg_s3", [Inf Inf], ...
    "MaximumVelocityViolation_deg_s", [Inf Inf], ...
    "MaximumAccelerationViolation_deg_s2", [Inf Inf], ...
    "MaximumJerkViolation_deg_s3", [Inf Inf], ...
    "MaximumPositionViolation_deg", [Inf Inf], ...
    "MaximumDynamicsDefect", Inf, ...
    "SegmentDynamicsDefect", zeros(0, 1), ...
    "SegmentCollocationDefect", zeros(0, 1), ...
    "MaximumVelocityBySegment_deg_s", zeros(0, 2), ...
    "MaximumAccelerationBySegment_deg_s2", zeros(0, 2), ...
    "MaximumJerkBySegment_deg_s3", zeros(0, 2));
end

function [minimumValue, maximumValue] = polynomialRange(powerCoefficient)
% PURPOSE
%   - Bound a power-basis polynomial with its Bernstein control hull.
bernsteinCoefficient = ...
    azElInternal.powerToBernstein(powerCoefficient);
minimumValue = min(bernsteinCoefficient, [], 1);
maximumValue = max(bernsteinCoefficient, [], 1);
end

function maximumAbsolute = polynomialMaximumAbsolute(powerCoefficient)
% PURPOSE
%   - Bound maximum component magnitudes with a Bernstein control hull.
[minimumValue, maximumValue] = polynomialRange(powerCoefficient);
maximumAbsolute = max(abs([minimumValue; maximumValue]), [], 1);
end
