function durationLowerBound_s = minimumDurationLowerBound( ...
        initialState, goalState, limits)
% PURPOSE
%   - Compute conservative necessary duration bounds from each state order.
positionBound_s = abs(goalState.position_deg - ...
    initialState.position_deg) ./ limits.maxVelocity_deg_s;
velocityBound_s = abs(goalState.velocity_deg_s - ...
    initialState.velocity_deg_s) ./ limits.maxAcceleration_deg_s2;
accelerationBound_s = abs(goalState.acceleration_deg_s2 - ...
    initialState.acceleration_deg_s2) ./ limits.maxJerk_deg_s3;
durationLowerBound_s = max([1e-4, positionBound_s, ...
    velocityBound_s, accelerationBound_s]);
end

function route_deg = removeDuplicateRoutePoints(route_deg)
% PURPOSE
%   - Remove only consecutive zero-length seed edges.
route_deg = double(route_deg);
keep = [true; any(abs(diff(route_deg, 1, 1)) > 1e-12, 2)];
route_deg = route_deg(keep, :);
end

function value = maximumOrZero(vector)
% PURPOSE
%   - Return the positive constraint violation of an optional vector.
if isempty(vector)
    value = 0;
else
    value = max(0, max(vector));
end
end

