function [guess, isFeasible, message, timeBudgetReached, ...
        failureReason] = ...
        seedInitialGuess( ...
        seedRoute_deg, meshTau, obstacleField, initialState, goalState, ...
        limits, options, durationLowerBound_s, candidateTimer, ...
        remainingTime_s)
% PURPOSE
%   - Fit one bounded, dynamically consistent HS-3 seed to a route.
route_deg = removeDuplicateRoutePoints(seedRoute_deg);
routeStep_deg = diff(route_deg, 1, 1);
routeArc_deg = [0; cumsum(hypot( ...
    routeStep_deg(:, 1), routeStep_deg(:, 2)))];
if routeArc_deg(end) <= eps
    routeFraction = [0; 1];
    route_deg = [initialState.position_deg; goalState.position_deg];
else
    routeFraction = routeArc_deg / routeArc_deg(end);
end

availableDuration_s = goalState.time_s - initialState.time_s;
if options.GoalTimeMode == "fixedarrival"
    durationGuess_s = availableDuration_s;
else
    geometricDuration_s = max(durationLowerBound_s, ...
        routeArc_deg(end) / max(min(limits.maxVelocity_deg_s), eps));
    routeHeading_rad = atan2(routeStep_deg(:, 2), routeStep_deg(:, 1));
    headingChange_rad = diff(routeHeading_rad);
    headingChange_rad = atan2( ...
        sin(headingChange_rad), cos(headingChange_rad));
    totalTurnFraction = sum(abs(headingChange_rad)) / pi;
    % A route with many turns needs time to redirect bounded velocity and
    % acceleration. This factor only orders feasibility trials.
    durationStretch = min(3, 1.5 + 0.5 * totalTurnFraction);
    durationGuess_s = min(availableDuration_s, max( ...
        durationStretch * geometricDuration_s, ...
        1.05 * durationLowerBound_s));
    hasTimedRouteDuration = ...
        isfield(options, "SeedRouteDuration_s") && ...
        isfinite(options.SeedRouteDuration_s) && ...
        options.SeedRouteDuration_s > 0;
    if hasTimedRouteDuration
        durationGuess_s = min(availableDuration_s, max( ...
            durationLowerBound_s, options.SeedRouteDuration_s));
    elseif isfield(options, "SeedSnapshotTime_s") && ...
            isfinite(options.SeedSnapshotTime_s) && ...
            options.SeedSnapshotTime_s > initialState.time_s
        snapshotCenteredDuration_s = 2 * ...
            (options.SeedSnapshotTime_s - initialState.time_s);
        durationGuess_s = min(availableDuration_s, max( ...
            durationLowerBound_s, snapshotCenteredDuration_s));
    end
end
durationGuess_s = max(durationGuess_s, 1e-6);
durationCandidates_s = durationGuess_s;
canTryLongerDuration = options.GoalTimeMode == "earliestarrival" && ...
    availableDuration_s > 0;
if canTryLongerDuration
    shortestTrialDuration_s = min(availableDuration_s, max( ...
        durationLowerBound_s, 1e-6));
    durationCandidates_s = adaptiveDurationTrialSequence( ...
        shortestTrialDuration_s, durationGuess_s, ...
        availableDuration_s, 33);
    durationCandidates_s = sort(durationCandidates_s, "ascend");
end

guess = emptySolution();
isFeasible = false;
timeBudgetReached = false;
failureReason = "initialGuessInfeasible";
lastFitMessage = "No duration was evaluated.";
lastCompletedFitMessage = "No duration trial completed.";
evaluatedDurationCount = 0;
for durationIndex = 1:numel(durationCandidates_s)
    if isfinite(remainingTime_s) && ...
            toc(candidateTimer) >= remainingTime_s
        timeBudgetReached = true;
        message = "The initial-guess time budget expired after " + ...
            string(evaluatedDurationCount) + " duration trials. " + ...
            "Last completed trial: " + lastCompletedFitMessage;
        return;
    end
    finalTime_s = initialState.time_s + ...
        durationCandidates_s(durationIndex);
    [trialGuess, trialIsFeasible, lastFitMessage, ...
        trialTimeBudgetReached, trialFailureReason] = ...
        fitHs3SeedAtDuration( ...
        route_deg, routeFraction, meshTau, obstacleField, ...
        initialState, goalState, ...
        limits, options, durationLowerBound_s, finalTime_s, ...
        candidateTimer, remainingTime_s);
    evaluatedDurationCount = evaluatedDurationCount + 1;
    failureReason = trialFailureReason;
    if trialTimeBudgetReached
        timeBudgetReached = true;
        message = "The initial-guess time budget expired after " + ...
            string(evaluatedDurationCount) + " duration trials. " + ...
            "Last completed trial: " + lastCompletedFitMessage;
        return;
    end
    lastCompletedFitMessage = "Duration " + ...
        string(durationCandidates_s(durationIndex)) + ...
        " seconds: " + lastFitMessage;
    if trialIsFeasible
        guess = trialGuess;
        isFeasible = true;
        failureReason = "";
        message = "A bounded HS-3-consistent initial guess was found " + ...
            "after " + string(evaluatedDurationCount) + ...
            " duration trials.";
        return;
    end
end
if options.GoalTimeMode == "fixedarrival"
    message = "The fixed-arrival horizon has no bounded HS-3 initial " + ...
        "guess. " + lastFitMessage;
else
    message = "No bounded HS-3 initial guess was found in " + ...
        string(evaluatedDurationCount) + ...
        " deterministic adaptive duration trials. " + ...
        lastFitMessage;
end
end

function durationCandidates_s = adaptiveDurationTrialSequence( ...
        lowerDuration_s, preferredDuration_s, upperDuration_s, ...
        maximumTrialCount)
% PURPOSE
%   - Expand deterministically around the preferred duration before the
%     distant horizon, so a nearby feasible seed is not skipped.
preferredDuration_s = min(upperDuration_s, max( ...
    lowerDuration_s, preferredDuration_s));
durationCandidates_s = preferredDuration_s;
baseStep_s = max(1e-3, 0.05 * max(1, preferredDuration_s));
expansionIndex = 0;
while numel(durationCandidates_s) < maximumTrialCount
    expansionIndex = expansionIndex + 1;
    expansionLevel = ceil(expansionIndex / 2);
    direction = 1;
    if mod(expansionIndex, 2) == 0
        direction = -1;
    end
    trialDuration_s = preferredDuration_s + direction * ...
        baseStep_s * 2 ^ (expansionLevel - 1);
    trialDuration_s = min(upperDuration_s, max( ...
        lowerDuration_s, trialDuration_s));
    isNewDuration = all(abs(durationCandidates_s - trialDuration_s) > ...
        eps(max(1, upperDuration_s)));
    if isNewDuration
        durationCandidates_s(end + 1, 1) = ...
            trialDuration_s; %#ok<AGROW>
    end
    coveredLowerBound = any(durationCandidates_s == lowerDuration_s);
    coveredUpperBound = any(durationCandidates_s == upperDuration_s);
    if coveredLowerBound && coveredUpperBound && ~isNewDuration
        break;
    end
end
end

function routeQueryFraction = temporalSeedRouteFraction( ...
        timeFraction, initialTime_s, finalTime_s, options)
% PURPOSE
%   - Use a space-time route law or center one snapshot route in time.
routeQueryFraction = timeFraction;
hasTimedRoute = isfield(options, "SeedRouteTimeFraction") && ...
    isfield(options, "SeedRouteProgress") && ...
    numel(options.SeedRouteTimeFraction) >= 2 && ...
    numel(options.SeedRouteTimeFraction) == ...
    numel(options.SeedRouteProgress) && ...
    all(diff(options.SeedRouteTimeFraction) > 0) && ...
    all(diff(options.SeedRouteProgress) >= 0);
if hasTimedRoute
    routeQueryFraction = interp1( ...
        options.SeedRouteTimeFraction, options.SeedRouteProgress, ...
        timeFraction, "linear", "extrap");
    routeQueryFraction = min(1, max(0, routeQueryFraction));
    return;
end
if ~isfield(options, "SeedSnapshotTime_s") || ...
        ~isfinite(options.SeedSnapshotTime_s)
    return;
end
snapshotFraction = (options.SeedSnapshotTime_s - initialTime_s) / ...
    (finalTime_s - initialTime_s);
if snapshotFraction <= 1e-6 || snapshotFraction >= 1 - 1e-6
    return;
end
% The graph has no time at each route vertex. Put its geometric midpoint at
% the source snapshot so equal spatial routes can seed different time laws.
routeQueryFraction = interp1([0; snapshotFraction; 1], ...
    [0; 0.5; 1], timeFraction, "linear");
end

function [guess, isFeasible, message, timeBudgetReached, ...
        failureReason] = ...
        fitHs3SeedAtDuration( ...
        route_deg, routeFraction, meshTau, obstacleField, ...
        initialState, goalState, ...
        limits, options, durationLowerBound_s, finalTime_s, ...
        candidateTimer, remainingTime_s)
% PURPOSE
%   - Fit one joint HS-3 chain to the route and its local separators.
duration_s = finalTime_s - initialState.time_s;
[fitTau, associationTau] = segmentCorridorTau(meshTau);
segmentCount = numel(meshTau) - 1;
zeroKnotControl = zeros(segmentCount + 1, 2);
zeroMidpointControl = zeros(segmentCount, 2);
freeSolution = integrateHs3ControlChain( ...
    initialState.time_s, finalTime_s, meshTau, ...
    endpointState(initialState), zeroKnotControl, ...
    zeroMidpointControl);
freeSampleState = [freeSolution.KnotState; freeSolution.MidpointState];
[freeContinuousState, ~] = continuousSeedControlValues( ...
    freeSolution, meshTau);
baseControl = boundaryQuinticControl( ...
    meshTau, initialState, goalState, duration_s);
layout = decisionLayout(segmentCount, ...
    options.GoalTimeMode == "earliestarrival");
[lowerBound, upperBound] = decisionBounds( ...
    layout, meshTau, initialState, goalState, limits, options, ...
    durationLowerBound_s, Inf);
verificationTolerance = max(1e-8, ...
    0.1 * options.NlpConstraintTolerance);
guess = emptySolution();
isFeasible = false;
failureReason = "initialGuessInfeasible";
if candidateTimeBudgetReached(candidateTimer, remainingTime_s)
    timeBudgetReached = true;
    message = "The joint HS-3 route projection expired.";
    return;
end
routeQueryFraction = temporalSeedRouteFraction( ...
    fitTau, initialState.time_s, finalTime_s, options);
targetPosition_deg = interp1(routeFraction, route_deg, ...
    routeQueryFraction, "linear", "extrap");
associationRouteFraction = temporalSeedRouteFraction( ...
    associationTau, initialState.time_s, finalTime_s, options);
associationPosition_deg = interp1(routeFraction, route_deg, ...
    associationRouteFraction, "linear", "extrap");
[stateResponse, fitPositionResponse, continuousStateResponse, ...
    continuousJerkResponse] = seedControlResponses( ...
    meshTau, duration_s, fitTau);
[freeFitState, ~] = sampleSolutionAtTau( ...
    freeSolution, meshTau, fitTau);
referenceCorridor = buildOptimizationCorridor( ...
    freeSolution, meshTau, obstacleField, initialState.time_s, ...
    associationPosition_deg, fitTau);
referenceCorridor.GeometryTimeInvariant = isfield( ...
    options, "ObstacleGeometryTimeInvariant") && ...
    logical(options.ObstacleGeometryTimeInvariant);
[timeOrderedControl, projectionIsFeasible, message, ...
    timeBudgetReached, failureReason] = fitJointSeedControl( ...
    stateResponse, fitPositionResponse, continuousStateResponse, ...
    continuousJerkResponse, freeSampleState, freeContinuousState, ...
    freeFitState(:, 1:2), targetPosition_deg, ...
    endpointState(goalState), baseControl, limits, options, ...
    referenceCorridor, obstacleField, initialState.time_s, ...
    finalTime_s, candidateTimer, remainingTime_s);
if ~projectionIsFeasible || timeBudgetReached
    return;
end
knotControl = timeOrderedControl(1:2:end, :);
midpointControl = timeOrderedControl(2:2:end, :);
guess = integrateHs3ControlChain( ...
    initialState.time_s, finalTime_s, meshTau, ...
    endpointState(initialState), knotControl, midpointControl);
decision = packDecision(guess, layout);
[equality, ~] = hs3EqualityDefects(guess, meshTau);
terminalStateDefect = guess.KnotState(end, :) - endpointState(goalState);
maximumBoundViolation = max([0; lowerBound - decision; ...
    decision - upperBound]);
maximumEqualityDefect = maximumAbsoluteOrZero( ...
    [equality; terminalStateDefect(:)]);
motionIsFeasible = all(isfinite(decision)) && ...
    maximumBoundViolation <= verificationTolerance && ...
    maximumEqualityDefect <= verificationTolerance;
if ~motionIsFeasible
    message = "The joint HS-3 seed exceeded a state, control, " + ...
        "or equality tolerance.";
    return;
end
trialTrajectory = reconstructTrajectory( ...
    guess, meshTau, initialState.time_s, options.SampleTime_s, ...
    options.ObstacleConstraintTolerance_deg);
[~, ~, collisionAssessment] = assessTrajectoryCollision( ...
    obstacleField, trialTrajectory, options);
isFeasible = true;
failureReason = "";
if collisionAssessment.CollisionFree
    message = "The joint HS-3 seed passed motion, corridor, and " + ...
        "continuous collision verification.";
    return;
end
message = "The bounded HS-3 warm start is not collision-free. " + ...
    "The nonlinear corridor and mesh stages must resolve it.";
end

function [stateResponse, fitPositionResponse, ...
        continuousStateResponse, continuousJerkResponse] = ...
        seedControlResponses(meshTau, duration_s, fitTau)
% PURPOSE
%   - Build exact affine state maps for time-ordered jerk ordinates.
segmentCount = numel(meshTau) - 1;
controlCount = 2 * segmentCount + 1;
sampleCount = 2 * segmentCount + 1;
stateResponse = zeros(3 * sampleCount, controlCount);
fitPositionResponse = zeros(numel(fitTau), controlCount);
continuousStateResponse = zeros(12 * segmentCount, controlCount);
continuousJerkResponse = zeros(segmentCount, controlCount);
for controlIndex = 1:controlCount
    timeOrderedControl = zeros(controlCount, 2);
    timeOrderedControl(controlIndex, 1) = 1;
    responseSolution = integrateHs3ControlChain( ...
        0, duration_s, meshTau, zeros(1, 6), ...
        timeOrderedControl(1:2:end, :), ...
        timeOrderedControl(2:2:end, :));
    sampleState = [responseSolution.KnotState(:, [1 3 5]); ...
        responseSolution.MidpointState(:, [1 3 5])];
    stateResponse(:, controlIndex) = sampleState(:);
    [fitState, ~] = sampleSolutionAtTau( ...
        responseSolution, meshTau, fitTau);
    fitPositionResponse(:, controlIndex) = fitState(:, 1);
    [continuousState, continuousJerk] = ...
        continuousSeedControlValues(responseSolution, meshTau);
    continuousState = continuousState(:, [1 3 5]);
    continuousStateResponse(:, controlIndex) = continuousState(:);
    continuousJerkResponse(:, controlIndex) = continuousJerk(:, 1);
end
end

function [stateControlPoints, interiorJerkControl] = ...
        continuousSeedControlValues(solution, meshTau)
% PURPOSE
%   - Evaluate the same interior Bernstein controls used by the NLP.
segmentCount = numel(meshTau) - 1;
stateControlPoints = zeros(4 * segmentCount, 6);
interiorJerkControl = zeros(segmentCount, 2);
duration_s = solution.FinalTime_s - solution.InitialTime_s;
for segmentIndex = 1:segmentCount
    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    firstControl = solution.KnotControl(segmentIndex, :);
    midpointControl = solution.MidpointControl(segmentIndex, :);
    lastControl = solution.KnotControl(segmentIndex + 1, :);
    statePower = segmentStatePowerCoefficients( ...
        solution.KnotState(segmentIndex, :), firstControl, ...
        midpointControl, lastControl, segmentDuration_s);
    stateBernstein = powerToBernstein(statePower);
    row = 4 * (segmentIndex - 1) + (1:4);
    stateControlPoints(row, :) = stateBernstein(2:end - 1, :);
    linearControl = -3 * firstControl + ...
        4 * midpointControl - lastControl;
    interiorJerkControl(segmentIndex, :) = ...
        firstControl + linearControl / 2;
end
end

function [control, isFeasible, message, timeBudgetReached, ...
        failureReason] = ...
        fitJointSeedControl( ...
        stateResponse, fitPositionResponse, continuousStateResponse, ...
        continuousJerkResponse, freeSampleState, freeContinuousState, ...
        freeFitPosition_deg, targetFitPosition_deg, goalState, ...
        baseControl, limits, options, corridor, obstacleField, ...
        initialTime_s, finalTime_s, candidateTimer, remainingTime_s)
% PURPOSE
%   - Fit both HS-3 axes with shared obstacle-side inequalities.
failureReason = "initialGuessInfeasible";
controlCount = size(stateResponse, 2);
axisModel = cell(2, 1);
for axisIndex = 1:2
    stateColumn = [axisIndex, axisIndex + 2, axisIndex + 4];
    positionBounds_deg = options.ElevationInterval_deg;
    if axisIndex == 1 && options.AllowAzimuthWrapping
        positionBounds_deg = [-Inf Inf];
    elseif axisIndex == 1
        positionBounds_deg = options.AzimuthInterval_deg;
    end
    axisModel{axisIndex} = axisSeedLinearModel( ...
        stateResponse, fitPositionResponse, continuousStateResponse, ...
        continuousJerkResponse, freeSampleState(:, stateColumn), ...
        freeContinuousState(:, stateColumn), ...
        freeFitPosition_deg(:, axisIndex), ...
        targetFitPosition_deg(:, axisIndex), goalState(stateColumn), ...
        baseControl(:, axisIndex), limits.maxJerk_deg_s3(axisIndex), ...
        limits.maxVelocity_deg_s(axisIndex), ...
        limits.maxAcceleration_deg_s2(axisIndex), ...
        positionBounds_deg);
end
objectiveMatrix = blkdiag( ...
    axisModel{1}.ObjectiveMatrix, axisModel{2}.ObjectiveMatrix);
objectiveTarget = [axisModel{1}.ObjectiveTarget; ...
    axisModel{2}.ObjectiveTarget];
inequalityMatrix = blkdiag( ...
    axisModel{1}.InequalityMatrix, axisModel{2}.InequalityMatrix);
inequalityTarget = [axisModel{1}.InequalityTarget; ...
    axisModel{2}.InequalityTarget];
equalityMatrix = blkdiag( ...
    axisModel{1}.EqualityMatrix, axisModel{2}.EqualityMatrix);
equalityTarget = [axisModel{1}.EqualityTarget; ...
    axisModel{2}.EqualityTarget];
motionInequalityMatrix = inequalityMatrix;
motionInequalityTarget = inequalityTarget;
continuousPositionCount = size(freeContinuousState, 1);
continuousPositionResponse = continuousStateResponse( ...
    1:continuousPositionCount, :);
[corridorMatrix, corridorTarget] = linearSeedCorridorConstraints( ...
    corridor, obstacleField, initialTime_s, finalTime_s, ...
    freeFitPosition_deg, fitPositionResponse, ...
    freeContinuousState(:, 1:2), continuousPositionResponse, ...
    limits.maxJerk_deg_s3, ...
    options.ObstacleConstraintTolerance_deg);
inequalityMatrix = [inequalityMatrix; corridorMatrix];
inequalityTarget = [inequalityTarget; corridorTarget];
initialControl = [axisModel{1}.InitialControl; ...
    axisModel{2}.InitialControl];
variableCount = 2 * controlCount;
lowerBound = -ones(variableCount, 1);
upperBound = ones(variableCount, 1);
verificationTolerance = max(1e-8, ...
    0.1 * options.NlpConstraintTolerance);
[motionPointIsFinite, motionEqualityResidual, ...
    motionInequalityResidual, motionControlViolation] = ...
    verifyLinearSeedPoint(initialControl, variableCount, ...
    equalityMatrix, equalityTarget, motionInequalityMatrix, ...
    motionInequalityTarget);
motionOnlyPointIsFeasible = motionPointIsFinite && ...
    motionEqualityResidual <= verificationTolerance && ...
    motionInequalityResidual <= verificationTolerance && ...
    motionControlViolation <= verificationTolerance;
isFeasible = false;
control = zeros(controlCount, 2);
try
    linearOptions = optimoptions("lsqlin", ...
        "Algorithm", "active-set", "Display", "none", ...
        "ConstraintTolerance", 1e-12, ...
        "OptimalityTolerance", 1e-10, ...
        "StepTolerance", 1e-12);
    [normalizedControl, ~, ~, linearExitFlag, linearOutput] = lsqlin( ...
        objectiveMatrix, objectiveTarget, inequalityMatrix, ...
        inequalityTarget, equalityMatrix, equalityTarget, lowerBound, ...
        upperBound, initialControl, linearOptions);
    linearMessage = string(linearOutput.message);
catch fitError
    timeBudgetReached = candidateTimeBudgetReached( ...
        candidateTimer, remainingTime_s);
    if timeBudgetReached
        message = "The joint HS-3 projection time budget expired.";
        return;
    end
    message = "The joint HS-3 least-squares solver failed: " + ...
        string(fitError.identifier) + ".";
    return;
end
timeBudgetReached = candidateTimeBudgetReached( ...
    candidateTimer, remainingTime_s);
if timeBudgetReached
    message = "The joint HS-3 projection time budget expired.";
    return;
end

[isFeasible, maximumEqualityResidual, ...
    maximumInequalityResidual, maximumControlViolation] = ...
    verifyLinearSeedPoint(normalizedControl, variableCount, ...
    equalityMatrix, equalityTarget, inequalityMatrix, ...
    inequalityTarget);
isFeasible = isFeasible && ...
    maximumEqualityResidual <= verificationTolerance && ...
    maximumInequalityResidual <= verificationTolerance && ...
    maximumControlViolation <= verificationTolerance;
if ~isFeasible && exist("linprog", "file") == 2
    try
        feasibilityOptions = optimoptions("linprog", "Display", "none", ...
            "ConstraintTolerance", 1e-10, ...
            "OptimalityTolerance", 1e-10);
        [feasibleControl, ~, feasibilityExitFlag, feasibilityOutput] = ...
            linprog(zeros(variableCount, 1), inequalityMatrix, ...
            inequalityTarget, equalityMatrix, equalityTarget, ...
            lowerBound, upperBound, feasibilityOptions);
    catch feasibilityError
        timeBudgetReached = candidateTimeBudgetReached( ...
            candidateTimer, remainingTime_s);
        if timeBudgetReached
            message = "The joint HS-3 feasibility time budget expired.";
            return;
        end
        message = "The joint HS-3 feasibility solver failed: " + ...
            string(feasibilityError.identifier) + ".";
        return;
    end
    timeBudgetReached = candidateTimeBudgetReached( ...
        candidateTimer, remainingTime_s);
    if timeBudgetReached
        message = "The joint HS-3 feasibility time budget expired.";
        return;
    end
    if feasibilityExitFlag == -2
        if ~motionOnlyPointIsFeasible || isempty(corridorMatrix)
            message = "The joint bounded HS-3 route and corridor are " + ...
                "infeasible. Exit flag: -2. " + ...
                string(feasibilityOutput.message);
            return;
        end
    elseif isempty(feasibleControl) || feasibilityExitFlag <= 0
        message = "The joint HS-3 feasibility solver returned no " + ...
            "proved point. Exit flag: " + ...
            string(feasibilityExitFlag) + ".";
        return;
    else
        normalizedControl = feasibleControl;
        [isFeasible, maximumEqualityResidual, ...
            maximumInequalityResidual, maximumControlViolation] = ...
            verifyLinearSeedPoint(normalizedControl, variableCount, ...
            equalityMatrix, equalityTarget, inequalityMatrix, ...
            inequalityTarget);
        isFeasible = isFeasible && ...
            maximumEqualityResidual <= verificationTolerance && ...
            maximumInequalityResidual <= verificationTolerance && ...
            maximumControlViolation <= verificationTolerance;
    end
end
if ~isFeasible && motionOnlyPointIsFeasible && ~isempty(corridorMatrix)
    normalizedControl = initialControl;
    [isFeasible, maximumEqualityResidual, ...
        maximumInequalityResidual, maximumControlViolation] = ...
        verifyLinearSeedPoint(normalizedControl, variableCount, ...
        equalityMatrix, equalityTarget, motionInequalityMatrix, ...
        motionInequalityTarget);
    isFeasible = isFeasible && ...
        maximumEqualityResidual <= verificationTolerance && ...
        maximumInequalityResidual <= verificationTolerance && ...
        maximumControlViolation <= verificationTolerance;
    linearMessage = "The motion-feasible HS-3 seed was retained because " + ...
        "the local linear corridor was infeasible.";
end
if ~isFeasible
    if motionOnlyPointIsFeasible && ~isempty(corridorMatrix)
        failureReason = "collisionValidationFailed";
    end
    message = "The joint HS-3 point failed residual verification. " + ...
        "Least-squares exit flag: " + string(linearExitFlag) + ". " + ...
        linearMessage;
    return;
end
control(:, 1) = limits.maxJerk_deg_s3(1) * ...
    normalizedControl(1:controlCount);
control(:, 2) = limits.maxJerk_deg_s3(2) * ...
    normalizedControl(controlCount + (1:controlCount));
failureReason = "";
message = "The joint bounded HS-3 route projection passed linear " + ...
    "feasibility verification. " + linearMessage;
end

function model = axisSeedLinearModel( ...
        stateResponse, fitPositionResponse, continuousStateResponse, ...
        continuousJerkResponse, freeSampleState, freeContinuousState, ...
        freeFitPosition, targetFitPosition, goalState, baseControl, ...
        jerkLimit, velocityLimit, accelerationLimit, positionBounds)
% PURPOSE
%   - Build one axis of the joint scaled HS-3 linear projection.
sampleCount = size(freeSampleState, 1);
controlCount = size(stateResponse, 2);
knotCount = (sampleCount + 1) / 2;
positionScale = max([1; max(targetFitPosition) - ...
    min(targetFitPosition); abs(goalState(1) - freeSampleState(1, 1))]);
stateScale = repmat([positionScale, max(1, velocityLimit), ...
    max(1, accelerationLimit)], sampleCount, 1);
stateScale = stateScale(:);
normalizedStateResponse = ...
    (jerkLimit * stateResponse) ./ stateScale;
terminalRow = [knotCount, sampleCount + knotCount, ...
    2 * sampleCount + knotCount];
equalityMatrix = normalizedStateResponse(terminalRow, :);
equalityTarget = (goalState(:) - ...
    freeSampleState(knotCount, :).') ./ stateScale(terminalRow);

stateLower = repmat([positionBounds(1), -velocityLimit, ...
    -accelerationLimit], sampleCount, 1);
stateUpper = repmat([positionBounds(2), velocityLimit, ...
    accelerationLimit], sampleCount, 1);
upperAllowance = (stateUpper(:) - freeSampleState(:)) ./ stateScale;
lowerAllowance = (freeSampleState(:) - stateLower(:)) ./ stateScale;
hasFiniteUpper = isfinite(upperAllowance);
hasFiniteLower = isfinite(lowerAllowance);
inequalityMatrix = [ ...
    normalizedStateResponse(hasFiniteUpper, :); ...
    -normalizedStateResponse(hasFiniteLower, :)];
inequalityTarget = [upperAllowance(hasFiniteUpper); ...
    lowerAllowance(hasFiniteLower)];

continuousPointCount = size(freeContinuousState, 1);
continuousScale = repmat([positionScale, max(1, velocityLimit), ...
    max(1, accelerationLimit)], continuousPointCount, 1);
continuousScale = continuousScale(:);
normalizedContinuousStateResponse = ...
    (jerkLimit * continuousStateResponse) ./ continuousScale;
continuousLower = repmat([positionBounds(1), -velocityLimit, ...
    -accelerationLimit], continuousPointCount, 1);
continuousUpper = repmat([positionBounds(2), velocityLimit, ...
    accelerationLimit], continuousPointCount, 1);
continuousUpperAllowance = (continuousUpper(:) - ...
    freeContinuousState(:)) ./ continuousScale;
continuousLowerAllowance = (freeContinuousState(:) - ...
    continuousLower(:)) ./ continuousScale;
hasFiniteContinuousUpper = isfinite(continuousUpperAllowance);
hasFiniteContinuousLower = isfinite(continuousLowerAllowance);
inequalityMatrix = [inequalityMatrix; ...
    normalizedContinuousStateResponse(hasFiniteContinuousUpper, :); ...
    -normalizedContinuousStateResponse(hasFiniteContinuousLower, :); ...
    continuousJerkResponse; -continuousJerkResponse];
inequalityTarget = [inequalityTarget; ...
    continuousUpperAllowance(hasFiniteContinuousUpper); ...
    continuousLowerAllowance(hasFiniteContinuousLower); ...
    ones(2 * size(continuousJerkResponse, 1), 1)];

normalizedPositionResponse = ...
    jerkLimit * fitPositionResponse / positionScale;
normalizedPositionTarget = ...
    (targetFitPosition - freeFitPosition) / positionScale;
firstDifference = diff(eye(controlCount), 1, 1);
objectiveMatrix = [normalizedPositionResponse; ...
    1e-3 * firstDifference; 1e-6 * eye(controlCount)];
objectiveTarget = [normalizedPositionTarget; ...
    zeros(size(firstDifference, 1) + controlCount, 1)];
model = struct( ...
    "ObjectiveMatrix", objectiveMatrix, ...
    "ObjectiveTarget", objectiveTarget, ...
    "InequalityMatrix", inequalityMatrix, ...
    "InequalityTarget", inequalityTarget, ...
    "EqualityMatrix", equalityMatrix, ...
    "EqualityTarget", equalityTarget, ...
    "InitialControl", min(1, max(-1, baseControl / jerkLimit)));
end

function [inequalityMatrix, inequalityTarget] = ...
        linearSeedCorridorConstraints( ...
        corridor, obstacleField, initialTime_s, finalTime_s, ...
        freePosition_deg, positionResponse, ...
        freeContinuousPosition_deg, continuousPositionResponse, ...
        jerkLimits_deg_s3, clearance_deg)
% PURPOSE
%   - Express frozen two-axis obstacle separators in jerk coordinates.
pointCount = numel(corridor.PointTau);
controlCount = size(positionResponse, 2);
if size(freePosition_deg, 1) ~= pointCount || ...
        size(positionResponse, 1) ~= pointCount
    error("optimizeAzElDirectCollocation:SeedCorridorSizeMismatch", ...
        "The joint seed response does not match the corridor points.");
end
activeCount = nnz(corridor.Active);
pointsPerSegment = 5;
segmentCount = size(freeContinuousPosition_deg, 1) / 4;
hasStaticSegmentRows = isfield(corridor, "GeometryTimeInvariant") && ...
    corridor.GeometryTimeInvariant && ...
    segmentCount == fix(segmentCount) && ...
    pointCount == pointsPerSegment * segmentCount;
maximumStaticRowCount = 0;
if hasStaticSegmentRows
    midpointRow = 3:pointsPerSegment:pointCount;
    maximumStaticRowCount = 6 * nnz(corridor.Active(midpointRow, :));
end
inequalityMatrix = zeros( ...
    activeCount + maximumStaticRowCount, 2 * controlCount);
inequalityTarget = ones(activeCount + maximumStaticRowCount, 1);
pointTime_s = initialTime_s + ...
    (finalTime_s - initialTime_s) * corridor.PointTau;
constraintIndex = 0;
for pointIndex = 1:pointCount
    for obstacleIndex = 1:numel(obstacleField.Obstacles)
        if ~corridor.Active(pointIndex, obstacleIndex)
            continue;
        end
        constraintIndex = constraintIndex + 1;
        edges_deg = obstacleEdgesAtTime( ...
            obstacleField.Obstacles(obstacleIndex), ...
            pointTime_s(pointIndex));
        if isempty(edges_deg)
            continue;
        end
        selectedEdgeIndex = min(size(edges_deg, 1), max(1, ...
            corridor.EdgeIndex(pointIndex, obstacleIndex)));
        edge_deg = edges_deg(selectedEdgeIndex, :);
        tangent_deg = edge_deg(3:4) - edge_deg(1:2);
        leftNormal = [-tangent_deg(2), tangent_deg(1)];
        normalLength = norm(leftNormal);
        if normalLength <= eps
            inequalityTarget(constraintIndex) = -clearance_deg;
            continue;
        end
        normal = corridor.SideSign(pointIndex, obstacleIndex) * ...
            leftNormal / normalLength;
        responseRow = positionResponse(pointIndex, :);
        inequalityMatrix(constraintIndex, 1:controlCount) = ...
            -normal(1) * jerkLimits_deg_s3(1) * responseRow;
        inequalityMatrix(constraintIndex, ...
            controlCount + (1:controlCount)) = ...
            -normal(2) * jerkLimits_deg_s3(2) * responseRow;
        inequalityTarget(constraintIndex) = dot( ...
            freePosition_deg(pointIndex, :) - edge_deg(1:2), ...
            normal) - clearance_deg;
    end
end
if hasStaticSegmentRows
    for segmentIndex = 1:segmentCount
        firstPointRow = pointsPerSegment * (segmentIndex - 1) + 1;
        midpointRow = pointsPerSegment * (segmentIndex - 1) + 3;
        lastPointRow = pointsPerSegment * segmentIndex;
        continuousRow = 4 * (segmentIndex - 1) + (1:4);
        staticFreePosition_deg = [ ...
            freePosition_deg(firstPointRow, :); ...
            freeContinuousPosition_deg(continuousRow, :); ...
            freePosition_deg(lastPointRow, :)];
        staticPositionResponse = [ ...
            positionResponse(firstPointRow, :); ...
            continuousPositionResponse(continuousRow, :); ...
            positionResponse(lastPointRow, :)];
        for obstacleIndex = 1:numel(obstacleField.Obstacles)
            if ~corridor.Active(midpointRow, obstacleIndex)
                continue;
            end
            edges_deg = obstacleEdgesAtTime( ...
                obstacleField.Obstacles(obstacleIndex), ...
                pointTime_s(midpointRow));
            if isempty(edges_deg)
                continue;
            end
            selectedEdgeIndex = min(size(edges_deg, 1), max(1, ...
                corridor.EdgeIndex(midpointRow, obstacleIndex)));
            edge_deg = edges_deg(selectedEdgeIndex, :);
            tangent_deg = edge_deg(3:4) - edge_deg(1:2);
            leftNormal = [-tangent_deg(2), tangent_deg(1)];
            normalLength = norm(leftNormal);
            if normalLength <= eps
                continue;
            end
            normal = corridor.SideSign(midpointRow, obstacleIndex) * ...
                leftNormal / normalLength;
            for staticRowIndex = 1:6
                constraintIndex = constraintIndex + 1;
                responseRow = staticPositionResponse(staticRowIndex, :);
                inequalityMatrix(constraintIndex, 1:controlCount) = ...
                    -normal(1) * jerkLimits_deg_s3(1) * responseRow;
                inequalityMatrix(constraintIndex, ...
                    controlCount + (1:controlCount)) = ...
                    -normal(2) * jerkLimits_deg_s3(2) * responseRow;
                inequalityTarget(constraintIndex) = dot( ...
                    staticFreePosition_deg(staticRowIndex, :) - ...
                    edge_deg(1:2), normal) - clearance_deg;
            end
        end
    end
end
inequalityMatrix = inequalityMatrix(1:constraintIndex, :);
inequalityTarget = inequalityTarget(1:constraintIndex);
end

function [isFinitePoint, maximumEqualityResidual, ...
        maximumInequalityResidual, maximumControlViolation] = ...
        verifyLinearSeedPoint(point, variableCount, equalityMatrix, ...
        equalityTarget, inequalityMatrix, inequalityTarget)
% PURPOSE
%   - Measure one joint linear seed without trusting a solver exit flag.
isFinitePoint = ~isempty(point) && numel(point) == variableCount && ...
    all(isfinite(point));
if ~isFinitePoint
    maximumEqualityResidual = Inf;
    maximumInequalityResidual = Inf;
    maximumControlViolation = Inf;
    return;
end
maximumEqualityResidual = maximumAbsoluteOrZero( ...
    equalityMatrix * point - equalityTarget);
maximumInequalityResidual = maximumOrZero( ...
    inequalityMatrix * point - inequalityTarget);
maximumControlViolation = max([0; abs(point) - 1]);
end

function control = boundaryQuinticControl( ...
        meshTau, initialState, goalState, duration_s)
% PURPOSE
%   - Supply an exact endpoint-feasible quadratic-jerk starting point.
midpointTau = 0.5 * (meshTau(1:end - 1) + meshTau(2:end));
timeOrderedTau = zeros(2 * numel(meshTau) - 1, 1);
timeOrderedTau(1:2:end) = meshTau;
timeOrderedTau(2:2:end) = midpointTau;
control = zeros(numel(timeOrderedTau), 2);
higherCoefficientMatrix = [1 1 1; 3 4 5; 6 12 20];
initialEndpoint = endpointState(initialState);
goalEndpoint = endpointState(goalState);
for axisIndex = 1:2
    stateColumn = [axisIndex, axisIndex + 2, axisIndex + 4];
    firstState = initialEndpoint(stateColumn);
    lastState = goalEndpoint(stateColumn);
    fixedCoefficient = [firstState(1); ...
        duration_s * firstState(2); ...
        0.5 * duration_s ^ 2 * firstState(3)];
    higherTarget = [ ...
        lastState(1) - sum(fixedCoefficient); ...
        duration_s * lastState(2) - fixedCoefficient(2) - ...
        2 * fixedCoefficient(3); ...
        duration_s ^ 2 * lastState(3) - 2 * fixedCoefficient(3)];
    higherCoefficient = higherCoefficientMatrix \ higherTarget;
    control(:, axisIndex) = (6 * higherCoefficient(1) + ...
        24 * higherCoefficient(2) * timeOrderedTau + ...
        60 * higherCoefficient(3) * timeOrderedTau .^ 2) / ...
        duration_s ^ 3;
end
end

function solution = integrateHs3ControlChain( ...
        initialTime_s, finalTime_s, meshTau, firstState, knotControl, ...
        midpointControl)
% PURPOSE
%   - Derive every state from one shared quadratic-jerk chain.
segmentCount = numel(meshTau) - 1;
solution = emptySolution();
solution.InitialTime_s = initialTime_s;
solution.FinalTime_s = finalTime_s;
solution.KnotState = zeros(segmentCount + 1, 6);
solution.MidpointState = zeros(segmentCount, 6);
solution.KnotControl = knotControl;
solution.MidpointControl = midpointControl;
solution.KnotState(1, :) = firstState;
duration_s = finalTime_s - initialTime_s;
for segmentIndex = 1:segmentCount
    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    statePower = segmentStatePowerCoefficients( ...
        solution.KnotState(segmentIndex, :), ...
        knotControl(segmentIndex, :), ...
        midpointControl(segmentIndex, :), ...
        knotControl(segmentIndex + 1, :), segmentDuration_s);
    state = evaluatePowerPolynomial(statePower, [0.5; 1]);
    solution.MidpointState(segmentIndex, :) = state(1, :);
    solution.KnotState(segmentIndex + 1, :) = state(2, :);
end
end

function state = endpointState(endpoint)
% PURPOSE
%   - Assemble one exact six-component endpoint row.
state = [endpoint.position_deg, endpoint.velocity_deg_s, ...
    endpoint.acceleration_deg_s2];
end

function [lowerBound, upperBound] = decisionBounds( ...
        layout, ~, initialState, goalState, limits, ~, ...
        durationLowerBound_s, finalTimeUpperOverride_s)
% PURPOSE
%   - Bound reduced HS-3 jerk ordinates and optional final time.
lowerBound = -Inf(layout.DecisionCount, 1);
upperBound = Inf(layout.DecisionCount, 1);
if layout.HasFinalTimeVariable
    lowerBound(layout.FinalTimeIndex) = ...
        initialState.time_s + durationLowerBound_s;
    finalTimeUpper_s = goalState.time_s;
    if isfinite(finalTimeUpperOverride_s)
        finalTimeUpper_s = min(finalTimeUpper_s, ...
            finalTimeUpperOverride_s);
    end
    upperBound(layout.FinalTimeIndex) = finalTimeUpper_s;
end

segmentCount = layout.SegmentCount;
controlLower = repmat(-limits.maxJerk_deg_s3, ...
    segmentCount + 1, 1);
controlUpper = repmat(limits.maxJerk_deg_s3, ...
    segmentCount + 1, 1);
midpointControlLower = repmat(-limits.maxJerk_deg_s3, ...
    segmentCount, 1);
midpointControlUpper = repmat(limits.maxJerk_deg_s3, ...
    segmentCount, 1);
lowerBound(layout.KnotControlIndex) = controlLower(:);
upperBound(layout.KnotControlIndex) = controlUpper(:);
lowerBound(layout.MidpointControlIndex) = midpointControlLower(:);
upperBound(layout.MidpointControlIndex) = midpointControlUpper(:);
end

function [decision, exitFlag, solverOutput, timeLimitReached] = solveNlp( ...
        initialDecision, lowerBound, upperBound, layout, meshTau, ...
        corridor, obstacleField, initialState, goalState, limits, ...
        options, objectiveMode, timeBudget_s)
% PURPOSE
%   - Run one bounded fmincon solve with stable tolerances and timeout.
solveTimer = tic;
timeLimitReached = false;
minimumAffineEvaluationCount = 2;
usesConvexAffineSolve = ~layout.HasFinalTimeVariable || ...
    objectiveMode == "feasibility" || objectiveMode == "minimumTime";
if usesConvexAffineSolve && ...
        options.MaximumNlpFunctionEvaluations < ...
        minimumAffineEvaluationCount
    decision = initialDecision;
    exitFlag = -1;
    solverOutput = struct( ...
        "iterations", 0, ...
        "funcCount", 0, ...
        "message", "The affine HS-3 subproblem needs at least " + ...
        string(minimumAffineEvaluationCount) + ...
        " constraint-map evaluations, but " + ...
        string(options.MaximumNlpFunctionEvaluations) + ...
        " were allowed.");
    return;
end
if ~layout.HasFinalTimeVariable
    [decision, exitFlag, solverOutput] = ...
        solveFixedArrivalConvexSubproblem( ...
        initialDecision, lowerBound, upperBound, layout, meshTau, ...
        corridor, obstacleField, initialState, goalState, limits, ...
        options, objectiveMode);
    timeLimitReached = isfinite(timeBudget_s) && ...
        toc(solveTimer) >= timeBudget_s;
    return;
end
if objectiveMode == "minimumTime"
    [decision, exitFlag, solverOutput, timeLimitReached] = ...
        solveMinimumTimeByConvexContinuation( ...
        initialDecision, lowerBound, upperBound, layout, meshTau, ...
        corridor, obstacleField, initialState, goalState, limits, ...
        options, timeBudget_s, solveTimer);
    return;
end
if objectiveMode == "feasibility"
    fixedLayout = decisionLayout(layout.SegmentCount, false);
    initialSolution = unpackDecision( ...
        initialDecision, layout, meshTau, initialState, goalState);
    trialFinalTime_s = ascendingFeasibilityTimes( ...
        initialState.time_s, initialSolution.FinalTime_s, ...
        goalState.time_s);
    fixedExitFlag = -2;
    fixedOutput = struct( ...
        "iterations", 0, "funcCount", 0, ...
        "message", "No fixed-arrival duration was evaluated.");
    totalFixedIterationCount = 0;
    totalFixedFunctionEvaluationCount = 0;
    initialDuration_s = max(eps, ...
        initialSolution.FinalTime_s - initialState.time_s);
    for trialIndex = 1:numel(trialFinalTime_s)
        if isfinite(timeBudget_s) && toc(solveTimer) >= timeBudget_s
            timeLimitReached = true;
            break;
        end
        fixedGoalState = goalState;
        fixedGoalState.time_s = trialFinalTime_s(trialIndex);
        trialDuration_s = ...
            fixedGoalState.time_s - initialState.time_s;
        controlScale = (initialDuration_s / trialDuration_s) ^ 3;
        fixedInitialSolution = initialSolution;
        fixedInitialSolution.FinalTime_s = fixedGoalState.time_s;
        fixedInitialSolution.KnotControl = ...
            controlScale * initialSolution.KnotControl;
        fixedInitialSolution.MidpointControl = ...
            controlScale * initialSolution.MidpointControl;
        fixedInitialDecision = packDecision( ...
            fixedInitialSolution, fixedLayout);
        [fixedLowerBound, fixedUpperBound] = decisionBounds( ...
            fixedLayout, meshTau, initialState, fixedGoalState, limits, ...
            options, 0, Inf);
        [fixedDecision, fixedExitFlag, fixedOutput] = ...
            solveFixedArrivalConvexSubproblem( ...
            fixedInitialDecision, fixedLowerBound, fixedUpperBound, ...
            fixedLayout, meshTau, corridor, obstacleField, ...
            initialState, fixedGoalState, limits, options, ...
            objectiveMode);
        totalFixedIterationCount = totalFixedIterationCount + ...
            outputValue(fixedOutput, "iterations");
        totalFixedFunctionEvaluationCount = ...
            totalFixedFunctionEvaluationCount + ...
            outputValue(fixedOutput, "funcCount");
        if fixedExitFlag <= 0
            continue;
        end
        fixedSolution = unpackDecision( ...
            fixedDecision, fixedLayout, meshTau, initialState, ...
            fixedGoalState);
        decision = packDecision(fixedSolution, layout);
        exitFlag = fixedExitFlag;
        solverOutput = fixedOutput;
        solverOutput.iterations = totalFixedIterationCount;
        solverOutput.funcCount = totalFixedFunctionEvaluationCount;
        solverOutput.message = ...
            "An ascending fixed-arrival convex trial established a " + ...
            "feasible point at " + string(fixedGoalState.time_s) + ...
            " seconds. " + string(fixedOutput.message);
        timeLimitReached = isfinite(timeBudget_s) && ...
            toc(solveTimer) >= timeBudget_s;
        return;
    end
    decision = initialDecision;
    exitFlag = fixedExitFlag;
    solverOutput = fixedOutput;
    solverOutput.iterations = totalFixedIterationCount;
    solverOutput.funcCount = totalFixedFunctionEvaluationCount;
    solverOutput.message = ...
        "No ascending fixed-arrival convex trial satisfied the " + ...
        "collision corridor on this mesh. Mesh or corridor refinement " + ...
        "is required. " + string(fixedOutput.message);
    timeLimitReached = isfinite(timeBudget_s) && ...
        toc(solveTimer) >= timeBudget_s;
    return;
end
objectiveFunction = @(decision) nlpObjective( ...
    decision, layout, meshTau, initialState, goalState, limits, ...
    objectiveMode, initialDecision);
constraintFunction = @(decision) nlpConstraints( ...
    decision, layout, meshTau, corridor, obstacleField, initialState, ...
    goalState, limits, options);
solverOptions = optimoptions("fmincon", ...
    "Algorithm", "interior-point", ...
    "Display", "none", ...
    "MaxIterations", options.MaximumNlpIterations, ...
    "MaxFunctionEvaluations", options.MaximumNlpFunctionEvaluations, ...
    "ConstraintTolerance", options.NlpConstraintTolerance, ...
    "OptimalityTolerance", options.NlpOptimalityTolerance, ...
    "StepTolerance", options.NlpStepTolerance, ...
    "FiniteDifferenceType", "forward", ...
    "ScaleProblem", true, ...
    "TypicalX", max(1, abs(initialDecision)), ...
    "OutputFcn", @stopForTimeBudget);
try
    [decision, ~, exitFlag, solverOutput] = fmincon( ...
        objectiveFunction, initialDecision, [], [], [], [], ...
        lowerBound, upperBound, constraintFunction, solverOptions);
catch exception
    decision = initialDecision;
    exitFlag = -99;
    solverOutput = struct( ...
        "iterations", 0, ...
        "funcCount", 0, ...
        "message", "fmincon failed: " + string(exception.message));
end

function trialFinalTime_s = ascendingFeasibilityTimes( ...
        initialTime_s, currentFinalTime_s, horizonTime_s)
% PURPOSE
%   - Cover short and long durations without assuming one obstacle event.
horizonDuration_s = horizonTime_s - initialTime_s;
currentDuration_s = min(horizonDuration_s, max(eps, ...
    currentFinalTime_s - initialTime_s));
durationMultiplier = [1; 1.25; 1.5; 2; 3; 4];
geometricDuration_s = currentDuration_s * durationMultiplier;
uniformDuration_s = linspace( ...
    currentDuration_s, horizonDuration_s, 4).';
trialDuration_s = unique([ ...
    geometricDuration_s; uniformDuration_s; horizonDuration_s]);
trialDuration_s = trialDuration_s( ...
    trialDuration_s >= currentDuration_s & ...
    trialDuration_s <= horizonDuration_s);
trialFinalTime_s = initialTime_s + trialDuration_s;
end

function [decision, exitFlag, solverOutput, timeLimitReached] = ...
        solveMinimumTimeByConvexContinuation( ...
        initialDecision, lowerBound, upperBound, layout, meshTau, ...
        corridor, obstacleField, initialState, goalState, limits, ...
        options, timeBudget_s, solveTimer)
% PURPOSE
%   - Reduce arrival time with verified fixed-duration convex subproblems.
% The reduced HS-3 state is affine in jerk for a fixed duration. A local
% time continuation therefore changes only one scalar between exact convex
% subproblems. This avoids a dense finite-difference Jacobian while keeping
% every accepted point subject to the complete collocation constraints.
fixedLayout = decisionLayout(layout.SegmentCount, false);
bestSolution = unpackDecision( ...
    initialDecision, layout, meshTau, initialState, goalState);
minimumFinalTime_s = lowerBound(layout.FinalTimeIndex);
maximumFinalTime_s = upperBound(layout.FinalTimeIndex);
bestSolution.FinalTime_s = min(maximumFinalTime_s, max( ...
    minimumFinalTime_s, bestSolution.FinalTime_s));
[bestFixedDecision, bestExitFlag, bestOutput, bestIsFeasible, ...
    bestCorridor] = ...
    solveFixedTimeTrial( ...
    bestSolution, bestSolution.FinalTime_s, "feasibility");
totalIterationCount = outputValue(bestOutput, "iterations");
totalFunctionEvaluationCount = outputValue(bestOutput, "funcCount");
trialCount = 1;
if ~bestIsFeasible
    decision = initialDecision;
    exitFlag = bestExitFlag;
    solverOutput = bestOutput;
    solverOutput.iterations = totalIterationCount;
    solverOutput.funcCount = totalFunctionEvaluationCount;
    solverOutput.message = ...
        "The initial fixed-duration convex subproblem was infeasible. " + ...
        string(bestOutput.message);
    timeLimitReached = isfinite(timeBudget_s) && ...
        toc(solveTimer) >= timeBudget_s;
    return;
end
bestGoalState = goalState;
bestGoalState.time_s = bestSolution.FinalTime_s;
bestSolution = unpackDecision( ...
    bestFixedDecision, fixedLayout, meshTau, initialState, ...
    bestGoalState);
bestFinalTime_s = bestSolution.FinalTime_s;
% One millisecond is small relative to the maintained motion examples and
% prevents mesh-dependent stopping error from dominating convergence.
arrivalTolerance_s = max(options.NlpConstraintTolerance, 1e-3);
continuationCount = 0;
maximumTimeContinuationTrialCount = 32;
maximumContinuationCount = min( ...
    maximumTimeContinuationTrialCount, ...
    max(0, options.MaximumNlpIterations));
lastOutput = bestOutput;
boundaryDerivativeTolerance = max( ...
    options.NlpConstraintTolerance, 1e-10);
initialEndpoint = endpointState(initialState);
goalEndpoint = endpointState(goalState);
hasZeroBoundaryDerivatives = max(abs([ ...
    initialEndpoint(3:6), goalEndpoint(3:6)])) <= ...
    boundaryDerivativeTolerance;
geometryIsTimeInvariant = isfield(corridor, "GeometryTimeInvariant") && ...
    corridor.GeometryTimeInvariant;
usesMonotoneStaticBisection = geometryIsTimeInvariant && ...
    hasZeroBoundaryDerivatives;
if usesMonotoneStaticBisection
    infeasibleFinalTime_s = minimumFinalTime_s;
    feasibleFinalTime_s = bestFinalTime_s;
    while feasibleFinalTime_s - infeasibleFinalTime_s > ...
            arrivalTolerance_s && ...
            continuationCount < maximumContinuationCount && ...
            totalFunctionEvaluationCount < ...
            options.MaximumNlpFunctionEvaluations
        if timeLimitReachedForContinuation()
            break;
        end
        trialFinalTime_s = 0.5 * ...
            (infeasibleFinalTime_s + feasibleFinalTime_s);
        [trialDecision, trialExitFlag, trialOutput, trialIsFeasible, ...
            trialCorridor] = solveFixedTimeTrial( ...
            bestSolution, trialFinalTime_s, "feasibility");
        continuationCount = continuationCount + 1;
        trialCount = trialCount + 1;
        totalIterationCount = totalIterationCount + ...
            outputValue(trialOutput, "iterations");
        totalFunctionEvaluationCount = ...
            totalFunctionEvaluationCount + ...
            outputValue(trialOutput, "funcCount");
        lastOutput = trialOutput;
        if trialIsFeasible
            trialGoalState = goalState;
            trialGoalState.time_s = trialFinalTime_s;
            bestExitFlag = trialExitFlag;
            bestSolution = unpackDecision( ...
                trialDecision, fixedLayout, meshTau, initialState, ...
                trialGoalState);
            bestFinalTime_s = trialFinalTime_s;
            feasibleFinalTime_s = trialFinalTime_s;
            bestCorridor = trialCorridor;
        else
            infeasibleFinalTime_s = trialFinalTime_s;
        end
    end
else
    timeStep_s = 0.5 * (bestFinalTime_s - minimumFinalTime_s);
    while timeStep_s > arrivalTolerance_s && ...
            bestFinalTime_s - minimumFinalTime_s > arrivalTolerance_s && ...
            continuationCount < maximumContinuationCount && ...
            totalFunctionEvaluationCount < ...
            options.MaximumNlpFunctionEvaluations
        if timeLimitReachedForContinuation()
            break;
        end
        trialFinalTime_s = max( ...
            minimumFinalTime_s, bestFinalTime_s - timeStep_s);
        [trialDecision, trialExitFlag, trialOutput, trialIsFeasible, ...
            trialCorridor] = solveFixedTimeTrial( ...
            bestSolution, trialFinalTime_s, "feasibility");
        continuationCount = continuationCount + 1;
        trialCount = trialCount + 1;
        totalIterationCount = totalIterationCount + ...
            outputValue(trialOutput, "iterations");
        totalFunctionEvaluationCount = ...
            totalFunctionEvaluationCount + ...
            outputValue(trialOutput, "funcCount");
        lastOutput = trialOutput;
        if trialIsFeasible
            trialGoalState = goalState;
            trialGoalState.time_s = trialFinalTime_s;
            bestExitFlag = trialExitFlag;
            bestSolution = unpackDecision( ...
                trialDecision, fixedLayout, meshTau, initialState, ...
                trialGoalState);
            bestFinalTime_s = trialFinalTime_s;
            bestCorridor = trialCorridor;
            timeStep_s = min(bestFinalTime_s - minimumFinalTime_s, ...
                1.5 * timeStep_s);
        else
            timeStep_s = 0.5 * timeStep_s;
        end
    end
end
canPolishJerk = ~timeLimitReachedForContinuation() && ...
    totalFunctionEvaluationCount < options.MaximumNlpFunctionEvaluations;
if canPolishJerk
    [polishedDecision, polishedExitFlag, polishedOutput, ...
        polishIsFeasible, polishedCorridor] = solveFixedTimeTrial( ...
        bestSolution, bestFinalTime_s, "minimumJerk");
    trialCount = trialCount + 1;
    totalIterationCount = totalIterationCount + ...
        outputValue(polishedOutput, "iterations");
    totalFunctionEvaluationCount = totalFunctionEvaluationCount + ...
        outputValue(polishedOutput, "funcCount");
    if polishIsFeasible
        polishedGoalState = goalState;
        polishedGoalState.time_s = bestFinalTime_s;
        bestSolution = unpackDecision( ...
            polishedDecision, fixedLayout, meshTau, initialState, ...
            polishedGoalState);
        bestExitFlag = polishedExitFlag;
        bestCorridor = polishedCorridor;
        lastOutput = polishedOutput;
    end
end
decision = packDecision(bestSolution, layout);
exitFlag = bestExitFlag;
solverOutput = lastOutput;
solverOutput.iterations = totalIterationCount;
solverOutput.funcCount = totalFunctionEvaluationCount;
solverOutput.Corridor = bestCorridor;
continuationMessage = "Local arrival-time continuation";
if usesMonotoneStaticBisection
    continuationMessage = "Monotone static arrival-time bisection";
end
solverOutput.message = ...
    continuationMessage + " retained a verified convex " + ...
    "subproblem after " + string(trialCount) + " duration trials. " + ...
    string(lastOutput.message);
timeLimitReached = isfinite(timeBudget_s) && ...
    toc(solveTimer) >= timeBudget_s;

    function [fixedDecision, fixedExitFlag, fixedOutput, isFeasible, ...
            trialCorridor] = ...
            solveFixedTimeTrial( ...
            referenceSolution, trialFinalTime_s, trialObjectiveMode)
        % PURPOSE
        %   - Solve and verify one fixed-duration continuation point.
        referenceDuration_s = max(eps, ...
            referenceSolution.FinalTime_s - initialState.time_s);
        trialDuration_s = max(eps, ...
            trialFinalTime_s - initialState.time_s);
        controlScale = (referenceDuration_s / trialDuration_s) ^ 3;
        trialSolution = referenceSolution;
        trialSolution.FinalTime_s = trialFinalTime_s;
        trialSolution.KnotControl = ...
            controlScale * referenceSolution.KnotControl;
        trialSolution.MidpointControl = ...
            controlScale * referenceSolution.MidpointControl;
        trialCorridor = corridor;
        geometryIsTimeInvariant = isfield( ...
            corridor, "GeometryTimeInvariant") && ...
            corridor.GeometryTimeInvariant;
        if ~geometryIsTimeInvariant
            trialCorridor = buildOptimizationCorridor( ...
                trialSolution, meshTau, obstacleField, ...
                initialState.time_s, zeros(0, 2), ...
                corridor.PointTau);
            if isfield(corridor, "PointClearance_deg") && ...
                    numel(corridor.PointClearance_deg) == ...
                    numel(trialCorridor.PointTau)
                trialCorridor.PointClearance_deg = ...
                    corridor.PointClearance_deg;
            end
            trialCorridor.GeometryTimeInvariant = false;
        end
        fixedInitialDecision = packDecision( ...
            trialSolution, fixedLayout);
        trialGoalState = goalState;
        trialGoalState.time_s = trialFinalTime_s;
        [fixedLowerBound, fixedUpperBound] = decisionBounds( ...
            fixedLayout, meshTau, initialState, trialGoalState, limits, ...
            options, 0, Inf);
        [fixedDecision, fixedExitFlag, fixedOutput] = ...
            solveFixedArrivalConvexSubproblem( ...
            fixedInitialDecision, fixedLowerBound, fixedUpperBound, ...
            fixedLayout, meshTau, trialCorridor, obstacleField, ...
            initialState, trialGoalState, limits, options, ...
            trialObjectiveMode);
        [trialInequality, trialEquality] = nlpConstraints( ...
            fixedDecision, fixedLayout, meshTau, trialCorridor, ...
            obstacleField, initialState, trialGoalState, limits, ...
            options);
        verificationTolerance = max( ...
            options.NlpConstraintTolerance, 1e-10);
        isFeasible = fixedExitFlag > 0 && ...
            maximumOrZero(trialInequality) <= verificationTolerance && ...
            maximumAbsoluteOrZero(trialEquality) <= ...
            verificationTolerance;
    end

    function reached = timeLimitReachedForContinuation()
        % PURPOSE
        %   - Apply the local wall-time limit between convex subproblems.
        reached = isfinite(timeBudget_s) && ...
            toc(solveTimer) >= timeBudget_s;
    end
end

function [decision, exitFlag, solverOutput] = ...
        solveFixedArrivalConvexSubproblem( ...
        initialDecision, lowerBound, upperBound, layout, meshTau, ...
        corridor, obstacleField, initialState, goalState, limits, ...
        options, objectiveMode)
% PURPOSE
%   - Solve the fixed-duration affine HS-3 subproblem without finite
%     differences.
% With fixed duration and frozen obstacle half-spaces, reduced HS-3 states
% and every enforced constraint are affine functions of the jerk ordinates.
% Direct dynamics propagation constructs that affine map once. This
% prevents an NLP tolerance from hiding an exact terminal-state constraint.
[inequalityMatrix, baseInequality, equalityMatrix, baseEquality] = ...
    fixedArrivalAffineConstraintMap( ...
    layout, meshTau, corridor, obstacleField, initialState, goalState, ...
    limits, options);
inequalityTarget = -baseInequality;
equalityTarget = -baseEquality;

% Verify the assembled map at the warm start and at one independent point.
% If a future constraint changes, fail visibly instead of solving a stale
% or incomplete mathematical program.
[initialInequality, initialEquality] = nlpConstraints( ...
    initialDecision, layout, meshTau, corridor, obstacleField, ...
    initialState, goalState, limits, options);
probeDecision = 0.37 * lowerBound + 0.63 * upperBound;
[probeInequality, probeEquality] = nlpConstraints( ...
    probeDecision, layout, meshTau, corridor, obstacleField, ...
    initialState, goalState, limits, options);
affineResidual = max([0; abs(initialInequality - ...
    (inequalityMatrix * initialDecision + baseInequality)); ...
    abs(initialEquality - ...
    (equalityMatrix * initialDecision + baseEquality)); ...
    abs(probeInequality - ...
    (inequalityMatrix * probeDecision + baseInequality)); ...
    abs(probeEquality - ...
    (equalityMatrix * probeDecision + baseEquality))]);
affineTolerance = max(1e-10, 10 * eps(max(1, ...
    max(abs([initialInequality; initialEquality; ...
    probeInequality; probeEquality])))));
if affineResidual > affineTolerance
    decision = initialDecision;
    exitFlag = -99;
    solverOutput = struct( ...
        "iterations", 0, ...
        "funcCount", minimumAffineEvaluationCount, ...
        "message", "The fixed-arrival constraint map was not affine. " + ...
        "The convex solve was not used.");
    return;
end

if objectiveMode == "minimumJerk"
    objectiveMatrix = fixedArrivalJerkObjectiveMatrix( ...
        layout, meshTau, goalState.time_s - initialState.time_s);
    objectiveTarget = zeros(size(objectiveMatrix, 1), 1);
else
    decisionScale = max(1, abs(initialDecision));
    objectiveMatrix = diag(1 ./ decisionScale);
    objectiveTarget = objectiveMatrix * initialDecision;
end
constraintMagnitude = max([1; abs(inequalityMatrix(:)); ...
    abs(equalityMatrix(:)); abs(inequalityTarget(:)); ...
    abs(equalityTarget(:))]);
linearConstraintTolerance = max(100 * eps, ...
    options.NlpConstraintTolerance / constraintMagnitude);
try
    linearOptions = optimoptions("lsqlin", ...
        "Algorithm", "active-set", ...
        "Display", "none", ...
        "ConstraintTolerance", linearConstraintTolerance, ...
        "OptimalityTolerance", options.NlpOptimalityTolerance, ...
        "StepTolerance", options.NlpStepTolerance);
    [decision, ~, ~, exitFlag, solverOutput] = lsqlin( ...
        objectiveMatrix, objectiveTarget, inequalityMatrix, ...
        inequalityTarget, equalityMatrix, equalityTarget, ...
        lowerBound, upperBound, initialDecision, linearOptions);
    solverOutput.funcCount = minimumAffineEvaluationCount;
catch exception
    decision = initialDecision;
    exitFlag = -99;
    solverOutput = struct( ...
        "iterations", 0, ...
        "funcCount", minimumAffineEvaluationCount, ...
        "message", "The fixed-arrival convex solver failed: " + ...
        string(exception.message));
end
end

function objectiveMatrix = fixedArrivalJerkObjectiveMatrix( ...
        layout, meshTau, duration_s)
% PURPOSE
%   - Factor the exact integral of squared quadratic jerk on the mesh.
% The three local jerk ordinates occur at normalized times 0, 1/2, and 1.
% Their Lagrange-basis Gram matrix is exact for quadratic jerk.
localGram = [4, 2, -1; 2, 16, 2; -1, 2, 4] / 30;
quadraticMatrix = zeros(layout.DecisionCount);
segmentCount = numel(meshTau) - 1;
for axisIndex = 1:2
    knotOffset = (axisIndex - 1) * (segmentCount + 1);
    midpointOffset = (axisIndex - 1) * segmentCount;
    for segmentIndex = 1:segmentCount
        localIndex = [ ...
            layout.KnotControlIndex(knotOffset + segmentIndex), ...
            layout.MidpointControlIndex( ...
            midpointOffset + segmentIndex), ...
            layout.KnotControlIndex(knotOffset + segmentIndex + 1)];
        segmentDuration_s = duration_s * ...
            (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
        quadraticMatrix(localIndex, localIndex) = ...
            quadraticMatrix(localIndex, localIndex) + ...
            segmentDuration_s * localGram;
    end
end
quadraticMatrix = 0.5 * (quadraticMatrix + quadraticMatrix.');
[objectiveMatrix, factorFlag] = chol(quadraticMatrix, "upper");
if factorFlag ~= 0
    [eigenvector, eigenvalue] = eig(quadraticMatrix, "vector");
    eigenvalue = max(0, real(eigenvalue));
    objectiveMatrix = diag(sqrt(eigenvalue)) * eigenvector.';
end
end

function [inequalityMatrix, inequalityOffset, equalityMatrix, ...
        equalityOffset] = fixedArrivalAffineConstraintMap( ...
        layout, meshTau, corridor, obstacleField, initialState, ...
        goalState, limits, options)
% PURPOSE
%   - Assemble the exact fixed-duration HS-3 constraint map once.
if layout.HasFinalTimeVariable
    error("optimizeAzElDirectCollocation:AffineMapHasTimeVariable", ...
        "A fixed-arrival affine map cannot contain a final-time variable.");
end
duration_s = goalState.time_s - initialState.time_s;
initialEndpoint = endpointState(initialState);
goalEndpoint = endpointState(goalState);
axisResponse = cell(2, 1);
axisDecisionIndex = cell(2, 1);
for axisIndex = 1:2
    stateIndex = [axisIndex, axisIndex + 2, axisIndex + 4];
    axisResponse{axisIndex} = fixedArrivalAxisResponse( ...
        meshTau, duration_s, initialEndpoint(stateIndex), ...
        corridor.PointTau);
    axisDecisionIndex{axisIndex} = ...
        timeOrderedAxisDecisionIndex(layout, axisIndex);
end

equalityMatrix = zeros(6, layout.DecisionCount);
equalityOffset = zeros(6, 1);
for axisIndex = 1:2
    stateIndex = [axisIndex, axisIndex + 2, axisIndex + 4];
    equalityMatrix(stateIndex, axisDecisionIndex{axisIndex}) = ...
        axisResponse{axisIndex}.FinalStateMatrix;
    equalityOffset(stateIndex) = ...
        axisResponse{axisIndex}.FinalStateBase(:) - ...
        goalEndpoint(stateIndex).';
end
[corridorMatrix, corridorOffset] = fixedArrivalCorridorConstraintMap( ...
    layout, meshTau, corridor, obstacleField, initialState.time_s, ...
    duration_s, options.ObstacleConstraintTolerance_deg, ...
    axisResponse, axisDecisionIndex);
[kinematicMatrix, kinematicOffset] = ...
    fixedArrivalKinematicConstraintMap( ...
    layout, limits, options, axisResponse, axisDecisionIndex);
inequalityMatrix = [corridorMatrix; kinematicMatrix];
inequalityOffset = [corridorOffset; kinematicOffset];
end

function response = fixedArrivalAxisResponse( ...
        meshTau, duration_s, initialAxisState, pointTau)
% PURPOSE
%   - Propagate all one-axis jerk basis vectors in one mesh pass.
segmentCount = numel(meshTau) - 1;
controlCount = 2 * segmentCount + 1;
pointTau = pointTau(:);
pointPositionBase = zeros(numel(pointTau), 1);
pointPositionMatrix = zeros(numel(pointTau), controlCount);
stateBernsteinBase = zeros(segmentCount, 6, 3);
stateBernsteinMatrix = zeros(segmentCount, 6, 3, controlCount);
interiorControlMatrix = zeros(segmentCount, controlCount);
startStateBase = reshape(initialAxisState, 1, 3);
startStateMatrix = zeros(3, controlCount);
bernsteinTransform = powerToBernstein(eye(6));
for segmentIndex = 1:segmentCount
    firstControlIndex = 2 * segmentIndex - 1;
    midpointControlIndex = firstControlIndex + 1;
    lastControlIndex = firstControlIndex + 2;
    firstControlRow = zeros(1, controlCount);
    midpointControlRow = zeros(1, controlCount);
    lastControlRow = zeros(1, controlCount);
    firstControlRow(firstControlIndex) = 1;
    midpointControlRow(midpointControlIndex) = 1;
    lastControlRow(lastControlIndex) = 1;
    controlPowerMatrix = [firstControlRow; ...
        -3 * firstControlRow + 4 * midpointControlRow - ...
        lastControlRow; ...
        2 * firstControlRow - 4 * midpointControlRow + ...
        2 * lastControlRow];
    interiorControlMatrix(segmentIndex, :) = ...
        -0.5 * firstControlRow + 2 * midpointControlRow - ...
        0.5 * lastControlRow;

    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    h = segmentDuration_s;
    statePowerBase = zeros(6, 3);
    statePowerBase(1, :) = startStateBase;
    statePowerBase(2, 1) = h * startStateBase(2);
    statePowerBase(3, 1) = h ^ 2 * startStateBase(3) / 2;
    statePowerBase(2, 2) = h * startStateBase(3);
    statePowerMatrix = zeros(6, 3, controlCount);
    statePowerMatrix(1, :, :) = reshape( ...
        startStateMatrix, 1, 3, controlCount);
    statePowerMatrix(2, 1, :) = reshape( ...
        h * startStateMatrix(2, :), 1, 1, controlCount);
    statePowerMatrix(3, 1, :) = reshape( ...
        h ^ 2 * startStateMatrix(3, :) / 2, 1, 1, controlCount);
    statePowerMatrix(4, 1, :) = reshape( ...
        h ^ 3 * controlPowerMatrix(1, :) / 6, ...
        1, 1, controlCount);
    statePowerMatrix(5, 1, :) = reshape( ...
        h ^ 3 * controlPowerMatrix(2, :) / 24, ...
        1, 1, controlCount);
    statePowerMatrix(6, 1, :) = reshape( ...
        h ^ 3 * controlPowerMatrix(3, :) / 60, ...
        1, 1, controlCount);
    statePowerMatrix(2, 2, :) = reshape( ...
        h * startStateMatrix(3, :), 1, 1, controlCount);
    statePowerMatrix(3, 2, :) = reshape( ...
        h ^ 2 * controlPowerMatrix(1, :) / 2, ...
        1, 1, controlCount);
    statePowerMatrix(4, 2, :) = reshape( ...
        h ^ 2 * controlPowerMatrix(2, :) / 6, ...
        1, 1, controlCount);
    statePowerMatrix(5, 2, :) = reshape( ...
        h ^ 2 * controlPowerMatrix(3, :) / 12, ...
        1, 1, controlCount);
    statePowerMatrix(2, 3, :) = reshape( ...
        h * controlPowerMatrix(1, :), 1, 1, controlCount);
    statePowerMatrix(3, 3, :) = reshape( ...
        h * controlPowerMatrix(2, :) / 2, ...
        1, 1, controlCount);
    statePowerMatrix(4, 3, :) = reshape( ...
        h * controlPowerMatrix(3, :) / 3, ...
        1, 1, controlCount);

    stateBernsteinBase(segmentIndex, :, :) = ...
        bernsteinTransform * statePowerBase;
    flatPowerMatrix = reshape( ...
        statePowerMatrix, 6, 3 * controlCount);
    stateBernsteinMatrix(segmentIndex, :, :, :) = reshape( ...
        bernsteinTransform * flatPowerMatrix, ...
        1, 6, 3, controlCount);
    if segmentIndex < segmentCount
        pointIsInSegment = pointTau >= meshTau(segmentIndex) & ...
            pointTau < meshTau(segmentIndex + 1);
    else
        pointIsInSegment = pointTau >= meshTau(segmentIndex) & ...
            pointTau <= meshTau(segmentIndex + 1);
    end
    if segmentIndex == 1
        pointIsInSegment = pointIsInSegment | pointTau < meshTau(1);
    elseif segmentIndex == segmentCount
        pointIsInSegment = pointIsInSegment | pointTau > meshTau(end);
    end
    pointIndex = find(pointIsInSegment);
    if ~isempty(pointIndex)
        segmentWidth = meshTau(segmentIndex + 1) - ...
            meshTau(segmentIndex);
        localTau = (pointTau(pointIndex) - meshTau(segmentIndex)) / ...
            segmentWidth;
        localTau = min(1, max(0, localTau));
        localPower = localTau .^ (0:5);
        pointPositionBase(pointIndex) = ...
            localPower * statePowerBase(:, 1);
        pointPositionMatrix(pointIndex, :) = ...
            localPower * reshape( ...
            statePowerMatrix(:, 1, :), 6, controlCount);
    end
    startStateBase = sum(statePowerBase, 1);
    startStateMatrix = reshape( ...
        sum(statePowerMatrix, 1), 3, controlCount);
end
response = struct( ...
    "PointPositionBase", pointPositionBase, ...
    "PointPositionMatrix", pointPositionMatrix, ...
    "StateBernsteinBase", stateBernsteinBase, ...
    "StateBernsteinMatrix", stateBernsteinMatrix, ...
    "InteriorControlMatrix", interiorControlMatrix, ...
    "FinalStateBase", startStateBase, ...
    "FinalStateMatrix", startStateMatrix);
end

