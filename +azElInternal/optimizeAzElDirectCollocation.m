    certificate.MaximumDynamicsDefect <= ...
    options.CollocationErrorTolerance;
collocationDefectWithinTolerance = maximumCollocationDefect <= ...
    options.NlpConstraintTolerance;
nlpInequalityWithinTolerance = maximumNlpInequalityViolation <= ...
    options.NlpConstraintTolerance;
continuousPolynomialExtremaVerified = velocityWithinLimits && ...
    accelerationWithinLimits && jerkWithinLimits && positionWithinBounds;
checks = [timeIsStrictlyIncreasing, initialStateMatched, ...
    terminalStateMatched, goalTimeSatisfied, collisionFree, ...
    velocityWithinLimits, accelerationWithinLimits, jerkWithinLimits, ...
    positionWithinBounds, curveSubdivisionConverged, ...
    dynamicsDefectWithinTolerance, ...
    collocationDefectWithinTolerance, nlpInequalityWithinTolerance];
names = ["strictTime" "initialState" "terminalState" "goalTime" ...
    "collision" "velocity" "acceleration" "jerk" "workspace" ...
    "curveSubdivision" "dynamicsDefect" "collocationDefect" ...
    "nlpInequality"];
issues = names(~checks);
passed = all(checks);
message = "Direct-collocation trajectory passed independent validation.";
if ~passed
    message = "Independent validation failed: " + ...
        strjoin(issues, ", ") + ".";
end
validation = struct( ...
    "Passed", passed, ...
    "Message", message, ...
    "TimeIsStrictlyIncreasing", timeIsStrictlyIncreasing, ...
    "InitialStateMatched", initialStateMatched, ...
    "TerminalStateMatched", terminalStateMatched, ...
    "GoalTimeSatisfied", goalTimeSatisfied, ...
    "CollisionFree", collisionFree, ...
    "BufferedChordQueryClear", bufferedChordQueryClear, ...
    "CollisionSafetyProven", collisionSafetyProven, ...
    "CollisionValidationScope", ...
    "Adaptive HS-3 chords passed an intersection query and a " + ...
    "conservative timed moving-edge clearance proof. A topology-changing " + ...
    "interval uses the union of both endpoint polygons.", ...
    "CurveSubdivisionConverged", curveSubdivisionConverged, ...
    "MaximumCurveDeviationBound_deg", max( ...
    trajectory.CurveDeviationBoundBySegment_deg), ...
    "VelocityWithinLimits", velocityWithinLimits, ...
    "AccelerationWithinLimits", accelerationWithinLimits, ...
    "JerkWithinLimits", jerkWithinLimits, ...
    "PositionWithinBounds", positionWithinBounds, ...
    "ContinuousPolynomialExtremaVerified", ...
    continuousPolynomialExtremaVerified, ...
    "DynamicsDefectWithinTolerance", dynamicsDefectWithinTolerance, ...
    "CollocationDefectWithinTolerance", ...
    collocationDefectWithinTolerance, ...
    "NlpInequalityWithinTolerance", nlpInequalityWithinTolerance, ...
    "InitialStateError", initialStateError, ...
    "TerminalStateError", terminalStateError, ...
    "MaximumDynamicsDefect", certificate.MaximumDynamicsDefect, ...
    "DynamicsConsistencyScope", ...
    "Internal consistency is certified because states are integrated " + ...
