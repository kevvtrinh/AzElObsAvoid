function [inequalityMatrix, inequalityOffset] = ...
        fixedArrivalCorridorConstraintMap( ...
        layout, meshTau, corridor, obstacleField, initialTime_s, ...
        duration_s, clearance_deg, axisResponse, axisDecisionIndex)
% PURPOSE
%   - Assemble point and static polynomial half-space constraints.
pointCount = numel(corridor.PointTau);
obstacleCount = numel(obstacleField.Obstacles);
pointClearance_deg = clearance_deg * ones(pointCount, 1);
if isfield(corridor, "PointClearance_deg") && ...
        numel(corridor.PointClearance_deg) == pointCount
    pointClearance_deg = max( ...
        pointClearance_deg, corridor.PointClearance_deg(:));
end
isStaticCorridor = isfield(corridor, "GeometryTimeInvariant") && ...
    corridor.GeometryTimeInvariant && ...
    isfield(corridor, "SelectedEdgeStart_deg");
polynomialConstraintRow = staticPolynomialConstraintRows( ...
    meshTau, corridor, isStaticCorridor);
maximumRowCount = nnz(corridor.Active) + ...
    6 * nnz(corridor.Active(polynomialConstraintRow, :));
inequalityMatrix = zeros(maximumRowCount, layout.DecisionCount);
inequalityOffset = -ones(maximumRowCount, 1);
pointTime_s = initialTime_s + duration_s * corridor.PointTau;
constraintIndex = 0;
for pointIndex = 1:pointCount
    for obstacleIndex = 1:obstacleCount
        if ~corridor.Active(pointIndex, obstacleIndex)
            continue;
        end
        constraintIndex = constraintIndex + 1;
        if isStaticCorridor
            edgeStart_deg = reshape(corridor.SelectedEdgeStart_deg( ...
                pointIndex, obstacleIndex, :), 1, 2);
            normal = reshape(corridor.SelectedNormal( ...
                pointIndex, obstacleIndex, :), 1, 2);
        else
            edges_deg = obstacleEdgesAtTime( ...
                obstacleField.Obstacles(obstacleIndex), ...
                pointTime_s(pointIndex));
            if isempty(edges_deg)
                inequalityOffset(constraintIndex) = -1;
                continue;
            end
            selectedEdgeIndex = min(size(edges_deg, 1), max(1, ...
                corridor.EdgeIndex(pointIndex, obstacleIndex)));
            edge_deg = edges_deg(selectedEdgeIndex, :);
            tangent_deg = edge_deg(3:4) - edge_deg(1:2);
            leftNormal = [-tangent_deg(2), tangent_deg(1)];
            normalLength = norm(leftNormal);
            if normalLength <= eps
                inequalityOffset(constraintIndex) = clearance_deg;
                continue;
            end
            normal = corridor.SideSign(pointIndex, obstacleIndex) * ...
                leftNormal / normalLength;
            edgeStart_deg = edge_deg(1:2);
        end
        basePosition_deg = [ ...
            axisResponse{1}.PointPositionBase(pointIndex), ...
            axisResponse{2}.PointPositionBase(pointIndex)];
        inequalityOffset(constraintIndex) = ...
            pointClearance_deg(pointIndex) - dot( ...
            basePosition_deg - edgeStart_deg, normal);
        for axisIndex = 1:2
            inequalityMatrix(constraintIndex, ...
                axisDecisionIndex{axisIndex}) = -normal(axisIndex) * ...
                axisResponse{axisIndex}.PointPositionMatrix( ...
                pointIndex, :);
        end
    end
end
if isStaticCorridor
    tauTolerance = 64 * eps(max(1, max(abs(meshTau))));
    for segmentIndex = 1:numel(meshTau) - 1
        if segmentIndex < numel(meshTau) - 1
            rowIsInSegment = corridor.PointTau >= ...
                meshTau(segmentIndex) - tauTolerance & ...
                corridor.PointTau < ...
                meshTau(segmentIndex + 1) - tauTolerance;
        else
            rowIsInSegment = corridor.PointTau >= ...
                meshTau(segmentIndex) - tauTolerance & ...
                corridor.PointTau <= ...
                meshTau(segmentIndex + 1) + tauTolerance;
        end
        corridorRows = find(polynomialConstraintRow & rowIsInSegment);
        for corridorRow = reshape(corridorRows, 1, [])
            for obstacleIndex = 1:obstacleCount
                if ~corridor.Active(corridorRow, obstacleIndex)
                    continue;
                end
                edgeStart_deg = reshape( ...
                    corridor.SelectedEdgeStart_deg( ...
                    corridorRow, obstacleIndex, :), 1, 2);
                normal = reshape(corridor.SelectedNormal( ...
                    corridorRow, obstacleIndex, :), 1, 2);
                polynomialClearance_deg = max( ...
                    clearance_deg, pointClearance_deg(corridorRow));
                for bernsteinIndex = 1:6
                    constraintIndex = constraintIndex + 1;
                    basePosition_deg = [ ...
                        axisResponse{1}.StateBernsteinBase( ...
                        segmentIndex, bernsteinIndex, 1), ...
                        axisResponse{2}.StateBernsteinBase( ...
                        segmentIndex, bernsteinIndex, 1)];
                    inequalityOffset(constraintIndex) = ...
                        polynomialClearance_deg - dot( ...
                        basePosition_deg - edgeStart_deg, normal);
                    for axisIndex = 1:2
                        responseRow = reshape( ...
                            axisResponse{axisIndex}. ...
                            StateBernsteinMatrix( ...
                            segmentIndex, bernsteinIndex, 1, :), ...
                            1, []);
                        inequalityMatrix(constraintIndex, ...
                            axisDecisionIndex{axisIndex}) = ...
                            -normal(axisIndex) * responseRow;
                    end
                end
            end
        end
    end
end
inequalityMatrix = inequalityMatrix(1:constraintIndex, :);
inequalityOffset = inequalityOffset(1:constraintIndex);
end

function polynomialConstraintRow = staticPolynomialConstraintRows( ...
        meshTau, corridor, isStaticCorridor)
% PURPOSE
%   - Select the midpoint corridor row for each static HS-3 segment.
polynomialConstraintRow = false(numel(corridor.PointTau), 1);
if ~isStaticCorridor
    return;
end
tauTolerance = 64 * eps(max(1, max(abs(meshTau))));
for segmentIndex = 1:numel(meshTau) - 1
    midpointTau = 0.5 * ...
        (meshTau(segmentIndex) + meshTau(segmentIndex + 1));
    [midpointDistance, midpointRow] = min(abs( ...
        corridor.PointTau - midpointTau));
    if midpointDistance <= tauTolerance
        polynomialConstraintRow(midpointRow) = true;
    end
end
end

function [inequalityMatrix, inequalityOffset] = ...
        fixedArrivalKinematicConstraintMap( ...
        layout, limits, options, axisResponse, axisDecisionIndex)
% PURPOSE
%   - Assemble continuous state and jerk Bernstein bounds.
azimuthBounds_deg = [-Inf Inf];
if ~options.AllowAzimuthWrapping
    azimuthBounds_deg = options.AzimuthInterval_deg;
end
stateLower = [azimuthBounds_deg(1), ...
    options.ElevationInterval_deg(1), ...
    -limits.maxVelocity_deg_s, -limits.maxAcceleration_deg_s2];
stateUpper = [azimuthBounds_deg(2), ...
    options.ElevationInterval_deg(2), ...
    limits.maxVelocity_deg_s, limits.maxAcceleration_deg_s2];
finiteStateIndex = find(isfinite(stateLower) & isfinite(stateUpper));
rowsPerSegment = 12 * numel(finiteStateIndex) + 4;
inequalityMatrix = zeros( ...
    layout.SegmentCount * rowsPerSegment, layout.DecisionCount);
inequalityOffset = zeros(layout.SegmentCount * rowsPerSegment, 1);
writeIndex = 0;
for segmentIndex = 1:layout.SegmentCount
    for componentIndex = reshape(finiteStateIndex, 1, [])
        axisIndex = mod(componentIndex - 1, 2) + 1;
        stateIndex = ceil(componentIndex / 2);
        baseValue = reshape(axisResponse{axisIndex}. ...
            StateBernsteinBase(segmentIndex, :, stateIndex), 6, 1);
        responseMatrix = reshape(axisResponse{axisIndex}. ...
            StateBernsteinMatrix(segmentIndex, :, stateIndex, :), ...
            6, []);
        row = writeIndex + (1:6);
        inequalityMatrix(row, axisDecisionIndex{axisIndex}) = ...
            -responseMatrix;
        inequalityOffset(row) = stateLower(componentIndex) - baseValue;
        writeIndex = writeIndex + 6;
    end
    for componentIndex = reshape(finiteStateIndex, 1, [])
        axisIndex = mod(componentIndex - 1, 2) + 1;
        stateIndex = ceil(componentIndex / 2);
        baseValue = reshape(axisResponse{axisIndex}. ...
            StateBernsteinBase(segmentIndex, :, stateIndex), 6, 1);
        responseMatrix = reshape(axisResponse{axisIndex}. ...
            StateBernsteinMatrix(segmentIndex, :, stateIndex, :), ...
            6, []);
        row = writeIndex + (1:6);
        inequalityMatrix(row, axisDecisionIndex{axisIndex}) = ...
            responseMatrix;
        inequalityOffset(row) = baseValue - stateUpper(componentIndex);
        writeIndex = writeIndex + 6;
    end
    for axisIndex = 1:2
        responseRow = axisResponse{axisIndex}. ...
            InteriorControlMatrix(segmentIndex, :);
        writeIndex = writeIndex + 1;
        inequalityMatrix(writeIndex, ...
            axisDecisionIndex{axisIndex}) = -responseRow;
        inequalityOffset(writeIndex) = -limits.maxJerk_deg_s3(axisIndex);
        writeIndex = writeIndex + 1;
        inequalityMatrix(writeIndex, ...
            axisDecisionIndex{axisIndex}) = responseRow;
        inequalityOffset(writeIndex) = -limits.maxJerk_deg_s3(axisIndex);
    end
end
end

