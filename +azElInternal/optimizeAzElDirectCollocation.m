function meshTau = initialMeshForSeed( ...
        seedRoute_deg, minimumSegmentCount, maximumSegmentCount)
% PURPOSE
%   - Put initial knots at important seed vertices and on a uniform base.
route_deg = removeDuplicateRoutePoints(seedRoute_deg);
step_deg = diff(route_deg, 1, 1);
arc_deg = [0; cumsum(vecnorm(step_deg, 2, 2))];
if arc_deg(end) <= eps
    vertexTau = [0; 1];
else
    vertexTau = arc_deg / arc_deg(end);
end
uniformTau = linspace(0, 1, minimumSegmentCount + 1).';
meshTau = unique([uniformTau; vertexTau]);
if numel(meshTau) - 1 <= maximumSegmentCount
    return;
end
% Preserve a deterministic subset when a dense boundary seed exceeds the
% public mesh cap. The endpoints and uniform base always remain present.
availableVertexCount = max(0, maximumSegmentCount + 1 - ...
    numel(uniformTau));
interiorVertexTau = vertexTau(vertexTau > 0 & vertexTau < 1);
if numel(interiorVertexTau) > availableVertexCount
    selectedIndex = unique(round(linspace(1, ...
        numel(interiorVertexTau), availableVertexCount)));
    interiorVertexTau = interiorVertexTau(selectedIndex);
end
meshTau = unique([uniformTau; interiorVertexTau]);
end

function layout = decisionLayout(segmentCount, hasFinalTimeVariable)
% PURPOSE
%   - Store only shared HS-3 jerk ordinates and optional final time.
% Moreno-Martin, Ros, and Celaya (2024) derive the separated HS-3 state
% polynomial from the higher-order input. This linear gimbal model permits
% exact state elimination without changing that polynomial. See citation.md.
nextIndex = 1;
finalTimeIndex = zeros(0, 1);
if hasFinalTimeVariable
    finalTimeIndex = nextIndex;
    nextIndex = nextIndex + 1;
end
knotControlIndex = nextIndex:nextIndex + 2 * (segmentCount + 1) - 1;
nextIndex = knotControlIndex(end) + 1;
midpointControlIndex = nextIndex:nextIndex + 2 * segmentCount - 1;
nextIndex = midpointControlIndex(end) + 1;
layout = struct( ...
    "SegmentCount", segmentCount, ...
    "HasFinalTimeVariable", logical(hasFinalTimeVariable), ...
    "FinalTimeIndex", finalTimeIndex, ...
    "KnotControlIndex", knotControlIndex, ...
    "MidpointControlIndex", midpointControlIndex, ...
    "DecisionCount", nextIndex - 1);
end

