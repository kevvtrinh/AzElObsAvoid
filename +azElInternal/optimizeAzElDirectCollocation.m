function meshTau = initialMeshForSeed( ...
        seedRoute_deg, minimumSegmentCount, maximumSegmentCount)
% PURPOSE
%   - Put initial knots at important seed vertices and on a uniform base.
route_deg = removeDuplicateRoutePoints(seedRoute_deg);
step_deg = diff(route_deg, 1, 1);
arc_deg = [0; cumsum(vecnorm(step_deg, 2, 2))];
if arc_deg(end) <= eps
    vertexTau = [0; 1];
else
    vertexTau = arc_deg / arc_deg(end);
end
uniformTau = linspace(0, 1, minimumSegmentCount + 1).';
meshTau = unique([uniformTau; vertexTau]);
if numel(meshTau) - 1 <= maximumSegmentCount
    return;
end
% Preserve a deterministic subset when a dense boundary seed exceeds the
% public mesh cap. The endpoints and uniform base always remain present.
availableVertexCount = max(0, maximumSegmentCount + 1 - ...
    numel(uniformTau));
interiorVertexTau = vertexTau(vertexTau > 0 & vertexTau < 1);
if numel(interiorVertexTau) > availableVertexCount
    selectedIndex = unique(round(linspace(1, ...
        numel(interiorVertexTau), availableVertexCount)));
    interiorVertexTau = interiorVertexTau(selectedIndex);
end
meshTau = unique([uniformTau; interiorVertexTau]);
end

