function [badSegment, refinementPriority] = refinementMask( ...
        solution, meshTau, certificate, ...
        limits, collisionMask, trajectory, obstacleField, options)
% PURPOSE
%   - Select stressed cells and rank collision cells before other stress.
segmentCount = numel(meshTau) - 1;
dynamicsStress = certificate.SegmentDynamicsDefect / ...
    options.CollocationErrorTolerance;
collocationStress = certificate.SegmentCollocationDefect / ...
    options.NlpConstraintTolerance;
badSegment = dynamicsStress > 1 | collocationStress > 1;
velocityStress = max(certificate.MaximumVelocityBySegment_deg_s ./ ...
    limits.maxVelocity_deg_s, [], 2);
accelerationStress = max( ...
    certificate.MaximumAccelerationBySegment_deg_s2 ./ ...
    limits.maxAcceleration_deg_s2, [], 2);
jerkStress = max(certificate.MaximumJerkBySegment_deg_s3 ./ ...
    limits.maxJerk_deg_s3, [], 2);
limitStress = max([velocityStress, accelerationStress, jerkStress], [], 2);
badSegment = badSegment | limitStress > 0.98;

[~, ~, sampleClearance_deg] = sampledMinimumObstacleClearance( ...
    obstacleField, trajectory.time_s, trajectory.position_deg);
minimumClearanceBySegment_deg = inf(segmentCount, 1);
for sampleIndex = 1:numel(sampleClearance_deg)
    segmentIndex = trajectory.segmentIndex(sampleIndex);
    if segmentIndex >= 1 && segmentIndex <= segmentCount
        minimumClearanceBySegment_deg(segmentIndex) = min( ...
            minimumClearanceBySegment_deg(segmentIndex), ...
            sampleClearance_deg(sampleIndex));
    end
end
clearanceRefinementThreshold_deg = max( ...
    10 * options.ObstacleConstraintTolerance_deg, ...
    0.5 * options.VisibilitySampleStep_deg);
clearanceStress = clearanceRefinementThreshold_deg ./ ...
    max(minimumClearanceBySegment_deg, eps);
badSegment = badSegment | minimumClearanceBySegment_deg <= ...
    clearanceRefinementThreshold_deg;

collisionStress = zeros(segmentCount, 1);
if any(collisionMask)
    collisionSegment = unique(trajectory.segmentIndex(collisionMask));
    collisionSegment = collisionSegment( ...
        collisionSegment >= 1 & collisionSegment <= segmentCount);
    badSegment(collisionSegment) = true;
    collisionStress(collisionSegment) = 1;
end
velocity = solution.KnotState(:, 3:4);
curvatureStress = zeros(segmentCount, 1);
for segmentIndex = 1:segmentCount
    firstSpeed = norm(velocity(segmentIndex, :));
    lastSpeed = norm(velocity(segmentIndex + 1, :));
    if firstSpeed <= 1e-8 || lastSpeed <= 1e-8
        continue;
    end
    directionCosine = dot(velocity(segmentIndex, :), ...
        velocity(segmentIndex + 1, :)) / (firstSpeed * lastSpeed);
    if directionCosine < cosd(20)
        badSegment(segmentIndex) = true;
        curvatureStress(segmentIndex) = 1;
    end
end
limitOrCurvatureStress = max( ...
    [limitStress, curvatureStress, clearanceStress], [], 2);
refinementPriority = [collisionStress, limitOrCurvatureStress, ...
    collocationStress, dynamicsStress];
end

function refined = resampleSolution(solution, oldMeshTau, newMeshTau)
% PURPOSE
%   - Warm-start an h-refined mesh from corrected segment polynomials.
newMidpointTau = 0.5 * (newMeshTau(1:end - 1) + newMeshTau(2:end));
[newKnotState, newKnotControl] = sampleSolutionAtTau( ...
    solution, oldMeshTau, newMeshTau);
[newMidpointState, newMidpointControl] = sampleSolutionAtTau( ...
    solution, oldMeshTau, newMidpointTau);
refined = struct( ...
    "InitialTime_s", solution.InitialTime_s, ...
    "FinalTime_s", solution.FinalTime_s, ...
    "KnotState", newKnotState, ...
    "MidpointState", newMidpointState, ...
    "KnotControl", newKnotControl, ...
    "MidpointControl", newMidpointControl);
end

function [state, control] = sampleSolutionAtTau( ...
        solution, meshTau, queryTau)
% PURPOSE
%   - Evaluate a collocation solution at arbitrary normalized times.
queryTau = queryTau(:);
state = zeros(numel(queryTau), 6);
control = zeros(numel(queryTau), 2);
duration_s = solution.FinalTime_s - solution.InitialTime_s;
segmentCount = numel(meshTau) - 1;
for segmentIndex = 1:segmentCount
    if segmentIndex < segmentCount
        queryIsInSegment = queryTau >= meshTau(segmentIndex) & ...
            queryTau < meshTau(segmentIndex + 1);
    else
        queryIsInSegment = queryTau >= meshTau(segmentIndex) & ...
            queryTau <= meshTau(segmentIndex + 1);
    end
    if segmentIndex == 1
        queryIsInSegment = queryIsInSegment | ...
            queryTau < meshTau(1);
    elseif segmentIndex == segmentCount
        queryIsInSegment = queryIsInSegment | ...
            queryTau > meshTau(end);
    end
    queryIndex = find(queryIsInSegment);
    if isempty(queryIndex)
        continue;
    end
    segmentWidth = meshTau(segmentIndex + 1) - meshTau(segmentIndex);
    localTau = (queryTau(queryIndex) - meshTau(segmentIndex)) / ...
        segmentWidth;
    localTau = min(1, max(0, localTau));
    segmentDuration_s = duration_s * segmentWidth;
    [state(queryIndex, :), control(queryIndex, :)] = ...
        interpolateSegment(solution, segmentIndex, ...
        segmentDuration_s, localTau);
end
end

function corridor = applyCollisionRepairClearance( ...
        corridor, meshTau, repairTau, repairBuffer_deg, ...
        baseClearance_deg)
% PURPOSE
%   - Require the complete curve tube to remain outside repaired edges.
pointClearance_deg = baseClearance_deg * ...
    ones(numel(corridor.PointTau), 1);
tauTolerance = 64 * eps(max(1, max(abs(meshTau))));
for repairIndex = 1:numel(repairTau)
    segmentIndex = find(meshTau <= ...
        repairTau(repairIndex) + tauTolerance, 1, "last");
    segmentIndex = min(numel(meshTau) - 1, max(1, segmentIndex));
    pointIsInSegment = corridor.PointTau >= ...
        meshTau(segmentIndex) - tauTolerance & ...
        corridor.PointTau <= ...
        meshTau(segmentIndex + 1) + tauTolerance;
    requiredClearance_deg = baseClearance_deg + ...
        repairBuffer_deg(repairIndex);
    pointClearance_deg(pointIsInSegment) = max( ...
        pointClearance_deg(pointIsInSegment), requiredClearance_deg);
end
corridor.PointClearance_deg = pointClearance_deg;
end

function [mergedTau, mergedBuffer_deg] = ...
        mergeCollisionRepairConstraints( ...
        existingTau, existingBuffer_deg, newTau, newBuffer_deg)
% PURPOSE
%   - Accumulate repair times and keep the largest tube bound at duplicates.
allTau = [existingTau(:); newTau(:)];
allBuffer_deg = [existingBuffer_deg(:); newBuffer_deg(:)];
mergedTau = zeros(0, 1);
mergedBuffer_deg = zeros(0, 1);
for repairIndex = 1:numel(allTau)
    duplicateIndex = find(abs(mergedTau - allTau(repairIndex)) <= ...
        64 * eps(max(1, abs(allTau(repairIndex)))), 1);
    if isempty(duplicateIndex)
        mergedTau(end + 1, 1) = allTau(repairIndex); %#ok<AGROW>
        mergedBuffer_deg(end + 1, 1) = ...
            allBuffer_deg(repairIndex); %#ok<AGROW>
    else
        mergedBuffer_deg(duplicateIndex) = max( ...
            mergedBuffer_deg(duplicateIndex), ...
            allBuffer_deg(repairIndex));
    end
end
[mergedTau, order] = sort(mergedTau);
mergedBuffer_deg = mergedBuffer_deg(order);
end

function [repairTau, repairBuffer_deg] = collisionConstraintTau( ...
        trajectory, sampleOccupied, segmentOccupied, ...
        initialTime_s, finalTime_s, minimumRepairBuffer_deg)
% PURPOSE
%   - Retain one occupied sample and recovery tube per affected HS-3 segment.
occupiedIndex = find(sampleOccupied(:));
repairTau = zeros(0, 1);
repairBuffer_deg = zeros(0, 1);
if isempty(occupiedIndex) || finalTime_s <= initialTime_s
    return;
end
occupiedSegmentIndex = trajectory.segmentIndex(occupiedIndex);
collidingSegmentIndex = unique(occupiedSegmentIndex, "stable");
repairTime_s = zeros(numel(collidingSegmentIndex), 1);
for collisionIndex = 1:numel(collidingSegmentIndex)
    inSegment = occupiedIndex(occupiedSegmentIndex == ...
        collidingSegmentIndex(collisionIndex));
    representativeIndex = inSegment(ceil(numel(inSegment) / 2));
    representativeTime_s = trajectory.time_s(representativeIndex);
    inboundSegmentIndex = representativeIndex - 1;
    if inboundSegmentIndex >= 1 && ...
            inboundSegmentIndex <= numel(segmentOccupied) && ...
            segmentOccupied(inboundSegmentIndex)
        representativeTime_s = 0.5 * ( ...
            trajectory.time_s(representativeIndex - 1) + ...
            trajectory.time_s(representativeIndex));
    end
    repairTime_s(collisionIndex) = representativeTime_s;
end
repairTau = (repairTime_s - initialTime_s) / ...
    (finalTime_s - initialTime_s);
repairTau = min(1, max(0, repairTau));
repairBuffer_deg = zeros(numel(collidingSegmentIndex), 1);
hasCurveBounds = isfield(trajectory, ...
    "CurveDeviationBoundBySegment_deg") && ...
    ~isempty(trajectory.CurveDeviationBoundBySegment_deg);
if hasCurveBounds
    boundedSegmentIndex = min( ...
        numel(trajectory.CurveDeviationBoundBySegment_deg), ...
        max(1, collidingSegmentIndex));
    repairBuffer_deg = ...
        trajectory.CurveDeviationBoundBySegment_deg( ...
        boundedSegmentIndex);
end
repairBuffer_deg = max(repairBuffer_deg, minimumRepairBuffer_deg);
end

function validation = validateSolution(solution, trajectory, certificate, ...
        collisionAssessment, maximumCollocationDefect, ...
        maximumNlpInequalityViolation, initialState, goalState, ~, options)
% PURPOSE
%   - Independently gate planner success on all continuous requirements.
tolerance = options.KinematicValidationTolerance;
bufferedChordQueryClear = ...
    collisionAssessment.BufferedChordQueryClear;
collisionSafetyProven = collisionAssessment.CollisionSafetyProven;
collisionFree = bufferedChordQueryClear && collisionSafetyProven;
timeIsStrictlyIncreasing = all(isfinite(trajectory.time_s)) && ...
    all(diff(trajectory.time_s) > 0);
initialTrajectoryState = [trajectory.position_deg(1, :), ...
    trajectory.velocity_deg_s(1, :), ...
    trajectory.acceleration_deg_s2(1, :)];
terminalTrajectoryState = [trajectory.position_deg(end, :), ...
    trajectory.velocity_deg_s(end, :), ...
    trajectory.acceleration_deg_s2(end, :)];
initialStateError = abs(initialTrajectoryState - endpointState(initialState));
terminalStateError = abs(terminalTrajectoryState - endpointState(goalState));
initialStateMatched = all(initialStateError <= tolerance);
terminalStateMatched = all(terminalStateError <= tolerance);
goalTimeSatisfied = solution.FinalTime_s <= ...
    goalState.time_s + options.NlpConstraintTolerance;
if options.GoalTimeMode == "fixedarrival"
    goalTimeSatisfied = abs(solution.FinalTime_s - goalState.time_s) <= ...
        options.NlpConstraintTolerance;
end
velocityWithinLimits = all( ...
    certificate.MaximumVelocityViolation_deg_s <= tolerance);
accelerationWithinLimits = all( ...
    certificate.MaximumAccelerationViolation_deg_s2 <= tolerance);
jerkWithinLimits = all( ...
    certificate.MaximumJerkViolation_deg_s3 <= tolerance);
positionWithinBounds = all( ...
    certificate.MaximumPositionViolation_deg <= tolerance);
curveSubdivisionConverged = ...
    ~isempty(trajectory.CurveSubdivisionConvergedBySegment) && ...
    all(trajectory.CurveSubdivisionConvergedBySegment);
