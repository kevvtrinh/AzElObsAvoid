function corridor = buildOptimizationCorridor( ...
        solution, meshTau, obstacleField, initialTime_s, ...
        referencePosition_deg, requestedPointTau)
% PURPOSE
%   - Freeze one nearby edge and free-side association per obstacle/node.
if nargin >= 6 && ~isempty(requestedPointTau)
    pointTau = requestedPointTau(:);
    associationTau = pointTau;
else
    [pointTau, associationTau] = segmentCorridorTau(meshTau);
end
if nargin >= 5 && ~isempty(referencePosition_deg)
    pointPosition_deg = referencePosition_deg;
else
    [pointState, ~] = sampleSolutionAtTau( ...
        solution, meshTau, associationTau);
    pointPosition_deg = pointState(:, 1:2);
end
if size(pointPosition_deg, 1) ~= numel(pointTau)
    error("optimizeAzElDirectCollocation:CorridorPointSizeMismatch", ...
        "referencePosition_deg must have one row for each corridor time.");
end
pointTime_s = initialTime_s + ...
    (solution.FinalTime_s - initialTime_s) * pointTau;
pointCount = numel(pointTau);
obstacleCount = numel(obstacleField.Obstacles);
orderedPoint = sortrows([pointTau, pointPosition_deg], 1);
orderedStep_deg = vecnorm(diff(orderedPoint(:, 2:3), 1, 1), 2, 2);
orderedStep_deg = orderedStep_deg(orderedStep_deg > 1e-10);
if isempty(orderedStep_deg)
    corridorActivationDistance_deg = Inf;
else
    % One local sample spacing retains the route boundary without
    % intersecting unrelated half-spaces from distant route sections.
    corridorActivationDistance_deg = 1.25 * median(orderedStep_deg);
end
edgeIndex = zeros(pointCount, obstacleCount);
sideSign = ones(pointCount, obstacleCount);
active = false(pointCount, obstacleCount);
selectedEdgeStart_deg = zeros(pointCount, obstacleCount, 2);
selectedNormal = zeros(pointCount, obstacleCount, 2);
for pointIndex = 1:pointCount
    queryPoint_deg = pointPosition_deg(pointIndex, :);
    for obstacleIndex = 1:obstacleCount
        edges_deg = obstacleEdgesAtTime( ...
            obstacleField.Obstacles(obstacleIndex), ...
            pointTime_s(pointIndex));
        if isempty(edges_deg)
            continue;
        end
        [nearestEdgeIndex, nearestPoint_deg] = ...
            nearestEdge(queryPoint_deg, edges_deg);
        edge_deg = edges_deg(nearestEdgeIndex, :);
        tangent_deg = edge_deg(3:4) - edge_deg(1:2);
        leftNormal = [-tangent_deg(2), tangent_deg(1)];
        normalLength = norm(leftNormal);
        if normalLength <= eps
            continue;
        end
        leftNormal = leftNormal / normalLength;
        signedSide = dot(queryPoint_deg - nearestPoint_deg, leftNormal);
        if abs(signedSide) <= 1e-12
            signedSide = dot(queryPoint_deg - edge_deg(1:2), leftNormal);
        end
        selectedSideSign = sign(signedSide);
        if selectedSideSign == 0
            selectedSideSign = 1;
        end
        pointIsInside = pointInsideEdges(queryPoint_deg, edges_deg);
        if pointIsInside
            selectedSideSign = -selectedSideSign;
        end
        edgeIndex(pointIndex, obstacleIndex) = nearestEdgeIndex;
        sideSign(pointIndex, obstacleIndex) = selectedSideSign;
        selectedEdgeStart_deg(pointIndex, obstacleIndex, :) = ...
            edge_deg(1:2);
        selectedNormal(pointIndex, obstacleIndex, :) = ...
            selectedSideSign * leftNormal / normalLength;
        pointDistance_deg = norm(queryPoint_deg - nearestPoint_deg);
        active(pointIndex, obstacleIndex) = pointIsInside || ...
            pointDistance_deg <= corridorActivationDistance_deg;
    end
end
corridor = struct( ...
    "EdgeIndex", edgeIndex, ...
    "SideSign", sideSign, ...
    "Active", active, ...
    "PointTau", pointTau, ...
    "PointClearance_deg", zeros(pointCount, 1), ...
    "SelectedEdgeStart_deg", selectedEdgeStart_deg, ...
    "SelectedNormal", selectedNormal, ...
    "ActivationDistance_deg", corridorActivationDistance_deg);
end

function inequality = corridorConstraints(solution, meshTau, corridor, ...
        obstacleField, initialTime_s, clearance_deg)
% PURPOSE
%   - Evaluate differentiable selected-edge half-space constraints.
[pointState, ~] = sampleSolutionAtTau( ...
    solution, meshTau, corridor.PointTau);
pointPosition_deg = pointState(:, 1:2);
pointTime_s = initialTime_s + ...
    (solution.FinalTime_s - initialTime_s) * corridor.PointTau;
activeCount = nnz(corridor.Active);
inequality = -ones(activeCount, 1);
pointClearance_deg = clearance_deg * ...
    ones(numel(corridor.PointTau), 1);
if isfield(corridor, "PointClearance_deg") && ...
        numel(corridor.PointClearance_deg) == numel(corridor.PointTau)
    pointClearance_deg = max( ...
        pointClearance_deg, corridor.PointClearance_deg(:));
end
constraintIndex = 0;
for pointIndex = 1:numel(corridor.PointTau)
    for obstacleIndex = 1:numel(obstacleField.Obstacles)
        if ~corridor.Active(pointIndex, obstacleIndex)
            continue;
        end
        constraintIndex = constraintIndex + 1;
        useSelectedStaticEdge = isfield( ...
            corridor, "GeometryTimeInvariant") && ...
            corridor.GeometryTimeInvariant && ...
            isfield(corridor, "SelectedEdgeStart_deg");
        if useSelectedStaticEdge
            edgeStart_deg = reshape(corridor.SelectedEdgeStart_deg( ...
                pointIndex, obstacleIndex, :), 1, 2);
            normal = reshape(corridor.SelectedNormal( ...
                pointIndex, obstacleIndex, :), 1, 2);
        else
            edges_deg = obstacleEdgesAtTime( ...
                obstacleField.Obstacles(obstacleIndex), ...
                pointTime_s(pointIndex));
            if isempty(edges_deg)
                inequality(constraintIndex) = -1;
                continue;
            end
            selectedEdgeIndex = min(size(edges_deg, 1), max(1, ...
                corridor.EdgeIndex(pointIndex, obstacleIndex)));
            edge_deg = edges_deg(selectedEdgeIndex, :);
            tangent_deg = edge_deg(3:4) - edge_deg(1:2);
            leftNormal = [-tangent_deg(2), tangent_deg(1)];
            normalLength = norm(leftNormal);
            if normalLength <= eps
                inequality(constraintIndex) = clearance_deg;
                continue;
            end
            normal = corridor.SideSign(pointIndex, obstacleIndex) * ...
                leftNormal / normalLength;
            edgeStart_deg = edge_deg(1:2);
        end
        separation_deg = dot( ...
            pointPosition_deg(pointIndex, :) - edgeStart_deg, normal);
        inequality(constraintIndex) = ...
            pointClearance_deg(pointIndex) - separation_deg;
    end
end
inequality = [inequality; staticSegmentCorridorConstraints( ...
    solution, meshTau, corridor, obstacleField, initialTime_s, ...
    clearance_deg)];
end

function inequality = staticSegmentCorridorConstraints( ...
        solution, meshTau, corridor, obstacleField, ~, ...
        clearance_deg)
% PURPOSE
%   - Keep every static HS-3 segment inside its visibility half-space.
segmentCount = numel(meshTau) - 1;
obstacleCount = numel(obstacleField.Obstacles);
isStaticCorridor = isfield(corridor, "GeometryTimeInvariant") && ...
    corridor.GeometryTimeInvariant && ...
    isfield(corridor, "SelectedEdgeStart_deg");
if ~isStaticCorridor || obstacleCount == 0
    inequality = zeros(0, 1);
    return;
end
tauTolerance = 64 * eps(max(1, max(abs(meshTau))));
polynomialConstraintRow = false(numel(corridor.PointTau), 1);
for segmentIndex = 1:segmentCount
    midpointTau = 0.5 * ...
        (meshTau(segmentIndex) + meshTau(segmentIndex + 1));
    [midpointDistance, midpointRow] = min(abs( ...
        corridor.PointTau - midpointTau));
    if midpointDistance <= tauTolerance
        polynomialConstraintRow(midpointRow) = true;
    end
end
inequality = zeros(6 * nnz(polynomialConstraintRow) * ...
    obstacleCount, 1);
constraintIndex = 0;
duration_s = solution.FinalTime_s - solution.InitialTime_s;
for segmentIndex = 1:segmentCount
    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    statePower = segmentStatePowerCoefficients( ...
        solution.KnotState(segmentIndex, :), ...
        solution.KnotControl(segmentIndex, :), ...
        solution.MidpointControl(segmentIndex, :), ...
        solution.KnotControl(segmentIndex + 1, :), ...
        segmentDuration_s);
    positionBernstein_deg = powerToBernstein(statePower(:, 1:2));
    if segmentIndex < segmentCount
        rowIsInSegment = corridor.PointTau >= ...
            meshTau(segmentIndex) - tauTolerance & ...
            corridor.PointTau < ...
            meshTau(segmentIndex + 1) - tauTolerance;
    else
        rowIsInSegment = corridor.PointTau >= ...
            meshTau(segmentIndex) - tauTolerance & ...
            corridor.PointTau <= ...
            meshTau(segmentIndex + 1) + tauTolerance;
    end
    constraintRows = find(polynomialConstraintRow & rowIsInSegment);
    for corridorRow = reshape(constraintRows, 1, [])
        for obstacleIndex = 1:obstacleCount
            if ~corridor.Active(corridorRow, obstacleIndex)
                continue;
            end
            edgeStart_deg = reshape( ...
                corridor.SelectedEdgeStart_deg( ...
                corridorRow, obstacleIndex, :), 1, 2);
            normal = reshape(corridor.SelectedNormal( ...
                corridorRow, obstacleIndex, :), 1, 2);
            separation_deg = ...
                (positionBernstein_deg - edgeStart_deg) * normal.';
            polynomialClearance_deg = clearance_deg;
            if isfield(corridor, "PointClearance_deg") && ...
                    numel(corridor.PointClearance_deg) >= corridorRow
                polynomialClearance_deg = max( ...
                    polynomialClearance_deg, ...
                    corridor.PointClearance_deg(corridorRow));
            end
            row = constraintIndex + (1:6);
            inequality(row) = ...
                polynomialClearance_deg - separation_deg;
            constraintIndex = constraintIndex + 6;
        end
    end
end
inequality = inequality(1:constraintIndex);
end

function inequality = continuousKinematicConstraints( ...
        solution, meshTau, limits, options)
% PURPOSE
%   - Bound HS-3 state and quadratic jerk everywhere using their
%     Bernstein control hulls rather than relying on samples alone.
segmentCount = numel(meshTau) - 1;
inequality = zeros(segmentCount * 76, 1);
writeIndex = 0;
duration_s = solution.FinalTime_s - solution.InitialTime_s;
azimuthBounds_deg = [-Inf Inf];
if ~options.AllowAzimuthWrapping
    azimuthBounds_deg = options.AzimuthInterval_deg;
end
stateLower = [azimuthBounds_deg(1), ...
    options.ElevationInterval_deg(1), ...
    -limits.maxVelocity_deg_s, -limits.maxAcceleration_deg_s2];
stateUpper = [azimuthBounds_deg(2), ...
    options.ElevationInterval_deg(2), ...
    limits.maxVelocity_deg_s, limits.maxAcceleration_deg_s2];
for segmentIndex = 1:segmentCount
    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    firstControl = solution.KnotControl(segmentIndex, :);
    midpointControl = solution.MidpointControl(segmentIndex, :);
    lastControl = solution.KnotControl(segmentIndex + 1, :);
    statePower = segmentStatePowerCoefficients( ...
        solution.KnotState(segmentIndex, :), firstControl, ...
        midpointControl, lastControl, segmentDuration_s);
    stateBernstein = powerToBernstein(statePower);
    finiteStateBound = isfinite(stateLower) & isfinite(stateUpper);
    lowerViolation = stateLower(finiteStateBound) - ...
        stateBernstein(:, finiteStateBound);
    upperViolation = stateBernstein(:, finiteStateBound) - ...
        stateUpper(finiteStateBound);
    stateRows = [lowerViolation(:); upperViolation(:)];
    stateRowCount = numel(stateRows);
    inequality(writeIndex + (1:stateRowCount)) = stateRows;
    writeIndex = writeIndex + stateRowCount;

    linearControl = -3 * firstControl + ...
        4 * midpointControl - lastControl;
    interiorControlBernstein = firstControl + linearControl / 2;
    controlRows = [ ...
        -limits.maxJerk_deg_s3 - interiorControlBernstein; ...
        interiorControlBernstein - limits.maxJerk_deg_s3];
    inequality(writeIndex + (1:numel(controlRows))) = controlRows(:);
    writeIndex = writeIndex + numel(controlRows);
end
inequality = inequality(1:writeIndex);
end

function edges_deg = obstacleEdgesAtTime(packedObstacle, queryTime_s)
% PURPOSE
%   - Match public collision geometry interpolation for selected edges.
obstacleTime_s = double(packedObstacle.TimeSeconds(:));
if isempty(obstacleTime_s)
    edges_deg = zeros(0, 4);
    return;
end
upperSliceIndex = find(obstacleTime_s >= queryTime_s, 1, "first");
if isempty(upperSliceIndex)
    upperSliceIndex = numel(obstacleTime_s);
end
lowerSliceIndex = find(obstacleTime_s <= queryTime_s, 1, "last");
if isempty(lowerSliceIndex)
    lowerSliceIndex = 1;
end
if lowerSliceIndex == upperSliceIndex
    edges_deg = packedSliceEdges(packedObstacle, lowerSliceIndex);
    return;
end
fraction = (queryTime_s - obstacleTime_s(lowerSliceIndex)) / ...
    (obstacleTime_s(upperSliceIndex) - obstacleTime_s(lowerSliceIndex));
fraction = min(1, max(0, fraction));
firstEdges_deg = packedSliceEdges(packedObstacle, lowerSliceIndex);
lastEdges_deg = packedSliceEdges(packedObstacle, upperSliceIndex);
topologyMatches = size(firstEdges_deg, 1) == size(lastEdges_deg, 1);
if isfield(packedObstacle, "TopologyMatchesNext") && ...
        numel(packedObstacle.TopologyMatchesNext) >= lowerSliceIndex
    topologyMatches = topologyMatches && ...
        packedObstacle.TopologyMatchesNext(lowerSliceIndex);
end
if topologyMatches
    edges_deg = (1 - fraction) * firstEdges_deg + fraction * lastEdges_deg;
elseif fraction < 0.5
    edges_deg = firstEdges_deg;
else
    edges_deg = lastEdges_deg;
end
end

function edges_deg = packedSliceEdges(packedObstacle, sliceIndex)
% PURPOSE
%   - Recover one packed obstacle slice as explicit edge rows.
firstEdgeIndex = double(packedObstacle.EdgeOffsets(sliceIndex));
lastEdgeIndex = double(packedObstacle.EdgeOffsets(sliceIndex + 1)) - 1;
if lastEdgeIndex < firstEdgeIndex
    edges_deg = zeros(0, 4);
    return;
end
edgeRows = firstEdgeIndex:lastEdgeIndex;
edges_deg = [ ...
    double(packedObstacle.EdgeStartAzimuthDeg(edgeRows)), ...
    double(packedObstacle.EdgeStartElevationDeg(edgeRows)), ...
    double(packedObstacle.EdgeEndAzimuthDeg(edgeRows)), ...
    double(packedObstacle.EdgeEndElevationDeg(edgeRows))];
end

function [edgeIndex, nearestPoint_deg] = nearestEdge(point_deg, edges_deg)
% PURPOSE
%   - Select the deterministic closest edge and its projection.
edgeStart_deg = edges_deg(:, 1:2);
edgeDelta_deg = edges_deg(:, 3:4) - edgeStart_deg;
edgeLengthSquared_deg2 = sum(edgeDelta_deg .^ 2, 2);
projectionFraction = sum((point_deg - edgeStart_deg) .* ...
    edgeDelta_deg, 2) ./ max(edgeLengthSquared_deg2, eps);
projectionFraction = min(1, max(0, projectionFraction));
projection_deg = edgeStart_deg + projectionFraction .* edgeDelta_deg;
distanceSquared_deg2 = sum((projection_deg - point_deg) .^ 2, 2);
[~, edgeIndex] = min(distanceSquared_deg2);
nearestPoint_deg = projection_deg(edgeIndex, :);
end

function inside = pointInsideEdges(point_deg, edges_deg)
% PURPOSE
%   - Classify one point for pre-solve separator orientation only.
y0 = edges_deg(:, 2);
y1 = edges_deg(:, 4);
crossesElevation = (y0 > point_deg(2)) ~= (y1 > point_deg(2));
crossingAzimuth_deg = edges_deg(:, 1) + ...
    (point_deg(2) - y0) .* (edges_deg(:, 3) - edges_deg(:, 1)) ./ ...
    max(abs(y1 - y0), eps) .* sign(y1 - y0 + eps);
inside = mod(nnz(crossesElevation & ...
    crossingAzimuth_deg > point_deg(1)), 2) == 1;
end

function trajectory = reconstructTrajectory( ...
        solution, meshTau, initialTime_s, sampleTime_s, ...
        curveTolerance_deg)
% PURPOSE
%   - Reconstruct the HS-3 curve with time and curvature subdivision.
segmentCount = numel(meshTau) - 1;
timeBuffer = cell(segmentCount, 1);
stateBuffer = cell(segmentCount, 1);
controlBuffer = cell(segmentCount, 1);
segmentIndexBuffer = cell(segmentCount, 1);
curveDeviationBoundBySegment_deg = zeros(segmentCount, 1);
curveSubdivisionConvergedBySegment = false(segmentCount, 1);
duration_s = solution.FinalTime_s - initialTime_s;
for segmentIndex = 1:segmentCount
    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    sampleCount = max(2, ceil(segmentDuration_s / sampleTime_s) + 1);
    localTau = unique([linspace(0, 1, sampleCount).'; 0.5]);
    [localTau, curveDeviationBoundBySegment_deg(segmentIndex), ...
        curveSubdivisionConvergedBySegment(segmentIndex)] = ...
        refineCurveSampleTau(solution, segmentIndex, ...
        segmentDuration_s, localTau, curveTolerance_deg);
    if segmentIndex < segmentCount
        localTau(end) = [];
    end
    [state, control] = interpolateSegment( ...
        solution, segmentIndex, segmentDuration_s, localTau);
    normalizedTime = meshTau(segmentIndex) + localTau * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    timeBuffer{segmentIndex} = initialTime_s + duration_s * normalizedTime;
    stateBuffer{segmentIndex} = state;
    controlBuffer{segmentIndex} = control;
    segmentIndexBuffer{segmentIndex} = repmat( ...
        segmentIndex, numel(localTau), 1);
end
state = vertcat(stateBuffer{:});
trajectory = struct( ...
    "time_s", vertcat(timeBuffer{:}), ...
    "position_deg", state(:, 1:2), ...
    "velocity_deg_s", state(:, 3:4), ...
    "acceleration_deg_s2", state(:, 5:6), ...
    "jerk_deg_s3", vertcat(controlBuffer{:}), ...
    "segmentIndex", vertcat(segmentIndexBuffer{:}), ...
    "CurveDeviationBoundBySegment_deg", ...
    curveDeviationBoundBySegment_deg, ...
    "CurveSubdivisionConvergedBySegment", ...
    curveSubdivisionConvergedBySegment);
end

function [localTau, maximumDeviationBound_deg, converged] = ...
        refineCurveSampleTau(solution, segmentIndex, ...
        segmentDuration_s, localTau, curveTolerance_deg)
% PURPOSE
%   - Bound each quintic arc's deviation from its checked linear chords.
statePower = segmentStatePowerCoefficients( ...
    solution.KnotState(segmentIndex, :), ...
    solution.KnotControl(segmentIndex, :), ...
    solution.MidpointControl(segmentIndex, :), ...
    solution.KnotControl(segmentIndex + 1, :), segmentDuration_s);
for refinementIndex = 1:12
    intervalStart = localTau(1:end - 1);
    intervalEnd = localTau(2:end);
    splitInterval = false(size(intervalStart));
    for intervalIndex = 1:numel(intervalStart)
        deviation_deg = maximumChordDeviation( ...
            statePower(:, 1:2), intervalStart(intervalIndex), ...
            intervalEnd(intervalIndex));
        splitInterval(intervalIndex) = ...
            deviation_deg > curveTolerance_deg;
    end
    if ~any(splitInterval)
        break;
    end
    midpoint = 0.5 * (intervalStart(splitInterval) + ...
        intervalEnd(splitInterval));
    localTau = unique([localTau; midpoint]);
end
intervalStart = localTau(1:end - 1);
intervalEnd = localTau(2:end);
deviationBound_deg = zeros(size(intervalStart));
for intervalIndex = 1:numel(intervalStart)
    deviationBound_deg(intervalIndex) = maximumChordDeviation( ...
        statePower(:, 1:2), intervalStart(intervalIndex), ...
        intervalEnd(intervalIndex));
end
maximumDeviationBound_deg = max(deviationBound_deg);
converged = maximumDeviationBound_deg <= curveTolerance_deg;
end

function deviationBound = maximumChordDeviation( ...
        positionPower, intervalStart, intervalEnd)
% PURPOSE
%   - Bound quintic-to-chord distance through exact component extrema.
endpointPosition = evaluatePowerPolynomial(positionPower, ...
    [intervalStart; intervalEnd]);
chordSlope = (endpointPosition(2, :) - endpointPosition(1, :)) / ...
    (intervalEnd - intervalStart);
chordIntercept = endpointPosition(1, :) - intervalStart * chordSlope;
deviationPower = positionPower;
deviationPower(1, :) = deviationPower(1, :) - chordIntercept;
deviationPower(2, :) = deviationPower(2, :) - chordSlope;
componentBound = polynomialMaximumAbsoluteOnInterval( ...
    deviationPower, intervalStart, intervalEnd);
deviationBound = norm(componentBound);
end

function maximumAbsolute = polynomialMaximumAbsoluteOnInterval( ...
        powerCoefficient, intervalStart, intervalEnd)
% PURPOSE
%   - Bound component magnitudes on a subinterval with a Bernstein hull.
restrictedPower = restrictPowerPolynomial( ...
    powerCoefficient, intervalStart, intervalEnd);
restrictedBernstein = powerToBernstein(restrictedPower);
maximumAbsolute = max(abs(restrictedBernstein), [], 1);
end

function restrictedPower = restrictPowerPolynomial( ...
        powerCoefficient, intervalStart, intervalEnd)
% PURPOSE
%   - Express p(a + (b-a)s) in ascending powers of s on [0,1].
degree = size(powerCoefficient, 1) - 1;
intervalWidth = intervalEnd - intervalStart;
persistent restrictionPatternByDegree
if isempty(restrictionPatternByDegree)
    restrictionPatternByDegree = cell(0, 1);
end
cacheIndex = degree + 1;
if numel(restrictionPatternByDegree) < cacheIndex || ...
        isempty(restrictionPatternByDegree{cacheIndex})
    [sourcePower, targetPower] = meshgrid(0:degree, 0:degree);
    validEntry = sourcePower >= targetPower;
    startExponent = sourcePower - targetPower;
    startExponent(~validEntry) = 0;
    binomialCoefficient = zeros(cacheIndex);
    for targetIndex = 0:degree
        for sourceIndex = targetIndex:degree
            binomialCoefficient(targetIndex + 1, sourceIndex + 1) = ...
                nchoosek(sourceIndex, targetIndex);
        end
    end
    restrictionPatternByDegree{cacheIndex} = struct( ...
        "BinomialCoefficient", binomialCoefficient, ...
        "StartExponent", startExponent, ...
        "WidthExponent", targetPower, ...
        "ValidEntry", validEntry);
end
pattern = restrictionPatternByDegree{cacheIndex};
restrictionTransform = pattern.BinomialCoefficient .* ...
    intervalStart .^ pattern.StartExponent .* ...
    intervalWidth .^ pattern.WidthExponent;
restrictionTransform(~pattern.ValidEntry) = 0;
restrictedPower = restrictionTransform * powerCoefficient;
end

