function candidate = optimizeAzElDirectCollocation( ...
        seedRoute_deg, obstacleField, initialState, goalState, limits, ...
        options)
%% Section 0: Header & Readme
% SYNTAX
%   candidate = azElInternal.optimizeAzElDirectCollocation( ...
%       seedRoute_deg, obstacleField, initialState, goalState, limits, ...
%       options)
%**************************************************************************
% PURPOSE
%   - Optimize spatial azimuth/elevation motion and arrival time together.
%   - Use a reduced separated HS-3 transcription with shared jerk,
%     local obstacle separators, and h-refinement.
%**************************************************************************
% INPUTS
%   - seedRoute_deg (N-by-2 numeric)
%       Collision-informed topology seed. Interior vertices initialize the
%       NLP but are never imposed as trajectory equalities.
%   - obstacleField (scalar packed obstacle field)
%       Canonical already-protected static or moving geometry.
%   - initialState, goalState (scalar structs)
%       Exact endpoint time, position, velocity, and acceleration data.
%   - limits (scalar struct)
%       Positive two-axis velocity, acceleration, and jerk limits.
%   - options (scalar resolved planner-options struct)
%       Direct-collocation mesh, solver, validation, and timing controls.
%**************************************************************************
% OUTPUTS
%   - candidate (scalar struct)
%       Stable optimized trajectory, validation, and solver diagnostics.
%       Normal infeasibility returns Success=false.
%**************************************************************************
% UNITS
%   - State ordering is [az el vAz vEl aAz aEl]. Angles use degrees and
%     time uses seconds; jerk control is [jAz jEl] in deg/s^3.
%**************************************************************************

%% Section 1: Initialize The Mesh And Seed

candidateTimer = tic;
candidate = azElInternal.emptyAzElHs3Candidate();
candidate.SeedRoute_deg = double(seedRoute_deg);
candidate.SeedRouteCost_deg = azElInternal.polylineLength(seedRoute_deg);
if isfield(options, "SeedRouteTimeFraction") && ...
        isfield(options, "SeedRouteProgress")
    candidate.SeedRouteTimeFraction = ...
        double(options.SeedRouteTimeFraction(:));
    candidate.SeedRouteProgress = double(options.SeedRouteProgress(:));
    candidate.TimedSeedLawUsed = ...
        numel(candidate.SeedRouteTimeFraction) >= 2 && ...
        numel(candidate.SeedRouteTimeFraction) == ...
        numel(candidate.SeedRouteProgress);
end

if exist("fmincon", "file") ~= 2
    candidate.Message = ...
        "Optimization Toolbox fmincon is required for direct collocation.";
    candidate.TerminationReason = "solverUnavailable";
    return;
end

durationLowerBound_s = minimumDurationLowerBound( ...
    initialState, goalState, limits);
availableDuration_s = goalState.time_s - initialState.time_s;
if durationLowerBound_s > availableDuration_s + ...
        options.NlpConstraintTolerance
    candidate.Message = "The goal horizon is shorter than a dynamic lower bound.";
    candidate.TerminationReason = "goalTimeInfeasible";
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
remainingTime_s = Inf;
if isfield(options, "RemainingPlanningTime_s")
    remainingTime_s = options.RemainingPlanningTime_s;
end
if remainingTime_s <= 0
    candidate.Message = "No candidate planning time was available.";
    candidate.TerminationReason = "planningTimeLimit";
    candidate.TimeBudgetReached = true;
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end

meshTau = initialMeshForSeed(seedRoute_deg, ...
    options.InitialCollocationSegmentCount, ...
    options.MaximumCollocationSegmentCount);
[guess, initialGuessIsFeasible, initialGuessMessage, ...
    initialGuessTimeBudgetReached, initialGuessFailureReason] = ...
    azElInternal.createAzElHs3InitialGuess( ...
    seedRoute_deg, meshTau, obstacleField, ...
    initialState, goalState, ...
    limits, options, durationLowerBound_s, candidateTimer, ...
    remainingTime_s);
candidate.InitialGuessProjectionSucceeded = initialGuessIsFeasible;
candidate.InitialGuessMessage = initialGuessMessage;
if initialGuessTimeBudgetReached || ...
        (isfinite(remainingTime_s) && ...
        toc(candidateTimer) >= remainingTime_s)
    candidate.Message = ...
        "The candidate time expired during initial-guess projection.";
    candidate.TerminationReason = "planningTimeLimit";
    candidate.TimeBudgetReached = true;
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
if ~initialGuessIsFeasible
    candidate.Message = initialGuessMessage;
    candidate.TerminationReason = initialGuessFailureReason;
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
initialLayout = azElInternal.azElHs3DecisionLayout( ...
    numel(meshTau) - 1, ...
    options.GoalTimeMode == "earliestarrival");
[initialLowerBound, initialUpperBound] = ...
    azElInternal.boundAzElHs3Decision( ...
    initialLayout, initialState, goalState, limits, ...
    durationLowerBound_s, Inf);
unboundedInitialDecision = ...
    azElInternal.packAzElHs3Decision(guess, initialLayout);
boundedInitialDecision = min(initialUpperBound, max( ...
    initialLowerBound, unboundedInitialDecision));
candidate.InitialGuessMaximumBoundAdjustment = max(abs( ...
    boundedInitialDecision - unboundedInitialDecision));
guess = azElInternal.unpackAzElHs3Decision( ...
    boundedInitialDecision, initialLayout, meshTau, initialState, goalState);
[initialGuessEquality, ~] = ...
    azElInternal.azElHs3EqualityDefects(guess, meshTau);
candidate.InitialGuessMaximumHs3Defect = ...
    maximumAbsoluteOrZero(initialGuessEquality);
candidate.InitialGuessInitialStateError = ...
    guess.KnotState(1, :) - endpointState(initialState);
candidate.InitialGuessTerminalStateError = ...
    guess.KnotState(end, :) - endpointState(goalState);
initialDecisionScale = max(1, max(abs(unboundedInitialDecision)));
initialRoundoffTolerance = max(1e-12, ...
    100 * eps(initialDecisionScale));
initialConsistencyTolerance = max(1e-10, ...
    options.NlpConstraintTolerance);
initialGuessWasChanged = ...
    candidate.InitialGuessMaximumBoundAdjustment > ...
    initialConsistencyTolerance;
initialGuessLostConsistency = ...
    candidate.InitialGuessMaximumHs3Defect > ...
    initialConsistencyTolerance || ...
    max(abs(candidate.InitialGuessInitialStateError)) > ...
    initialConsistencyTolerance || ...
    max(abs(candidate.InitialGuessTerminalStateError)) > ...
    initialConsistencyTolerance;
if initialGuessWasChanged || initialGuessLostConsistency
    candidate.InitialGuessProjectionSucceeded = false;
    candidate.InitialGuessMessage = ...
        "Bound protection changed the projected HS-3 seed beyond " + ...
        "roundoff.";
    candidate.Message = candidate.InitialGuessMessage;
    candidate.TerminationReason = "initialGuessInfeasible";
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
if candidate.InitialGuessMaximumBoundAdjustment > ...
        initialRoundoffTolerance
    candidate.InitialGuessMessage = candidate.InitialGuessMessage + ...
        " Bound protection applied a numerical adjustment within the " + ...
        "NLP constraint tolerance.";
end
segmentCountHistory = zeros(0, 1);
maximumDefectHistory = zeros(0, 1);
meshObjectiveHistory = zeros(0, 1);
meshObjectiveChangeHistory = zeros(0, 1);
previousValidatedMeshObjective = NaN;
meshRefinementConverged = false;
meshRefinementConvergenceTolerance = NaN;
solverExitFlagHistory = zeros(0, 1);
solverMessageHistory = strings(0, 1);
solverTimeLimitReachedHistory = false(0, 1);
solverMeshPassHistory = zeros(0, 1);
solverCorridorPassHistory = zeros(0, 1);
solverStageHistory = strings(0, 1);
totalIterationCount = 0;
totalFunctionEvaluationCount = 0;
totalCorridorRelinearizationCount = 0;
lastSolution = emptySolution();
lastTrajectory = azElInternal.reconstructAzElHs3Trajectory();
lastCertificate = azElInternal.certifyAzElHs3Trajectory();
lastCollisionFree = false;
lastBufferedChordQueryClear = false;
lastCollisionSafetyProven = false;
lastCollisionClearanceDiagnostics = ...
    azElInternal.emptyCollisionClearanceDiagnostics();
lastCollisionMask = false(0, 1);
lastExitFlag = NaN;
lastSolverMessage = "The NLP was not evaluated.";
lastMaximumCollocationDefect = Inf;
lastMaximumNlpInequalityViolation = Inf;
lastSolvedMeshTau = zeros(0, 1);
retainedSolution = emptySolution();
retainedTrajectory = azElInternal.reconstructAzElHs3Trajectory();
retainedCertificate = azElInternal.certifyAzElHs3Trajectory();
retainedValidation = azElInternal.emptyTrajectoryValidation();
retainedCollisionClearanceDiagnostics = ...
    azElInternal.emptyCollisionClearanceDiagnostics();
retainedMaximumCollocationDefect = Inf;
retainedMaximumNlpInequalityViolation = Inf;
retainedMeshTau = zeros(0, 1);
retainedExitFlag = NaN;
retainedSolverMessage = "No validated mesh was retained.";
retainedObjective = Inf;
retainedSource = "";
% A frozen corridor receives most of its remaining finite budget. A small
% bounded share stays available for input-driven association updates.
maximumCorridorRetryReserveFraction = 0.25;
obstacleGeometryTimeInvariant = isfield( ...
    options, "ObstacleGeometryTimeInvariant") && ...
    logical(options.ObstacleGeometryTimeInvariant);

initialGuessTrajectory = ...
    azElInternal.reconstructAzElHs3Trajectory( ...
    guess, meshTau, initialState.time_s, options.SampleTime_s, ...
    options.ObstacleConstraintTolerance_deg);
if candidateTimeBudgetReached(candidateTimer, remainingTime_s)
    candidate.Message = ...
        "The candidate time expired during initial-trajectory reconstruction.";
    candidate.TerminationReason = "planningTimeLimit";
    candidate.TimeBudgetReached = true;
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
[~, ~, initialGuessCollisionAssessment] = ...
    azElInternal.assessAzElHs3TrajectoryCollision( ...
    obstacleField, initialGuessTrajectory, options);
collisionValidationPerformed = true;
initialGuessCollisionFree = initialGuessCollisionAssessment.CollisionFree;
candidate.InitialGuessCollisionFree = initialGuessCollisionFree;
if ~initialGuessCollisionFree
    candidate.InitialGuessMessage = candidate.InitialGuessMessage + ...
        " The warm start is not collision-free; the nonlinear " + ...
        "corridor and mesh stages must resolve it.";
end
candidate.CollisionValidationPerformed = true;
candidate.CollisionFree = initialGuessCollisionFree;
candidate.CollisionValidationPassed = initialGuessCollisionFree;
candidate.BufferedChordQueryClear = ...
    initialGuessCollisionAssessment.BufferedChordQueryClear;
candidate.CollisionSafetyProven = ...
    initialGuessCollisionAssessment.CollisionSafetyProven;
candidate.CollisionClearanceDiagnostics = ...
    initialGuessCollisionAssessment.ClearanceDiagnostics;
if candidateTimeBudgetReached(candidateTimer, remainingTime_s)
    candidate.Message = ...
        "The candidate time expired during initial collision validation.";
    candidate.TerminationReason = "planningTimeLimit";
    candidate.TimeBudgetReached = true;
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
initialGuessCertificate = azElInternal.certifyAzElHs3Trajectory( ...
    guess, meshTau, limits, options);
if candidateTimeBudgetReached(candidateTimer, remainingTime_s)
    candidate.Message = ...
        "The candidate time expired during initial continuous validation.";
    candidate.TerminationReason = "planningTimeLimit";
    candidate.TimeBudgetReached = true;
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
initialGuessCorridor = azElInternal.buildAzElHs3OptimizationCorridor( ...
    guess, meshTau, obstacleField, initialState.time_s, ...
    seedCorridorReferencePosition( ...
    seedRoute_deg, guess, meshTau, options));
initialGuessCorridor.GeometryTimeInvariant = ...
    obstacleGeometryTimeInvariant;
if candidateTimeBudgetReached(candidateTimer, remainingTime_s)
    candidate.Message = ...
        "The candidate time expired during initial corridor construction.";
    candidate.TerminationReason = "planningTimeLimit";
    candidate.TimeBudgetReached = true;
    candidate.ElapsedTime_s = toc(candidateTimer);
    return;
end
initialGuessDecision = ...
    azElInternal.packAzElHs3Decision(guess, initialLayout);
[initialGuessInequality, initialGuessEquality] = ...
    azElInternal.evaluateAzElHs3NlpConstraints( ...
    initialGuessDecision, initialLayout, meshTau, ...
    initialGuessCorridor, obstacleField, initialState, goalState, ...
    limits, options);
initialGuessMaximumCollocationDefect = ...
    maximumAbsoluteOrZero(initialGuessEquality);
initialGuessMaximumNlpInequalityViolation = ...
    maximumOrZero(initialGuessInequality);
initialGuessNeedsCorridorProjection = ...
    initialGuessMaximumCollocationDefect > ...
    options.NlpConstraintTolerance || ...
    initialGuessMaximumNlpInequalityViolation > ...
    options.NlpConstraintTolerance;
if initialGuessNeedsCorridorProjection && ...
        toc(candidateTimer) < remainingTime_s
    projectionGoalState = goalState;
    projectionGoalState.time_s = guess.FinalTime_s;
    projectionLayout = azElInternal.azElHs3DecisionLayout( ...
        numel(meshTau) - 1, false);
    projectionInitialDecision = ...
        azElInternal.packAzElHs3Decision(guess, projectionLayout);
    [projectionLowerBound, projectionUpperBound] = ...
        azElInternal.boundAzElHs3Decision( ...
        projectionLayout, initialState, projectionGoalState, ...
        limits, 0, Inf);
    projectionOptions = options;
    projectionOptions.MaximumNlpFunctionEvaluations = max( ...
        options.MaximumNlpFunctionEvaluations, ...
        numel(projectionInitialDecision) + 2);
    [projectionDecision, projectionExitFlag, ~, ~] = ...
        azElInternal.solveAzElHs3Nlp( ...
        projectionInitialDecision, projectionLowerBound, ...
        projectionUpperBound, projectionLayout, meshTau, ...
        initialGuessCorridor, obstacleField, initialState, ...
        projectionGoalState, limits, projectionOptions, ...
        "feasibility", remainingTime_s - toc(candidateTimer));
    projectedGuess = azElInternal.unpackAzElHs3Decision( ...
        projectionDecision, projectionLayout, meshTau, initialState, ...
        projectionGoalState);
    projectedTrajectory = ...
        azElInternal.reconstructAzElHs3Trajectory( ...
        projectedGuess, meshTau, initialState.time_s, ...
        options.SampleTime_s, options.ObstacleConstraintTolerance_deg);
    [~, ~, projectedCollisionAssessment] = ...
        azElInternal.assessAzElHs3TrajectoryCollision( ...
        obstacleField, projectedTrajectory, options);
    projectedCertificate = azElInternal.certifyAzElHs3Trajectory( ...
        projectedGuess, meshTau, limits, options);
    [projectedInequality, projectedEquality] = ...
        azElInternal.evaluateAzElHs3NlpConstraints( ...
        projectionDecision, projectionLayout, meshTau, ...
        initialGuessCorridor, obstacleField, initialState, ...
        projectionGoalState, limits, options);
    projectedMaximumCollocationDefect = ...
        maximumAbsoluteOrZero(projectedEquality);
    projectedMaximumNlpInequalityViolation = ...
        maximumOrZero(projectedInequality);
    projectedValidation = azElInternal.validateAzElHs3Solution( ...
        projectedGuess, projectedTrajectory, projectedCertificate, ...
        projectedCollisionAssessment, ...
        projectedMaximumCollocationDefect, ...
        projectedMaximumNlpInequalityViolation, initialState, ...
        projectionGoalState, limits, options);
    if projectionExitFlag > 0 && projectedValidation.Passed
        guess = projectedGuess;
        initialGuessTrajectory = projectedTrajectory;
        initialGuessCollisionAssessment = ...
            projectedCollisionAssessment;
        initialGuessCollisionFree = ...
            projectedCollisionAssessment.CollisionFree;
        initialGuessCertificate = projectedCertificate;
        initialGuessMaximumCollocationDefect = ...
            projectedMaximumCollocationDefect;
        initialGuessMaximumNlpInequalityViolation = ...
            projectedMaximumNlpInequalityViolation;
        candidate.InitialGuessMessage = ...
            candidate.InitialGuessMessage + ...
            " The fixed-duration affine projection also satisfied the " + ...
            "frozen obstacle corridor.";
    end
end
initialGuessValidation = azElInternal.validateAzElHs3Solution( ...
    guess, initialGuessTrajectory, initialGuessCertificate, ...
    initialGuessCollisionAssessment, initialGuessMaximumCollocationDefect, ...
    initialGuessMaximumNlpInequalityViolation, initialState, ...
    goalState, limits, options);
candidate.InitialGuessValidationPassed = initialGuessValidation.Passed;
candidate.InitialGuessCollisionFree = initialGuessCollisionFree;
candidate.CollisionFree = initialGuessCollisionFree;
candidate.CollisionValidationPassed = initialGuessCollisionFree;
candidate.BufferedChordQueryClear = ...
    initialGuessCollisionAssessment.BufferedChordQueryClear;
candidate.CollisionSafetyProven = ...
    initialGuessCollisionAssessment.CollisionSafetyProven;
candidate.CollisionClearanceDiagnostics = ...
    initialGuessCollisionAssessment.ClearanceDiagnostics;
candidate.ArrivalTime_s = guess.FinalTime_s;
candidate.MotionDuration_s = guess.FinalTime_s - initialState.time_s;
candidate.IntegratedSquaredJerk = ...
    azElInternal.azElHs3IntegratedSquaredJerk(guess, meshTau);
candidate.MaximumCollocationDefect = ...
    initialGuessMaximumCollocationDefect;
candidate.MaximumNlpInequalityViolation = ...
    initialGuessMaximumNlpInequalityViolation;
candidate.MaximumDynamicsDefect = ...
    initialGuessCertificate.MaximumDynamicsDefect;
candidate.MaximumVelocity_deg_s = ...
    initialGuessCertificate.MaximumVelocity_deg_s;
candidate.MaximumAcceleration_deg_s2 = ...
    initialGuessCertificate.MaximumAcceleration_deg_s2;
candidate.MaximumJerk_deg_s3 = ...
    initialGuessCertificate.MaximumJerk_deg_s3;
candidate.MaximumVelocityViolation_deg_s = ...
    initialGuessCertificate.MaximumVelocityViolation_deg_s;
candidate.MaximumAccelerationViolation_deg_s2 = ...
    initialGuessCertificate.MaximumAccelerationViolation_deg_s2;
candidate.MaximumJerkViolation_deg_s3 = ...
    initialGuessCertificate.MaximumJerkViolation_deg_s3;
candidate.Trajectory = initialGuessTrajectory;
candidate.Validation = initialGuessValidation;
candidate.MeshTau = meshTau;
stoppedByTimeBudget = candidateTimeBudgetReached( ...
    candidateTimer, remainingTime_s);
if initialGuessValidation.Passed
    retainedSolution = guess;
    retainedTrajectory = initialGuessTrajectory;
    retainedCertificate = initialGuessCertificate;
    retainedValidation = initialGuessValidation;
    retainedCollisionClearanceDiagnostics = ...
        initialGuessCollisionAssessment.ClearanceDiagnostics;
    retainedMaximumCollocationDefect = ...
        initialGuessMaximumCollocationDefect;
    retainedMaximumNlpInequalityViolation = ...
        initialGuessMaximumNlpInequalityViolation;
    retainedMeshTau = meshTau;
    retainedExitFlag = NaN;
    retainedSolverMessage = ...
        "A validated HS-3 initial guess was retained as a fallback.";
    retainedObjective = guess.FinalTime_s;
    if options.GoalTimeMode == "fixedarrival"
        retainedObjective = ...
            azElInternal.azElHs3IntegratedSquaredJerk(guess, meshTau);
    end
    retainedSource = "validatedInitialGuess";
end

%% Section 2: Solve And Refine The Hermite--Simpson NLP

earliestFeasibilityEstablished = options.GoalTimeMode ~= ...
    "earliestarrival" || retainedValidation.Passed;
for meshPassIndex = 1:options.MaximumMeshRefinementPasses + 1
    segmentCount = numel(meshTau) - 1;
    meshWasSolved = false;
    meshValidatedObjective = Inf;
    layout = azElInternal.azElHs3DecisionLayout(segmentCount, ...
        options.GoalTimeMode == "earliestarrival");

    corridorRelinearizationIndex = 0;
    collisionRepairTau = zeros(0, 1);
    collisionRepairBuffer_deg = zeros(0, 1);
    continueWithSameCorridor = false;
    sameCorridorContinuationCount = 0;
    while corridorRelinearizationIndex <= ...
            options.MaximumCorridorRelinearizations
        elapsedTime_s = toc(candidateTimer);
        if elapsedTime_s >= remainingTime_s
            stoppedByTimeBudget = true;
            break;
        end

        isSameCorridorContinuation = continueWithSameCorridor;
        continueWithSameCorridor = false;
        if ~isSameCorridorContinuation
            if corridorRelinearizationIndex == 0
                referencePosition_deg = seedCorridorReferencePosition( ...
                    seedRoute_deg, guess, meshTau, options);
                corridor = azElInternal.buildAzElHs3OptimizationCorridor( ...
                    guess, meshTau, obstacleField, ...
                    initialState.time_s, referencePosition_deg);
            else
                % A collision repair must follow the failed curve. Reusing
                % the seed would recreate the same separating planes.
                [defaultPointTau, ~] = ...
                    azElInternal.azElHs3CorridorTau(meshTau);
                requestedPointTau = unique([ ...
                    defaultPointTau; collisionRepairTau]);
                corridor = azElInternal.buildAzElHs3OptimizationCorridor( ...
                    guess, meshTau, obstacleField, initialState.time_s, ...
                    zeros(0, 2), requestedPointTau);
                corridor = azElInternal.applyAzElHs3CorridorRepair( ...
                    corridor, meshTau, collisionRepairTau, ...
                    collisionRepairBuffer_deg, ...
                    options.ObstacleConstraintTolerance_deg);
            end
            corridor.GeometryTimeInvariant = ...
                obstacleGeometryTimeInvariant;
            if corridorRelinearizationIndex > 0
                totalCorridorRelinearizationCount = ...
                    totalCorridorRelinearizationCount + 1;
            end
        end
        [lowerBound, upperBound] = azElInternal.boundAzElHs3Decision( ...
            layout, initialState, goalState, limits, ...
            durationLowerBound_s, Inf);
        initialDecision = azElInternal.packAzElHs3Decision(guess, layout);
        initialDecision = min(upperBound, max(lowerBound, initialDecision));
        hasActiveCorridor = any(corridor.Active, "all");
        remainingCorridorRetryCount = max(0, ...
            options.MaximumCorridorRelinearizations - ...
            corridorRelinearizationIndex);
        primaryObjectiveMode = "minimumTime";
        primaryStage = "primaryMinimumTime";
        if options.GoalTimeMode == "fixedarrival"
            primaryObjectiveMode = "feasibility";
            primaryStage = "primaryFeasibility";
        elseif ~earliestFeasibilityEstablished
            primaryObjectiveMode = "feasibility";
            primaryStage = "earliestFeasibility";
        end
        availableSolveTime_s = remainingTime_s - toc(candidateTimer);
        if availableSolveTime_s <= 0
            stoppedByTimeBudget = true;
            break;
        end
        canReserveCorridorRetry = isfinite(availableSolveTime_s) && ...
            hasActiveCorridor && remainingCorridorRetryCount > 0 && ...
            ~isSameCorridorContinuation;
        solveTimeBudget_s = availableSolveTime_s;
        if canReserveCorridorRetry
            corridorRetryReserveFraction = min( ...
                maximumCorridorRetryReserveFraction, ...
                0.10 * remainingCorridorRetryCount);
            solveTimeBudget_s = ...
                (1 - corridorRetryReserveFraction) * availableSolveTime_s;
        end
        [decision, exitFlag, solverOutput, solveTimeLimitReached] = ...
            azElInternal.solveAzElHs3Nlp( ...
            initialDecision, lowerBound, upperBound, layout, meshTau, ...
            corridor, obstacleField, initialState, goalState, limits, ...
            options, primaryObjectiveMode, solveTimeBudget_s);
        if isfield(solverOutput, "Corridor")
            corridor = solverOutput.Corridor;
        end
        solverExitFlagHistory(end + 1, 1) = exitFlag; %#ok<AGROW>
        solverMessageHistory(end + 1, 1) = ...
            string(solverOutput.message); %#ok<AGROW>
        solverTimeLimitReachedHistory(end + 1, 1) = ...
            solveTimeLimitReached; %#ok<AGROW>
        solverMeshPassHistory(end + 1, 1) = ...
            meshPassIndex; %#ok<AGROW>
        solverCorridorPassHistory(end + 1, 1) = ...
            corridorRelinearizationIndex; %#ok<AGROW>
        solverStageHistory(end + 1, 1) = primaryStage; %#ok<AGROW>
        if ~meshWasSolved
            segmentCountHistory(end + 1, 1) = segmentCount; %#ok<AGROW>
            meshWasSolved = true;
        end
        totalIterationCount = totalIterationCount + ...
            outputValue(solverOutput, "iterations");
        totalFunctionEvaluationCount = totalFunctionEvaluationCount + ...
            outputValue(solverOutput, "funcCount");
        solution = azElInternal.unpackAzElHs3Decision( ...
            decision, layout, meshTau, initialState, goalState);
        [nonlinearInequality, nonlinearEquality] = ...
            azElInternal.evaluateAzElHs3NlpConstraints( ...
            decision, layout, meshTau, corridor, obstacleField, ...
            initialState, goalState, limits, options);
        maximumInequality = maximumOrZero(nonlinearInequality);
        maximumEquality = maximumAbsoluteOrZero(nonlinearEquality);
        maximumCollocationDefect = maximumEquality;

        trajectory = azElInternal.reconstructAzElHs3Trajectory( ...
            solution, meshTau, ...
            initialState.time_s, options.SampleTime_s, ...
            options.ObstacleConstraintTolerance_deg);
        [~, collisionDetails, collisionAssessment] = ...
            azElInternal.assessAzElHs3TrajectoryCollision( ...
            obstacleField, trajectory, options);
        collisionFree = collisionAssessment.CollisionFree;
        certificate = azElInternal.certifyAzElHs3Trajectory( ...
            solution, meshTau, limits, options);
        currentValidation = azElInternal.validateAzElHs3Solution( ...
            solution, trajectory, ...
            certificate, collisionAssessment, maximumCollocationDefect, ...
            maximumInequality, initialState, goalState, limits, options);

        lastSolution = solution;
        lastTrajectory = trajectory;
        lastExitFlag = exitFlag;
        lastSolverMessage = string(solverOutput.message);
        lastMaximumCollocationDefect = maximumCollocationDefect;
        lastMaximumNlpInequalityViolation = maximumInequality;
        lastSolvedMeshTau = meshTau;
        lastCollisionFree = collisionFree;
        lastBufferedChordQueryClear = ...
            collisionAssessment.BufferedChordQueryClear;
        lastCollisionSafetyProven = ...
            collisionAssessment.CollisionSafetyProven;
        lastCollisionClearanceDiagnostics = ...
            collisionAssessment.ClearanceDiagnostics;
        lastCollisionMask = collisionAssessment.RefinementMask;
        lastCertificate = certificate;

        if currentValidation.Passed
            currentObjective = solution.FinalTime_s;
            if options.GoalTimeMode == "fixedarrival"
                currentObjective = ...
                    azElInternal.azElHs3IntegratedSquaredJerk( ...
                    solution, meshTau);
            end
            meshValidatedObjective = min( ...
                meshValidatedObjective, currentObjective);
            if currentObjective < retainedObjective
                retainedObjective = currentObjective;
                retainedSolution = solution;
                retainedTrajectory = trajectory;
                retainedCertificate = certificate;
                retainedValidation = currentValidation;
                retainedCollisionClearanceDiagnostics = ...
                    collisionAssessment.ClearanceDiagnostics;
                retainedMaximumCollocationDefect = ...
                    maximumCollocationDefect;
                retainedMaximumNlpInequalityViolation = ...
                    maximumInequality;
                retainedMeshTau = meshTau;
                retainedExitFlag = exitFlag;
                retainedSolverMessage = string(solverOutput.message);
                retainedSource = "primaryNlp";
                if primaryStage == "earliestFeasibility"
                    retainedSource = "earliestFeasibility";
                end
            end
        end

        candidateSolveBudgetReached = isfinite(remainingTime_s) && ...
            toc(candidateTimer) >= remainingTime_s;
        if candidateSolveBudgetReached
            stoppedByTimeBudget = true;
            break;
        end
        if currentValidation.Passed && ...
                primaryStage == "earliestFeasibility"
            earliestFeasibilityEstablished = true;
            guess = solution;
            continueWithSameCorridor = true;
            sameCorridorContinuationCount = 0;
            continue;
        end
        if currentValidation.Passed
            break;
        end
        repairNeedsRefinement = ...
            corridorRelinearizationIndex > 0 && exitFlag <= 0;
        if repairNeedsRefinement
            % The collision-generated half-spaces cannot be represented by
            % this mesh. Add local mesh freedom before another solver call.
            break;
        end
        canRelinearizeCorridor = ...
            ~collisionAssessment.CollisionFree && ...
            collisionDetails.EvaluatedSegmentCount > 0 && ...
            hasActiveCorridor && ...
            corridorRelinearizationIndex < ...
            options.MaximumCorridorRelinearizations;
        if canRelinearizeCorridor
            corridorRelinearizationIndex = ...
                corridorRelinearizationIndex + 1;
            [newRepairTau, newRepairBuffer_deg] = ...
                azElInternal.findAzElHs3CollisionRepairs( ...
                trajectory, collisionAssessment.RefinementMask, ...
                collisionDetails.SegmentOccupied, ...
                initialState.time_s, solution.FinalTime_s, ...
                max(10 * options.ObstacleConstraintTolerance_deg, ...
                    0.5 * options.VisibilitySampleStep_deg));
            [collisionRepairTau, collisionRepairBuffer_deg] = ...
                azElInternal.mergeAzElHs3CollisionRepairs( ...
                collisionRepairTau, collisionRepairBuffer_deg, ...
                newRepairTau, newRepairBuffer_deg);
            guess = solution;
            continue;
        end
        canUseReservedContinuation = solveTimeLimitReached && ...
            canReserveCorridorRetry && collisionFree;
        canPolishNonconvergedEquality = collisionFree && ...
            exitFlag <= 0 && ...
            (~currentValidation.CollocationDefectWithinTolerance || ...
            ~currentValidation.NlpInequalityWithinTolerance) && ...
            sameCorridorContinuationCount < 1;
        if canUseReservedContinuation || canPolishNonconvergedEquality
            % The local limit protected retry time. If no obstacle
            % association update is needed, use one warm-start continuation
            % to spend that time or polish a nonconverged equality point.
            guess = solution;
            continueWithSameCorridor = true;
            sameCorridorContinuationCount = ...
                sameCorridorContinuationCount + 1;
            continue;
        end
        break;
    end

    if ~meshWasSolved || isempty(lastTrajectory.time_s)
        break;
    end

    maximumDefectHistory(end + 1, 1) = ...
        lastCertificate.MaximumDynamicsDefect; %#ok<AGROW>
    if isfinite(meshValidatedObjective)
        meshObjectiveHistory(end + 1, 1) = ...
            meshValidatedObjective; %#ok<AGROW>
        objectiveChange = NaN;
        if isfinite(previousValidatedMeshObjective)
            objectiveChange = abs(meshValidatedObjective - ...
                previousValidatedMeshObjective);
            if options.GoalTimeMode == "earliestarrival"
                meshRefinementConvergenceTolerance = max(1e-3, ...
                    options.ArrivalTimeTieTolerance_s);
            else
                meshRefinementConvergenceTolerance = ...
                    options.NlpOptimalityTolerance * max(1, abs( ...
                    previousValidatedMeshObjective));
            end
            meshRefinementConverged = objectiveChange <= ...
                meshRefinementConvergenceTolerance;
        end
        meshObjectiveChangeHistory(end + 1, 1) = ...
            objectiveChange; %#ok<AGROW>
        previousValidatedMeshObjective = meshValidatedObjective;
    else
        meshObjectiveHistory(end + 1, 1) = NaN; %#ok<AGROW>
        meshObjectiveChangeHistory(end + 1, 1) = NaN; %#ok<AGROW>
    end
    if stoppedByTimeBudget
        break;
    end

    % A certified mesh does not need more resolution after its objective
    % change is smaller than the planner's existing decision tolerance.
    if meshRefinementConverged
        break;
    end

    [badSegment, refinementPriority] = ...
        azElInternal.selectAzElHs3RefinementSegments( ...
        lastSolution, meshTau, ...
        lastCertificate, limits, lastCollisionMask, lastTrajectory, ...
        obstacleField, options);
    canRefine = meshPassIndex <= options.MaximumMeshRefinementPasses && ...
        any(badSegment) && ...
        segmentCount < options.MaximumCollocationSegmentCount;
    if ~canRefine
        break;
    end

    maximumNewSegments = options.MaximumCollocationSegmentCount - ...
        segmentCount;
    badSegmentIndex = find(badSegment);
    if numel(badSegmentIndex) > maximumNewSegments
        ranking = [-refinementPriority(badSegmentIndex, :), ...
            badSegmentIndex];
        [~, stressOrder] = sortrows(ranking, 1:size(ranking, 2));
        badSegmentIndex = badSegmentIndex( ...
            stressOrder(1:maximumNewSegments));
    end
    refinedMeshTau = meshTau;
    refinedMeshTau = sort([refinedMeshTau; ...
        0.5 * (meshTau(badSegmentIndex) + ...
        meshTau(badSegmentIndex + 1))]);
    guess = azElInternal.resampleAzElHs3Solution( ...
        lastSolution, meshTau, refinedMeshTau);
    meshTau = refinedMeshTau;
end

