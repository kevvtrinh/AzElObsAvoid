controlPower = quadraticControlPower( ...
    firstControl, midpointControl, lastControl);
control = evaluatePowerPolynomial(controlPower, localTau);
end

function statePower = segmentStatePowerCoefficients( ...
        firstState, firstControl, midpointControl, lastControl, ...
        segmentDuration_s)
% PURPOSE
%   - Integrate the quadratic jerk into one consistent HS-3 state chain.
% Moreno-Martin, Ros, and Celaya (2024), generalized HS-M Eqs. 51 and
% 57-60, are specialized here to M=3. Each normalized-time coefficient
% keeps its required power of h, consistent with the corrected Kelly
% Eq. 4.13 erratum. See citation.md.
controlPower = quadraticControlPower( ...
    firstControl, midpointControl, lastControl);
jerk0 = controlPower(1, :);
jerk1 = controlPower(2, :);
jerk2 = controlPower(3, :);
h = segmentDuration_s;
statePower = zeros(6, 6);
statePower(1, :) = firstState;
statePower(2, 1:2) = h * firstState(3:4);
statePower(3, 1:2) = h ^ 2 * firstState(5:6) / 2;
statePower(4, 1:2) = h ^ 3 * jerk0 / 6;
statePower(5, 1:2) = h ^ 3 * jerk1 / 24;
statePower(6, 1:2) = h ^ 3 * jerk2 / 60;
statePower(2, 3:4) = h * firstState(5:6);
statePower(3, 3:4) = h ^ 2 * jerk0 / 2;
statePower(4, 3:4) = h ^ 2 * jerk1 / 6;
statePower(5, 3:4) = h ^ 2 * jerk2 / 12;
statePower(2, 5:6) = h * jerk0;
statePower(3, 5:6) = h * jerk1 / 2;
statePower(4, 5:6) = h * jerk2 / 3;
end

function controlPower = quadraticControlPower( ...
        firstControl, midpointControl, lastControl)
% PURPOSE
%   - Form the quadratic jerk power coefficients on normalized time.
controlPower = [firstControl; ...
    -3 * firstControl + 4 * midpointControl - lastControl; ...
    2 * firstControl - 4 * midpointControl + 2 * lastControl];
end

function value = evaluatePowerPolynomial(powerCoefficient, localTau)
% PURPOSE
%   - Evaluate ascending power coefficients at normalized segment times.
localTau = localTau(:);
power = localTau .^ (0:size(powerCoefficient, 1) - 1);
value = power * powerCoefficient;
end

function bernsteinCoefficient = powerToBernstein(powerCoefficient)
% PURPOSE
%   - Convert ascending power coefficients to one Bernstein control hull.
degree = size(powerCoefficient, 1) - 1;
persistent transformByDegree
if isempty(transformByDegree)
    transformByDegree = cell(0, 1);
end
cacheIndex = degree + 1;
if numel(transformByDegree) < cacheIndex || ...
        isempty(transformByDegree{cacheIndex})
    transform = zeros(cacheIndex, cacheIndex);
    for bernsteinIndex = 0:degree
        for powerIndex = 0:bernsteinIndex
            transform(bernsteinIndex + 1, powerIndex + 1) = ...
                nchoosek(bernsteinIndex, powerIndex) / ...
                nchoosek(degree, powerIndex);
        end
    end
    transformByDegree{cacheIndex} = transform;
end
bernsteinCoefficient = ...
    transformByDegree{cacheIndex} * powerCoefficient;
end

function certificate = certifyContinuousTrajectory( ...
        solution, meshTau, limits, options)
% PURPOSE
%   - Conservatively bound HS-3 state, jerk, and dynamics polynomials.
segmentCount = numel(meshTau) - 1;
duration_s = solution.FinalTime_s - solution.InitialTime_s;
maximumVelocityBySegment_deg_s = zeros(segmentCount, 2);
maximumAccelerationBySegment_deg_s2 = zeros(segmentCount, 2);
maximumJerkBySegment_deg_s3 = zeros(segmentCount, 2);
minimumPositionBySegment_deg = zeros(segmentCount, 2);
maximumPositionBySegment_deg = zeros(segmentCount, 2);
segmentDynamicsDefect = zeros(segmentCount, 1);
for segmentIndex = 1:segmentCount
    segmentDuration_s = duration_s * ...
        (meshTau(segmentIndex + 1) - meshTau(segmentIndex));
    firstState = solution.KnotState(segmentIndex, :);
    firstControl = solution.KnotControl(segmentIndex, :);
    midpointControl = solution.MidpointControl(segmentIndex, :);
    lastControl = solution.KnotControl(segmentIndex + 1, :);
    statePower = segmentStatePowerCoefficients(firstState, ...
        firstControl, midpointControl, lastControl, segmentDuration_s);
    [minimumPositionBySegment_deg(segmentIndex, :), ...
        maximumPositionBySegment_deg(segmentIndex, :)] = ...
        polynomialRange(statePower(:, 1:2));
