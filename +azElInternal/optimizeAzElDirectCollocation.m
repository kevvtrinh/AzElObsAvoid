function objective = nlpObjective(decision, layout, meshTau, ...
        initialState, goalState, limits, objectiveMode, referenceDecision)
% PURPOSE
%   - Select feasibility, minimum time, or jerk refinement objectives.
if objectiveMode == "feasibility"
    decisionScale = max(1, abs(referenceDecision));
    normalizedChange = (decision - referenceDecision) ./ decisionScale;
    objective = mean(normalizedChange .^ 2);
    return;
end
solution = unpackDecision( ...
    decision, layout, meshTau, initialState, goalState);
horizon_s = goalState.time_s - initialState.time_s;
if objectiveMode == "minimumTime"
    objective = (solution.FinalTime_s - initialState.time_s) / ...
        max(horizon_s, eps);
else
    jerkScale = max(1, horizon_s * sum(limits.maxJerk_deg_s3 .^ 2));
    objective = integratedJerk(solution, meshTau) / jerkScale;
end
end

