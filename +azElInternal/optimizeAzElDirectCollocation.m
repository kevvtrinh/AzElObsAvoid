function integratedSquaredJerk = integratedJerk(solution, meshTau)
% PURPOSE
%   - Integrate squared quadratic jerk exactly on every segment.
segmentDuration_s = (solution.FinalTime_s - solution.InitialTime_s) * ...
    diff(meshTau);
powerIndex = (0:2).';
integrationGram = 1 ./ (powerIndex + powerIndex.' + 1);
integratedSquaredJerk = 0;
for segmentIndex = 1:numel(segmentDuration_s)
    controlPower = quadraticControlPower( ...
        solution.KnotControl(segmentIndex, :), ...
        solution.MidpointControl(segmentIndex, :), ...
        solution.KnotControl(segmentIndex + 1, :));
    integratedSquaredJerk = integratedSquaredJerk + ...
        segmentDuration_s(segmentIndex) * sum( ...
        controlPower .* (integrationGram * controlPower), "all");
end
end

function durationLowerBound_s = minimumDurationLowerBound( ...
        initialState, goalState, limits)
% PURPOSE
%   - Compute conservative necessary duration bounds from each state order.
positionBound_s = abs(goalState.position_deg - ...
    initialState.position_deg) ./ limits.maxVelocity_deg_s;
velocityBound_s = abs(goalState.velocity_deg_s - ...
    initialState.velocity_deg_s) ./ limits.maxAcceleration_deg_s2;
accelerationBound_s = abs(goalState.acceleration_deg_s2 - ...
    initialState.acceleration_deg_s2) ./ limits.maxJerk_deg_s3;
durationLowerBound_s = max([1e-4, positionBound_s, ...
    velocityBound_s, accelerationBound_s]);
end

function length_deg = routeLength(route_deg)
% PURPOSE
%   - Compute deterministic seed ordering cost.
if size(route_deg, 1) < 2
    length_deg = 0;
    return;
end
step_deg = diff(route_deg, 1, 1);
length_deg = sum(hypot(step_deg(:, 1), step_deg(:, 2)));
end

function route_deg = removeDuplicateRoutePoints(route_deg)
% PURPOSE
