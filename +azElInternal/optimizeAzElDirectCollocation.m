        polynomialMaximumAbsolute(statePower(:, 3:4));
    maximumAccelerationBySegment_deg_s2(segmentIndex, :) = ...
        polynomialMaximumAbsolute(statePower(:, 5:6));
    controlPower = quadraticControlPower( ...
        firstControl, midpointControl, lastControl);
    maximumJerkBySegment_deg_s3(segmentIndex, :) = ...
        polynomialMaximumAbsolute(controlPower);

    derivativePower = (1:size(statePower, 1) - 1).' .* ...
        statePower(2:end, :) / segmentDuration_s;
    paddedControlPower = [controlPower; zeros(2, 2)];
    dynamicsPower = azElDynamics( ...
        statePower(1:end - 1, :), paddedControlPower);
