function [stateIndex, distance_deg] = bestPartialState(arrivalTime_s, data)
% PURPOSE
%   - Identify the reached safe-interval state nearest to the goal.
reachedStateIndex = find(isfinite(arrivalTime_s));
if isempty(reachedStateIndex)
    stateIndex = 0;
    distance_deg = Inf;
    return;
end
nodeIndex = data.StateNodeIndex(reachedStateIndex);
delta_deg = data.SpatialPosition_deg(nodeIndex, :) - ...
    data.GoalState.position_deg;
candidateDistance_deg = hypot(delta_deg(:, 1), delta_deg(:, 2));
ranking = [candidateDistance_deg, arrivalTime_s(reachedStateIndex), ...
    reachedStateIndex];
[~, order] = sortrows(ranking, [1 2 3]);
stateIndex = reachedStateIndex(order(1));
distance_deg = candidateDistance_deg(order(1));
end

function candidate = reconstructTimedCandidate( ...
        terminalStateIndex, arrivalTime_s, parentStateIndex, ...
        parentEdgeId, parentDepartureTime_s, data)
% PURPOSE
%   - Expand implicit safe waiting into a strict timed polyline.
stateSequence = terminalStateIndex;
while stateSequence(1) ~= data.StartStateIndex
    parentIndex = parentStateIndex(stateSequence(1));
    if parentIndex == 0
        error("buildAzElSafeIntervalRoadmap:CorruptParentTrace", ...
            "The selected SIPP parent trace does not reach the start.");
    end
    stateSequence = [parentIndex; stateSequence]; %#ok<AGROW>
end
spatialNodeSequence = data.StateNodeIndex(stateSequence);
safeIntervalSequence = data.StateIntervalIndex(stateSequence);
position_deg = data.SpatialPosition_deg(spatialNodeSequence(1), :);
time_s = data.InitialState.time_s;
edgeIdSequence = zeros(numel(stateSequence) - 1, 1);
edgeDepartureTime_s = zeros(numel(stateSequence) - 1, 1);
edgeArrivalTime_s = zeros(numel(stateSequence) - 1, 1);
waitDuration_s = 0;
waitEventCount = 0;
for transitionIndex = 2:numel(stateSequence)
    targetStateIndex = stateSequence(transitionIndex);
    sourcePosition_deg = position_deg(end, :);
    departureTime_s = parentDepartureTime_s(targetStateIndex);
    targetArrivalTime_s = arrivalTime_s(targetStateIndex);
    if departureTime_s > time_s(end) + ...
            data.Options.SafeIntervalTimeTolerance_s
        position_deg(end + 1, :) = sourcePosition_deg; %#ok<AGROW>
        time_s(end + 1, 1) = departureTime_s; %#ok<AGROW>
        waitDuration_s = waitDuration_s + ...
            departureTime_s - time_s(end - 1);
        waitEventCount = waitEventCount + 1;
    end
    targetNodeIndex = data.StateNodeIndex(targetStateIndex);
    position_deg(end + 1, :) = ...
        data.SpatialPosition_deg(targetNodeIndex, :); %#ok<AGROW>
    time_s(end + 1, 1) = targetArrivalTime_s; %#ok<AGROW>
    edgeIdSequence(transitionIndex - 1) = ...
        parentEdgeId(targetStateIndex);
    edgeDepartureTime_s(transitionIndex - 1) = departureTime_s;
    edgeArrivalTime_s(transitionIndex - 1) = targetArrivalTime_s;
end
if data.Options.GoalTimeMode == "fixedarrival" && ...
        data.GoalState.time_s > time_s(end) + ...
        data.Options.SafeIntervalTimeTolerance_s
    position_deg(end + 1, :) = position_deg(end, :);
    time_s(end + 1, 1) = data.GoalState.time_s;
    waitDuration_s = waitDuration_s + ...
        data.GoalState.time_s - time_s(end - 1);
    waitEventCount = waitEventCount + 1;
end
candidate = emptyTimedCandidate();
candidate.Success = true;
candidate.Message = "The SIPP-IP candidate reached the goal.";
candidate.TerminationReason = "goalReached";
candidate.StateIndex = stateSequence;
candidate.SpatialNodeIndex = spatialNodeSequence;
candidate.SafeIntervalIndex = safeIntervalSequence;
candidate.Position_deg = position_deg;
candidate.Time_s = time_s;
candidate.EdgeIdSequence = edgeIdSequence;
candidate.EdgeDepartureTime_s = edgeDepartureTime_s;
candidate.EdgeArrivalTime_s = edgeArrivalTime_s;
candidate.ArrivalTime_s = time_s(end);
candidate.AngularLength_deg = sum( ...
    data.SpatialEdgeLength_deg(edgeIdSequence));
candidate.WaitDuration_s = waitDuration_s;
candidate.WaitEventCount = waitEventCount;
candidate.RouteSignature = routeSignature(candidate, data.Options);
end

function signature = routeSignature(candidate, options)
% PURPOSE
%   - Distinguish spatial route order and meaningful waiting decisions.
