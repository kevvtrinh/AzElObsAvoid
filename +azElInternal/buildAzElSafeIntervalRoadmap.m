function departureTime_s = refineDepartureBoundary(data, ...
        sourcePosition_deg, targetPosition_deg, blockedTime_s, ...
        clearTime_s, duration_s)
% PURPOSE
%   - Refine an infeasible-to-feasible departure transition.
for refinementIndex = 1:64
    if clearTime_s - blockedTime_s <= ...
            data.Options.SafeIntervalTimeTolerance_s
        break;
    end
    midpointTime_s = 0.5 * (blockedTime_s + clearTime_s);
    if traversalIsBlocked(data, sourcePosition_deg, ...
            targetPosition_deg, midpointTime_s, duration_s)
        blockedTime_s = midpointTime_s;
    else
        clearTime_s = midpointTime_s;
    end
end
departureTime_s = clearTime_s;
end

function duration_s = minimumTravelDuration( ...
        sourcePosition_deg, targetPosition_deg, maximumVelocity_deg_s, ...
        maximumAcceleration_deg_s2, maximumJerk_deg_s3, ...
        timeTolerance_s)
% PURPOSE
%   - Compute a synchronized rest-to-rest S-curve edge duration.
displacement_deg = abs(targetPosition_deg - sourcePosition_deg);
axisDuration_s = zeros(1, 2);
for axisIndex = 1:2
    axisDuration_s(axisIndex) = restToRestAxisDuration( ...
        displacement_deg(axisIndex), ...
        maximumVelocity_deg_s(axisIndex), ...
        maximumAcceleration_deg_s2(axisIndex), ...
        maximumJerk_deg_s3(axisIndex));
end
duration_s = max(axisDuration_s);
if ~isfinite(duration_s) || duration_s <= 0
    duration_s = timeTolerance_s;
end
end

function duration_s = restToRestAxisDuration( ...
        displacement_deg, maximumVelocity_deg_s, ...
        maximumAcceleration_deg_s2, maximumJerk_deg_s3)
% PURPOSE
%   - Solve one symmetric jerk-limited rest-to-rest timing profile.
if displacement_deg <= 0
    duration_s = 0;
    return;
end
hasAccelerationLimit = isfinite(maximumAcceleration_deg_s2);
hasJerkLimit = isfinite(maximumJerk_deg_s3);
if ~hasJerkLimit && ~hasAccelerationLimit
    duration_s = displacement_deg / maximumVelocity_deg_s;
    return;
end
if ~hasJerkLimit
    triangularPeakVelocity_deg_s = sqrt( ...
        displacement_deg * maximumAcceleration_deg_s2);
    if triangularPeakVelocity_deg_s <= maximumVelocity_deg_s
        duration_s = 2 * sqrt( ...
            displacement_deg / maximumAcceleration_deg_s2);
    else
        duration_s = displacement_deg / maximumVelocity_deg_s + ...
            maximumVelocity_deg_s / maximumAcceleration_deg_s2;
    end
    return;
end
if ~hasAccelerationLimit
    triangularJerkTime_s = (displacement_deg / ...
        (2 * maximumJerk_deg_s3)) ^ (1 / 3);
    triangularPeakVelocity_deg_s = maximumJerk_deg_s3 * ...
        triangularJerkTime_s ^ 2;
    if triangularPeakVelocity_deg_s <= maximumVelocity_deg_s
        duration_s = 4 * triangularJerkTime_s;
    else
        jerkTime_s = sqrt( ...
            maximumVelocity_deg_s / maximumJerk_deg_s3);
        accelerationDistance_deg = 2 * maximumJerk_deg_s3 * ...
            jerkTime_s ^ 3;
        cruiseTime_s = max(0, ...
            (displacement_deg - accelerationDistance_deg) / ...
            maximumVelocity_deg_s);
        duration_s = 4 * jerkTime_s + cruiseTime_s;
    end
    return;
end

triangularJerkTime_s = (displacement_deg / ...
    (2 * maximumJerk_deg_s3)) ^ (1 / 3);
triangularPeakAcceleration_deg_s2 = maximumJerk_deg_s3 * ...
    triangularJerkTime_s;
triangularPeakVelocity_deg_s = maximumJerk_deg_s3 * ...
    triangularJerkTime_s ^ 2;
if triangularPeakAcceleration_deg_s2 <= ...
        maximumAcceleration_deg_s2 && ...
        triangularPeakVelocity_deg_s <= maximumVelocity_deg_s
    duration_s = 4 * triangularJerkTime_s;
    return;
end

velocityBeforeAcceleration = maximumVelocity_deg_s <= ...
    maximumAcceleration_deg_s2 ^ 2 / maximumJerk_deg_s3;
if velocityBeforeAcceleration
    jerkTime_s = sqrt( ...
        maximumVelocity_deg_s / maximumJerk_deg_s3);
    accelerationDistance_deg = 2 * maximumJerk_deg_s3 * ...
        jerkTime_s ^ 3;
    cruiseTime_s = max(0, ...
        (displacement_deg - accelerationDistance_deg) / ...
        maximumVelocity_deg_s);
    duration_s = 4 * jerkTime_s + cruiseTime_s;
    return;
end

jerkTime_s = maximumAcceleration_deg_s2 / maximumJerk_deg_s3;
constantAccelerationTime_s = 0.5 * ( ...
    -3 * jerkTime_s + sqrt(jerkTime_s ^ 2 + ...
    4 * displacement_deg / maximumAcceleration_deg_s2));
constantAccelerationTime_s = max(0, constantAccelerationTime_s);
peakVelocity_deg_s = maximumAcceleration_deg_s2 * ...
    (jerkTime_s + constantAccelerationTime_s);
if peakVelocity_deg_s <= maximumVelocity_deg_s
    duration_s = 4 * jerkTime_s + ...
        2 * constantAccelerationTime_s;
    return;
end

constantAccelerationTime_s = ...
    maximumVelocity_deg_s / maximumAcceleration_deg_s2 - jerkTime_s;
constantAccelerationTime_s = max(0, constantAccelerationTime_s);
accelerationDistance_deg = 2 * maximumAcceleration_deg_s2 * ( ...
    jerkTime_s ^ 2 + 1.5 * jerkTime_s * ...
    constantAccelerationTime_s + ...
    0.5 * constantAccelerationTime_s ^ 2);
cruiseTime_s = max(0, ...
    (displacement_deg - accelerationDistance_deg) / ...
    maximumVelocity_deg_s);
duration_s = 4 * jerkTime_s + ...
    2 * constantAccelerationTime_s + cruiseTime_s;
end

function allowsWaiting = startStateAllowsWaiting(data)
