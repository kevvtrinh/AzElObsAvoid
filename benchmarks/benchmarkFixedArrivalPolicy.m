function [runs, results] = benchmarkFixedArrivalPolicy(repetitions)
%% Section 0: Header & Readme
% SYNTAX
%   [runs, results] = benchmarkFixedArrivalPolicy()
%   [runs, results] = benchmarkFixedArrivalPolicy(repetitions)
%**************************************************************************
% PURPOSE
%   - Measure the fixed-arrival shortcut and next method policy on four
%     deterministic requests that favor different guide sources.
%**************************************************************************
% INPUTS
%   - repetitions (positive integer scalar, optional; default 3)
%       Number of measured runs after one warmup run per case.
%**************************************************************************
% OUTPUTS
%   - runs (table)
%       Per-run timing, attempt sequence, validation, and motion-quality data.
%   - results (N-by-1 cell array)
%       Complete corresponding public planner results. Ordinary planning
%       failures remain Success = false; invalid input throws.
%**************************************************************************
% UNITS
%   - Coordinates are degrees and time is seconds.
%**************************************************************************

%% Section 1: Load Deterministic Source Requests

if nargin < 1
    repetitions = 3;
end
validateattributes(repetitions, {'numeric'}, ...
    {'scalar', 'integer', 'positive', 'finite'});
repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(repositoryRoot, fullfile(repositoryRoot, 'trajectory'), ...
    fullfile(repositoryRoot, 'examples'));
spatialScenario = createRandomAzimuthScenario(1, true);
cases(1) = struct('Name', "Random 1 with static obstacle", ...
    'obstacles', spatialScenario.Obstacles, ...
    'initial', spatialScenario.InitialState, ...
    'goal', spatialScenario.GoalState, ...
    'limits', spatialScenario.Limits, ...
    'options', spatialScenario.Options);
request = jsondecode(fileread(fullfile(repositoryRoot, 'tests', 'fixtures', ...
    'savedMovingDetour.json')));
sources = cell(numel(request.obstacles), 1);
for sourceIndex = 1:numel(sources)
    source = request.obstacles(sourceIndex);
    frames = source.keyframes;
    sources{sourceIndex} = obstacleAvoidance.obstacles.createObstacle( ...
        source.name, [frames.time_s].', ...
        arrayfun(@(frame) frame.vertices_units(:, 1), frames, ...
            'UniformOutput', false), ...
        arrayfun(@(frame) frame.vertices_units(:, 2), frames, ...
            'UniformOutput', false), source.safetyMargin_units);
end
request.options.GoalTimeMode = 'fixedArrival';
cases(2) = struct('Name', "Saved moving detour", ...
    'obstacles', obstacleAvoidance.obstacles.combineObstacles(sources), ...
    'initial',   request.initialState, ...
    'goal',      request.goalState, ...
    'limits',    request.limits, ...
    'options',   request.options);
timedScenario = createRandomAzimuthScenario(26, true);
cases(3) = struct('Name', "Random 26 with static obstacle", ...
    'obstacles', timedScenario.Obstacles, ...
    'initial', timedScenario.InitialState, ...
    'goal', timedScenario.GoalState, ...
    'limits', timedScenario.Limits, ...
    'options', timedScenario.Options);
curtain_units = [-0.2,-7;0.2,-7;0.2,7;-0.2,7];
openCurtain_units = curtain_units + [0,14];
curtain = obstacleAvoidance.obstacles.createObstacle('recurrent curtain', ...
    [0;1;1.1;4;4.1;12], ...
    {curtain_units(:,1);curtain_units(:,1);openCurtain_units(:,1); ...
    openCurtain_units(:,1);curtain_units(:,1);curtain_units(:,1)}, ...
    {curtain_units(:,2);curtain_units(:,2);openCurtain_units(:,2); ...
    openCurtain_units(:,2);curtain_units(:,2);curtain_units(:,2)},0);
cases(4) = struct('Name', "Recurrent curtain timed search", ...
    'obstacles', curtain, ...
    'initial', struct('time_s',0,'position_units',[-4,0]), ...
    'goal', struct('time_s',12,'position_units',[4,0]), ...
    'limits', struct('xInterval_units',[-5,5],'yInterval_units',[-6,6], ...
    'maxVelocity_units_s',[4,4],'maxAcceleration_units_s2',[4,4], ...
    'maxJerk_units_s3',[8,8]), ...
    'options', struct('GoalTimeMode','fixedArrival','TemporalResolution_s',0.25));

%% Section 2: Warm And Measure The Unified Policy

measuredRunCount = numel(cases) * repetitions;
rows             = cell(measuredRunCount, 1);
results          = cell(measuredRunCount, 1);
rowIndex         = 0;
for caseIndex = 1:numel(cases)
    caseRequest = cases(caseIndex);
    for repetition = 0:repetitions
        timer  = tic;
        result = planner(caseRequest.obstacles, caseRequest.initial, caseRequest.goal, ...
            caseRequest.limits, caseRequest.options);
        elapsed_s = toc(timer);
        passed    = result.Success && ...
            obstacleAvoidance.validateTrajectory(result).Passed;
        arrival_s    = NaN;
        length_units = NaN;
        searchTime_s  = NaN;
        if result.Success
            arrival_s    = result.ArrivalTime_s;
            length_units = result.MotionLength_units;
        end
        if isfield(result.Diagnostics.VisibilityGraph, 'TimedSearch')
            searchTime_s = result.Diagnostics.VisibilityGraph.TimedSearch.ElapsedTime_s;
        end
        attempts = result.Diagnostics.Attempts;
        attemptCount = numel(attempts);
        solverAttemptCount = 1;
        totalAlternatingIterations = result.Diagnostics.SolverDiagnostics.IterationCount;
        attemptSequence = "singleSpatialSolve";
        if ~isempty(attempts)
            solverAttemptCount = sum([attempts.SolverAttempted]);
            totalAlternatingIterations = sum([attempts.IterationCount]);
            attemptSequence = strjoin([attempts.Kind], " > ");
        end
        fprintf(['%s repetition %d: %.6f s; valid %d; arrival %.9f; ' ...
            'length %.12f; attempts %s; %s\n'], caseRequest.Name, repetition, ...
            elapsed_s, passed, arrival_s, length_units, ...
            attemptSequence, result.TerminationReason);
        if repetition == 0
            continue
        end
        rowIndex = rowIndex + 1;
        rows{rowIndex} = struct( ...
            'Case',                  caseRequest.Name, ...
            'Repetition',            repetition, ...
            'Runtime_s',             elapsed_s, ...
            'Success',               result.Success, ...
            'IndependentValidation', passed, ...
            'Arrival_s',             arrival_s, ...
            'Length_units',          length_units, ...
            'AttemptCount',          attemptCount, ...
            'SolverAttemptCount',    solverAttemptCount, ...
            'AlternatingIterations', totalAlternatingIterations, ...
            'AttemptSequence',       attemptSequence, ...
            'SearchTime_s',          searchTime_s, ...
            'TerminationReason',     result.TerminationReason);
        results{rowIndex} = result;
    end
end
runs = struct2table(vertcat(rows{:}));
end
