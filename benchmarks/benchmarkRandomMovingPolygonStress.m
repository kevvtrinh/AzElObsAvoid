function report = benchmarkRandomMovingPolygonStress( ...
        randomSeeds, benchmarkOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   report = benchmarkRandomMovingPolygonStress()
%   report = benchmarkRandomMovingPolygonStress(randomSeeds)
%   report = benchmarkRandomMovingPolygonStress( ...
%       randomSeeds, benchmarkOverrides)
%**************************************************************************
% PURPOSE
%   - Stress the public HS3 planner with deterministic large random polygons
%     that
%     translate across most of the Az/El frame while rotating at least 180
%     degrees.
%   - Preserve exact inputs and returned diagnostics for every failure.
%   - Keep an analytically clear boundary witness outside planner inputs so
%     search failures are distinguishable from obvious geometric no-paths.
%**************************************************************************
% INPUTS
%   - randomSeeds (numeric vector, optional; default 1001:1012)
%       Nonnegative deterministic scenario seeds.
%   - benchmarkOverrides (scalar struct, optional; default struct())
%       .ObstacleCount is an integer at least two (default 3).
%       .MissionTime_s is positive (default 60).
%       .MaximumPlanningTime_s is positive (default 30).
%       .PrintProgress is logical (default true).
%       .PlannerOverrides is a scalar HS3 option struct (default struct()).
%**************************************************************************
% OUTPUTS
%   - report (scalar struct)
%       Controls plus one record per seed. Each record retains exact
%       inputs, scenario geometry, result, independent validation, wall
%       time, and the analytic witness-clearance lower bound.
%**************************************************************************
% UNITS
%   - Positions, radii, and clearance are degrees. Time is seconds and
%     derivatives use deg/s, deg/s^2, and deg/s^3.
%**************************************************************************

%% Section 1: Resolve Reproducible Controls

if nargin < 1 || isempty(randomSeeds)
    randomSeeds = 1001:1012;
end
if nargin < 2 || isempty(benchmarkOverrides)
    benchmarkOverrides = struct();
end
validateattributes(randomSeeds, {'numeric'}, ...
    {'real', 'finite', 'vector', 'integer', 'nonnegative'});
defaults = struct( ...
    "ObstacleCount", 3, ...
    "MissionTime_s", 60, ...
    "MaximumPlanningTime_s", 30, ...
    "PrintProgress", true, ...
    "PlannerOverrides", struct());
[controls, unknownNames] = azElInput.resolveOptions( ...
    defaults, benchmarkOverrides);
if ~isempty(unknownNames)
    warning("benchmarkRandomMovingPolygonStress:UnknownOptions", ...
        "Ignoring unknown fields: %s. No behavior changed.", ...
        strjoin(unknownNames, ", "));
end
validateattributes(controls.ObstacleCount, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', '>=', 2});
validateattributes(controls.MissionTime_s, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(controls.MaximumPlanningTime_s, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
controls.PrintProgress = azElInput.normalizeLogicalScalar( ...
    controls.PrintProgress, "PrintProgress", ...
    "benchmarkRandomMovingPolygonStress:InvalidPrintProgress");
if ~isstruct(controls.PlannerOverrides) || ...
        ~isscalar(controls.PlannerOverrides)
    error("benchmarkRandomMovingPolygonStress:InvalidPlannerOverrides", ...
        "PlannerOverrides must be a scalar struct.");
end
randomSeeds = double(randomSeeds(:));

%% Section 2: Run Every Seed With HS3

recordCount = numel(randomSeeds);
records = repmat(emptyRecord(), recordCount, 1);
for seedIndex = 1:numel(randomSeeds)
    randomSeed = randomSeeds(seedIndex);
    [obstacles, initialState, goalState, limits, scenario] = ...
        createStressScenario(randomSeed, controls);
    records(seedIndex) = runStressCase( ...
        randomSeed, obstacles, initialState, goalState, limits, ...
        scenario, controls);
    if controls.PrintProgress
        printRecord(records(seedIndex));
    end
end

%% Section 3: Assemble Failure-Preserving Evidence

passed = [records.Success].' & [records.IndependentValidationPassed].';
report = struct( ...
    "BenchmarkName", "randomMovingPolygonStress", ...
    "Controls", controls, ...
    "RandomSeeds", randomSeeds, ...
    "Records", records, ...
    "PassedCount", nnz(passed), ...
    "FailedCount", nnz(~passed));
end

%% Section 4: Local Functions

function [obstacles, initialState, goalState, limits, scenario] = ...
        createStressScenario(randomSeed, controls)
% Create several large rotating polygons with a clear outer witness route.
rng(randomSeed, "twister");
missionTime_s = controls.MissionTime_s;
obstacleTime_s = linspace(0, missionTime_s, 13).';
obstacleCount = controls.ObstacleCount;
safetyMargin_deg = 0.25;
centerAzimuthLimit_deg = 17.5;
centerElevation_deg = linspace(-4, 4, obstacleCount).';
obstacleCells = cell(obstacleCount, 1);
histories = cell(obstacleCount, 1);
maximumSourceRadius_deg = zeros(obstacleCount, 1);
rotationTravel_deg = zeros(obstacleCount, 1);

% Each source polygon is star-shaped, simple, and has five to twelve vertices.
for obstacleIndex = 1:obstacleCount
    vertexCount = randi([5 12]);
    nominalAngles_rad = (0:vertexCount - 1).' * ...
        (2 * pi / vertexCount);
    angularJitter_rad = (rand(vertexCount, 1) - 0.5) * ...
        (0.55 * 2 * pi / vertexCount);
    sourceAngles_rad = sort(nominalAngles_rad + angularJitter_rad);
    nominalRadius_deg = 6.5 + 1.5 * rand;
    sourceRadius_deg = nominalRadius_deg * ...
        (0.68 + 0.32 * rand(vertexCount, 1));
    sourcePosition_deg = sourceRadius_deg .* ...
        [cos(sourceAngles_rad), sin(sourceAngles_rad)];
    maximumSourceRadius_deg(obstacleIndex) = max(sourceRadius_deg);
    initialRotation_deg = 360 * rand;
    rotationTravel_deg(obstacleIndex) = 180 + 180 * rand;
    if mod(obstacleIndex, 2) == 1
        startAzimuth_deg = -centerAzimuthLimit_deg;
        endAzimuth_deg = centerAzimuthLimit_deg;
    else
        startAzimuth_deg = centerAzimuthLimit_deg;
        endAzimuth_deg = -centerAzimuthLimit_deg;
    end
    verticalPhase_rad = 2 * pi * rand;
    sliceTransform = @(source_deg, sampleTime_s, sampleIndex) ...
        transformStressPolygon( ...
        source_deg, sampleTime_s, sampleIndex, missionTime_s, ...
        startAzimuth_deg, endAzimuth_deg, ...
        centerElevation_deg(obstacleIndex), verticalPhase_rad, ...
        initialRotation_deg, rotationTravel_deg(obstacleIndex));
    [obstacleCells{obstacleIndex}, histories{obstacleIndex}] = ...
        azElObstacles.makeMovingAzElObstacleData( ...
        "Random crossing polygon " + obstacleIndex, ...
        obstacleTime_s, sourcePosition_deg(:, 1), ...
        sourcePosition_deg(:, 2), sliceTransform, ...
        safetyMargin_deg, struct("Verbose", false));
end
obstacles = azElObstacles.combineAzElObstacles(obstacleCells);

workspaceAzimuth_deg = [-30 30];
workspaceElevation_deg = [-20 20];
startPosition_deg = [-28 0];
goalPosition_deg = [28 0];
witnessElevation_deg = -18;
maximumRadiusWithMargin_deg = ...
    max(maximumSourceRadius_deg) + safetyMargin_deg;
sideClearanceLowerBound_deg = ...
    abs(startPosition_deg(1) - (-centerAzimuthLimit_deg)) - ...
    maximumRadiusWithMargin_deg;
maximumCenterExcursion_deg = ...
    max(abs(centerElevation_deg)) + 0.75;
bottomClearanceLowerBound_deg = ...
    abs(witnessElevation_deg) - maximumCenterExcursion_deg - ...
    maximumRadiusWithMargin_deg;
witnessClearanceLowerBound_deg = min( ...
    sideClearanceLowerBound_deg, bottomClearanceLowerBound_deg);
if witnessClearanceLowerBound_deg <= 0
    error("benchmarkRandomMovingPolygonStress:InvalidWitness", ...
        "Generated radial bounds do not leave the declared witness route clear.");
end

initialState = struct( ...
    "time_s", 0, "position_deg", startPosition_deg, ...
    "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", missionTime_s, "position_deg", goalPosition_deg, ...
    "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
limits = struct( ...
    "maxVelocity_deg_s", [4 4], ...
    "maxAcceleration_deg_s2", [1.5 1.5], ...
    "maxJerk_deg_s3", [3 3], ...
    "azimuthInterval_deg", workspaceAzimuth_deg, ...
    "elevationInterval_deg", workspaceElevation_deg);
scenario = struct( ...
    "ObstacleTime_s", obstacleTime_s, ...
    "ObstacleHistories", {histories}, ...
    "MaximumSourceRadius_deg", maximumSourceRadius_deg, ...
    "RotationTravel_deg", rotationTravel_deg, ...
    "WitnessRoute_deg", [ ...
        startPosition_deg; ...
        startPosition_deg(1) witnessElevation_deg; ...
        goalPosition_deg(1) witnessElevation_deg; ...
        goalPosition_deg], ...
    "WitnessClearanceLowerBound_deg", ...
        witnessClearanceLowerBound_deg);
end

function transformed_deg = transformStressPolygon( ...
        sourcePosition_deg, sampleTime_s, ~, missionTime_s, ...
        startAzimuth_deg, endAzimuth_deg, centerElevation_deg, ...
        verticalPhase_rad, initialRotation_deg, rotationTravel_deg)
% Translate across the frame and rotate through at least one half-turn.
progress = min(max(sampleTime_s / missionTime_s, 0), 1);
smoothProgress = 10 * progress^3 - 15 * progress^4 + 6 * progress^5;
center_deg = [ ...
    startAzimuth_deg + ...
        smoothProgress * (endAzimuth_deg - startAzimuth_deg), ...
    centerElevation_deg + ...
        0.75 * sin(2 * pi * progress + verticalPhase_rad)];
rotation_rad = deg2rad( ...
    initialRotation_deg + rotationTravel_deg * smoothProgress);
rotationMatrix = [ ...
    cos(rotation_rad) -sin(rotation_rad); ...
    sin(rotation_rad) cos(rotation_rad)];
transformed_deg = sourcePosition_deg * rotationMatrix.' + center_deg;
end

function record = runStressCase( ...
        randomSeed, obstacles, initialState, goalState, ...
        limits, scenario, controls)
% Run HS3 once and preserve unsuccessful evidence without retrying.
plannerOptions = controls.PlannerOverrides;
plannerOptions.PlannerMethod = "hs3";
plannerOptions.GoalTimeMode = "earliestArrival";
plannerOptions.MaximumPlanningTime_s = controls.MaximumPlanningTime_s;
plannerOptions.RandomSeed = randomSeed;
plannerTimer = tic;
result = planAzElMotion( ...
    obstacles, initialState, goalState, limits, plannerOptions);
plannerWallTime_s = toc(plannerTimer);
validation = validateAzElTrajectory();
if result.Success
    validation = validateAzElTrajectory(result);
end
record = emptyRecord();
record.RandomSeed = randomSeed;
record.Method = "hs3";
record.Success = result.Success;
record.IndependentValidationPassed = ...
    result.Success && validation.Passed;
record.TerminationReason = result.TerminationReason;
record.SelectedMotionSource = result.SelectedMotionSource;
record.PlannerWallTime_s = plannerWallTime_s;
record.ArrivalTime_s = result.ArrivalTime_s;
record.WitnessClearanceLowerBound_deg = ...
    scenario.WitnessClearanceLowerBound_deg;
record.Inputs = struct( ...
    "obstacles", obstacles, ...
    "initialState", initialState, ...
    "goalState", goalState, ...
    "limits", limits, ...
    "options", result.Options);
record.Scenario = scenario;
record.PlannerResult = result;
record.IndependentValidation = validation;
end

function record = emptyRecord()
% Define stable success/failure evidence for one HS3 seed.
record = struct( ...
    "RandomSeed", NaN, ...
    "Method", "", ...
    "Success", false, ...
    "IndependentValidationPassed", false, ...
    "TerminationReason", "", ...
    "SelectedMotionSource", "", ...
    "PlannerWallTime_s", NaN, ...
    "ArrivalTime_s", NaN, ...
    "WitnessClearanceLowerBound_deg", NaN, ...
    "Inputs", struct(), ...
    "Scenario", struct(), ...
    "PlannerResult", struct(), ...
    "IndependentValidation", validateAzElTrajectory());
end

function printRecord(record)
% Print concise evidence while retaining complete records in the report.
fprintf( ...
    "random=%d method=%s success=%d validation=%d wall_s=%.6f " + ...
    "arrival_s=%.6g witness_clearance_deg=%.6g reason=%s\n", ...
    record.RandomSeed, record.Method, record.Success, ...
    record.IndependentValidationPassed, record.PlannerWallTime_s, ...
    record.ArrivalTime_s, record.WitnessClearanceLowerBound_deg, ...
    record.TerminationReason);
end
