function report = benchmarkObstaclePlannerProfile( ...
        randomSeed, optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   report = benchmarkObstaclePlannerProfile()
%   report = benchmarkObstaclePlannerProfile(randomSeed)
%   report = benchmarkObstaclePlannerProfile(randomSeed, optionOverrides)
%**************************************************************************
% PURPOSE
%   - Profile one deterministic moving-polygon stress request after warmup.
%   - Report planner work counts without changing planner decisions.
%**************************************************************************
% INPUTS
%   - randomSeed (nonnegative integer scalar, optional; default 1011)
%       Selects the deterministic stress geometry.
%   - optionOverrides (scalar struct, optional; default struct())
%       .RunWarmup controls the unprofiled first run (default true).
%       .PrintProgress prints the stable counter summary (default true).
%       .StressOverrides is forwarded to the stress benchmark (default
%       struct()). Its PrintProgress field is forced false.
%**************************************************************************
% OUTPUTS
%   - report (scalar struct)
%       Contains controls, warmup and profiled records, profiler counters,
%       retained collision work, and the complete profiler information.
%**************************************************************************
% UNITS
%   - Runtime is seconds. Collision intervals and calls are counts.
%**************************************************************************

%% Section 1: Resolve Reproducible Controls

if nargin < 1 || isempty(randomSeed)
    randomSeed = 1011;
end
if nargin < 2 || isempty(optionOverrides)
    optionOverrides = struct();
end
validateattributes(randomSeed, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', 'nonnegative'});
defaults = struct( ...
    "RunWarmup", true, ...
    "PrintProgress", true, ...
    "StressOverrides", struct());
[options, unknownNames] = obstacleAvoidance.input.resolveOptions( ...
    defaults, optionOverrides);
if ~isempty(unknownNames)
    warning("benchmarkObstaclePlannerProfile:UnknownOptions", ...
        "Ignoring unknown fields: %s. No behavior changed.", ...
        strjoin(unknownNames, ", "));
end
options.RunWarmup = obstacleAvoidance.input.normalizeLogicalScalar( ...
    options.RunWarmup, "RunWarmup", ...
    "benchmarkObstaclePlannerProfile:InvalidRunWarmup");
options.PrintProgress = obstacleAvoidance.input.normalizeLogicalScalar( ...
    options.PrintProgress, "PrintProgress", ...
    "benchmarkObstaclePlannerProfile:InvalidPrintProgress");
if ~isstruct(options.StressOverrides) || ...
        ~isscalar(options.StressOverrides)
    error("benchmarkObstaclePlannerProfile:InvalidStressOverrides", ...
        "StressOverrides must be a scalar struct.");
end
options.StressOverrides.PrintProgress = false;

%% Section 2: Warm The Fixed Request

warmupRecord = struct();
if options.RunWarmup
    warmup = benchmarkRandomMovingPolygonStress( ...
        randomSeed, options.StressOverrides);
    warmupRecord = warmup.Records;
end

%% Section 3: Profile The Identical Request

profile clear;
profile on;
profileCleanup = onCleanup(@() profile("off"));
profiled = benchmarkRandomMovingPolygonStress( ...
    randomSeed, options.StressOverrides);
profile off;
delete(profileCleanup);
profileInformation = profile("info");
profiledRecord = profiled.Records;

%% Section 4: Assemble Stable Work Counters

functionTable = profileInformation.FunctionTable;
plannerResult = profiledRecord.PlannerResult;
grid = plannerResult.SearchDiagnostics.Grid;
seedSummaries = plannerResult.SeedSummaries;
if isempty(seedSummaries)
    retainedCollisionIntervalCount = ...
        plannerResult.Validation.CollisionIntervalCount;
    retainedUnresolvedIntervalCount = ...
        plannerResult.Validation.UnresolvedIntervalCount;
else
    retainedCollisionIntervalCount = ...
        sum([seedSummaries.CollisionIntervalCount]);
    retainedUnresolvedIntervalCount = ...
        sum([seedSummaries.UnresolvedIntervalCount]);
end
routeStateCount = fieldValueOrZero(grid, "HomologyStateCount");
expandedRouteStateCount = fieldValueOrZero(grid, "ExpandedCount");
counters = struct( ...
    "ValidationCallCount", exactCallCount( ...
    functionTable, "validateTrajectory>validateSampledHistory"), ...
    "ValidationTemplateCallCount", exactCallCount( ...
    functionTable, "validateTrajectory>createEmptyValidation"), ...
    "RetainedCollisionIntervalCount", retainedCollisionIntervalCount, ...
    "RetainedUnresolvedIntervalCount", retainedUnresolvedIntervalCount, ...
    "ShapeAtTimeCallCount", exactCallCount( ...
    functionTable, "shapeAtTime"), ...
    "PolyshapeConstructionCount", exactCallCount( ...
    functionTable, "polyshape.polyshape>polyshape.polyshape"), ...
    "OccupancyQueryCount", exactCallCount( ...
    functionTable, "queryObstacleOccupancyAtTime"), ...
    "RouteStateCount", routeStateCount, ...
    "ExpandedRouteStateCount", expandedRouteStateCount, ...
    "ConeprogCallCount", exactCallCount(functionTable, "coneprog"));
report = struct( ...
    "BenchmarkName", "obstaclePlannerProfile", ...
    "RandomSeed", double(randomSeed), ...
    "Options", options, ...
    "WarmupRecord", warmupRecord, ...
    "ProfiledRecord", profiledRecord, ...
    "Counters", counters, ...
    "ProfileInformation", profileInformation);
if options.PrintProgress
    printReport(report);
end
end

%% Section 5: Local Functions

function count = exactCallCount(functionTable, functionName)
% Count one profiler function without including local helper name matches.
names = string({functionTable.FunctionName});
matchingIndex = find(names == functionName);
if isempty(matchingIndex)
    count = 0;
else
    count = sum([functionTable(matchingIndex).NumCalls]);
end
end

function value = fieldValueOrZero(record, fieldName)
% Read one optional nonnegative search count from a diagnostic record.
value = 0;
if isstruct(record) && isscalar(record) && isfield(record, fieldName)
    value = double(record.(fieldName));
end
end

function printReport(report)
% Print enough evidence to compare a later identical profiler run.
record = report.ProfiledRecord;
counters = report.Counters;
fprintf( ...
    "seed=%d success=%s validation=%s wall_s=%.9f reason=%s\n", ...
    report.RandomSeed, logicalText(record.Success), ...
    logicalText(record.IndependentValidationPassed), ...
    record.PlannerWallTime_s, record.TerminationReason);
fprintf( ...
    "validation=%d collision_intervals=%d unresolved=%d " + ...
    "shape_at_time=%d polyshape=%d occupancy=%d route_states=%d " + ...
    "expanded_states=%d coneprog=%d\n", ...
    counters.ValidationCallCount, ...
    counters.RetainedCollisionIntervalCount, ...
    counters.RetainedUnresolvedIntervalCount, ...
    counters.ShapeAtTimeCallCount, ...
    counters.PolyshapeConstructionCount, ...
    counters.OccupancyQueryCount, counters.RouteStateCount, ...
    counters.ExpandedRouteStateCount, counters.ConeprogCallCount);
end

function text = logicalText(value)
% Render scalar logical benchmark status as true or false.
if logical(value)
    text = "true";
else
    text = "false";
end
end
