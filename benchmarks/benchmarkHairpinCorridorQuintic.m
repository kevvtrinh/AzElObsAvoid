function report = benchmarkHairpinCorridorQuintic( hairpinCount, benchmarkOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   report = benchmarkHairpinCorridorQuintic()
%   report = benchmarkHairpinCorridorQuintic(hairpinCount)
%   report = benchmarkHairpinCorridorQuintic( ...
%       hairpinCount, benchmarkOverrides)
%**************************************************************************
% PURPOSE
%   - Exercise compact C3/C4 motion through a deterministic alternating-end
%     maze that requires repeated near-180-degree turns.
%**************************************************************************
% INPUTS
%   - hairpinCount (positive integer scalar, optional; default 12)
%       Number of alternating horizontal walls; the path reverses lateral
%       direction between consecutive wall openings.
%   - benchmarkOverrides (scalar struct, optional; default struct())
%       .FigureVisible is "on" or "off" (default "off").
%       .PrintProgress is logical (default true).
%       .RandomSeed is a nonnegative integer (default 325).
%       .RouteVertexCount is an integer >= 2 or Inf (default Inf).
%**************************************************************************
% OUTPUTS
%   - report (scalar benchmark record)
%       Scenario inputs, geometric seed, candidate motion, independent
%       validation, stage timings, and an optional workspace figure.
%**************************************************************************
% UNITS
%   - Position and clearance are degrees; time is seconds; histories are
%     N-by-2 [azimuth elevation].
%**************************************************************************

%% Section 1: Resolve Controls

if nargin < 1 || isempty(hairpinCount)
    hairpinCount = 12;
end
if nargin < 2 || isempty(benchmarkOverrides)
    benchmarkOverrides = struct();
end
validateattributes(hairpinCount, {'numeric'}, {'real', 'finite', 'scalar', 'integer', 'positive'});
defaults = struct( "FigureVisible", "off", "PrintProgress", true, "RandomSeed", 325, "RouteVertexCount", Inf);
[controls, unknownNames] = azElInternal.resolveOptions( ...
    defaults, benchmarkOverrides);
if ~isempty(unknownNames)
    warning("benchmarkHairpinCorridorQuintic:UnknownOptions", ...
        "Ignoring unknown fields: %s. No behavior changed.", strjoin(unknownNames, ", "));
end
controls.FigureVisible = lower(string(controls.FigureVisible));
if ~isscalar(controls.FigureVisible) || ~any(controls.FigureVisible == ["on", "off"])
    error("benchmarkHairpinCorridorQuintic:InvalidVisibility", ...
        "FigureVisible must be scalar text equal to 'on' or 'off'.");
end
controls.PrintProgress = azElInternal.normalizeLogicalScalar( ...
    controls.PrintProgress, "PrintProgress", "benchmarkHairpinCorridorQuintic:InvalidPrintControl");
validateattributes(controls.RandomSeed, {'numeric'}, {'real', 'finite', 'scalar', 'integer', 'nonnegative'});
validateattributes(controls.RouteVertexCount, {'numeric'}, {'real', 'scalar', 'positive'});
if isfinite(controls.RouteVertexCount)
    validateattributes(controls.RouteVertexCount, {'numeric'}, {'integer', '>=', 2});
end

%% Section 2: Construct The Alternating-End Maze

wallSpacing_deg = 4;
wallHalfThickness_deg = 0.35;
workspaceHalfWidth_deg = 10;
openingInnerEdgeMagnitude_deg = 6.5;
safetyMargin_deg = 0.15;
bottomElevation_deg = 0;
topElevation_deg = wallSpacing_deg * (hairpinCount + 1);
obstacleCells = cell(hairpinCount, 1);

% Place each wall at the next elevation and alternate its opening to force repeated reversals.
for wallIndex = 1:hairpinCount
    wallElevation_deg = wallSpacing_deg * wallIndex;
    if mod(wallIndex, 2) == 1
        wallAzimuthInterval_deg = [ -workspaceHalfWidth_deg, openingInnerEdgeMagnitude_deg];
    else
        wallAzimuthInterval_deg = [ -openingInnerEdgeMagnitude_deg, workspaceHalfWidth_deg];
    end
    wallAzimuth_deg = wallAzimuthInterval_deg([1 2 2 1]).';
    wallElevationBoundary_deg = wallElevation_deg + wallHalfThickness_deg * [-1 -1 1 1].';
    obstacleCells{wallIndex} = makeAzElObstacleData( ...
        "alternating wall " + wallIndex, 0, wallAzimuth_deg, wallElevationBoundary_deg, safetyMargin_deg);
end
obstacles = [obstacleCells{:}].';
obstacles = azElInternal.obstacles.prepareDynamic(obstacles);
initialState = struct( ...
    "time_s", 0, "position_deg", [0, 0.5 * wallSpacing_deg], "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", 120 * (hairpinCount + 1), ...
    "position_deg", [0, topElevation_deg - 0.5 * wallSpacing_deg], ...
    "velocity_deg_s", [0 0], "acceleration_deg_s2", [0 0]);
limits = struct( ...
    "maxVelocity_deg_s", [2 2], ...
    "maxAcceleration_deg_s2", [1 1], ...
    "maxJerk_deg_s3", [2 2], ...
    "azimuthInterval_deg", [-workspaceHalfWidth_deg, ...
    workspaceHalfWidth_deg], "elevationInterval_deg", [bottomElevation_deg, topElevation_deg]);

%% Section 3: Generate One Maintained Topology Seed

plannerOptions = planAzElMotion();
plannerOptions.GoalTimeMode = "earliestArrival";
plannerOptions.MaximumSeedCount = 3;
plannerOptions.RandomSeed = controls.RandomSeed;
rng(controls.RandomSeed, "twister");
seedTimer = tic;
[seeds, seedDiagnostics] = azElInternal.generateTopologySeeds( ...
    obstacles, initialState, goalState, limits, plannerOptions);
seedGenerationTime_s = toc(seedTimer);
visibilitySeedIndex = find( [seeds.Source] == "visibilityGraph", 1, "first");
if isempty(visibilitySeedIndex)
    error("benchmarkHairpinCorridorQuintic:MissingVisibilitySeed", ...
        "The %d-wall maze produced no visibility-graph seed. " + ...
        "Nodes=%d, edges=%d, homology states=%d, expanded=%d, " + ...
        "truncated=%d, rejected transitions=%d, exhaustive=%d, " + ...
        "estimated work=%.0f, budget=%.0f.", ...
        hairpinCount, seedDiagnostics.NodeCount, ...
        seedDiagnostics.VisibilityEdgeCount, ...
        seedDiagnostics.HomologyStateCount, ...
        seedDiagnostics.ExpandedCount, ...
        seedDiagnostics.HomologySearchTruncated, ...
        seedDiagnostics.RejectedTransitionCount, ...
        seedDiagnostics.ExhaustiveVisibilityUsed, ...
        seedDiagnostics.EstimatedExhaustiveVisibilityWork, seedDiagnostics.VisibilityWorkBudget);
end
route_deg = seeds(visibilitySeedIndex).position_deg;
if controls.RouteVertexCount < size(route_deg, 1)
    error("benchmarkHairpinCorridorQuintic:RouteReductionRemoved", ...
        "Compact scaling uses all %d input-derived route vertices; " + ...
        "RouteVertexCount=%d would change the topology.", ...
        size(route_deg, 1), controls.RouteVertexCount);
end

%% Section 4: Construct And Independently Validate Motion

candidateTimer = tic;
[motion, compactDiagnostics] = ...
    azElPlannerMethods.corridor.internal.motion.solveCompactC3Candidate( ...
    seeds(visibilitySeedIndex), obstacles, initialState, goalState, ...
    limits, plannerOptions);
motion.OptimizerDiagnostics.CompactC3 = compactDiagnostics;
candidateWallTime_s = toc(candidateTimer);
validationTimer = tic;
validation = azElPlannerMethods.corridor.validateTrajectory( motion, obstacles, initialState, goalState, limits, plannerOptions);
validationTime_s = toc(validationTimer);

%% Section 5: Plot The Returned Evidence

figureHandle = gobjects(0);

if controls.FigureVisible == "on"
    figureHandle = figure( ...
        "Name", "Hairpin corridor quintic benchmark", ...
        "Visible", controls.FigureVisible, "Color", "w", "Position", [100 100 900 1000]);
    axesHandle = axes(figureHandle);
    hold(axesHandle, "on");
    grid(axesHandle, "on");
    box(axesHandle, "on");

    % Draw every protected wall separately while keeping obstacle patches out of the legend.
    for obstacleIndex = 1:numel(obstacles)
        patch(axesHandle, obstacles(obstacleIndex).az_deg{1}, ...
            obstacles(obstacleIndex).el_deg{1}, [0.85 0.25 0.2], ...
            "FaceAlpha", 0.3, "EdgeColor", [0.65 0.08 0.05], "HandleVisibility", "off");
    end
    plot(axesHandle, route_deg(:, 1), route_deg(:, 2), "--", ...
        "Color", [0.1 0.35 0.8], "DisplayName", "Visibility route");
    if ~isempty(motion.ReducedRoute_deg)
        plot(axesHandle, motion.ReducedRoute_deg(:, 1), ...
            motion.ReducedRoute_deg(:, 2), "o-", "Color", [0.55 0.1 0.7], "DisplayName", "Reduced route");
    end
    if motion.Success
        plot(axesHandle, motion.position_deg(:, 1), ...
            motion.position_deg(:, 2), "k-", "LineWidth", 2, "DisplayName", "Validated quintic motion");
    end
    plot(axesHandle, initialState.position_deg(1), ...
        initialState.position_deg(2), "go", "MarkerFaceColor", "g", "DisplayName", "Start");
    plot(axesHandle, goalState.position_deg(1), ...
        goalState.position_deg(2), "ro", "MarkerFaceColor", "r", "DisplayName", "Goal");
    xlabel(axesHandle, "Azimuth (deg)");
    ylabel(axesHandle, "Elevation (deg)");
    title(axesHandle, hairpinCount + "-wall hairpin maze: " + motion.TerminationReason);
    axis(axesHandle, "equal");
    xlim(axesHandle, limits.azimuthInterval_deg);
    ylim(axesHandle, limits.elevationInterval_deg);
    legend(axesHandle, "Location", "eastoutside");
end

%% Section 6: Assemble The Benchmark Record

report = struct( ...
    "BenchmarkName", "alternatingEndHairpinCorridor", ...
    "MotionMethod", "compactC3", ...
    "HairpinCount", hairpinCount, ...
    "Controls", controls, ...
    "Obstacles", obstacles, ...
    "InitialState", initialState, ...
    "GoalState", goalState, ...
    "Limits", limits, ...
    "PlannerOptions", plannerOptions, ...
    "Route_deg", route_deg, ...
    "SeedDiagnostics", seedDiagnostics, ...
    "Motion", motion, ...
    "CompactDiagnostics", compactDiagnostics, ...
    "IndependentValidation", validation, ...
    "SeedGenerationTime_s", seedGenerationTime_s, ...
    "CandidateWallTime_s", candidateWallTime_s, "ValidationTime_s", validationTime_s, "FigureHandle", figureHandle);
if controls.PrintProgress
    fprintf( ...
        "hairpins=%d route=%d->%d success=%d validation=%d " + ...
        "certificate=%d duration_s=%.12g clearance_deg=%.12g " + ...
        "candidate_s=%.12g reason=%s\n", ...
        hairpinCount, size(route_deg, 1), ...
        size(motion.ReducedRoute_deg, 1), motion.Success, ...
        validation.Passed, ...
        validation.SeedCorridorCertified, ...
        motion.MotionDuration_s, validation.MinimumClearance_deg, candidateWallTime_s, motion.TerminationReason);
end
end
