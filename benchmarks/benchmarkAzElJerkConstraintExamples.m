function record = extractRunRecord( ...
        result, catalogEntry, jerkConstrained, repetitionIndex, ...
        executionOrder, wallTime_s)
%% Section 0: Header & Readme
% SYNTAX
%   record = extractRunRecord(result, catalogEntry, jerkConstrained, ...
%       repetitionIndex, executionOrder, wallTime_s)
%**************************************************************************
% PURPOSE
%   - Extract compact performance, path, kinematic, and solver metrics.
%**************************************************************************
% INPUTS
%   - result (scalar planner-result struct)
%       Successful example output.
%   - catalogEntry (scalar catalog struct)
%       Example provenance and invocation.
%   - jerkConstrained (logical scalar)
%       Executed jerk mode.
%   - repetitionIndex, executionOrder (positive integer scalars)
%       Benchmark ordering metadata.
%   - wallTime_s (nonnegative scalar)
%       End-to-end example runtime.
%**************************************************************************
% OUTPUTS
%   - record (scalar struct)
%       One stable raw benchmark row.
%**************************************************************************
% UNITS
%   - Physical field names carry seconds and degree-based units.
%**************************************************************************
timedPath = result.timedSlopePath;
diagnostics = timedPath.ConstraintDiagnostics;
candidateCount = height(result.candidateDiagnostics);
feasibleCandidateCount = nnz( ...
    result.candidateDiagnostics.Retimed & ...
    result.candidateDiagnostics.CollisionFree);
selectedRouteLength_deg = polylineLength(result.selectedRoute_deg);
smoothPathLength_deg = NaN;
if isstruct(result.smoothPath) && isfield(result.smoothPath, "TotalLength_deg")
    smoothPathLength_deg = result.smoothPath.TotalLength_deg;
end
record = emptyRunRecord();
record.Example = catalogEntry.Name;
record.Invocation = catalogEntry.Invocation;
record.JerkConstrained = logical(jerkConstrained);
record.Repetition = repetitionIndex;
record.ExecutionOrder = executionOrder;
record.Success = logical(result.Success);
record.ExampleValidationPassed = ...
    logical(result.ExampleValidation.Passed);
record.StrictTimeBase = all(diff(timedPath.time_s) > 0);
record.InputIdentityVerified = false;
record.TerminationReason = string(result.TerminationReason);
record.WallTime_s = wallTime_s;
record.FinalPlannerElapsedTime_s = result.ElapsedPlanningTime_s;
record.ArrivalTime_s = result.goalLineInterceptTime_s;
record.MinimumMotionDuration_s = timedPath.MinimumMotionDuration_s;
record.WaitDuration_s = timedPath.WaitDuration_s;
record.SelectedRouteLength_deg = selectedRouteLength_deg;
record.SmoothPathLength_deg = smoothPathLength_deg;
record.SampleCount = numel(timedPath.time_s);
record.PeakVelocityByAxis_deg_s = ...
    max(abs(timedPath.velocity_deg_s), [], 1);
record.PeakAccelerationByAxis_deg_s2 = ...
    max(abs(timedPath.acceleration_deg_s2), [], 1);
record.PeakJerkByAxis_deg_s3 = finiteColumnPeak(timedPath.jerk_deg_s3);
record.CandidateRouteCount = candidateCount;
record.FeasibleCandidateCount = feasibleCandidateCount;
record.SelectedCandidateIndex = result.selectedCandidateIndex;
record.RetimerType = string(timedPath.RetimerType);
record.TimeOptimizationAttempted = logical(fieldOrDefault( ...
    diagnostics, "TimeOptimizationAttempted", false));
record.TimeOptimizationSucceeded = logical(fieldOrDefault( ...
    diagnostics, "TimeOptimizationSucceeded", false));
record.TimeOptimizationIterationCount = fieldOrDefault( ...
    diagnostics, "TimeOptimizationIterationCount", 0);
record.TimeOptimizationFunctionCount = fieldOrDefault( ...
    diagnostics, "TimeOptimizationFunctionCount", 0);
end

