function peak = finiteColumnPeak(values)
%% Section 0: Header & Readme
% SYNTAX
%   peak = finiteColumnPeak(values)
%**************************************************************************
% PURPOSE
%   - Return each column's largest finite absolute value.
%**************************************************************************
% INPUTS
%   - values (numeric matrix)
%       Samples arranged by row, with one measured axis per column.
%**************************************************************************
% OUTPUTS
%   - peak (1-by-N numeric row vector)
%       Per-column peak, or NaN when a column has no finite samples.
%**************************************************************************
% UNITS
%   - Output units match the corresponding input column.
%**************************************************************************
values = abs(double(values));
peak = NaN(1, size(values, 2));
for columnIndex = 1:size(values, 2)
    finiteValues = values(isfinite(values(:, columnIndex)), columnIndex);
    if ~isempty(finiteValues)
        peak(columnIndex) = max(finiteValues);
    end
end
end

function length_deg = polylineLength(position_deg)
%% Section 0: Header & Readme
% SYNTAX
%   length_deg = polylineLength(position_deg)
%**************************************************************************
% PURPOSE
%   - Compute the Euclidean length of an azimuth/elevation polyline.
%**************************************************************************
% INPUTS
%   - position_deg (N-by-2 numeric matrix)
%       Ordered [azimuth elevation] vertices.
%**************************************************************************
% OUTPUTS
%   - length_deg (nonnegative numeric scalar)
%       Sum of Euclidean segment lengths.
%**************************************************************************
% UNITS
%   - Position and returned length are degrees.
%**************************************************************************
if size(position_deg, 1) < 2
    length_deg = 0;
    return;
end
length_deg = sum(vecnorm(diff(double(position_deg), 1, 1), 2, 2));
end

function value = fieldOrDefault(structure, fieldName, defaultValue)
%% Section 0: Header & Readme
% SYNTAX
%   value = fieldOrDefault(structure, fieldName, defaultValue)
%**************************************************************************
% PURPOSE
%   - Read one optional nonempty field while preserving a stable fallback.
%**************************************************************************
% INPUTS
%   - structure (scalar struct or other value)
%       Candidate diagnostics structure.
%   - fieldName (string scalar or character vector)
%       Field to read when present and nonempty.
%   - defaultValue (any value)
%       Value returned when the requested field is unavailable.
%**************************************************************************
% OUTPUTS
%   - value (any value)
%       Requested field value or the supplied default.
%**************************************************************************
% UNITS
%   - Units are inherited from the requested field or default value.
%**************************************************************************
value = defaultValue;
if isstruct(structure) && isfield(structure, fieldName) && ...
        ~isempty(structure.(fieldName))
    value = structure.(fieldName);
end
end

function summaryTable = summarizeRuns(runTable, catalog)
%% Section 0: Header & Readme
% SYNTAX
%   summaryTable = summarizeRuns(runTable, catalog)
%**************************************************************************
% PURPOSE
%   - Summarize repeated runtime and motion metrics by example and mode.
%**************************************************************************
% INPUTS
%   - runTable (table)
%       One row per completed benchmark execution.
%   - catalog (structure array)
%       Ordered shared-example catalog.
%**************************************************************************
% OUTPUTS
%   - summaryTable (table)
%       Median runtime and motion metrics plus aggregate pass status.
%**************************************************************************
% UNITS
%   - Field names carry seconds and degree-based units where applicable.
%**************************************************************************
template = struct( ...
    "Example", "", ...
    "JerkConstrained", false, ...
    "RunCount", 0, ...
    "MedianWallTime_s", NaN, ...
    "MinimumWallTime_s", NaN, ...
    "MaximumWallTime_s", NaN, ...
    "MedianFinalPlannerElapsedTime_s", NaN, ...
    "MedianArrivalTime_s", NaN, ...
    "MedianMotionDuration_s", NaN, ...
    "MedianSelectedRouteLength_deg", NaN, ...
    "MedianSmoothPathLength_deg", NaN, ...
    "AllRunsPassed", false);
summaries = repmat(template, 2 * numel(catalog), 1);
summaryIndex = 0;
for exampleIndex = 1:numel(catalog)
    for jerkConstrained = [false true]
        summaryIndex = summaryIndex + 1;
        selectedRows = runTable.Example == catalog(exampleIndex).Name & ...
            runTable.JerkConstrained == jerkConstrained;
        selected = runTable(selectedRows, :);
        summaries(summaryIndex) = struct( ...
            "Example", catalog(exampleIndex).Name, ...
            "JerkConstrained", logical(jerkConstrained), ...
            "RunCount", height(selected), ...
            "MedianWallTime_s", median(selected.WallTime_s), ...
            "MinimumWallTime_s", min(selected.WallTime_s), ...
            "MaximumWallTime_s", max(selected.WallTime_s), ...
            "MedianFinalPlannerElapsedTime_s", ...
                median(selected.FinalPlannerElapsedTime_s), ...
            "MedianArrivalTime_s", median(selected.ArrivalTime_s), ...
            "MedianMotionDuration_s", ...
                median(selected.MinimumMotionDuration_s), ...
            "MedianSelectedRouteLength_deg", ...
                median(selected.SelectedRouteLength_deg), ...
            "MedianSmoothPathLength_deg", ...
                median(selected.SmoothPathLength_deg), ...
            "AllRunsPassed", all(selected.Success & ...
                selected.ExampleValidationPassed & ...
                selected.StrictTimeBase & ...
                selected.InputIdentityVerified));
    end
end
summaryTable = struct2table(summaries);
end

function comparisonTable = compareModeSummaries(summaryTable, catalog)
%% Section 0: Header & Readme
% SYNTAX
%   comparisonTable = compareModeSummaries(summaryTable, catalog)
%**************************************************************************
% PURPOSE
%   - Put paired no-jerk and finite-jerk metrics on one row per example.
%**************************************************************************
% INPUTS
%   - summaryTable (table)
%       Per-example, per-mode benchmark summaries.
%   - catalog (structure array)
%       Ordered shared-example catalog.
%**************************************************************************
% OUTPUTS
%   - comparisonTable (table)
%       Runtime, arrival, path-length, and pass comparisons by example.
%**************************************************************************
% UNITS
%   - Field names carry seconds and degree-based units; ratios are unitless.
%**************************************************************************
template = struct( ...
    "Example", "", ...
    "NoJerkWallTime_s", NaN, ...
    "JerkWallTime_s", NaN, ...
    "JerkToNoJerkRuntimeRatio", NaN, ...
    "NoJerkArrivalTime_s", NaN, ...
    "JerkArrivalTime_s", NaN, ...
    "JerkArrivalDelay_s", NaN, ...
    "JerkToNoJerkArrivalRatio", NaN, ...
    "NoJerkMotionDuration_s", NaN, ...
    "JerkMotionDuration_s", NaN, ...
    "NoJerkSmoothPathLength_deg", NaN, ...
    "JerkSmoothPathLength_deg", NaN, ...
    "SmoothPathLengthDelta_deg", NaN, ...
    "BothModesPassed", false);
comparisons = repmat(template, numel(catalog), 1);
for exampleIndex = 1:numel(catalog)
    exampleRows = summaryTable.Example == catalog(exampleIndex).Name;
    noJerk = summaryTable(exampleRows & ...
        ~summaryTable.JerkConstrained, :);
    jerk = summaryTable(exampleRows & summaryTable.JerkConstrained, :);
    comparisons(exampleIndex) = struct( ...
        "Example", catalog(exampleIndex).Name, ...
        "NoJerkWallTime_s", noJerk.MedianWallTime_s, ...
        "JerkWallTime_s", jerk.MedianWallTime_s, ...
        "JerkToNoJerkRuntimeRatio", ...
            jerk.MedianWallTime_s / noJerk.MedianWallTime_s, ...
        "NoJerkArrivalTime_s", noJerk.MedianArrivalTime_s, ...
        "JerkArrivalTime_s", jerk.MedianArrivalTime_s, ...
        "JerkArrivalDelay_s", ...
            jerk.MedianArrivalTime_s - noJerk.MedianArrivalTime_s, ...
        "JerkToNoJerkArrivalRatio", ...
            jerk.MedianArrivalTime_s / noJerk.MedianArrivalTime_s, ...
        "NoJerkMotionDuration_s", noJerk.MedianMotionDuration_s, ...
        "JerkMotionDuration_s", jerk.MedianMotionDuration_s, ...
        "NoJerkSmoothPathLength_deg", ...
            noJerk.MedianSmoothPathLength_deg, ...
        "JerkSmoothPathLength_deg", jerk.MedianSmoothPathLength_deg, ...
        "SmoothPathLengthDelta_deg", ...
            jerk.MedianSmoothPathLength_deg - ...
            noJerk.MedianSmoothPathLength_deg, ...
        "BothModesPassed", ...
            noJerk.AllRunsPassed && jerk.AllRunsPassed);
end
comparisonTable = struct2table(comparisons);
end

function referenceTable = catalogReferenceTable(catalog)
