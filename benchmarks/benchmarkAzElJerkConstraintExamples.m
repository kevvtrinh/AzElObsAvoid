function [result, wallTime_s] = runExampleWithFigureCleanup( ...
        catalogEntry, exampleOptions)
%% Section 0: Header & Readme
% SYNTAX
%   [result, wallTime_s] = runExampleWithFigureCleanup( ...
%       catalogEntry, exampleOptions)
%**************************************************************************
% PURPOSE
%   - Time one complete example call and close only figures it creates.
%**************************************************************************
% INPUTS
%   - catalogEntry (scalar catalog struct)
%       Entry containing the example function handle.
%   - exampleOptions (scalar struct)
%       Identical headless planner controls plus the selected jerk mode.
%**************************************************************************
% OUTPUTS
%   - result (scalar planner-result struct)
%       Complete example output.
%   - wallTime_s (nonnegative scalar)
%       End-to-end example runtime.
%**************************************************************************
% UNITS
%   - Wall time is seconds.
%**************************************************************************
existingFigures = findall(groot, "Type", "figure");
figureCleanup = onCleanup(@() closeNewFigures(existingFigures));
startTime = tic;
result = catalogEntry.Run(exampleOptions);
wallTime_s = toc(startTime);
clear figureCleanup;
end

function closeNewFigures(existingFigures)
%% Section 0: Header & Readme
% SYNTAX
%   closeNewFigures(existingFigures)
%**************************************************************************
% PURPOSE
%   - Close benchmark-created figures without disturbing prior user figures.
%**************************************************************************
% INPUTS
%   - existingFigures (graphics-handle array)
%       Figures that existed before the benchmarked example call.
%**************************************************************************
% OUTPUTS
%   - None.
%**************************************************************************
% UNITS
%   - Graphics handles are dimensionless.
%**************************************************************************
currentFigures = findall(groot, "Type", "figure");
for figureIndex = 1:numel(currentFigures)
    wasAlreadyOpen = any(currentFigures(figureIndex) == existingFigures);
    if ~wasAlreadyOpen && isgraphics(currentFigures(figureIndex))
        close(currentFigures(figureIndex));
    end
end
end

function validateBenchmarkResult(result, exampleName, jerkConstrained)
%% Section 0: Header & Readme
% SYNTAX
%   validateBenchmarkResult(result, exampleName, jerkConstrained)
%**************************************************************************
% PURPOSE
%   - Require success, validation, strict time, and the requested jerk mode.
%**************************************************************************
% INPUTS
%   - result (scalar planner-result struct)
%       Completed example output.
%   - exampleName (scalar text)
%       Scenario name used in failure diagnostics.
%   - jerkConstrained (logical scalar)
%       Expected finite-jerk state.
%**************************************************************************
% OUTPUTS
%   - None. An invalid benchmark run raises an identified error.
%**************************************************************************
% UNITS
%   - Trajectory time is seconds; mode controls are dimensionless.
%**************************************************************************
hasValidation = isfield(result, "ExampleValidation") && ...
    isstruct(result.ExampleValidation) && ...
    isfield(result.ExampleValidation, "Passed") && ...
    result.ExampleValidation.Passed;
hasStrictTime = isfield(result, "timedSlopePath") && ...
    numel(result.timedSlopePath.time_s) >= 2 && ...
    all(isfinite(result.timedSlopePath.time_s)) && ...
    all(diff(result.timedSlopePath.time_s) > 0);
modeMatches = isfield(result.timedSlopePath, "ConstraintDiagnostics") && ...
    logical(result.timedSlopePath.ConstraintDiagnostics.JerkConstrained) == ...
    logical(jerkConstrained);
if ~result.Success || ~hasValidation || ~hasStrictTime || ~modeMatches
    error("benchmarkAzElJerkConstraintExamples:ExampleFailed", ...
        "%s failed in jerk=%d mode: %s", ...
        exampleName, jerkConstrained, string(result.Message));
end
end

function snapshot = extractInputSnapshot(result, catalogEntry)
%% Section 0: Header & Readme
% SYNTAX
%   snapshot = extractInputSnapshot(result, catalogEntry)
%**************************************************************************
% PURPOSE
%   - Retain caller-visible request data needed for strict pair comparison.
%**************************************************************************
% INPUTS
%   - result (scalar planner-result struct)
%       Successful example output echoing resolved inputs.
%   - catalogEntry (scalar catalog struct)
%       Intercept comparison policy for this example.
%**************************************************************************
% OUTPUTS
%   - snapshot (scalar struct)
%       Obstacles, states, non-jerk limits, options, and jerk provenance.
%**************************************************************************
% UNITS
%   - Snapshot fields retain their documented planner units.
%**************************************************************************
limitsExceptJerk = result.limits;
if isfield(limitsExceptJerk, "maxJerk_deg_s3")
    limitsExceptJerk = rmfield(limitsExceptJerk, "maxJerk_deg_s3");
end
targetMotion = struct();
interceptOptions = struct();
if catalogEntry.IsIntercept
    targetMotion = result.TargetMotion;
    interceptOptions = result.InterceptOptions;
end
snapshot = struct( ...
    "AzElData", result.azElData, ...
    "InitialState", result.initialState, ...
    "GoalState", result.goalState, ...
    "LimitsExceptJerk", limitsExceptJerk, ...
    "PlannerOptions", result.Options, ...
    "TargetMotion", targetMotion, ...
    "InterceptOptions", interceptOptions, ...
    "ConfiguredFiniteJerk_deg_s3", ...
        result.ExampleConfiguration.ConfiguredFiniteMaxJerk_deg_s3, ...
    "AppliedJerkLimit_deg_s3", result.limits.maxJerk_deg_s3);
end

function check = comparePairedInputs( ...
        noJerk, jerk, catalogEntry, repetitionIndex)
%% Section 0: Header & Readme
% SYNTAX
%   check = comparePairedInputs( ...
%       noJerk, jerk, catalogEntry, repetitionIndex)
%**************************************************************************
% PURPOSE
%   - Prove the pair differs only in finite-versus-infinite applied jerk.
%**************************************************************************
% INPUTS
%   - noJerk, jerk (scalar snapshot structs)
%       Resolved input snapshots for both modes.
%   - catalogEntry (scalar catalog struct)
%       Goal comparison policy for this example.
%   - repetitionIndex (positive integer scalar)
%       Repetition associated with the pair.
%**************************************************************************
% OUTPUTS
%   - check (scalar struct)
%       Per-input equality flags and aggregate Passed status.
%**************************************************************************
% UNITS
%   - Equality flags and repetition indices are dimensionless.
%**************************************************************************
obstaclesEqual = isequaln(noJerk.AzElData, jerk.AzElData);
initialStateEqual = isequaln(noJerk.InitialState, jerk.InitialState);
if catalogEntry.IsIntercept
    goalOrInterceptRequestEqual = ...
        isequaln(noJerk.TargetMotion, jerk.TargetMotion) && ...
        isequaln(noJerk.InterceptOptions, jerk.InterceptOptions);
    if ~catalogEntry.GoalIsDerived
        goalOrInterceptRequestEqual = goalOrInterceptRequestEqual && ...
            isequaln(noJerk.GoalState, jerk.GoalState);
    end
else
    goalOrInterceptRequestEqual = ...
        isequaln(noJerk.GoalState, jerk.GoalState);
end
limitsExceptJerkEqual = isequaln( ...
    noJerk.LimitsExceptJerk, jerk.LimitsExceptJerk);
plannerOptionsEqual = isequaln( ...
    noJerk.PlannerOptions, jerk.PlannerOptions);
configuredFiniteJerkEqual = isequaln( ...
    noJerk.ConfiguredFiniteJerk_deg_s3, ...
    jerk.ConfiguredFiniteJerk_deg_s3);
onlyJerkLimitDiffers = ...
    all(isinf(noJerk.AppliedJerkLimit_deg_s3)) && ...
    isequaln(jerk.AppliedJerkLimit_deg_s3, ...
        jerk.ConfiguredFiniteJerk_deg_s3) && ...
    all(isfinite(jerk.AppliedJerkLimit_deg_s3));
passed = obstaclesEqual && initialStateEqual && ...
    goalOrInterceptRequestEqual && limitsExceptJerkEqual && ...
    plannerOptionsEqual && configuredFiniteJerkEqual && ...
    onlyJerkLimitDiffers;
check = struct( ...
    "Example", catalogEntry.Name, ...
    "Repetition", repetitionIndex, ...
    "ObstaclesEqual", obstaclesEqual, ...
    "InitialStateEqual", initialStateEqual, ...
    "GoalOrInterceptRequestEqual", goalOrInterceptRequestEqual, ...
    "LimitsExceptJerkEqual", limitsExceptJerkEqual, ...
    "PlannerOptionsEqual", plannerOptionsEqual, ...
    "ConfiguredFiniteJerkEqual", configuredFiniteJerkEqual, ...
    "OnlyJerkLimitDiffers", onlyJerkLimitDiffers, ...
    "Passed", passed);
end

