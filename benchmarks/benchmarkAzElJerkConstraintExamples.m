function report = benchmarkAzElJerkConstraintExamples(optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   report = benchmarkAzElJerkConstraintExamples()
%   report = benchmarkAzElJerkConstraintExamples(optionOverrides)
%**************************************************************************
% PURPOSE
%   - Benchmark every maintained example shared with the reference main
%     revision using finite-jerk and unconstrained-jerk retiming.
%   - Prove that each paired run uses identical obstacle, state, limit, and
%     planner inputs except for limits.maxJerk_deg_s3.
%   - Compare complete planner modes. Finite jerk can change geometric
%     smoothing and candidate selection, so this is not an isolated retimer
%     comparison on one fixed path.
%**************************************************************************
% INPUTS
%   - optionOverrides (scalar struct, optional; default struct())
%       .RepetitionCount is a positive integer (default 1).
%       .RunWarmup is logical or binary numeric (default true).
%       .Verbose is logical or binary numeric (default true).
%**************************************************************************
% OUTPUTS
%   - report (scalar struct)
%       Reference revision, environment, strict paired-input checks, raw
%       runs, summaries, and jerk-versus-no-jerk comparisons. A corrupt
%       input pair or failed example raises an identified benchmark error.
%**************************************************************************
% UNITS
%   - Position and path length are degrees. Time is seconds. Velocity,
%     acceleration, and jerk use deg/s, deg/s^2, and deg/s^3 by axis.
%**************************************************************************

%% Section 1: Resolve Benchmark Controls
if nargin < 1 || isempty(optionOverrides)
    optionOverrides = struct();
end
options = resolveBenchmarkOptions(optionOverrides);
benchmarkFile = mfilename("fullpath");
repositoryRoot = fileparts(fileparts(benchmarkFile));
originalPath = path;
pathCleanup = onCleanup(@() path(originalPath));
addpath(repositoryRoot, fullfile(repositoryRoot, "examples"));

catalog = sharedExampleCatalog();
commonExampleOptions = struct( ...
    "FigureVisible", "off", ...
    "ShowAnimation", false, ...
    "ShowKinematicPlot", false, ...
    "ShowSweptSurfaces", false, ...
    "Verbose", false, ...
    "UseParallel", "off");

%% Section 2: Warm Up The Shared Execution Path
if options.RunWarmup
    warmupCatalog = catalog(end);
    for enableJerkConstraint = [false true]
        warmupOptions = commonExampleOptions;
        warmupOptions.EnableJerkConstraint = enableJerkConstraint;
        [warmupResult, ~] = runExampleWithFigureCleanup( ...
            warmupCatalog, warmupOptions);
        validateBenchmarkResult( ...
            warmupResult, warmupCatalog.Name, enableJerkConstraint);
        clear warmupResult;
    end
end

%% Section 3: Run Paired Shared Examples
maximumRunCount = numel(catalog) * options.RepetitionCount * 2;
runs = repmat(emptyRunRecord(), maximumRunCount, 1);
inputChecks = repmat(emptyInputCheckRecord(), ...
    numel(catalog) * options.RepetitionCount, 1);
runCount = 0;
inputCheckCount = 0;
for repetitionIndex = 1:options.RepetitionCount
    for exampleIndex = 1:numel(catalog)
        if mod(exampleIndex + repetitionIndex, 2) == 0
            jerkExecutionOrder = [false true];
        else
            jerkExecutionOrder = [true false];
        end
        pairedSnapshots = cell(1, 2);
        pairedRunIndices = zeros(1, 2);
        for orderIndex = 1:2
            enableJerkConstraint = jerkExecutionOrder(orderIndex);
            exampleOptions = commonExampleOptions;
            exampleOptions.EnableJerkConstraint = enableJerkConstraint;
            [result, wallTime_s] = runExampleWithFigureCleanup( ...
                catalog(exampleIndex), exampleOptions);
            validateBenchmarkResult(result, catalog(exampleIndex).Name, ...
                enableJerkConstraint);

            runCount = runCount + 1;
            runs(runCount) = extractRunRecord( ...
                result, catalog(exampleIndex), enableJerkConstraint, ...
                repetitionIndex, orderIndex, wallTime_s);
            modeStorageIndex = 1 + double(enableJerkConstraint);
            pairedSnapshots{modeStorageIndex} = extractInputSnapshot( ...
                result, catalog(exampleIndex));
            pairedRunIndices(modeStorageIndex) = runCount;
            if options.Verbose
                fprintf( ...
                    "[%d/%d] %s | jerk=%d | wall %.3f s | " + ...
                    "arrival %.6f s | %s\n", ...
                    runCount, maximumRunCount, catalog(exampleIndex).Name, ...
                    enableJerkConstraint, wallTime_s, ...
                    result.goalLineInterceptTime_s, ...
                    string(result.timedSlopePath.RetimerType));
            end
            clear result;
        end

        inputCheckCount = inputCheckCount + 1;
        inputChecks(inputCheckCount) = comparePairedInputs( ...
            pairedSnapshots{1}, pairedSnapshots{2}, ...
            catalog(exampleIndex), repetitionIndex);
        if ~inputChecks(inputCheckCount).Passed
            error("benchmarkAzElJerkConstraintExamples:InputMismatch", ...
                "Paired inputs differ beyond maxJerk_deg_s3 for %s.", ...
                catalog(exampleIndex).Name);
        end
        for pairedModeIndex = 1:2
            runs(pairedRunIndices(pairedModeIndex)).InputIdentityVerified = ...
                true;
        end
    end
end
runs = runs(1:runCount);
inputChecks = inputChecks(1:inputCheckCount);

%% Section 4: Summarize Timing And Motion Differences
runTable = struct2table(runs);
inputCheckTable = struct2table(inputChecks);
summaryTable = summarizeRuns(runTable, catalog);
pairComparison = compareModeSummaries(summaryTable, catalog);
referenceExamples = catalogReferenceTable(catalog);
allRunsPassed = all(runTable.Success & ...
    runTable.ExampleValidationPassed & runTable.StrictTimeBase & ...
    runTable.InputIdentityVerified);
allInputsPassed = all(inputCheckTable.Passed);

%% Section 5: Assemble Reproducible Report
report = struct( ...
    "BenchmarkName", "Shared example jerk-constraint benchmark", ...
    "Timestamp", datetime("now", "TimeZone", "local"), ...
    "MATLABRelease", string(version('-release')), ...
    "MATLABVersion", string(version), ...
    "Platform", string(computer), ...
    "MATLABCoreCount", feature("numcores"), ...
    "OptimizationAvailable", optimizationIsAvailable(), ...
    "ImplementationBaseRevision", ...
        "a79d1bf868f5029ac96777f474082e5443596370", ...
    "ImplementationState", ...
        "Current worktree including the benchmarked feature changes", ...
    "ReferenceRepository", ...
        "https://github.com/kevvtrinh/AzElObsAvoid", ...
    "ReferenceBranch", "main", ...
    "ReferenceRevision", ...
        "d25a0e840772c1d243b9c2aa59c25163150e7257", ...
    "ReferenceAudit", ...
        "Upstream scenario provenance was audited statically. " + ...
        "This benchmark executes the current worktree only.", ...
    "InputNormalizationPolicy", ...
        "Both modes use origin/main's finite-jerk physical horizon; " + ...
        "headless display options are identical and only maxJerk changes.", ...
    "ReferenceExamples", referenceExamples, ...
    "RepetitionCount", options.RepetitionCount, ...
    "TimingIsIndicative", options.RepetitionCount < 3, ...
    "TimingInterpretation", ...
        "One-repetition wall ratios are order/cache sensitive; use at " + ...
        "least three repetitions for runtime conclusions.", ...
    "ComparisonScope", ...
        "Complete planner modes; smoothing and selected path may differ.", ...
    "WarmupExecuted", options.RunWarmup, ...
    "CommonExampleOptions", commonExampleOptions, ...
    "ExecutionOrder", runTable(:, [ ...
        "Example" "JerkConstrained" "Repetition" "ExecutionOrder"]), ...
    "InputChecks", inputCheckTable, ...
    "Runs", runTable, ...
    "Summary", summaryTable, ...
    "PairComparison", pairComparison, ...
    "Passed", allRunsPassed && allInputsPassed);

if options.Verbose
    fprintf("\nPaired input checks: %d/%d passed.\n", ...
        nnz(inputCheckTable.Passed), height(inputCheckTable));
    disp(pairComparison(:, [ ...
        "Example" "NoJerkWallTime_s" "JerkWallTime_s" ...
        "JerkToNoJerkRuntimeRatio" "NoJerkArrivalTime_s" ...
        "JerkArrivalTime_s" "JerkArrivalDelay_s"]));
end
if ~report.Passed
    error("benchmarkAzElJerkConstraintExamples:BenchmarkFailed", ...
        "At least one shared example or paired-input check failed.");
end
clear pathCleanup;
end

%% Section 6: Local Functions
function options = resolveBenchmarkOptions(optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = resolveBenchmarkOptions(optionOverrides)
%**************************************************************************
% PURPOSE
%   - Resolve the small benchmark control surface and reject ambiguity.
%**************************************************************************
% INPUTS
%   - optionOverrides (scalar struct)
%       Optional nonempty benchmark controls already defaulted by the caller.
%**************************************************************************
% OUTPUTS
%   - options (scalar struct)
%       Validated RepetitionCount, RunWarmup, and Verbose values.
%**************************************************************************
% UNITS
%   - RepetitionCount is dimensionless.
%**************************************************************************
defaults = struct( ...
    "RepetitionCount", 1, ...
    "RunWarmup", true, ...
    "Verbose", true);
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("benchmarkAzElJerkConstraintExamples:InvalidOptions", ...
        "optionOverrides must be a scalar struct.");
end
unknownFields = setdiff( ...
    fieldnames(optionOverrides), fieldnames(defaults), "stable");
if ~isempty(unknownFields)
    warning("benchmarkAzElJerkConstraintExamples:UnknownOptions", ...
        "Ignoring unknown option fields: %s.", ...
        strjoin(string(unknownFields), ", "));
    optionOverrides = rmfield(optionOverrides, unknownFields);
end
options = defaults;
overrideNames = fieldnames(optionOverrides);
for fieldIndex = 1:numel(overrideNames)
    fieldName = overrideNames{fieldIndex};
    if ~isempty(optionOverrides.(fieldName))
        options.(fieldName) = optionOverrides.(fieldName);
    end
end
validateattributes(options.RepetitionCount, {'numeric'}, ...
    {'real','finite','scalar','integer','positive'});
options.RunWarmup = benchmarkLogicalScalar( ...
    options.RunWarmup, "RunWarmup");
options.Verbose = benchmarkLogicalScalar(options.Verbose, "Verbose");
end

function value = benchmarkLogicalScalar(value, fieldName)
%% Section 0: Header & Readme
% SYNTAX
%   value = benchmarkLogicalScalar(value, fieldName)
%**************************************************************************
% PURPOSE
%   - Normalize one logical-or-binary-numeric benchmark option.
%**************************************************************************
% INPUTS
%   - value (logical or numeric scalar)
%       Candidate control value.
%   - fieldName (scalar text)
%       Field name used in an actionable validation error.
%**************************************************************************
% OUTPUTS
%   - value (logical scalar)
%       Normalized control.
%**************************************************************************
% UNITS
%   - All values are dimensionless.
%**************************************************************************
validateattributes(value, {'logical','numeric'}, ...
    {'real','finite','scalar'});
if isnumeric(value) && value ~= 0 && value ~= 1
    error("benchmarkAzElJerkConstraintExamples:InvalidLogicalOption", ...
        "%s must be logical or numeric 0 or 1.", fieldName);
end
value = logical(value);
end

