        [0 -0.1], [0.5 0], [0 -0.2], [0.5 0], [5 3.5], [4 1], ...
        [5 1000], [-1000 1000; -1000 1000], []), ...
    createCase("case 16 reordered", [-10 -10], [200 21], [-2 -2], ...
        [-21 21], [-1 -1], [-5 5], [60 60], [5 5], [1 1], ...
        [-1000 1000; -1000 1000], [])};
