function report = benchmarkOrganicObstacleRobustness( ...
        randomSeeds, benchmarkOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   report = benchmarkOrganicObstacleRobustness()
%   report = benchmarkOrganicObstacleRobustness(randomSeeds)
%   report = benchmarkOrganicObstacleRobustness( ...
%       randomSeeds, benchmarkOverrides)
%**************************************************************************
% PURPOSE
%   - Compare compact quintic and standalone HS3 planning on deterministic
%     rough U shapes, convex organic blobs, and nonconvex organic stars.
%   - Add one convex obstacle on the returned HS3 base path and detect
%     method infeasibility, large arrival gaps, and non-monotone arrivals.
%   - Preserve exact inputs, results, validation, and geometry for diagnosis.
%**************************************************************************
% INPUTS
%   - randomSeeds (integer vector, optional; default 4101:4108)
%   - benchmarkOverrides (scalar struct, optional; default struct())
%       .MaximumPlanningTime_s is the per-HS3 cooperative budget (115).
%       .MissionTime_s is the latest arrival (100).
%       .PrintProgress prints one line per run (true).
%       .PlannerOverrides supplies common public planner overrides.
%**************************************************************************
% OUTPUTS
%   - report (scalar struct)
%       Four method records and paired metamorphic diagnostics per seed.
%**************************************************************************
% UNITS
%   - Position and clearance are degrees; time is seconds.
%**************************************************************************

%% Section 1: Resolve Deterministic Controls

if nargin < 1 || isempty(randomSeeds)
    randomSeeds = 4101:4108;
end
if nargin < 2 || isempty(benchmarkOverrides)
    benchmarkOverrides = struct();
end
validateattributes(randomSeeds, {'numeric'}, ...
    {'real', 'finite', 'vector', 'integer', 'nonnegative'});
defaults = struct( ...
    "MaximumPlanningTime_s", 115, ...
    "MissionTime_s", 100, ...
    "PrintProgress", true, ...
    "PlannerOverrides", struct());
[controls, unknownNames] = azElInternal.resolveOptions( ...
    defaults, benchmarkOverrides);
if ~isempty(unknownNames)
    warning("benchmarkOrganicObstacleRobustness:UnknownOptions", ...
        "Ignoring unknown fields: %s. No behavior changed.", ...
        strjoin(unknownNames, ", "));
end
validateattributes(controls.MaximumPlanningTime_s, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(controls.MissionTime_s, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
controls.PrintProgress = azElInternal.normalizeLogicalScalar( ...
    controls.PrintProgress, "PrintProgress", ...
    "benchmarkOrganicObstacleRobustness:InvalidPrintProgress");
if ~isstruct(controls.PlannerOverrides) || ...
        ~isscalar(controls.PlannerOverrides)
    error("benchmarkOrganicObstacleRobustness:InvalidPlannerOverrides", ...
        "PlannerOverrides must be a scalar struct.");
end
randomSeeds = double(randomSeeds(:));

%% Section 2: Run Base And Added-Obstacle Variants

methods = ["corridorQuintic" "hs3"];
recordCount = 4 * numel(randomSeeds);
methodRecords = repmat(emptyMethodRecord(), recordCount, 1);
pairDiagnostics = repmat(emptyPairDiagnostics(), numel(randomSeeds), 1);
recordIndex = 0;
for seedIndex = 1:numel(randomSeeds)
    randomSeed = randomSeeds(seedIndex);
    [baseObstacles, initialState, goalState, limits, scene] = ...
        createOrganicScene(randomSeed, controls.MissionTime_s);
    baseRecords = repmat(emptyMethodRecord(), 2, 1);
    for methodIndex = 1:2
        baseRecords(methodIndex) = runMethod( ...
            randomSeed, "base", methods(methodIndex), baseObstacles, ...
            initialState, goalState, limits, scene, controls);
        recordIndex = recordIndex + 1;
        methodRecords(recordIndex) = baseRecords(methodIndex);
        printRecord(baseRecords(methodIndex), controls.PrintProgress);
    end

    [addedObstacle, addedCenter_deg] = obstacleOnHs3Path( ...
        baseRecords(2), controls.MissionTime_s, randomSeed);
    augmentedObstacles = combineAzElObstacles( ...
        baseObstacles, addedObstacle);
    augmentedScene = scene;
    augmentedScene.AddedObstacleCenter_deg = addedCenter_deg;
    augmentedScene.AddedObstacle = addedObstacle;
    augmentedRecords = repmat(emptyMethodRecord(), 2, 1);
    for methodIndex = 1:2
        augmentedRecords(methodIndex) = runMethod( ...
            randomSeed, "addedObstacle", methods(methodIndex), ...
            augmentedObstacles, initialState, goalState, limits, ...
            augmentedScene, controls);
        recordIndex = recordIndex + 1;
        methodRecords(recordIndex) = augmentedRecords(methodIndex);
        printRecord(augmentedRecords(methodIndex), controls.PrintProgress);
    end
    pairDiagnostics(seedIndex) = comparePair( ...
        randomSeed, baseRecords, augmentedRecords, addedCenter_deg);
end

%% Section 3: Assemble Failure-Preserving Evidence

validSuccess = [methodRecords.Success].' & ...
    [methodRecords.IndependentValidationPassed].';
report = struct( ...
    "BenchmarkName", "organicObstacleRobustness", ...
    "Controls", controls, ...
    "RandomSeeds", randomSeeds, ...
    "MethodRecords", methodRecords, ...
    "PairDiagnostics", pairDiagnostics, ...
    "ValidSuccessCount", nnz(validSuccess), ...
    "FailureCount", nnz(~validSuccess), ...
    "CompactFalseInfeasibilityCount", nnz( ...
        [pairDiagnostics.CompactFailedHs3PassedBase] | ...
        [pairDiagnostics.CompactFailedHs3PassedAdded]), ...
    "CompactNonMonotoneArrivalCount", nnz( ...
        [pairDiagnostics.CompactAddedObstacleWasFaster]), ...
    "Hs3NonMonotoneArrivalCount", nnz( ...
        [pairDiagnostics.Hs3AddedObstacleWasFaster]), ...
    "LargeMethodGapCount", nnz(abs([ ...
        pairDiagnostics.BaseHs3MinusCompactArrival_s, ...
        pairDiagnostics.AddedHs3MinusCompactArrival_s]) > 1));
end

function [obstacles, initialState, goalState, limits, scene] = ...
        createOrganicScene(randomSeed, missionTime_s)
% Create one rough concave U, convex blob, and nonconvex star.
rng(randomSeed, "twister");
time_s = [0; missionTime_s];
safetyMargin_deg = 0.2;

uPosition_deg = roughUShape();
uScale = 0.82 + 0.28 * rand;
uRotation_deg = -22 + 44 * rand;
uCenter_deg = [-2 + 4 * rand, -1.2 + 2.4 * rand];
uPosition_deg = transformShape( ...
    uScale * uPosition_deg, uRotation_deg, uCenter_deg);
uObstacle = makeAzElObstacleData( ...
    "rough concave U", time_s, ...
    uPosition_deg(:, 1), uPosition_deg(:, 2), safetyMargin_deg);

convexCenter_deg = [-11 + 2 * rand, 2.5 + 3 * rand];
convexPosition_deg = convexOrganicBlob(14, [3.8 2.5]);
convexPosition_deg = transformShape( ...
    convexPosition_deg, -25 + 50 * rand, convexCenter_deg);
convexObstacle = makeAzElObstacleData( ...
    "convex organic blob", time_s, ...
    convexPosition_deg(:, 1), convexPosition_deg(:, 2), ...
    safetyMargin_deg);

starCenter_deg = [10 + 2 * rand, -4.5 + 3 * rand];
starPosition_deg = nonconvexOrganicStar(7, 4.2, 2.1);
starPosition_deg = transformShape( ...
    starPosition_deg, 360 * rand, starCenter_deg);
starObstacle = makeAzElObstacleData( ...
    "nonconvex organic star", time_s, ...
    starPosition_deg(:, 1), starPosition_deg(:, 2), ...
    safetyMargin_deg);
obstacles = combineAzElObstacles( ...
    uObstacle, convexObstacle, starObstacle);

initialState = struct( ...
    "time_s", 0, ...
    "position_deg", [-25 0], ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
goalState = struct( ...
    "time_s", missionTime_s, ...
    "position_deg", [25 0], ...
    "velocity_deg_s", [0 0], ...
    "acceleration_deg_s2", [0 0]);
limits = struct( ...
    "maxVelocity_deg_s", [3 3], ...
    "maxAcceleration_deg_s2", [1 1], ...
    "maxJerk_deg_s3", [2 2], ...
    "azimuthInterval_deg", [-30 30], ...
    "elevationInterval_deg", [-18 18]);
scene = struct( ...
    "ShapeClasses", ["roughConcaveU" "convexOrganic" "nonconvexOrganic"], ...
    "SourceBoundaries_deg", {{ ...
        uPosition_deg, convexPosition_deg, starPosition_deg}}, ...
    "SafetyMargin_deg", safetyMargin_deg, ...
    "ClearWitnessRoute_deg", [-25 0; -25 -16; 25 -16; 25 0]);
end

function position_deg = roughUShape()
% Add small normal offsets along every edge of a simple concave U polygon.
corner_deg = [ ...
    -5 -5; 5 -5; 5 5; 2.1 5; 2.1 -1.6; ...
    -2.1 -1.6; -2.1 5; -5 5];
edgeCount = size(corner_deg, 1);
position_deg = zeros(3 * edgeCount, 2);
writeIndex = 0;
for edgeIndex = 1:edgeCount
    nextIndex = mod(edgeIndex, edgeCount) + 1;
    edge_deg = corner_deg(nextIndex, :) - corner_deg(edgeIndex, :);
    normal = [-edge_deg(2), edge_deg(1)] / norm(edge_deg);
    for fraction = [0 1/3 2/3]
        writeIndex = writeIndex + 1;
        roughness_deg = 0;
        if fraction > 0
            roughness_deg = 0.14 * (2 * rand - 1);
        end
        position_deg(writeIndex, :) = corner_deg(edgeIndex, :) + ...
            fraction * edge_deg + roughness_deg * normal;
    end
end
end

function position_deg = convexOrganicBlob(vertexCount, radius_deg)
% Take the hull of a smoothly perturbed ellipse to retain convexity.
angle_rad = (0:vertexCount - 1).' * (2 * pi / vertexCount);
angle_rad = angle_rad + 0.12 * sin(3 * angle_rad + 2 * pi * rand);
radialScale = 1 + 0.08 * sin(2 * angle_rad + 2 * pi * rand);
points_deg = radialScale .* [ ...
    radius_deg(1) * cos(angle_rad), ...
    radius_deg(2) * sin(angle_rad)];
hullIndex = convhull(points_deg(:, 1), points_deg(:, 2));
position_deg = points_deg(hullIndex(1:end - 1), :);
end

function position_deg = nonconvexOrganicStar(armCount, outerRadius_deg, ...
        innerRadius_deg)
% Create a simple alternating-radius organic star.
vertexCount = 2 * armCount;
angle_rad = (0:vertexCount - 1).' * (2 * pi / vertexCount);
radius_deg = repmat([outerRadius_deg; innerRadius_deg], armCount, 1);
radius_deg = radius_deg .* (1 + 0.08 * sin(3 * angle_rad + 2 * pi * rand));
position_deg = radius_deg .* [cos(angle_rad), sin(angle_rad)];
end

function transformed_deg = transformShape(position_deg, rotation_deg, ...
        center_deg)
% Rotate around the local origin and translate into the workspace.
angle_rad = deg2rad(rotation_deg);
rotation = [cos(angle_rad) -sin(angle_rad); ...
    sin(angle_rad) cos(angle_rad)];
transformed_deg = position_deg * rotation.' + center_deg;
end

function record = runMethod(randomSeed, variant, method, obstacles, ...
        initialState, goalState, limits, scene, controls)
% Run one public method and preserve exact success or failure evidence.
options = controls.PlannerOverrides;
options.PlannerMethod = method;
options.GoalTimeMode = "earliestArrival";
options.RandomSeed = randomSeed;
if method == "hs3"
    options.MaximumPlanningTime_s = controls.MaximumPlanningTime_s;
end
timer = tic;
result = planAzElMotion( ...
    obstacles, initialState, goalState, limits, options);
wallTime_s = toc(timer);
validation = validateAzElTrajectory();
if result.Success
    validation = validateAzElTrajectory(result);
end
record = emptyMethodRecord();
record.RandomSeed = randomSeed;
record.Variant = variant;
record.Method = method;
record.Success = result.Success;
record.IndependentValidationPassed = result.Success && validation.Passed;
record.ArrivalTime_s = result.ArrivalTime_s;
record.WallTime_s = wallTime_s;
record.TerminationReason = result.TerminationReason;
record.Inputs = struct( ...
    "obstacles", obstacles, ...
    "initialState", initialState, ...
    "goalState", goalState, ...
    "limits", limits, ...
    "options", result.Options);
record.Scene = scene;
record.Result = result;
record.IndependentValidation = validation;
end

function [obstacle, center_deg] = obstacleOnHs3Path( ...
        hs3BaseRecord, missionTime_s, randomSeed)
% Place a convex organic obstacle on the middle of the returned HS3 path.
if hs3BaseRecord.Success
    position_deg = hs3BaseRecord.Result.position_deg;
    centerIndex = max(2, min(size(position_deg, 1) - 1, ...
        round(0.55 * size(position_deg, 1))));
    center_deg = position_deg(centerIndex, :);
else
    center_deg = [0 0];
end
rng(randomSeed + 100000, "twister");
boundary_deg = convexOrganicBlob(12, [1.9 1.5]);
boundary_deg = transformShape( ...
    boundary_deg, 360 * rand, center_deg);
obstacle = makeAzElObstacleData( ...
    "added path obstacle", [0; missionTime_s], ...
    boundary_deg(:, 1), boundary_deg(:, 2), 0.2);
end

function diagnostics = comparePair( ...
        randomSeed, baseRecords, augmentedRecords, addedCenter_deg)
% Record method gaps and the obstacle-addition monotonicity check.
diagnostics = emptyPairDiagnostics();
diagnostics.RandomSeed = randomSeed;
diagnostics.AddedObstacleCenter_deg = addedCenter_deg;
diagnostics.CompactFailedHs3PassedBase = ...
    ~baseRecords(1).Success && baseRecords(2).IndependentValidationPassed;
diagnostics.CompactFailedHs3PassedAdded = ...
    ~augmentedRecords(1).Success && ...
    augmentedRecords(2).IndependentValidationPassed;
if all([baseRecords.Success])
    diagnostics.BaseHs3MinusCompactArrival_s = ...
        baseRecords(2).ArrivalTime_s - baseRecords(1).ArrivalTime_s;
end
if all([augmentedRecords.Success])
    diagnostics.AddedHs3MinusCompactArrival_s = ...
        augmentedRecords(2).ArrivalTime_s - ...
        augmentedRecords(1).ArrivalTime_s;
end
if baseRecords(2).Success && augmentedRecords(2).Success
    diagnostics.Hs3ArrivalChange_s = ...
        augmentedRecords(2).ArrivalTime_s - baseRecords(2).ArrivalTime_s;
    diagnostics.Hs3AddedObstacleWasFaster = ...
        diagnostics.Hs3ArrivalChange_s < -1e-3;
end
if baseRecords(1).Success && augmentedRecords(1).Success
    diagnostics.CompactArrivalChange_s = ...
        augmentedRecords(1).ArrivalTime_s - baseRecords(1).ArrivalTime_s;
    diagnostics.CompactAddedObstacleWasFaster = ...
        diagnostics.CompactArrivalChange_s < -1e-3;
end
end

function record = emptyMethodRecord()
% Define one stable planner-run evidence record.
record = struct( ...
    "RandomSeed", NaN, ...
    "Variant", "", ...
    "Method", "", ...
    "Success", false, ...
    "IndependentValidationPassed", false, ...
    "ArrivalTime_s", NaN, ...
    "WallTime_s", NaN, ...
    "TerminationReason", "", ...
    "Inputs", struct(), ...
    "Scene", struct(), ...
    "Result", struct(), ...
    "IndependentValidation", validateAzElTrajectory());
end

function diagnostics = emptyPairDiagnostics()
% Define stable paired-method and obstacle-addition diagnostics.
diagnostics = struct( ...
    "RandomSeed", NaN, ...
    "AddedObstacleCenter_deg", [NaN NaN], ...
    "CompactFailedHs3PassedBase", false, ...
    "CompactFailedHs3PassedAdded", false, ...
    "BaseHs3MinusCompactArrival_s", NaN, ...
    "AddedHs3MinusCompactArrival_s", NaN, ...
    "CompactArrivalChange_s", NaN, ...
    "CompactAddedObstacleWasFaster", false, ...
    "Hs3ArrivalChange_s", NaN, ...
    "Hs3AddedObstacleWasFaster", false);
end

function printRecord(record, enabled)
% Print one compact line while complete evidence remains in the report.
if ~enabled
    return;
end
fprintf( ...
    "organic=%d variant=%s method=%s success=%d validation=%d " + ...
    "arrival=%.6g wall=%.6f reason=%s\n", ...
    record.RandomSeed, record.Variant, record.Method, record.Success, ...
    record.IndependentValidationPassed, record.ArrivalTime_s, ...
    record.WallTime_s, record.TerminationReason);
end
