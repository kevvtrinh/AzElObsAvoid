function [runs, results] = benchmarkEarliestArrivalPolicy(repetitions)
%% Section 0: Header & Readme
% SYNTAX
%   [runs, results] = benchmarkEarliestArrivalPolicy()
%   [runs, results] = benchmarkEarliestArrivalPolicy(repetitions)
%**************************************************************************
% PURPOSE
%   - Measure the consolidated earliest-arrival coordinator on deterministic
%     requests that select each retained method family.
%   - Record runtime, motion quality, next method use, and stopping evidence.
%**************************************************************************
% INPUTS
%   - repetitions (positive integer scalar, optional; default 3)
%       Number of measured runs after one warmup run per case.
%**************************************************************************
% OUTPUTS
%   - runs (table)
%       Per-run runtime, quality, validation, attempt, and search-budget data.
%   - results (N-by-1 cell array)
%       Complete corresponding public planner results.
%**************************************************************************
% UNITS
%   - Coordinates are generic units. Time is seconds; jerk is units/s^3.
%**************************************************************************

%% Section 1: Load Deterministic Requests

if nargin < 1
    repetitions = 3;
end
validateattributes(repetitions, {'numeric'}, ...
    {'scalar', 'integer', 'positive', 'finite'});
repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(repositoryRoot, fullfile(repositoryRoot, 'trajectory'));
cases = createCases();

%% Section 2: Warm And Measure The Unified Policy

measuredRunCount = numel(cases) * repetitions;
rows             = cell(measuredRunCount, 1);
results          = cell(measuredRunCount, 1);
rowIndex         = 0;
for caseIndex = 1:numel(cases)
    caseRequest = cases(caseIndex);
    for repetition = 0:repetitions
        timer = tic;
        result = planner(caseRequest.Obstacles, caseRequest.InitialState, ...
            caseRequest.GoalState, caseRequest.Limits, caseRequest.Options);
        runtime_s = toc(timer);
        independentlyValid = result.Success && ...
            obstacleAvoidance.validateTrajectory(result).Passed;

        arrival_s     = NaN;
        length_units  = NaN;
        peakJerk_units_s3 = NaN;
        if result.Success
            arrival_s           = result.ArrivalTime_s;
            length_units        = result.MotionLength_units;
            peakJerk_units_s3   = max(vecnorm(result.jerk_units_s3, 2, 2));
        end

        attempts = result.Attempts;
        attemptSequence = "none";
        solverAttemptCount = 0;
        totalAlternatingIterations = 0;
        if ~isempty(attempts)
            attemptSequence = strjoin([attempts.Kind], " > ");
            solverAttemptCount = sum([attempts.SolverAttempted]);
            totalAlternatingIterations = sum([attempts.IterationCount]);
        end

        arrivalTimeTrialCount = 0;
        prescreenedCandidateCount = 0;
        candidateLimitReached = false;
        trialLimitReached = false;
        if isfield(result, 'TemporalSearch') && ...
                isfield(result.TemporalSearch, 'SolverTrialCount')
            arrivalTimeTrialCount = result.TemporalSearch.SolverTrialCount;
            prescreenedCandidateCount = ...
                result.TemporalSearch.PrescreenedCandidateCount;
            candidateLimitReached = result.TemporalSearch.CandidateLimitReached;
            trialLimitReached = result.TemporalSearch.TrialLimitReached;
        end

        fprintf(['%s repetition %d: %.6f s; valid %d; arrival %.9f; ' ...
            'length %.12f; attempts %s\n'], ...
            caseRequest.Name, repetition, runtime_s, independentlyValid, ...
            arrival_s, length_units, attemptSequence);
        if repetition == 0
            continue
        end

        rowIndex = rowIndex + 1;
        rows{rowIndex} = struct( ...
            'Case',                         caseRequest.Name, ...
            'Repetition',                   repetition, ...
            'Runtime_s',                    runtime_s, ...
            'Success',                      result.Success, ...
            'IndependentValidation',        independentlyValid, ...
            'Arrival_s',                    arrival_s, ...
            'Length_units',                 length_units, ...
            'PeakJerk_units_s3',            peakJerk_units_s3, ...
            'SelectedAttemptIndex',         result.EarliestArrival.SelectedAttemptIndex, ...
            'AttemptCount',                 numel(attempts), ...
            'SolverAttemptCount',           solverAttemptCount, ...
            'ArrivalTimeTrialCount',      arrivalTimeTrialCount, ...
            'PrescreenedCandidateCount',    prescreenedCandidateCount, ...
            'CandidateLimitReached',        candidateLimitReached, ...
            'TrialLimitReached',            trialLimitReached, ...
            'AlternatingIterations',        totalAlternatingIterations, ...
            'AttemptSequence',              attemptSequence, ...
            'GlobalEarliestProven',         result.EarliestArrival.GlobalEarliestProven, ...
            'TerminationReason',            result.TerminationReason);
        results{rowIndex} = result;
    end
end
runs = struct2table(vertcat(rows{:}));
end

%% Section 3: Deterministic Case Construction

function cases = createCases()
    limits = struct( ...
        'xInterval_units',          [-30, 30], ...
        'yInterval_units',          [-30, 30], ...
        'maxVelocity_units_s',      [2, 2], ...
        'maxAcceleration_units_s2', [1, 1], ...
        'maxJerk_units_s3',         [2, 2]);

    remoteBox_units = [-0.5,-0.5;0.5,-0.5;0.5,0.5;-0.5,0.5];
    remoteFirst_units = remoteBox_units + [0, 8];
    remoteLast_units  = remoteBox_units + [2, 8];
    remoteMover = obstacleAvoidance.obstacles.createObstacle( ...
        'remote mover', [0;20], ...
        {remoteFirst_units(:,1);remoteLast_units(:,1)}, ...
        {remoteFirst_units(:,2);remoteLast_units(:,2)}, 0);
    cases(1) = struct( ...
        'Name',         "Zero-delay departure best plan so far", ...
        'Obstacles',    remoteMover, ...
        'InitialState', restState(0, [0,0]), ...
        'GoalState',    restState(20, [4,0]), ...
        'Limits',       limits, ...
        'Options',      struct('GoalTimeMode','earliestArrival'));

    barrier_units = [-0.2,-3;0.2,-3;0.2,3;-0.2,3];
    barrierTime_s = [0;6;6.5;12];
    barrierOffsetY_units = [0;0;8;8];
    barrierXByTime_units = repmat({barrier_units(:,1)}, 4, 1);
    barrierYByTime_units = arrayfun(@(offset_units) ...
        barrier_units(:,2) + offset_units, barrierOffsetY_units, ...
        'UniformOutput', false);
    barrier = obstacleAvoidance.obstacles.createObstacle( ...
        'translating barrier', barrierTime_s, barrierXByTime_units, ...
        barrierYByTime_units, 0.1);
    cases(2) = struct( ...
        'Name',         "Delayed departure retained", ...
        'Obstacles',    barrier, ...
        'InitialState', restState(0, [-5,0]), ...
        'GoalState',    restState(12, [5,0]), ...
        'Limits',       struct('xInterval_units',[-6,6], ...
            'yInterval_units',[-3,3], 'maxVelocity_units_s',[2,2], ...
            'maxAcceleration_units_s2',[1,1], 'maxJerk_units_s3',[2,2]), ...
        'Options',      struct('GoalTimeMode','earliestArrival'));

    angle_rad = (0:23).' * (2*pi/24);
    circle_units = [1.5*cos(angle_rad), 1.5*sin(angle_rad)];
    circleOffsetY_units = [0;0;3;3];
    circle = obstacleAvoidance.obstacles.createObstacle( ...
        'rising circle', [0;5.5;6.5;15], ...
        repmat({circle_units(:,1)}, 4, 1), ...
        arrayfun(@(offset_units) circle_units(:,2) + offset_units, ...
        circleOffsetY_units, 'UniformOutput', false), 0.1);
    cases(3) = struct( ...
        'Name',         "Timed homotopy beats departure", ...
        'Obstacles',    circle, ...
        'InitialState', restState(0, [-6,0]), ...
        'GoalState',    restState(15, [6,0]), ...
        'Limits',       struct('maxVelocity_units_s',[2,2], ...
            'maxAcceleration_units_s2',[1,1], 'maxJerk_units_s3',[2,2]), ...
        'Options',      struct('GoalTimeMode','earliestArrival', ...
            'TemporalResolution_s',0.5));

    nonrestInitial = restState(0, [0,0]);
    nonrestInitial.velocity_units_s = [0.1,0];
    cases(4) = struct( ...
        'Name',         "Nonrest arrival-time clock", ...
        'Obstacles',    [], ...
        'InitialState', nonrestInitial, ...
        'GoalState',    restState(10, [4,0]), ...
        'Limits',       limits, ...
        'Options',      struct('GoalTimeMode','earliestArrival'));

    targetTime_s = (0:2:12).';
    targetMotion = struct( ...
        'time_s', targetTime_s, ...
        'position_units', [4+0.1*targetTime_s, ones(size(targetTime_s))], ...
        'InterpolationMethod', 'linear');
    cases(5) = struct( ...
        'Name',         "Moving-target arrival-time clock", ...
        'Obstacles',    [], ...
        'InitialState', restState(0, [0,0]), ...
        'GoalState',    struct('time_s',12,'targetMotion',targetMotion), ...
        'Limits',       limits, ...
        'Options',      struct('GoalTimeMode','earliestArrival', ...
            'TemporalResolution_s',0.5));

    cases(6) = struct( ...
        'Name',         "Static spatial variable clock", ...
        'Obstacles',    [], ...
        'InitialState', restState(0, [0,0]), ...
        'GoalState',    restState(10, [4,1]), ...
        'Limits',       limits, ...
        'Options',      struct('GoalTimeMode','earliestArrival'));
end

function value = restState(time_s, position_units)
    value = struct( ...
        'time_s',                 time_s, ...
        'position_units',         position_units, ...
        'velocity_units_s',       [0,0], ...
        'acceleration_units_s2',  [0,0]);
end
