function [bounds, dynamics, checks] = validatePolynomialTrajectory( ...
        polynomial, time_s, position_deg, velocity_deg_s, ...
        acceleration_deg_s2, jerk_deg_s3, initialState, goalState, limits, ...
        options, tolerance, rangeCheck)
%% Section 0: Header & Readme
% SYNTAX
%   [bounds, dynamics, checks] = ...
%       obstacleAvoidance.validation.validatePolynomialTrajectory( ...
%       polynomial, time_s, position_deg, velocity_deg_s, ...
%       acceleration_deg_s2, jerk_deg_s3, initialState, goalState, limits, ...
%       options, tolerance, rangeCheck)
%**************************************************************************
% PURPOSE
%   - Validate a degree-neutral piecewise polynomial independently.
%   - Check its time base, derivative chain, knots, endpoints, sampled
%     histories, and continuous physical bounds.
%**************************************************************************
% INPUTS
%   - polynomial (scalar planner polynomial struct)
%       Ascending-power position coefficients have degree at least three;
%       each derivative array has one fewer coefficient.
%   - time_s and sampled histories (numeric arrays)
%       Returned absolute times and N-by-2 position through jerk histories.
%   - initialState, goalState, limits, options (scalar structs)
%       Resolved inputs governing endpoints, bounds, and azimuth wrapping.
%   - tolerance (nonnegative finite scalar)
%       Absolute state and polynomial consistency tolerance.
%   - rangeCheck (function handle)
%       Complete polynomial range certificate for normalized time [0, 1].
%**************************************************************************
% OUTPUTS
%   - bounds, dynamics, checks (scalar structs)
%       Stable continuous-bound, derivative, format, and history checks.
%**************************************************************************
% UNITS
%   - Position is degrees. Derivatives use deg/s, deg/s^2, and deg/s^3.
%     Time is seconds.
%**************************************************************************

%% Section 1: Validate The Polynomial Representation

checks = createEmptyChecks();
bounds = createBounds(false(1, 4));
dynamics = struct("Consistent", false, "MaximumResidual", Inf);
requiredFields = {'SegmentCount', 'SegmentStartTime_s', ...
    'SegmentDuration_s', 'FinalTime_s', 'positionPower_deg', ...
    'velocityPower_deg_s', 'accelerationPower_deg_s2', ...
    'jerkPower_deg_s3'};
if ~isstruct(polynomial) || ~isscalar(polynomial) || ...
        ~all(isfield(polynomial, requiredFields))
    return;
end
segmentCount = polynomial.SegmentCount;
segmentDuration_s = double(polynomial.SegmentDuration_s(:));
segmentStartTime_s = double(polynomial.SegmentStartTime_s(:));
countIsValid = isnumeric(segmentCount) && isscalar(segmentCount) && ...
    isfinite(segmentCount) && segmentCount >= 1 && segmentCount == fix(segmentCount);
durationIsValid = isnumeric(polynomial.SegmentDuration_s) && ...
    any(numel(segmentDuration_s) == [1 segmentCount]) && ...
    all(isfinite(segmentDuration_s)) && all(segmentDuration_s > 0);
finalTimeIsValid = isnumeric(polynomial.FinalTime_s) && ...
    isscalar(polynomial.FinalTime_s) && isfinite(polynomial.FinalTime_s);
if ~(countIsValid && durationIsValid && finalTimeIsValid)
    return;
end
if isscalar(segmentDuration_s)
    segmentDuration_s = repmat(segmentDuration_s, segmentCount, 1);
end
powerArrays = {polynomial.positionPower_deg, ...
    polynomial.velocityPower_deg_s, ...
    polynomial.accelerationPower_deg_s2, polynomial.jerkPower_deg_s3};
positionCoefficientCount = size(powerArrays{1}, 3);
arraysAreValid = numel(segmentStartTime_s) == segmentCount && ...
    all(isfinite(segmentStartTime_s));
for derivativeOrder = 0:3
    array = powerArrays{derivativeOrder + 1};
    arraysAreValid = arraysAreValid && isnumeric(array) && ...
        positionCoefficientCount >= 4 && ...
        size(array, 1) == segmentCount && size(array, 2) == 2 && ...
        size(array, 3) == positionCoefficientCount - derivativeOrder && ...
        all(isfinite(array), "all");
end
checks.FormatValid = arraysAreValid;
if ~checks.FormatValid
    return;
end

%% Section 2: Check Time, Bounds, And The Derivative Chain

expectedStartTime_s = segmentStartTime_s(1) + ...
    [0; cumsum(segmentDuration_s(1:end - 1))];
expectedFinalTime_s = segmentStartTime_s(1) + sum(segmentDuration_s);
timeTolerance_s = max(tolerance, 100 * eps(max(1, ...
    max(abs([expectedStartTime_s; expectedFinalTime_s])))));
sampleTimeIsConsistent = ~isempty(time_s) && all(isfinite(time_s)) && ...
    abs(time_s(1) - segmentStartTime_s(1)) <= timeTolerance_s && ...
    abs(time_s(end) - expectedFinalTime_s) <= timeTolerance_s && ...
    all(time_s >= segmentStartTime_s(1) - timeTolerance_s) && ...
    all(time_s <= expectedFinalTime_s + timeTolerance_s);
checks.TimeBaseConsistent = sampleTimeIsConsistent && ...
    max(abs(segmentStartTime_s - expectedStartTime_s)) <= timeTolerance_s && ...
    abs(polynomial.FinalTime_s - expectedFinalTime_s) <= timeTolerance_s;
checks.InitialTimeMatched = ...
    abs(segmentStartTime_s(1) - initialState.time_s) <= timeTolerance_s;
lowerLimits = {[limits.azimuthInterval_deg(1), ...
    limits.elevationInterval_deg(1)], -limits.maxVelocity_deg_s, ...
    -limits.maxAcceleration_deg_s2, -limits.maxJerk_deg_s3};
upperLimits = {[limits.azimuthInterval_deg(2), ...
    limits.elevationInterval_deg(2)], limits.maxVelocity_deg_s, ...
    limits.maxAcceleration_deg_s2, limits.maxJerk_deg_s3};
within = true(1, 4);
for segmentIndex = 1:segmentCount
    for axisIndex = 1:2
        for derivativeOrder = 0:3
            shouldCheck = derivativeOrder > 0 || axisIndex > 1 || ...
                ~options.AllowAzimuthWrapping;
            if shouldCheck && within(derivativeOrder + 1)
                power = reshape(powerArrays{derivativeOrder + 1}( ...
                    segmentIndex, axisIndex, :), [], 1);
                within(derivativeOrder + 1) = rangeCheck(power, ...
                    lowerLimits{derivativeOrder + 1}(axisIndex), ...
                    upperLimits{derivativeOrder + 1}(axisIndex), tolerance);
            end
        end
    end
end
bounds = createBounds(within);
durationScale_s = reshape(segmentDuration_s, [], 1, 1);
dynamicsResidual = zeros(0, 1);
for derivativeOrder = 0:2
    source = powerArrays{derivativeOrder + 1};
    derivative = source(:, :, 2:end) .* ...
        reshape(1:size(source, 3) - 1, 1, 1, []) ./ durationScale_s;
    dynamicsResidual = [dynamicsResidual; ...
        derivative(:) - powerArrays{derivativeOrder + 2}(:)]; %#ok<AGROW>
end
maximumDynamicsResidual = max(abs(dynamicsResidual));
dynamics = struct("Consistent", maximumDynamicsResidual <= tolerance, ...
    "MaximumResidual", maximumDynamicsResidual);

%% Section 3: Check Knots, Endpoints, And Sampled Histories

maximumSegmentContinuityResidual = 0;
if segmentCount > 1
    previousSegmentIndex = (1:segmentCount - 1).';
    previousEndTime_s = segmentStartTime_s(1:end - 1) + ...
        segmentDuration_s(1:end - 1);
    [~, previousPosition_deg, previousVelocity_deg_s, ...
        previousAcceleration_deg_s2] = ...
        bmtpEngine.evaluatePolynomial( ...
        polynomial, previousEndTime_s, previousSegmentIndex);
    nextInitialState = [reshape(powerArrays{1}(2:end, :, 1), [], 2), ...
        reshape(powerArrays{2}(2:end, :, 1), [], 2), ...
        reshape(powerArrays{3}(2:end, :, 1), [], 2)];
    previousFinalState = [previousPosition_deg, previousVelocity_deg_s, ...
        previousAcceleration_deg_s2];
    maximumSegmentContinuityResidual = ...
        max(abs(previousFinalState - nextInitialState), [], "all");
end
checks.MaximumSegmentContinuityResidual = ...
    maximumSegmentContinuityResidual;
checks.SegmentContinuity = maximumSegmentContinuityResidual <= tolerance;
initialPolynomialState = [reshape(powerArrays{1}(1, :, 1), 1, 2), ...
    reshape(powerArrays{2}(1, :, 1), 1, 2), ...
    reshape(powerArrays{3}(1, :, 1), 1, 2)];
terminalPolynomialState = [sum(reshape(powerArrays{1}(end, :, :), 2, []), 2).', ...
    sum(reshape(powerArrays{2}(end, :, :), 2, []), 2).', ...
    sum(reshape(powerArrays{3}(end, :, :), 2, []), 2).'];
goalPosition_deg = obstacleAvoidance.input.goalPositionAtTime( ...
    goalState, polynomial.FinalTime_s);
expectedEndpointState = [initialState.position_deg, ...
    initialState.velocity_deg_s, initialState.acceleration_deg_s2, ...
    goalPosition_deg, goalState.velocity_deg_s, goalState.acceleration_deg_s2];
checks.EndpointStatesMatched = max(abs([initialPolynomialState, ...
    terminalPolynomialState] - expectedEndpointState)) <= tolerance;
[~, polynomialPosition_deg, polynomialVelocity_deg_s, ...
    polynomialAcceleration_deg_s2, polynomialJerk_deg_s3] = ...
    bmtpEngine.evaluatePolynomial(polynomial, time_s);
historySizesMatch = isequal(size(position_deg), size(polynomialPosition_deg)) && ...
    isequal(size(velocity_deg_s), size(polynomialVelocity_deg_s)) && ...
    isequal(size(acceleration_deg_s2), size(polynomialAcceleration_deg_s2)) && ...
    isequal(size(jerk_deg_s3), size(polynomialJerk_deg_s3));
if historySizesMatch
    checks.MaximumHistoryResidual = max(abs([ ...
        position_deg - polynomialPosition_deg, ...
        velocity_deg_s - polynomialVelocity_deg_s, ...
        acceleration_deg_s2 - polynomialAcceleration_deg_s2, ...
        jerk_deg_s3 - polynomialJerk_deg_s3]), [], "all");
    checks.HistoryConsistent = checks.MaximumHistoryResidual <= tolerance;
end
checks.Valid = checks.FormatValid && checks.InitialTimeMatched && ...
    checks.TimeBaseConsistent && checks.SegmentContinuity && ...
    checks.EndpointStatesMatched && checks.HistoryConsistent;
end

%% Section 4: Local Functions

function checks = createEmptyChecks()
% Define stable polynomial checks for every invalid representation.
checks = struct("Valid", false, "FormatValid", false, ...
    "InitialTimeMatched", false, "TimeBaseConsistent", false, ...
    "SegmentContinuity", false, "EndpointStatesMatched", false, ...
    "HistoryConsistent", false, ...
    "MaximumSegmentContinuityResidual", Inf, ...
    "MaximumHistoryResidual", Inf);
end

function bounds = createBounds(within)
% Assemble continuous-bound checks in stable public order.
bounds = struct("Valid", all(within), ...
    "PositionWithinLimits", within(1), ...
    "VelocityWithinLimits", within(2), ...
    "AccelerationWithinLimits", within(3), ...
    "JerkWithinLimits", within(4));
end
