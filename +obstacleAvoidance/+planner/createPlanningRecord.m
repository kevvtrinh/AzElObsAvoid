function [result, emptySeedSummary] = createPlanningRecord(obstacles, initialState, goalState, limits, options, validationTemplate)
%% Section 0: Header & Readme
% SYNTAX
%   [result, emptySeedSummary] = createPlanningRecord( ...
%       obstacles, initialState, goalState, limits, options, validationTemplate)
% PURPOSE
%   Define stable internal motion and candidate-summary records.
% INPUTS
%   Canonical obstacles, normalized states/limits/options, and empty validation.
% OUTPUTS
%   result holds planning data; emptySeedSummary initializes each attempt.
%   Success and failure use the same fields and empty-value conventions.
% UNITS
%   Coordinate units, seconds, and derivatives in units/s, units/s^2, and units/s^3.

%% Section 1: Create Planner Templates

% Use the same result fields and array shapes for success and failure.

emptySeed = obstacleAvoidance.search.createEmptyPathGuess();

emptySeedSummary = struct();
emptySeedSummary.SeedIndex                     = 0;
emptySeedSummary.SeedSource                    = "";
emptySeedSummary.OptimizerFeasible             = false;
emptySeedSummary.ValidationPassed              = false;
emptySeedSummary.CollisionFree                 = false;
emptySeedSummary.CollisionResolved             = false;
emptySeedSummary.MinimumClearance_units          = NaN;
emptySeedSummary.UnresolvedIntervalCount       = 0;
emptySeedSummary.ArrivalTime_s                 = NaN;
emptySeedSummary.TrajectoryDuration_s          = NaN;
emptySeedSummary.MotionLength_units              = Inf;
emptySeedSummary.IntegratedSquaredJerk_units2_s5 = Inf;
emptySeedSummary.KinematicUtilization          = 0;
emptySeedSummary.MaximumConstraintViolation    = Inf;
emptySeedSummary.SeedPlanningElapsedTime_s     = 0;
emptySeedSummary.TerminationReason             = "notRun";
emptySeedSummary.Message                       = "";
emptySeedSummary.SolverDiagnostics             = struct();

emptyPolynomial = struct("SegmentCount", 0, "SegmentStartTime_s", zeros(0, 1), ...
    "SegmentDuration_s", NaN, ...
    "SegmentBreakTau", zeros(0, 1), ...
    "FinalTime_s", NaN, ...
    "positionPower_units", zeros(0, 2, 6), ...
    "velocityPower_units_s", zeros(0, 2, 5), ...
    "accelerationPower_units_s2", zeros(0, 2, 4), ...
    "jerkPower_units_s3", zeros(0, 2, 3), ...
    "TerminalState", struct("position_units", [NaN NaN], "velocity_units_s", [NaN NaN], ...
    "acceleration_units_s2", [NaN NaN]));

emptyPlane = struct();
emptyPlane.Active        = false;
emptyPlane.Normal        = zeros(2, 2);
emptyPlane.Offset_units    = zeros(1, 2);
emptyPlane.SignedGap_units = NaN;
emptyPlane.Verified      = false;
emptyPlane.ExitFlag      = NaN;
emptyPlaneCertificate = struct("Kind", "", "Passed", false, "ExactRegionCount", 0, ...
    "SolverRegionCount", 0, "Regions_units", {cell(0, 1)}, ...
    "Planes", repmat(emptyPlane, 0, 0), "RequiredGap_units", NaN, ...
    "RoundoffReserve_units", NaN, ...
    "MinimumSignedGap_units", NaN, "CoveragePassed", false, ...
    "Coverage", struct(), "AllPairCount", 0, ...
    "VerifiedPairCount", 0, "ReusedPairCount", 0, ...
    "AnalyticPairCount", 0, "ConicPairCount", 0);

searchDiagnostics = struct("GraphSearch", struct(), ...
    "BestPartialSeedIndex", 0, ...
    "ValidatedCandidateCount", 0, ...
    "AttemptedSeedCount", 0, ...
    "StageTiming", obstacleAvoidance.planner.createStageTiming());

%% Section 2: Assemble The Stable Result

% Keep inputs and diagnostics so failures can be inspected without rerunning.

result = struct("Success", false, "Message", "Planning was not completed.", ...
    "TerminationReason", "notRun", ...
    "Options", options, ...
    "Inputs", struct("obstacles", obstacles, ...
    "initialState", initialState, ...
    "goalState", goalState, ...
    "limits", limits), ...
    "Seeds", repmat(emptySeed, 0, 1), ...
    "SeedSummaries", repmat(emptySeedSummary, 0, 1), ...
    "SelectedSeedIndex", 0, ...
    "SelectedSeed_units", zeros(0, 2), ...
    "time_s", zeros(0, 1), ...
    "position_units", zeros(0, 2), ...
    "velocity_units_s", zeros(0, 2), ...
    "acceleration_units_s2", zeros(0, 2), ...
    "jerk_units_s3", zeros(0, 2), ...
    "Polynomial", emptyPolynomial, ...
    "SeedCorridorBoundary_units", zeros(0, 2), ...
    "SeedCorridor", struct([]), ...
    "PlaneCertificate", emptyPlaneCertificate, ...
    "Validation", validationTemplate, ...
    "ArrivalTime_s", NaN, "TrajectoryDuration_s", NaN, ...
    "FirstValidatedMotionTime_s", NaN, ...
    "SearchDiagnostics", searchDiagnostics, ...
    "ElapsedPlanningTime_s", 0);
end
