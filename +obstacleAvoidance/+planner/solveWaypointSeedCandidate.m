function candidate = solveWaypointSeedCandidate( ...
        initialState, goalState, limits, options, seed)
%% Section 0: Header & Readme
% SYNTAX
%   candidate = obstacleAvoidance.planner.solveWaypointSeedCandidate( ...
%       initialState, goalState, limits, options, seed)
%**************************************************************************
% PURPOSE
%   - Compose exact rest-to-rest Ruckig segments along a spatial seed.
%**************************************************************************
% INPUTS
%   - initialState, goalState (normalized scalar state structs)
%       Endpoint fields use planner names and 1-by-2 rows.
%   - limits, options (normalized scalar planner-input structs)
%   - seed (scalar topology-seed struct)
%       position_deg contains at least three spatial visibility waypoints.
%**************************************************************************
% OUTPUTS
%   - candidate (scalar struct)
%       Stable candidate motion or an identified segment failure. The public
%       planner independently validates any complete returned motion.
%**************************************************************************
% UNITS
%   - Position is degrees; time is seconds; derivatives use deg/s powers.
%**************************************************************************

%% Section 1: Create The Exact Segment Requests

solveTimer = tic;
route_deg = double(seed.position_deg);
validateattributes(route_deg, {'numeric'}, ...
    {'real', 'finite', '2d', 'ncols', 2});
if size(route_deg, 1) < 3
    error("solveWaypointSeedCandidate:InsufficientWaypoints", ...
        "seed.position_deg must contain at least three route vertices.");
end
engineLimits = struct( ...
    "maximumVelocity", limits.maxVelocity_deg_s, ...
    "maximumAcceleration", limits.maxAcceleration_deg_s2, ...
    "maximumJerk", limits.maxJerk_deg_s3, ...
    "positionLower", [limits.azimuthInterval_deg(1), ...
    limits.elevationInterval_deg(1)], ...
    "positionUpper", [limits.azimuthInterval_deg(2), ...
    limits.elevationInterval_deg(2)]);
if options.AllowAzimuthWrapping
    engineLimits.positionLower(1) = -Inf;
    engineLimits.positionUpper(1) = Inf;
end
engineOptions = struct( ...
    "TimeMode", "earliestArrival", ...
    "FinalTime", [], ...
    "SampleTime", options.SampleTime_s, ...
    "ConstraintTolerance", options.ConstraintTolerance, ...
    "ArrivalTimeTolerance", options.ArrivalTimeTolerance_s, ...
    "Verbose", false);

%% Section 2: Solve Every Route Edge

partCount = size(route_deg, 1) - 1;
polynomialParts = cell(partCount, 1);
integratedSquaredJerk_deg2_s5 = 0;
maximumConstraintViolation = 0;
currentTime_s = initialState.time_s;
for partIndex = 1:partCount
    engineInitialState = struct( ...
        "time", currentTime_s, ...
        "position", route_deg(partIndex, :), ...
        "velocity", [0 0], ...
        "acceleration", [0 0]);
    if partIndex == 1
        engineInitialState.velocity = initialState.velocity_deg_s;
        engineInitialState.acceleration = initialState.acceleration_deg_s2;
    end
    terminalVelocity_deg_s = [0 0];
    terminalAcceleration_deg_s2 = [0 0];
    if partIndex == partCount
        terminalVelocity_deg_s = goalState.velocity_deg_s;
        terminalAcceleration_deg_s2 = goalState.acceleration_deg_s2;
        if options.GoalTimeMode == "fixedArrival"
            engineOptions.TimeMode = "fixed";
            engineOptions.FinalTime = goalState.time_s;
        end
    end
    engineTerminalState = struct( ...
        "position", route_deg(partIndex + 1, :), ...
        "velocity", terminalVelocity_deg_s, ...
        "acceleration", terminalAcceleration_deg_s2, ...
        "maximumTime", goalState.time_s);
    part = planTrajRuckig( ...
        engineInitialState, engineTerminalState, ...
        engineLimits, engineOptions);
    if ~part.Success
        candidate = createFailedCandidate( ...
            seed, part, toc(solveTimer));
        return;
    end
    polynomialParts{partIndex} = part.Polynomial;
    integratedSquaredJerk_deg2_s5 = ...
        integratedSquaredJerk_deg2_s5 + part.IntegratedSquaredJerk;
    maximumConstraintViolation = max( ...
        maximumConstraintViolation, part.MaximumConstraintViolation);
    currentTime_s = part.FinalTime;
end

%% Section 3: Assemble One Planner Candidate

enginePolynomial = combinePolynomials(polynomialParts);
polynomial = convertPolynomial(enginePolynomial);
uniformTime_s = (initialState.time_s: ...
    options.SampleTime_s:enginePolynomial.FinalTime).';
queryTime_s = unique([uniformTime_s; ...
    enginePolynomial.SegmentStartTime; enginePolynomial.FinalTime]);
[time_s, position_deg, velocity_deg_s, ...
    acceleration_deg_s2, jerk_deg_s3] = ...
    obstacleAvoidance.planner.evaluatePlannerPolynomial( ...
    polynomial, queryTime_s);
elapsedTime_s = toc(solveTimer);
diagnostics = obstacleAvoidance.planner.createEmptySolverDiagnostics();
diagnostics.Identifier = "ruckigWaypointComposition";
diagnostics.ConstraintRepresentation = "exactSwitchingSegments";
diagnostics.StageOneExitFlag = 1;
diagnostics.MaximumInequalityViolation = maximumConstraintViolation;
diagnostics.MaximumEqualityViolation = maximumConstraintViolation;
diagnostics = obstacleAvoidance.planner.createEmptySolverDiagnostics( ...
    diagnostics, elapsedTime_s, 0);
candidate = struct( ...
    "SeedIndex", seed.Index, ...
    "SeedSource", seed.Source, ...
    "OptimizerFeasible", true, ...
    "Message", "Exact rest-to-rest waypoint motion was constructed.", ...
    "TerminationReason", "goalReached", ...
    "time_s", time_s, ...
    "position_deg", position_deg, ...
    "velocity_deg_s", velocity_deg_s, ...
    "acceleration_deg_s2", acceleration_deg_s2, ...
    "jerk_deg_s3", jerk_deg_s3, ...
    "Polynomial", polynomial, ...
    "FinalTime_s", enginePolynomial.FinalTime, ...
    "MotionDuration_s", enginePolynomial.FinalTime - initialState.time_s, ...
    "MotionLength_deg", sum(vecnorm(diff(position_deg), 2, 2)), ...
    "IntegratedSquaredJerk_deg2_s5", ...
    integratedSquaredJerk_deg2_s5, ...
    "MaximumConstraintViolation", maximumConstraintViolation, ...
    "ArrivalAtHorizon", abs(enginePolynomial.FinalTime - ...
    goalState.time_s) <= options.ArrivalTimeTolerance_s, ...
    "SeedCorridorBoundary_deg", zeros(0, 2), ...
    "SeedCorridor", struct([]), ...
    "SolverDiagnostics", diagnostics);
end

%% Section 4: Local Functions

function combined = combinePolynomials(parts)
% Concatenate exact switching segments without changing local coefficients.
combined = parts{1};
for partIndex = 2:numel(parts)
    part = parts{partIndex};
    combined.SegmentStartTime = [ ...
        combined.SegmentStartTime; part.SegmentStartTime];
    combined.SegmentDuration = [ ...
        combined.SegmentDuration; part.SegmentDuration];
    combined.positionPower = cat(1, ...
        combined.positionPower, part.positionPower);
    combined.velocityPower = cat(1, ...
        combined.velocityPower, part.velocityPower);
    combined.accelerationPower = cat(1, ...
        combined.accelerationPower, part.accelerationPower);
    combined.jerkPower = cat(1, combined.jerkPower, part.jerkPower);
    combined.SegmentCount = combined.SegmentCount + part.SegmentCount;
    combined.FinalTime = part.FinalTime;
    combined.TerminalState = part.TerminalState;
end
end

function polynomial = convertPolynomial(enginePolynomial)
% Translate exact-engine coefficient names at the planner boundary.
terminalState = enginePolynomial.TerminalState;
polynomial = struct( ...
    "SegmentCount", enginePolynomial.SegmentCount, ...
    "SegmentStartTime_s", enginePolynomial.SegmentStartTime, ...
    "SegmentDuration_s", enginePolynomial.SegmentDuration, ...
    "FinalTime_s", enginePolynomial.FinalTime, ...
    "positionPower_deg", enginePolynomial.positionPower, ...
    "velocityPower_deg_s", enginePolynomial.velocityPower, ...
    "accelerationPower_deg_s2", enginePolynomial.accelerationPower, ...
    "jerkPower_deg_s3", enginePolynomial.jerkPower, ...
    "TerminalState", struct( ...
    "position_deg", terminalState.position, ...
    "velocity_deg_s", terminalState.velocity, ...
    "acceleration_deg_s2", terminalState.acceleration));
end

function candidate = createFailedCandidate(seed, engineResult, elapsedTime_s)
% Preserve the exact segment failure in the ordinary candidate format.
diagnostics = obstacleAvoidance.planner.createEmptySolverDiagnostics();
diagnostics.Identifier = "ruckigWaypointComposition";
diagnostics.ConstraintRepresentation = "exactSwitchingSegments";
diagnostics.MaximumInequalityViolation = ...
    engineResult.MaximumConstraintViolation;
diagnostics.MaximumEqualityViolation = ...
    engineResult.MaximumConstraintViolation;
diagnostics = obstacleAvoidance.planner.createEmptySolverDiagnostics( ...
    diagnostics, elapsedTime_s, 0);
candidate = struct( ...
    "SeedIndex", seed.Index, ...
    "SeedSource", seed.Source, ...
    "OptimizerFeasible", false, ...
    "Message", engineResult.Message, ...
    "TerminationReason", engineResult.TerminationReason, ...
    "time_s", zeros(0, 1), ...
    "position_deg", zeros(0, 2), ...
    "velocity_deg_s", zeros(0, 2), ...
    "acceleration_deg_s2", zeros(0, 2), ...
    "jerk_deg_s3", zeros(0, 2), ...
    "Polynomial", struct(), ...
    "FinalTime_s", NaN, ...
    "MotionDuration_s", NaN, ...
    "MotionLength_deg", Inf, ...
    "IntegratedSquaredJerk_deg2_s5", Inf, ...
    "MaximumConstraintViolation", ...
    engineResult.MaximumConstraintViolation, ...
    "ArrivalAtHorizon", false, ...
    "SeedCorridorBoundary_deg", zeros(0, 2), ...
    "SeedCorridor", struct([]), ...
    "SolverDiagnostics", diagnostics);
end
