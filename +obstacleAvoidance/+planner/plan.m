function [repairSegmentCount, polishSegmentCount, signature, ...
        mayReplaceOrdinarySolve] = ...
        hybridSegmentCounts(profile, options)
% Scale repair work by route size and reserve dense polish for measured gain.
initialDuration_s = profile.InitialSectionDuration_s(:);
sectionDuration_s = profile.SectionDuration_s(:);
positiveTimeSaving_s = max(0, initialDuration_s - sectionDuration_s);
relativePositiveTimeSaving = sum(positiveTimeSaving_s) / ...
    sum(initialDuration_s);
edgeCount = numel(sectionDuration_s);
signature = struct( ...
    "EdgeCount", edgeCount, ...
    "TotalPositiveTimeSaving_s", sum(positiveTimeSaving_s), ...
    "RelativePositiveTimeSaving", relativePositiveTimeSaving);
minimumRepairSegmentCount = 12;
segmentsPerEdge = 1.75;
repairSegmentCount = min(options.MaximumCollocationSegmentCount, max( ...
    minimumRepairSegmentCount, ceil(segmentsPerEdge * edgeCount)));

% A two-percent pass-through saving is materially above solver tolerances and
% identifies routes where waypoint-state propagation changes the timing basin.
% Low-gain routes retain the cheaper established 14-segment finish.
meaningfulRelativeSaving = 0.02;
lowGainPolishSegmentCount = 14;
highGainPolishSegmentCount = 20;
hasFullyReversingRoute = ...
    profile.SolverDiagnostics.WaypointStateSearchMode == ...
    "coupledReversing";
hasHighGainSignature = ...
    relativePositiveTimeSaving >= meaningfulRelativeSaving || ...
    hasFullyReversingRoute;
if hasHighGainSignature
    requestedPolishSegmentCount = highGainPolishSegmentCount;
else
    requestedPolishSegmentCount = lowGainPolishSegmentCount;
end
polishSegmentCount = min( ...
    options.MaximumCollocationSegmentCount, requestedPolishSegmentCount);
mayReplaceOrdinarySolve = hasHighGainSignature && ...
    options.MaximumCollocationSegmentCount >= highGainPolishSegmentCount;
end

function stageTiming = addCandidateTiming(stageTiming, candidate)
% Add exclusive solver/corridor and independent-validation timings.
diagnostics = candidate.SolverDiagnostics;
stageTiming.CorridorConstructionElapsedTime_s = ...
    stageTiming.CorridorConstructionElapsedTime_s + ...
    diagnostics.CorridorConstructionElapsedTime_s;
stageTiming.MotionSolvingElapsedTime_s = ...
    stageTiming.MotionSolvingElapsedTime_s + ...
    diagnostics.MotionSolvingElapsedTime_s;
validation = candidate.Validation;
stageTiming.CollisionCheckingElapsedTime_s = ...
    stageTiming.CollisionCheckingElapsedTime_s + ...
    validation.CollisionCheckingElapsedTime_s;
stageTiming.FinalValidationElapsedTime_s = ...
    stageTiming.FinalValidationElapsedTime_s + max(0, ...
    validation.ElapsedTime_s - validation.CollisionCheckingElapsedTime_s);
end

function repeats = reproducesSolve(candidate, previousSolve, options)
% Compare arrival and clearance so a stalled relinearization is not repaid.
repeats = ~isempty(candidate.time_s) && ...
    matchesWithin(candidate.FinalTime_s, previousSolve.FinalTime_s, ...
    options.ArrivalTimeTolerance_s) && ...
    matchesWithin(candidate.Validation.MinimumClearance_deg, ...
    previousSolve.MinimumClearance_deg, ...
    max(options.CollisionClearanceTolerance_deg, 1e-9));
end

function relativeLengthExcess = coarseMotionLengthExcess(candidate, seed)
% Measure route inflation so the caller can scale one bounded quality pass.
if isempty(candidate.position_deg) || ~isfinite(seed.Length_deg) || ...
        seed.Length_deg <= 0
    relativeLengthExcess = 0;
    return;
end
motionLength_deg = sum(vecnorm(diff( ...
    candidate.position_deg, 1, 1), 2, 2));
relativeLengthExcess = motionLength_deg / seed.Length_deg - 1;
end

