function isSupported = supportsStaticDurationContinuation( ...
        seed, initialState, goalState, constraintTolerance_deg)
% Certify an axis-aligned monotone slalom with repeated lateral reversals.
isSupported = false;
position_deg = seed.position_deg;
displacement_deg = goalState.position_deg - initialState.position_deg;
scale_deg = max(1, max(abs(displacement_deg)));
geometryTolerance_deg = max(1e-10, ...
    constraintTolerance_deg * scale_deg);
activeAxis = find(abs(displacement_deg) > geometryTolerance_deg);
if numel(activeAxis) ~= 1 || size(position_deg, 1) < 4
    return;
end
primaryAxis = activeAxis(1);
lateralAxis = 3 - primaryAxis;
primaryIncrement_deg = diff(position_deg(:, primaryAxis));
progressDirection = sign(displacement_deg(primaryAxis));
if any(progressDirection * primaryIncrement_deg < ...
        -geometryTolerance_deg)
    return;
end
primaryTravel_deg = sum(abs(primaryIncrement_deg));
if abs(primaryTravel_deg - abs(displacement_deg(primaryAxis))) > ...
        geometryTolerance_deg
    return;
end
nearDirectLengthThreshold = 0.02;
directLength_deg = abs(displacement_deg(primaryAxis));
if seed.Length_deg / directLength_deg - 1 > ...
        nearDirectLengthThreshold
    return;
end
lateralOffset_deg = position_deg(:, lateralAxis) - ...
    initialState.position_deg(lateralAxis);
lateralSign = sign(lateralOffset_deg( ...
    abs(lateralOffset_deg) > geometryTolerance_deg));
if numel(lateralSign) < 3
    return;
end
retainedSign = [true; diff(lateralSign) ~= 0];
lateralSign = lateralSign(retainedSign);
minimumLateralReversalCount = 2;
isSupported = nnz(diff(lateralSign) ~= 0) >= ...
    minimumLateralReversalCount;
end

function isUsable = timingProfileIsUsable(profile)
% A direct exact motion can bound time even when no obstacle corridor exists.
