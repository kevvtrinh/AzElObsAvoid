end

function [candidate, diagnostics, stageTiming] = ...
        runStaticDurationContinuation( ...
        timingProfile, seed, obstacles, initialState, goalState, limits, ...
        options, stageTiming)
% Descend a fixed static route through a bounded normalized-time schedule.
% Only optimizer-feasible and independently valid trials become warm starts.
candidate = [];
floorDuration_s = timingProfile.FinalTime_s - initialState.time_s;
durationMultipliers = [1.25, 1.20, 1.15, 1.10, 1.05, 1.025];
targetTime_s = initialState.time_s + ...
    durationMultipliers * floorDuration_s;
withinHorizon = targetTime_s <= ...
    goalState.time_s + options.ArrivalTimeTolerance_s;
targetTime_s = targetTime_s(withinHorizon);
durationMultipliers = durationMultipliers(withinHorizon);
edgeCount = size(seed.position_deg, 1) - 1;
minimumContinuationSegmentCount = 14;
segmentsPerEdge = 2;
segmentCount = min(options.MaximumCollocationSegmentCount, max([ ...
    options.CollocationSegmentCount, minimumContinuationSegmentCount, ...
    segmentsPerEdge * edgeCount]));
trialTemplate = struct( ...
    "TargetTime_s", NaN, ...
    "OptimizerFeasible", false, ...
    "ValidationPassed", false, ...
    "MotionLength_deg", NaN, ...
    "MaximumConstraintViolation", Inf, ...
    "ElapsedTime_s", NaN, ...
    "TerminationReason", "notRun");
trials = repmat(trialTemplate, numel(targetTime_s), 1);
acceptedCandidate = [];
attemptCount = 0;
for targetIndex = 1:numel(targetTime_s)
    attemptCount = attemptCount + 1;
    trialGoalState = goalState;
    trialGoalState.time_s = targetTime_s(targetIndex);
    trialOptions = options;
    trialOptions.GoalTimeMode = "fixedArrival";
    trialOptions.CollocationSegmentCount = segmentCount;
    trialOptions.MaximumSolverTime_s = ...
        hs3Engine.defaultOptions().MaximumSolveTime;
    trialSeed = seed;
    trialSeed.EstimatedDuration_s = ...
        targetTime_s(targetIndex) - initialState.time_s;
    if ~isempty(acceptedCandidate)
        trialSeed.MotionWarmStart = createDurationScaledWarmStart( ...
            acceptedCandidate, initialState, targetTime_s(targetIndex));
    end
    trial = obstacleAvoidance.planner.solveRouteCandidate( ...
        obstacles, initialState, trialGoalState, limits, trialOptions, ...
        trialSeed);
    trial.Validation = validateCandidate( ...
        trial, obstacles, initialState, trialGoalState, limits, ...
        trialOptions);
    stageTiming = addCandidateTiming(stageTiming, trial);
    trials(targetIndex) = struct( ...
        "TargetTime_s", targetTime_s(targetIndex), ...
        "OptimizerFeasible", trial.OptimizerFeasible, ...
        "ValidationPassed", trial.Validation.Passed, ...
        "MotionLength_deg", trial.MotionLength_deg, ...
        "MaximumConstraintViolation", ...
        trial.MaximumConstraintViolation, ...
        "ElapsedTime_s", trial.SolverDiagnostics.ElapsedTime_s + ...
        trial.Validation.ElapsedTime_s, ...
        "TerminationReason", trial.TerminationReason);
    if ~trial.OptimizerFeasible || ~trial.Validation.Passed
        break;
    end
    acceptedCandidate = trial;
end
trials = trials(1:attemptCount);
targetReached = ~isempty(targetTime_s) && ...
    attemptCount == numel(targetTime_s) && ...
    ~isempty(acceptedCandidate) && ...
    matchesWithin(acceptedCandidate.FinalTime_s, targetTime_s(end), ...
    options.ArrivalTimeTolerance_s);
if targetReached
    acceptedCandidate.Validation = validateCandidate( ...
        acceptedCandidate, obstacles, initialState, goalState, limits, ...
        options);
    acceptedCandidate.ArrivalAtHorizon = matchesWithin( ...
        acceptedCandidate.FinalTime_s, goalState.time_s, ...
        options.ArrivalTimeTolerance_s);
    if acceptedCandidate.OptimizerFeasible && ...
            acceptedCandidate.Validation.Passed
        candidate = acceptedCandidate;
    end
end
diagnostics = struct( ...
    "Applied", attemptCount > 0, ...
    "TimingFloor_s", timingProfile.FinalTime_s, ...
    "DurationMultipliers", durationMultipliers(:), ...
    "SegmentCount", segmentCount, ...
    "AttemptCount", attemptCount, ...
    "Trial", trials, ...
    "TargetReached", targetReached, ...
    "Accepted", ~isempty(candidate), ...
    "AcceptedFinalTime_s", NaN);
if ~isempty(candidate)
    diagnostics.AcceptedFinalTime_s = candidate.FinalTime_s;
end
end

function warmStart = createDurationScaledWarmStart( ...
        candidate, initialState, finalTime_s)
% Preserve one valid spatial curve while scaling all time derivatives.
polynomial = candidate.Polynomial;
segmentBreakTau = polynomial.SegmentBreakTau;
segmentCount = polynomial.SegmentCount;
controlTau = zeros(2 * segmentCount + 1, 1);
controlTau(1:2:end) = segmentBreakTau;
controlTau(2:2:end - 1) = ...
    (segmentBreakTau(1:end - 1) + segmentBreakTau(2:end)) / 2;
oldDuration_s = candidate.FinalTime_s - initialState.time_s;
oldControlTime_s = initialState.time_s + controlTau * oldDuration_s;
[~, ~, ~, ~, oldJerk_deg_s3] = ...
    obstacleAvoidance.planner.evaluatePlannerPolynomial( ...
    polynomial, oldControlTime_s);
newDuration_s = finalTime_s - initialState.time_s;
newJerk_deg_s3 = oldJerk_deg_s3 * ...
    (oldDuration_s / newDuration_s)^3;
engineInitialState = struct( ...
    "time", initialState.time_s, ...
    "position", initialState.position_deg, ...
    "velocity", initialState.velocity_deg_s, ...
    "acceleration", initialState.acceleration_deg_s2);
uniformBreakTau = (0:segmentCount).' / segmentCount;
if isempty(segmentBreakTau) || isequal(segmentBreakTau, uniformBreakTau)
    enginePolynomial = hs3Engine.polynomial.createTrajectoryPolynomial( ...
        newJerk_deg_s3, engineInitialState, finalTime_s, segmentCount);
else
    enginePolynomial = hs3Engine.polynomial.createTrajectoryPolynomial( ...
        newJerk_deg_s3, engineInitialState, finalTime_s, segmentCount, ...
        segmentBreakTau);
end
if isfield(enginePolynomial, "SegmentBreakTau")
    resolvedSegmentBreakTau = enginePolynomial.SegmentBreakTau;
else
    resolvedSegmentBreakTau = uniformBreakTau;
end
warmPolynomial = struct( ...
    "SegmentCount", enginePolynomial.SegmentCount, ...
    "SegmentStartTime_s", enginePolynomial.SegmentStartTime, ...
    "SegmentDuration_s", enginePolynomial.SegmentDuration, ...
    "SegmentBreakTau", resolvedSegmentBreakTau, ...
    "FinalTime_s", enginePolynomial.FinalTime, ...
    "positionPower_deg", enginePolynomial.positionPower, ...
    "velocityPower_deg_s", enginePolynomial.velocityPower, ...
    "accelerationPower_deg_s2", enginePolynomial.accelerationPower, ...
    "jerkPower_deg_s3", enginePolynomial.jerkPower, ...
    "TerminalState", struct( ...
    "position_deg", enginePolynomial.TerminalState.position, ...
    "velocity_deg_s", enginePolynomial.TerminalState.velocity, ...
    "acceleration_deg_s2", ...
    enginePolynomial.TerminalState.acceleration));
sampleTau = (candidate.time_s - candidate.time_s(1)) / oldDuration_s;
warmStart = struct( ...
    "FinalTime_s", finalTime_s, ...
    "Polynomial", warmPolynomial, ...
    "time_s", initialState.time_s + sampleTau * newDuration_s, ...
    "position_deg", candidate.position_deg);
end

function [candidate, profile, stageTiming] = ...
        runPassThroughHs3WarmStart( ...
        profile, seed, obstacles, initialState, goalState, limits, ...
        options, stageTiming)
% Repair one precomputed rsruckig-style profile with two bounded HS3 solves.
% Both outputs undergo canonical validation; an invalid repair never replaces
% the original exact profile as the free-time warm start.
candidate = [];
if isempty(profile.time_s)
    return;
end

repairGoalState = goalState;
repairGoalState.time_s = profile.FinalTime_s;
repairOptions = options;
repairOptions.GoalTimeMode = "fixedArrival";
repairOptions.MaximumSolverTime_s = ...
    hs3Engine.defaultOptions().MaximumSolveTime;
[repairSegmentCount, polishSegmentCount, hybridSignature, ...
    mayReplaceOrdinarySolve] = ...
    hybridSegmentCounts(profile, options);
repairOptions.CollocationSegmentCount = repairSegmentCount;
repairSeed = seed;
repairSeed.MotionWarmStart = profile;
repaired = obstacleAvoidance.planner.solveRouteCandidate( ...
    obstacles, initialState, repairGoalState, limits, repairOptions, ...
    repairSeed);
repaired.Validation = validateCandidate( ...
    repaired, obstacles, initialState, repairGoalState, limits, ...
    repairOptions);
stageTiming = addCandidateTiming(stageTiming, repaired);
if repaired.Validation.Passed
    candidate = repaired;
end

polishOptions = options;
polishOptions.GoalTimeMode = "earliestArrival";
polishOptions.MaximumSolverTime_s = ...
    hs3Engine.defaultOptions().MaximumSolveTime;
polishOptions.CollocationSegmentCount = polishSegmentCount;
polishSeed = seed;
if repaired.Validation.Passed
    % An optimizer can return sampled motion after an infeasible exit. Only
    % a canonically validated repair may replace the original Ruckig warm
    % start; otherwise its residual can push the free-time solve into a
    % slower or worse basin.
    polishSeed.MotionWarmStart = repaired;
else
    polishSeed.MotionWarmStart = profile;
end
polished = obstacleAvoidance.planner.solveRouteCandidate( ...
    obstacles, initialState, goalState, limits, polishOptions, polishSeed);
polished.Validation = validateCandidate( ...
    polished, obstacles, initialState, goalState, limits, polishOptions);
stageTiming = addCandidateTiming(stageTiming, polished);
if polished.Validation.Passed && (isempty(candidate) || ...
        candidateImproves(polished, candidate, "earliestArrival"))
    candidate = polished;
end
profile.SolverDiagnostics.SectionSignature = hybridSignature;
profile.SolverDiagnostics.RepairSegmentCount = repairSegmentCount;
profile.SolverDiagnostics.PolishSegmentCount = polishSegmentCount;
profile.SolverDiagnostics.MayReplaceOrdinarySolve = ...
    mayReplaceOrdinarySolve;
end

