function options = resolvePlannerOptions(optionOverrides)
%% Section 0: Header & Readme
% SYNTAX
%   options = resolvePlannerOptions()
%   options = resolvePlannerOptions(optionOverrides)
%**************************************************************************
% PURPOSE
%   - Resolve and validate obstacle-planner search and motion options.
%**************************************************************************
% INPUTS
%   - optionOverrides (scalar struct, optional; default struct())
%       Partial planner option overrides. Empty fields use defaults; unknown
%       fields are warned about once and ignored.
%**************************************************************************
% OUTPUTS
%   - options (scalar struct)
%       Fully populated, normalized, and validated planner options.
%**************************************************************************
% UNITS
%   - Time fields use seconds and angular clearance fields use degrees.
%**************************************************************************

%% Section 1: Resolve Defaults

% Create every default in one place. Apply user values only after the complete
% default record exists. If an option appears to change between calls, inspect
% this section and the generic override helper.

% These defaults balance nonlinear-programming accuracy with bounded work.
% Counts limit the search and mesh refinement work. Tolerances define accepted
% errors for arrival, optimization, and collision checks. This function sets all
% defaults in one place. Thus, planner stages use the same omitted values.
defaults = struct( ...
    "GoalTimeMode", "earliestArrival", ...
    "SampleTime_s", 0.05, ...
    "AllowAzimuthWrapping", false, ...
    "CollectAllSeedCandidates", false, ...
    "WaypointWarmStartMode", "none", ...
    "MaximumSeedCount", 5, ...
    "SeedClusterDistance_deg", 0, ...
    "CollocationSegmentCount", 10, ...
    "MaximumCollocationSegmentCount", 64, ...
    "MaximumMeshRefinementPasses", 2, ...
    "MaximumNlpIterations", 300, ...
    "MaximumNlpFunctionEvaluations", 30000, ...
    "ArrivalTimeTolerance_s", 1e-3, ...
    "ConstraintTolerance", 1e-7, ...
    "OptimalityTolerance", 1e-7, ...
    "StepTolerance", 1e-10, ...
    "CollisionClearanceTolerance_deg", 1e-7, ...
    "CollisionMinimumTimeStep_s", 0.00025, ...
    "Verbose", false);
if nargin == 0 || isempty(optionOverrides)
    optionOverrides = struct();
end
if ~isstruct(optionOverrides) || ~isscalar(optionOverrides)
    error("planTrajectory:InvalidOptions", ...
        "optionOverrides must be a scalar struct.");
end
for movedName = ["AzimuthInterval_deg", "ElevationInterval_deg"]
    % Workspace bounds describe the planning request, not how motion is solved.
    % Reject the old option name. The error gives the new field location. Do not
    % ignore a workspace setting because it can change feasibility.
    if isfield(optionOverrides, movedName)
        replacementName = lower(extractBefore(movedName, "Interval")) + ...
            "Interval_deg";
        error("planTrajectory:WorkspaceLimitMoved", ...
            "%s has moved from options to limits.%s.", ...
            movedName, replacementName);
    end
end
[options, unknownNames] = obstacleAvoidance.input.resolveOptions(defaults, optionOverrides);
if ~isempty(unknownNames)
    warning("planTrajectory:UnknownOptions", ...
        "Ignoring unknown option fields: %s. No behavior changed.", ...
        strjoin(unknownNames, ", "));
end

%% Section 2: Normalize Public Values

% Convert text and logical values to one representation. Check integer work
% limits and positive tolerances before the solver uses them. Error identifiers
% from this section point to one invalid option rather than planner failure.

% earliestArrival allows the optimizer to choose any feasible arrival up to the
% horizon. fixedArrival requires the trajectory to end at goalState.time_s.
options.GoalTimeMode = string(options.GoalTimeMode);
if ~isscalar(options.GoalTimeMode) || ~any( ...
        options.GoalTimeMode == ["earliestArrival", "fixedArrival"])
    error("planTrajectory:InvalidGoalTimeMode", ...
        "GoalTimeMode must be 'earliestArrival' or 'fixedArrival'.");
end
options.WaypointWarmStartMode = string(options.WaypointWarmStartMode);
if ~isscalar(options.WaypointWarmStartMode) || ~any( ...
        options.WaypointWarmStartMode == ["none", "passThrough"])
    error("planTrajectory:InvalidWaypointWarmStartMode", ...
        "WaypointWarmStartMode must be 'none' or 'passThrough'.");
end
for name = ["AllowAzimuthWrapping", "CollectAllSeedCandidates", "Verbose"]
    options.(name) = obstacleAvoidance.input.normalizeLogicalScalar( ...
        options.(name), name, "planTrajectory:InvalidLogicalOption");
end
validateattributes(options.SampleTime_s, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'positive'});
validateattributes(options.MaximumSeedCount, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', '>=', 1, '<=', 9});
validateattributes(options.SeedClusterDistance_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'nonnegative'});
validateattributes(options.CollocationSegmentCount, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', '>=', 2, '<=', 80});
validateattributes(options.MaximumCollocationSegmentCount, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', ...
    '>=', options.CollocationSegmentCount, '<=', 80});
validateattributes(options.MaximumMeshRefinementPasses, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'integer', '>=', 0, '<=', 2});
for name = ["MaximumNlpIterations", "MaximumNlpFunctionEvaluations"]
    % Iteration and evaluation limits are separate because one solver iteration
    % may evaluate the objective and constraints many times.
    validateattributes(options.(name), {'numeric'}, ...
        {'real', 'finite', 'scalar', 'integer', 'positive'});
end
for name = ["ArrivalTimeTolerance_s", ...
        "ConstraintTolerance", "OptimalityTolerance", "StepTolerance", ...
        "CollisionMinimumTimeStep_s"]
    validateattributes(options.(name), {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'});
end
validateattributes(options.CollisionClearanceTolerance_deg, {'numeric'}, ...
    {'real', 'finite', 'scalar', 'nonnegative'});
end
