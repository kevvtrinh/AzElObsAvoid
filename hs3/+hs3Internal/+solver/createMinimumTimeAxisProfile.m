function profile = createMinimumTimeAxisProfile( ...
        initialState, terminalState, limits)
%% Section 0: Header & Readme
% SYNTAX
%   profile = hs3Internal.solver.createMinimumTimeAxisProfile( ...
%       initialState, terminalState, limits)
%**************************************************************************
% PURPOSE
%   - Create the shortest one-dimensional position trajectory admitted by
%     symmetric velocity, acceleration, and jerk limits.
%**************************************************************************
% INPUTS
%   - initialState (scalar struct)
%       Scalar time, position, velocity, and acceleration fields.
%   - terminalState (scalar struct)
%       Scalar position, velocity, and acceleration fields.
%   - limits (scalar struct)
%       Positive scalar maximumVelocity, maximumAcceleration, and
%       maximumJerk fields.
%**************************************************************************
% OUTPUTS
%   - profile (scalar struct)
%       Success, seven phase durations and jerks, minimum duration, and the
%       exact phase-boundary state histories. Unsupported numerical edge
%       cases return Success = false so the maintained optimizer can run.
%**************************************************************************
% UNITS
%   - Time and coordinate units are caller-defined and must be consistent.
%**************************************************************************

% The switching equations are adapted from Ruckig v0.19.4 under its MIT
% license; see hs3/THIRD_PARTY_NOTICES.txt.

%% Section 1: Create Candidate Switching Profiles

context = createContext(initialState, terminalState, limits);
candidates = repmat(createEmptyCandidate(), 0, 1);
directions = [1, -1];

for direction = directions
    directedLimits = createDirectedLimits(context, direction);
    candidates = appendVelocityProfiles(candidates, context, directedLimits);
    candidates = appendAccelerationProfiles( ...
        candidates, context, directedLimits);
    candidates = appendUnconstrainedProfiles( ...
        candidates, context, directedLimits);
end

%% Section 2: Select The Shortest Valid Profile

profile = createEmptyProfile();
if isempty(candidates)
    profile.Message = ...
        "No exact jerk-switching family satisfied the boundary states.";
    return;
end

durations = zeros(numel(candidates), 1);
for candidateIndex = 1:numel(candidates)
    durations(candidateIndex) = sum(candidates(candidateIndex).PhaseDuration);
end
[minimumDuration, selectedIndex] = min(durations);
selected = candidates(selectedIndex);
profile.Success = true;
profile.Message = "An exact minimum-time axis profile was created.";
profile.PhaseDuration = selected.PhaseDuration;
profile.PhaseJerk = selected.PhaseJerk;
profile.Duration = minimumDuration;
profile.FinalTime = initialState.time + minimumDuration;
profile.Position = selected.Position;
profile.Velocity = selected.Velocity;
profile.Acceleration = selected.Acceleration;
profile.Family = selected.Family;
profile.PathLength = selected.PathLength;
end

%% Section 3: Local Functions

function context = createContext(initialState, terminalState, limits)
% Cache the scalar boundary powers used by several switching families.
context = struct( ...
    "p0", initialState.position, ...
    "pf", terminalState.position, ...
    "v0", initialState.velocity, ...
    "vf", terminalState.velocity, ...
    "a0", initialState.acceleration, ...
    "af", terminalState.acceleration, ...
    "vMaximum", limits.maximumVelocity, ...
    "aMaximum", limits.maximumAcceleration, ...
    "jMaximum", limits.maximumJerk);
context.displacement = context.pf - context.p0;
context.v0Squared = context.v0^2;
context.vfSquared = context.vf^2;
context.a0Squared = context.a0^2;
context.afSquared = context.af^2;
context.a0Cubed = context.a0^3;
context.afCubed = context.af^3;
context.a0Fourth = context.a0^4;
context.afFourth = context.af^4;
end

function directed = createDirectedLimits(context, direction)
% Reverse every signed bound together so one equation set covers both ways.
directed = struct( ...
    "vMaximum", direction * context.vMaximum, ...
    "vMinimum", -direction * context.vMaximum, ...
    "aMaximum", direction * context.aMaximum, ...
    "aMinimum", -direction * context.aMaximum, ...
    "jMaximum", direction * context.jMaximum);
end

function candidates = appendVelocityProfiles(candidates, context, limits)
% Add the four families whose middle phase reaches the velocity bound.
vMaximum = limits.vMaximum;
aMaximum = limits.aMaximum;
aMinimum = limits.aMinimum;
jMaximum = limits.jMaximum;
jSquared = jMaximum^2;

phase = zeros(1, 7);
phase(1) = (-context.a0 + aMaximum) / jMaximum;
phase(2) = (context.a0Squared / 2 - aMaximum^2 - ...
    jMaximum * (context.v0 - vMaximum)) / (aMaximum * jMaximum);
phase(3) = aMaximum / jMaximum;
phase(4) = (3 * (context.a0Fourth * aMinimum - ...
    context.afFourth * aMaximum) + 8 * aMaximum * aMinimum * ...
    (context.afCubed - context.a0Cubed + 3 * jMaximum * ...
    (context.a0 * context.v0 - context.af * context.vf)) + ...
    6 * context.a0Squared * aMinimum * ...
    (aMaximum^2 - 2 * jMaximum * context.v0) - ...
    6 * context.afSquared * aMaximum * ...
    (aMinimum^2 - 2 * jMaximum * context.vf) - ...
    12 * jMaximum * (aMaximum * aMinimum * ...
    (aMaximum * (context.v0 + vMaximum) - ...
    aMinimum * (context.vf + vMaximum) - ...
    2 * jMaximum * context.displacement) + ...
    (aMinimum - aMaximum) * jMaximum * vMaximum^2 + ...
    jMaximum * (aMaximum * context.vfSquared - ...
    aMinimum * context.v0Squared))) / ...
    (24 * aMaximum * aMinimum * jSquared * vMaximum);
phase(5) = -aMinimum / jMaximum;
phase(6) = -(context.afSquared / 2 - aMinimum^2 - ...
    jMaximum * (context.vf - vMaximum)) / (aMinimum * jMaximum);
phase(7) = phase(5) + context.af / jMaximum;
candidates = appendCandidate(candidates, context, limits, ...
    phase, "accelerationVelocity");

timeAcceleration0 = safeSqrt(context.a0Squared / (2 * jSquared) + ...
    (vMaximum - context.v0) / jMaximum);
timeAcceleration1 = safeSqrt(context.afSquared / (2 * jSquared) + ...
    (vMaximum - context.vf) / jMaximum);
if isfinite(timeAcceleration0)
    phase(1:3) = [timeAcceleration0 - context.a0 / jMaximum, ...
        0, timeAcceleration0];
    phase(4) = -(3 * context.afFourth - 8 * aMinimum * ...
        (context.afCubed - context.a0Cubed) - 24 * aMinimum * ...
        jMaximum * (context.a0 * context.v0 - context.af * context.vf) + ...
        6 * context.afSquared * ...
        (aMinimum^2 - 2 * jMaximum * context.vf) - ...
        12 * jMaximum * (2 * aMinimum * jMaximum * ...
        context.displacement + aMinimum^2 * ...
        (context.vf + vMaximum) + jMaximum * ...
        (vMaximum^2 - context.vfSquared) + aMinimum * ...
        timeAcceleration0 * (context.a0Squared - ...
        2 * jMaximum * (context.v0 + vMaximum)))) / ...
        (24 * aMinimum * jSquared * vMaximum);
    candidates = appendCandidate(candidates, context, limits, ...
        phase, "terminalAccelerationVelocity");
end

if isfinite(timeAcceleration1)
    phase(1) = (-context.a0 + aMaximum) / jMaximum;
    phase(2) = (context.a0Squared / 2 - aMaximum^2 - ...
        jMaximum * (context.v0 - vMaximum)) / (aMaximum * jMaximum);
    phase(3) = aMaximum / jMaximum;
    phase(4) = (3 * context.a0Fourth + 8 * aMaximum * ...
        (context.afCubed - context.a0Cubed) + 24 * aMaximum * ...
        jMaximum * (context.a0 * context.v0 - context.af * context.vf) + ...
        6 * context.a0Squared * ...
        (aMaximum^2 - 2 * jMaximum * context.v0) - ...
        12 * jMaximum * (-2 * aMaximum * jMaximum * ...
        context.displacement + aMaximum^2 * ...
        (context.v0 + vMaximum) + jMaximum * ...
        (vMaximum^2 - context.v0Squared) + aMaximum * ...
        timeAcceleration1 * (-context.afSquared + ...
        2 * (context.vf + vMaximum) * jMaximum))) / ...
        (24 * aMaximum * jSquared * vMaximum);
    phase(5:7) = [timeAcceleration1, 0, ...
        timeAcceleration1 + context.af / jMaximum];
    candidates = appendCandidate(candidates, context, limits, ...
        phase, "initialAccelerationVelocity");
end

if isfinite(timeAcceleration0) && isfinite(timeAcceleration1)
    phase(1:3) = [timeAcceleration0 - context.a0 / jMaximum, ...
        0, timeAcceleration0];
    phase(4) = (context.afCubed - context.a0Cubed) / ...
        (3 * jSquared * vMaximum) + ...
        (context.a0 * context.v0 - context.af * context.vf + ...
        (context.afSquared * timeAcceleration1 + ...
        context.a0Squared * timeAcceleration0) / 2) / ...
        (jMaximum * vMaximum) - ...
        (context.v0 / vMaximum + 1) * timeAcceleration0 - ...
        (context.vf / vMaximum + 1) * timeAcceleration1 + ...
        context.displacement / vMaximum;
    phase(5:7) = [timeAcceleration1, 0, ...
        timeAcceleration1 + context.af / jMaximum];
    candidates = appendCandidate(candidates, context, limits, ...
        phase, "velocity");
end
end

function candidates = appendAccelerationProfiles(candidates, context, limits)
% Add the two families that reach both signed acceleration bounds.
aMaximum = limits.aMaximum;
aMinimum = limits.aMinimum;
jMaximum = limits.jMaximum;
jSquared = jMaximum^2;
denominator = aMaximum - aMinimum;

radicand = (3 * (context.afFourth * aMaximum - ...
    context.a0Fourth * aMinimum) + aMaximum * aMinimum * ...
    (8 * (context.a0Cubed - context.afCubed) + ...
    3 * aMaximum * aMinimum * (aMaximum - aMinimum) + ...
    6 * aMinimum * context.afSquared - ...
    6 * aMaximum * context.a0Squared) + ...
    12 * jMaximum * (aMaximum * aMinimum * ...
    ((aMaximum - 2 * context.a0) * context.v0 - ...
    (aMinimum - 2 * context.af) * context.vf) + ...
    aMinimum * context.a0Squared * context.v0 - ...
    aMaximum * context.afSquared * context.vf)) / ...
    (3 * denominator * jSquared) + ...
    4 * (aMaximum * context.vfSquared - ...
    aMinimum * context.v0Squared - 2 * aMinimum * aMaximum * ...
    context.displacement) / denominator;
if radicand < 0
    return;
end

root = sqrt(radicand) / 2;
baseInitial = context.a0Squared / (2 * aMaximum * jMaximum) + ...
    (aMinimum - 2 * aMaximum) / (2 * jMaximum) - ...
    context.v0 / aMaximum;
baseTerminal = -context.afSquared / (2 * aMinimum * jMaximum) - ...
    (aMaximum - 2 * aMinimum) / (2 * jMaximum) + ...
    context.vf / aMinimum;
phase = zeros(1, 7);
phase([1, 3, 5, 7]) = [ ...
    (-context.a0 + aMaximum) / jMaximum, ...
    aMaximum / jMaximum, -aMinimum / jMaximum, ...
    -aMinimum / jMaximum + context.af / jMaximum];

phase(2) = baseInitial - root / aMaximum;
phase(6) = baseTerminal + root / aMinimum;
candidates = appendCandidate(candidates, context, limits, ...
    phase, "accelerationBounds");

phase(2) = baseInitial + root / aMaximum;
phase(6) = baseTerminal - root / aMinimum;
candidates = appendCandidate(candidates, context, limits, ...
    phase, "accelerationBounds");
end

function candidates = appendUnconstrainedProfiles(candidates, context, limits)
% Add quartic families with no velocity plateau and at most one accel hold.
aMaximum = limits.aMaximum;
aMinimum = limits.aMinimum;
jMaximum = limits.jMaximum;
jSquared = jMaximum^2;

h2None = (context.a0Squared - context.afSquared) / ...
    (2 * jMaximum) + context.vf - context.v0;
h2NoneSquared = h2None^2;
rootsNone = realQuarticRoots([1, 0, ...
    -2 * (context.a0Squared + context.afSquared - ...
    2 * jMaximum * (context.v0 + context.vf)) / jSquared, ...
    4 * (context.a0Cubed - context.afCubed + ...
    3 * jMaximum * (context.af * context.vf - ...
    context.a0 * context.v0)) / (3 * jMaximum * jSquared) - ...
    4 * context.displacement / jMaximum, ...
    -h2NoneSquared / jSquared]);
for rootIndex = 1:numel(rootsNone)
    time = rootsNone(rootIndex);
    if time < (context.a0 - context.af) / jMaximum || ...
            time > (aMaximum - aMinimum) / jMaximum || time <= eps
        continue;
    end
    h1 = jMaximum * time^2;
    residual = -h2NoneSquared / (4 * jMaximum * time) + ...
        h2None * (context.af / jMaximum + time) + ...
        (4 * context.a0Cubed + 2 * context.afCubed - ...
        6 * context.a0Squared * (context.af + 2 * jMaximum * time) + ...
        12 * (context.af - context.a0) * jMaximum * context.v0 + ...
        3 * jSquared * (-4 * context.displacement + ...
        (h1 + 8 * context.v0) * time)) / (12 * jSquared);
    derivative = h2None + 2 * context.v0 - ...
        context.a0Squared / jMaximum + h2NoneSquared / (4 * h1) + ...
        3 * h1 / 4;
    if isfinite(derivative) && derivative ~= 0
        time = time - residual / derivative;
    end
    h0 = h2None / (2 * jMaximum * time);
    phase = [h0 + time / 2 - context.a0 / jMaximum, ...
        0, time, 0, 0, 0, -h0 + time / 2 + ...
        context.af / jMaximum];
    candidates = appendCandidate(candidates, context, limits, ...
        phase, "unconstrained");
end

h3Initial = (context.a0Squared - context.afSquared) / ...
    (2 * aMaximum * jMaximum) + ...
    (context.vf - context.v0) / aMaximum;
h0Initial = 3 * (context.afFourth - context.a0Fourth) + ...
    8 * (context.a0Cubed - context.afCubed) * aMaximum + ...
    24 * aMaximum * jMaximum * ...
    (context.af * context.vf - context.a0 * context.v0) - ...
    6 * context.a0Squared * (aMaximum^2 - ...
    2 * jMaximum * context.v0) + 6 * context.afSquared * ...
    (aMaximum^2 - 2 * jMaximum * context.vf) + ...
    12 * jMaximum * (jMaximum * (context.vfSquared - ...
    context.v0Squared - 2 * aMaximum * context.displacement) - ...
    aMaximum^2 * (context.vf - context.v0));
h2Initial = -context.afSquared + aMaximum^2 + ...
    2 * jMaximum * context.vf;
rootsInitial = realQuarticRoots([1, -2 * aMaximum / jMaximum, ...
    h2Initial / jSquared, 0, h0Initial / (12 * jSquared^2)]);
for rootIndex = 1:numel(rootsInitial)
    time = rootsInitial(rootIndex);
    if time < (aMaximum - context.af) / jMaximum || ...
            time > (aMaximum - aMinimum) / jMaximum || time <= eps
        continue;
    end
    h1 = jMaximum * time;
    residual = h0Initial / (12 * jSquared * time) + ...
        time * (h2Initial + h1 * (h1 - 2 * aMaximum));
    derivative = 2 * (h2Initial + h1 * (2 * h1 - 3 * aMaximum));
    if isfinite(derivative) && derivative ~= 0
        time = time - residual / derivative;
    end
    phase = [(-context.a0 + aMaximum) / jMaximum, ...
        h3Initial - 2 * time + jMaximum / aMaximum * time^2, ...
        time, 0, 0, 0, (context.af - aMaximum) / jMaximum + time];
    candidates = appendCandidate(candidates, context, limits, ...
        phase, "initialAcceleration");
end

h3Terminal = -(context.a0Squared + context.afSquared) / ...
    (2 * jMaximum * aMinimum) + aMinimum / jMaximum + ...
    (context.vf - context.v0) / aMinimum;
h0Terminal = (context.a0Fourth - context.afFourth) / 4 + ...
    2 * (context.afCubed - context.a0Cubed) * aMinimum / 3 + ...
    (context.a0Squared - context.afSquared) * aMinimum^2 / 2 + ...
    jMaximum * (context.afSquared * context.vf + ...
    context.a0Squared * context.v0 + 2 * aMinimum * ...
    (jMaximum * context.displacement - context.a0 * context.v0 - ...
    context.af * context.vf) + aMinimum^2 * ...
    (context.v0 + context.vf) + jMaximum * ...
    (context.v0Squared - context.vfSquared));
h2Terminal = context.a0Squared - context.a0 * aMinimum + ...
    2 * jMaximum * context.v0;
rootsTerminal = realQuarticRoots([1, ...
    2 * (2 * context.a0 - aMinimum) / jMaximum, ...
    (5 * context.a0Squared + aMinimum * ...
    (aMinimum - 6 * context.a0) + 2 * jMaximum * context.v0) / ...
    jSquared, 2 * (context.a0 - aMinimum) * h2Terminal / ...
    (jSquared * jMaximum), h0Terminal / jSquared^2]);
for rootIndex = 1:numel(rootsTerminal)
    time = rootsTerminal(rootIndex);
    if time < (aMinimum - context.a0) / jMaximum || ...
            time > (aMaximum - context.a0) / jMaximum || time <= eps
        continue;
    end
    for refinementIndex = 1:3
        h1 = jMaximum * time;
        residual = -(h0Terminal / 2 + h1 * ...
            (context.a0Cubed + 2 * jMaximum * context.a0 * context.v0 + ...
            context.a0 * (aMinimum - 2 * h1) * (aMinimum - h1) + ...
            context.a0Squared * (5 * h1 / 2 - 2 * aMinimum) + ...
            aMinimum^2 * h1 / 2 + jMaximum * ...
            (h1 / 2 - aMinimum) * (h1 * time + 2 * context.v0))) / ...
            jMaximum;
        derivative = (aMinimum - context.a0 - h1) * ...
            (h2Terminal + h1 * ...
            (4 * context.a0 - aMinimum + 2 * h1));
        if abs(residual) <= 1e-9 || ~isfinite(derivative) || derivative == 0
            break;
        end
        time = time - min(residual / derivative, time);
    end
    phase = [time, 0, (context.a0 - aMinimum) / jMaximum + time, ...
        0, 0, h3Terminal - ...
        (2 * context.a0 + jMaximum * time) * time / aMinimum, ...
        (context.af - aMinimum) / jMaximum];
    candidates = appendCandidate(candidates, context, limits, ...
        phase, "terminalAcceleration");
end
end

function candidates = appendCandidate( ...
        candidates, context, limits, phaseDuration, family)
% Integrate one seven-phase UDDU law and retain it only when fully valid.
phaseJerk = limits.jMaximum * [1, 0, -1, 0, -1, 0, 1];
initialState = struct( ...
    "position", context.p0, ...
    "velocity", context.v0, ...
    "acceleration", context.a0);
terminalState = struct( ...
    "position", context.pf, ...
    "velocity", context.vf, ...
    "acceleration", context.af);
physicalLimits = struct( ...
    "maximumVelocity", context.vMaximum, ...
    "maximumAcceleration", context.aMaximum);
evaluated = hs3Internal.solver.evaluateAxisSwitchingProfile( ...
    initialState, terminalState, physicalLimits, ...
    phaseDuration, phaseJerk, family);
if ~evaluated.Success
    return;
end

candidate = createEmptyCandidate();
candidate.PhaseDuration = evaluated.PhaseDuration;
candidate.PhaseJerk = evaluated.PhaseJerk;
candidate.Position = evaluated.Position;
candidate.Velocity = evaluated.Velocity;
candidate.Acceleration = evaluated.Acceleration;
candidate.Family = family;
candidate.PathLength = evaluated.PathLength;
candidates(end + 1, 1) = candidate;
end

function values = realQuarticRoots(coefficients)
% Keep numerically real roots and let the exact profile check reject the rest.
allRoots = roots(coefficients);
imaginaryTolerance = 1e-8 * max(1, max(abs(allRoots)));
isReal = abs(imag(allRoots)) <= imaginaryTolerance;
values = sort(real(allRoots(isReal))).';
end

function value = safeSqrt(radicand)
% Return NaN for a genuinely negative radical while accepting roundoff at zero.
if radicand < -64 * eps(max(1, abs(radicand)))
    value = NaN;
else
    value = sqrt(max(0, radicand));
end
end

function candidate = createEmptyCandidate()
% Define one exact switching candidate with stable diagnostic fields.
candidate = struct( ...
    "PhaseDuration", zeros(1, 7), ...
    "PhaseJerk", zeros(1, 7), ...
    "Position", zeros(1, 8), ...
    "Velocity", zeros(1, 8), ...
    "Acceleration", zeros(1, 8), ...
    "Family", "", ...
    "PathLength", Inf);
end

function profile = createEmptyProfile()
% Return an explicit unsupported-family record for the optimizer fallback.
profile = struct( ...
    "Success", false, ...
    "Message", "No exact axis profile was created.", ...
    "PhaseDuration", zeros(1, 7), ...
    "PhaseJerk", zeros(1, 7), ...
    "Duration", NaN, ...
    "FinalTime", NaN, ...
    "Position", zeros(1, 8), ...
    "Velocity", zeros(1, 8), ...
    "Acceleration", zeros(1, 8), ...
    "Family", "", ...
    "PathLength", Inf);
end
