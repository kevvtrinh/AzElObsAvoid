function solution = solveFixedTime( ...
        initialState, terminalState, limits, options, ...
        pathConstraints, finalTime)
%% Section 0: Header & Readme
% SYNTAX
%   solution = hs3Internal.solveFixedTime(initialState, terminalState, limits, ...
%       options, pathConstraints, finalTime)
%**************************************************************************
% PURPOSE
%   - Solve the fixed-duration HS3 minimum-integrated-jerk convex QP.
%**************************************************************************
% INPUTS
%   - initialState, terminalState, limits, options (resolved scalar structs)
%   - pathConstraints (resolved scalar struct), optional affine path rows.
%   - finalTime (finite scalar), absolute terminal time.
%**************************************************************************
% OUTPUTS
%   - solution (scalar struct)
%       Stable solver status, decision, objective, violations, and diagnostics.
%**************************************************************************
% UNITS
%   - Time and coordinate units are caller-defined and must be consistent.
%**************************************************************************

%% Section 1: Assemble The Exact Affine QP

solverTimer = tic;
segmentCount = options.SegmentCount;
dimensionCount = numel(initialState.position);
controlCount = 2 * segmentCount + 1;
decisionCount = dimensionCount * controlCount;
duration = finalTime - initialState.time;
zeroDecision = zeros(decisionCount, 1);
constraintFunction = @(decision) hs3Internal.evaluateConstraints( ...
    decision, false, finalTime, finalTime, finalTime, segmentCount, ...
    initialState, terminalState, limits, pathConstraints);
[zeroInequality, zeroEquality] = constraintFunction(zeroDecision);
[inequalityMatrix, equalityMatrix] = hs3Internal.buildFixedConstraintMatrices( ...
    segmentCount, duration, dimensionCount, limits, pathConstraints);
if size(inequalityMatrix, 1) ~= numel(zeroInequality) || ...
        size(equalityMatrix, 1) ~= numel(zeroEquality)
    error("solveFixedTime:ConstraintGradientSizeMismatch", ...
        "The exact fixed-time constraint maps have inconsistent row counts.");
end
inequalityBound = -zeroInequality;
equalityBound = -zeroEquality;
[~, ~, jerkHessian] = hs3Internal.integratedSquaredJerk( ...
    zeroDecision, false, finalTime, segmentCount, ...
    initialState.time, dimensionCount);
lowerBound = reshape(repmat( ...
    limits.jerkLower, controlCount, 1), [], 1);
upperBound = reshape(repmat( ...
    limits.jerkUpper, controlCount, 1), [], 1);
initialDecision = minimumNormEqualityPoint( ...
    equalityMatrix, equalityBound, decisionCount);

%% Section 2: Solve And Measure Feasibility

problem = struct( ...
    "Decision0", initialDecision, ...
    "LowerBound", lowerBound, ...
    "UpperBound", upperBound, ...
    "TypicalDecision", max(1, abs(initialDecision)), ...
    "IsFreeTime", false, ...
    "ConstraintFunction", constraintFunction, ...
    "ObjectiveFunction", @(decision) hs3Internal.integratedSquaredJerk( ...
    decision, false, finalTime, segmentCount, ...
    initialState.time, dimensionCount), ...
    "ProgressFunction", @(~, ~, ~) false, ...
    "InequalityMatrix", inequalityMatrix, ...
    "InequalityBound", inequalityBound, ...
    "EqualityMatrix", equalityMatrix, ...
    "EqualityBound", equalityBound, ...
    "Hessian", jerkHessian, ...
    "SolverTimer", solverTimer);
core = hs3Internal.optimize(problem, options);
if strlength(core.StageOneErrorIdentifier) > 0
    terminationReason = "solverError";
    message = "Fixed-time HS3 solve failed: " + ...
        core.StageOneErrorMessage;
elseif core.OptimizerFeasible
    terminationReason = "optimizerFeasible";
    message = "Fixed-time HS3 returned a constraint-feasible solution.";
else
    terminationReason = "optimizerInfeasible";
    message = "Fixed-time HS3 did not satisfy all constraints.";
end
solution = struct( ...
    "Success", core.OptimizerFeasible, ...
    "Message", message, ...
    "TerminationReason", terminationReason, ...
    "Decision", core.Decision, ...
    "FinalTime", finalTime, ...
    "Objective", core.StageOneObjective, ...
    "ExitFlag", core.StageOneExitFlag, ...
    "Output", core.StageOneOutput, ...
    "MaximumInequalityViolation", core.MaximumInequalityViolation, ...
    "MaximumEqualityViolation", core.MaximumEqualityViolation, ...
    "MaximumConstraintViolation", core.MaximumConstraintViolation, ...
    "ErrorIdentifier", core.StageOneErrorIdentifier, ...
    "ErrorMessage", core.StageOneErrorMessage, ...
    "ElapsedTime", core.ElapsedTime);
if options.Verbose
    fprintf("[HS3] fixed-time exit=%g, feasible=%d, objective=%.9g.\n", ...
        core.StageOneExitFlag, core.OptimizerFeasible, ...
        core.StageOneObjective);
end
end

%% Section 3: Local Functions

function decision = minimumNormEqualityPoint( ...
        equalityMatrix, equalityBound, decisionCount)
%% Section 0: Header & Readme
% SYNTAX
%   decision = minimumNormEqualityPoint( ...
%       equalityMatrix, equalityBound, decisionCount)
%**************************************************************************
% PURPOSE
%   - Construct a deterministic terminal-state-feasible QP starting point.
%**************************************************************************
% INPUTS
%   - equalityMatrix (M-by-V numeric), terminal-state Jacobian.
%   - equalityBound (M-by-1 numeric), terminal-state right-hand side.
%   - decisionCount (positive integer scalar), jerk decision count.
%**************************************************************************
% OUTPUTS
%   - decision (V-by-1 numeric), minimum-norm equality solution.
%**************************************************************************
% UNITS
%   - Decision values use coordinate/time^3.
%**************************************************************************
if isempty(equalityMatrix)
    decision = zeros(decisionCount, 1);
    return;
end
decision = equalityMatrix.' * ...
    ((equalityMatrix * equalityMatrix.') \ equalityBound);
end
